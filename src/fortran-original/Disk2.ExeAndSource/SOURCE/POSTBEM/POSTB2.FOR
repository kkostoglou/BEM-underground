      SUBROUTINE PLCARSTR(SLT1,SA1,XTIME,KATEG,NTOT,NPLOT,NDTOT,
     &  NDPLOT,LETOT,LEPLOT,T1MIN,T1MAX,R1MIN,R1MAX,KPLOT,KONN,
     &  SLN1,LDIR1,N1,N3,N4,N7,N9,IPSG,INDX,NUNIT)
C
C     FOR THE NODES
C     PLOTS THE HOOP STRESSES OR DISPLACEMENTS IN CARTESIAN SYSTEM,
C     BY CALLING PLOTHOOPN
C     KPLOT(2) : 0 THE PLOTS ARE DRAWN ONE BY ONE
C                1 THE PLOTS ARE DRAWN ALL IN THE SAME PAGE
C     KPLOT(3) : 0 THE PLOTS ARE DRAWN IN NORMAL AXES
C                1 THE PLOTS ARE DRAWN IN DIMENSIONLESS AXES
C     NUNIT: INDEX FOR UNITS SYSTEM
C        1: SI SYSTEM (INTARNATIONAL)
C        2: IMPERIAL

      IMPLICIT REAL*8 (A-H,O-Y)
      INCLUDE 'FGRAPH.FD'
      COMMON/TIT/FNAMEIN,TITLE,TITLY
      COMMON/CONTR/NNODE,NELEM,NTINT,NP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM
      CHARACTER FNAMEIN*14,TITLE*45,TITLY*20
      DIMENSION SLT1(N9,N4,N3),SA1(N9)
      DIMENSION XTIME(N9)
      DIMENSION NPLOT(NTOT),NDPLOT(NDTOT),LEPLOT(LETOT)
      DIMENSION LDIR1(N1),SLN1(N1)
      DIMENSION KONN(N3,N4)
      DIMENSION KPLOT(INDX)
C ************** RESTRICTION OF THE PROGRAM ***********
C     MAXIMUM 5 ELEMENTS JOININIG TO ONE NODE
      DIMENSION KDIR(5),NDIR(5)
      DIMENSION XW(2),YW(2)
      INTEGER*2 ISTATUS,ISTYLE
      CHARACTER*20         list
      INTEGER*2 MAXX,MAXY,XPOS,YPOS
      INTEGER*4            ifont
      CHARACTER*10         options(6)
      RECORD/WXYCOORD/POSITION
      RECORD/XYCOORD/XYS
      RECORD/XYCOORD/XYS1
      CHARACTER*255 BUFFER
      COMMON /FNTS/NFONTS,IFONT,OPTIONS,MAXX,MAXY
C
      PI=3.14159265359
      TOL=1.0E-6
      TOL1=1.0E-11
      JPL=0
      NOD=3
      DO 22 I=1,5
        KDIR(I)=0
        NDIR(I)=0
  22  CONTINUE
      DT=TIM/DFLOAT(NTINT)
      R11MIN=R1MIN
      R11MAX=R1MAX
      T11MIN=T1MIN
      T11MAX=T1MAX
C     FOR SI UNIT SYSTEM, MULTIPLY LIMITS BY 1000 (mm)
      IF(NUNIT.EQ.1) THEN
        IF((KATEG.EQ.21).OR.(KATEG.EQ.22)) THEN
          R11MIN=1000.0*R1MIN
          R11MAX=1000.0*R1MAX
        ENDIF
      ENDIF
      IF(KPLOT(3).EQ.1) T11MAX=NTINT
C     NEW SCALING
C      CALL GLIMIT(T11MIN,T11MAX,R11MIN,R11MAX,0.0,0.0)
C      CALL GSCALE
      XW(1)=1.3*T11MIN
      XW(2)=1.3*T11MAX
      YW(1)=1.3*R11MIN
      YW(2)=1.3*R11MAX
      ISTATUS=SETWINDOW(.TRUE.,XW(1),YW(1),XW(2),YW(2))
C     CHECK IF THE PLOT NUMBER HAS BE GIVEN
      KFOUND=0
      DO 94 IPL=1,NTOT
        IF(NPLOT(IPL).EQ.KATEG) KFOUND=1
  94  CONTINUE
      IF(KFOUND.EQ.0) GO TO 99
C      CALL GCLEAR
      CALL CLEARSCREEN($GCLEARSCREEN)
C     CASE THAT ALL THE PLOTS ARE DRAWN IN THE SAME PAGE (NPLOT=28)
      IF(KPLOT(2).EQ.1) THEN
CC       CREATE A SEGMENT FOR PLOTING WITH RASCON
        IPSG=IPSG+1
C        CALL GSEGCR(IPSG)
      ENDIF
C     PLOT AXES
C      CALL PLOTAXES(XW,YW,XTIME,N9)
C      CALL PLOTAXES(XW,YW,N9)
      CALL PLOTAXES(T11MIN,R11MIN,T11MAX,R11MAX,N9)
      DO 13 I=1,NNODE
        KDIAK=0
        KDIAK1=0
C       COUNTER OF THE NUMBER OF PLOTS OF NODE I FOUND IN  ELEMENT.NODES (LEPLOT)
        KIN=0
C       CASE THAT THE PLOTS ARE DRAWN IN DIFFERENT PAGES
        IF(KPLOT(2).EQ.0) CALL CLEARSCREEN($GCLEARSCREEN)
C             GCLEAR
C       CHECK TO FIND IF THE NODE I IS IN THE ARRAY NDPLOT
        IF(NDTOT.GT.0) THEN
          DO 2 K=1,NDTOT
            K1=NDPLOT(K)
            IF(I.EQ.K1) KDIAK=1
  2       CONTINUE
CC         IN CASE THAT NOT FOUND RETURN
C          IF(KDIAK.EQ.0) GO TO 13
        ENDIF
C       CHECK TO FIND IF THE NODE I IS IN THE ARRAY LEPLOT
        IF(LETOT.GT.0) THEN
          DO 4 K=1,LETOT
            K1=LEPLOT(K)
C           IF K ODD, THEN K IS THE NUMBER OF ELEMENT
C           IF K EVEN, THEN K IS THE NUMBER OF NODE WE WANT THE PLOT
            K2=K/2
C           REMAINDER = K-INT(K/2)*2
C            LR=MOD(K1,2)
            LR=MOD(K,2)
C           K EVEN (LR.EQ.0)
C           K ODD (LR.NE.0)
            IF(LR.NE.0) GO TO 4
C           IN CASE THAT NODE FOUND IN LEPLOT
            IF(I.EQ.K1) THEN
              KDIAK1=1
C             INCREASE BY 1 THE COUNTER OF THE NUMBER OF PLOTS OF NODE I 
C             FOUND IN  ELEMENT.NODES (LEPLOT)
              KIN=KIN+1
C             KEEP THE NUMBER OF THE ELEMENT
              LE1=LEPLOT(K-1)
              KDIR(KIN)=LE1
C             FIND AND KEEP THE NUMBER OF THE NODE IN THE ELEMENT
              DO 6 II=1,NOD
                LN=KONN(LE1,II)
                IF(LN.EQ.I) NDIR(KIN)=II
  6           CONTINUE
            ENDIF
  4       CONTINUE
CC         IN CASE THAT NOT FOUND RETURN
C          IF(KDIAK.EQ.0) GO TO 13
        ENDIF
C       IF NOT PLOT FOUND IN LEPLOT
        IF(KIN.EQ.0) KIN=1

C       IN CASE THAT NOT FOUND IN BOTH CHECKS RETURN
        IF((KDIAK.EQ.0).AND.(KDIAK1.EQ.0)) GO TO 13
C        IF((KDIAK.EQ.0).AND.(KDIAK1.EQ.0)) GO TO 99
        CALL CLREAL(SA1,N9)
        IND=I
C       LOOP FOR ALL THE THE PLOTS OF NODE I (FOR ALL THE ELEMENTS THAT
C       ARE INCLUDED IN ELEMELT.NODES (LEPLOT)
        DO 20 IK=1,KIN
          DO 30 NCOUNT=1,NTINT
            TT=DT*DFLOAT(NCOUNT-1)
C           IN THE CASE THAT THE EXAMINING NODE I HAS BEEN INTRODUCED IN
C           NODE.PLOTS (NDPLOT) AND NOT FOUND IN ELEMELT.NODES (LEPLOT),
C           CALCULATE THE MAGNITUDES AT THE NODES, BY ADDING THE VALUES AT
C           NEIGHBORHOUND ELEMENTS AND TAKING THE MEAN VALUE.
            IF((KDIAK.EQ.1).AND.(KDIAK1.EQ.0)) THEN
C             FIND THE ACCUMULATIVE VALUES FOR A NODE
              CALL CLREAL(SLN1,N1)
              DO 72 JCL=1,NELEM
                DO 72 II=1,NOD
                  LN=KONN(JCL,II)
                  SLN1(LN)=SLN1(LN)+SLT1(NCOUNT,II,JCL)
  72          CONTINUE
C             CALCULTE THE MEAN VALUE AT THE NODE
C              DO 74 II=1,NNODE
                SLN1(I)=SLN1(I)/LDIR1(I)
C  74          CONTINUE
            ENDIF
C           IN THE CASE THAT THE EXAMINING NODE I HAS BEEN INTRODUCED IN 
C           NODE.PLOTS (NDPLOT) AND IN ELEMELT.NODES (LEPLOT) ALSO, OR ONLY
C           IN ELEMELT.NODES (LEPLOT) PLOT THE REAL MAGNITUDES AT THE NODES,
C           WITHOUT ADDING THE VALUES AT NEIGHBORHOUND ELEMENTS AND WITHOUT 
C           TAKING THE MEAN VALUE.
C
            IF(KDIAK1.EQ.1) THEN
              CALL CLREAL(SLN1,N1)
              DO 76 JCL=1,NELEM
                DO 76 II=1,NOD
                  LN=KONN(JCL,II)
                  JCL1=JCL
                  II1=II
C                 IF NODE I IS ENCOUNTERED MANY TIMES, ACCEPT THE VALUES
C                 FOR THE NODE THAT BELONG TO THE CURRENT EXAMINING ELEMENT
                  IF(I.EQ.LN) THEN
                    JCL1=KDIR(IK)
                    II1=NDIR(IK)
                  ENDIF
                  SLN1(LN)=SLT1(NCOUNT,II1,JCL1)
  76          CONTINUE
            ENDIF
            STEM1=SLN1(I)
C
C           IN CASE OF DISPLACEMENTS MULTIPLY BY 1000, TO HAVE BETTER VALUES FOR
C           THE PLOTTING OF THE AXIS
C           IN SI SYSTEM, THIS IS EQUEVELANT TO CONVERT THE M TO MM.
            IF(NUNIT.EQ.1) THEN
              IF((KATEG.EQ.21).OR.(KATEG.EQ.22)) STEM1=1000.0*STEM1
            ENDIF
C
C            SA1(NCOUNT)=SNGL(STEM1)
            SA1(NCOUNT)=STEM1
C           VALUES OF TIME FOR X AXIS
C           CASE THAT NPLOT=29, DRAW THE GRAPHS IN REAL X (TIME) AXIS
C            IF(KPLOT(3).EQ.0) XTIME(NCOUNT)=SNGL(TT)
            IF(KPLOT(3).EQ.0) XTIME(NCOUNT)=TT
C           CASE THAT NPLOT=29, DRAW THE GRAPHS IN DIMENSIONLESS X (TIME) AXIS
C           IT IS TAKEN AS RATIO TO THE TOTAL TIME
            IF(KPLOT(3).EQ.1) XTIME(NCOUNT)=NCOUNT
C           TH=Y/X
  30      CONTINUE
C         CASE THAT ALL THE PLOTS ARE NOT DRAWN IN THE SAME PAGE
          IF(KPLOT(2).EQ.0) THEN
CC           CREATE A SEGMENT FOR PLOTING WITH RASCON
            IPSG=IPSG+1
C            CALL GSEGCR(IPSG)
          ENDIF
          JPL=JPL+1
          CALL PLOTHOOPN(SA1,XTIME,N9,IND,KPLOT,JPL,INDX,
     &                   T11MIN,R11MIN,T11MAX,R11MAX)
CC         CLOSE THE SEGMENT
C          IF(KPLOT(2).EQ.0) CALL GSEGCL(IPSG)
  20    CONTINUE
  13  CONTINUE
C     CASE THAT ALL THE PLOTS ARE DRAWN IN THE SAME PAGE (NPLOT=28)
      IF(KPLOT(2).EQ.1)THEN
C       WRITE THE TITLE OF THE INPUT FILE
C        RI=IND
C        CALL RTXANG(0.)
C        CALL GSCAMM
C        CALL RTXHEI(5.)
C        CALL RTX(-1,FNAMEIN,8.,1.)
C        CALL RTX(-1,TITLE,80.,1.)
C        CALL GSCALE
C        CALL GDIAGC('WAIT')
        XPOS=1
        YPOS=MAXY-20
        CALL MOVETO(XPOS,YPOS,XYS)
        WRITE(BUFFER,'(A)') TITLE
        CALL OUTGTEXT(BUFFER(1:LEN_TRIM(BUFFER)))
        READ(*,*)
      ENDIF
C     CLOSE THE SEGMENT
C     IF(KPLOT(2).EQ.1) CALL GSEGCL(IPSG)
  99  CONTINUE
      RETURN
      END
