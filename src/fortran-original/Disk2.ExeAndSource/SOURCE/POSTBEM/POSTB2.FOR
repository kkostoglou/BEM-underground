      SUBROUTINE PLCARINT(SDINT,SA1,XTIME,KATEG,NTOT,NPLOT,NDTOT,
     &  NDPLOT,LETOT,LEPLOT,T1MIN,T1MAX,R1MIN,R1MAX,KPLOT,KONN,
     &  SLN1,LDIR1,N1,N3,N4,N7,N9,IPSG,INDX,NUNIT)
C
C     FOR THE NODES
C     PLOTS THE DISPLACEMENT AT INTERNAL POINTS IN CARTESIAN SYSTEM,
C     BY CALLING PLOTHOOPN
C     KPLOT(2) : 0 THE PLOTS ARE DRAWN ONE BY ONE
C                1 THE PLOTS ARE DRAWN ALL IN THE SAME PAGE
C     KPLOT(3) : 0 THE PLOTS ARE DRAWN IN NORMAL AXES
C                1 THE PLOTS ARE DRAWN IN DIMENSIONLESS AXES
C     NUNIT: INDEX FOR UNITS SYSTEM
C        1: SI SYSTEM (INTARNATIONAL)
C        2: IMPERIAL
      IMPLICIT REAL*8 (A-H,O-Y)
      INCLUDE 'FGRAPH.FD'
      COMMON/TIT/FNAMEIN,TITLE,TITLY
      COMMON/CONTR/NNODE,NELEM,NTINT,NP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM
      CHARACTER FNAMEIN*14,TITLE*45,TITLY*20
      DIMENSION SA1(N9)
      DIMENSION XTIME(N9)
      DIMENSION NPLOT(NTOT),NDPLOT(NDTOT),LEPLOT(LETOT)
      DIMENSION LDIR1(N1)
      DIMENSION KONN(N3,N4)
      DIMENSION KPLOT(INDX)
C ************** RESTRICTION OF THE PROGRAM ***********
C     MAXIMUM 5 ELEMENTS JOININIG TO ONE NODE
      DIMENSION KDIR(5),NDIR(5)
      DIMENSION XW(2),YW(2)
      INTEGER*2 ISTATUS,ISTYLE
      CHARACTER*20         list
      INTEGER*2 MAXX,MAXY,XPOS,YPOS
      INTEGER*4            ifont
      CHARACTER*10         options(6)
      RECORD/WXYCOORD/POSITION
      RECORD/XYCOORD/XYS
      RECORD/XYCOORD/XYS1
      CHARACTER*255 BUFFER
      COMMON /FNTS/NFONTS,IFONT,OPTIONS,MAXX,MAXY
C     INTERNAL POINTS WITH THEIR CO-ORDINATES
      COMMON/INTERN/NINT,CINT(10,2)
      DIMENSION SDINT(N9,NINT)
C
      PI=3.14159265359
      TOL=1.0E-6
      TOL1=1.0E-11
      JPL=0
      NOD=3
      DO 22 I=1,5
        KDIR(I)=0
        NDIR(I)=0
  22  CONTINUE
      DT=TIM/DFLOAT(NTINT)
      R11MIN=R1MIN
      R11MAX=R1MAX
      T11MIN=T1MIN
      T11MAX=T1MAX
C     FOR SI UNIT SYSTEM, MULTIPLY LIMITS BY 1000 (mm)
      IF((KATEG.EQ.6).AND.(NUNIT.EQ.1)) THEN
        R11MIN=1000.0*R1MIN
        R11MAX=1000.0*R1MAX
      ENDIF
      IF(KPLOT(3).EQ.1) T11MAX=NTINT
C     NEW SCALING
C      CALL GLIMIT(T11MIN,T11MAX,R11MIN,R11MAX,0.0,0.0)
C      CALL GSCALE
      XW(1)=1.3*T11MIN
      XW(2)=1.3*T11MAX
      YW(1)=1.3*R11MIN
      YW(2)=1.3*R11MAX
      ISTATUS=SETWINDOW(.TRUE.,XW(1),YW(1),XW(2),YW(2))
C     CHECK IF THE PLOT NUMBER HAS BE GIVEN
      KFOUND=0
      DO 94 IPL=1,NTOT
        IF(NPLOT(IPL).EQ.KATEG) KFOUND=1
  94  CONTINUE
      IF(KFOUND.EQ.0) GO TO 99
C      CALL GCLEAR
      CALL CLEARSCREEN($GCLEARSCREEN)
C     CASE THAT ALL THE PLOTS ARE DRAWN IN THE SAME PAGE (NPLOT=28)
      IF(KPLOT(2).EQ.1) THEN
CC       CREATE A SEGMENT FOR PLOTING WITH RASCON
        IPSG=IPSG+1
C        CALL GSEGCR(IPSG)
      ENDIF
C     PLOT AXES
C      CALL PLOTAXES(XW,YW,XTIME,N9)
C      CALL PLOTAXES(XW,YW,N9)
      CALL PLOTAXES(T11MIN,R11MIN,T11MAX,R11MAX,N9)
C     LOOP FOR ALL THE INTERNAL NODES
      DO 13 I=1,NINT
        KDIAK=0
        KDIAK1=0
C       COUNTER OF THE NUMBER OF PLOTS OF NODE I FOUND IN  ELEMENT.NODES (LEPLOT)
        KIN=0
        CALL CLREAL(SA1,N9)
        IND=I
          DO 30 NCOUNT=1,NTINT
            TT=DT*DFLOAT(NCOUNT-1)
            CALL CLREAL(SLN1,N1)
            STEM1=SDINT(NCOUNT,I)
C           IN CASE OF DISPLACEMENTS MULTIPLY BY 1000, TO HAVE BETTER VALUES FOR
C           THE PLOTTING OF THE AXIS
C           IN SI SYSTEM, THIS IS EQUEVELANT TO CONVERT THE M TO MM.
            IF(NUNIT.EQ.1) THEN
              IF(KATEG.EQ.6) STEM1=1000.0*STEM1
            ENDIF
C
            SA1(NCOUNT)=STEM1
C           VALUES OF TIME FOR X AXIS
C           CASE THAT NPLOT=29, DRAW THE GRAPHS IN REAL X (TIME) AXIS
C            IF(KPLOT(3).EQ.0) XTIME(NCOUNT)=SNGL(TT)
            IF(KPLOT(3).EQ.0) XTIME(NCOUNT)=TT
C           CASE THAT NPLOT=29, DRAW THE GRAPHS IN DIMENSIONLESS X (TIME) AXIS
C           IT IS TAKEN AS RATIO TO THE TOTAL TIME
            IF(KPLOT(3).EQ.1) XTIME(NCOUNT)=NCOUNT
C           TH=Y/X
  30      CONTINUE
C         CASE THAT ALL THE PLOTS ARE NOT DRAWN IN THE SAME PAGE
          IF(KPLOT(2).EQ.0) THEN
CC           CREATE A SEGMENT FOR PLOTING WITH RASCON
            IPSG=IPSG+1
C            CALL GSEGCR(IPSG)
          ENDIF
          JPL=JPL+1
          CALL PLOTHOOPN(SA1,XTIME,N9,IND,KPLOT,JPL,INDX,
     &                   T11MIN,R11MIN,T11MAX,R11MAX)
C         J=J+1
CC         CLOSE THE SEGMENT
C          IF(KPLOT(2).EQ.0) CALL GSEGCL(IPSG)
  20    CONTINUE
  13  CONTINUE
C     CASE THAT ALL THE PLOTS ARE DRAWN IN THE SAME PAGE (NPLOT=28)
      IF(KPLOT(2).EQ.1)THEN
C       WRITE THE TITLE OF THE INPUT FILE
C        RI=IND
C        CALL RTXANG(0.)
C        CALL GSCAMM
C        CALL RTXHEI(5.)
C        CALL RTX(-1,FNAMEIN,8.,1.)
C        CALL RTX(-1,TITLE,80.,1.)
C        CALL GSCALE
C        CALL GDIAGC('WAIT')
        XPOS=1
        YPOS=MAXY-20
        CALL MOVETO(XPOS,YPOS,XYS)
        WRITE(BUFFER,'(A)') TITLE
        CALL OUTGTEXT(BUFFER(1:LEN_TRIM(BUFFER)))
        READ(*,*)
      ENDIF
C     CLOSE THE SEGMENT
C     IF(KPLOT(2).EQ.1) CALL GSEGCL(IPSG)
  99  CONTINUE
      RETURN
      END
