      SUBROUTINE PLOTHOOP(XCR,YCR,SR1,RATE1,XCE,YCE,
     &  XCN,YCN,KONN,NONN,N1,N3,N4,N7,N9,NSUB,NNODEB,NELEMB,
     &  NBOUN,CP1,XCEN1,YCEN1,NCOUNT,SLN1,LDIR1,NPLOT,NTOT,
     &  KPLOT,INDX,NDTOT,NDPLOT,NSHAP,NDIS,LCRN)
C
C     PLOT THE HOOP STRESSES (NORMAL, TANGENTIAL, SHEAR)
C     PLOTS IN RADIAL DIRECTION TO THE SURFACE OF THE MESH
      IMPLICIT REAL*8 (A-H,O-Y)
      INCLUDE 'FGRAPH.FD'
      COMMON/CONTR/NNODE,NELEM,NTINT,NP
      COMMON/PROBL/NDOMA,NREGI
      COMMON/TIT/FNAMEIN,TITLE,TITLY
      CHARACTER FNAMEIN*14,TITLE*45,TITLY*20
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION NNODEB(NBOUN),NELEMB(NBOUN)
      DIMENSION SR1(N4,N3)
      DIMENSION KONN(N3,N4)
      DIMENSION NONN(N1,N4)
      DIMENSION XCE(N3,NSUB+1),YCE(N3,NSUB+1)
      DIMENSION XCN(N4,N3),YCN(N4,N3)
      DIMENSION NREGI(5)
      DIMENSION LDIR1(N1),SLN1(N1)
      DIMENSION NPLOT(NTOT),KPLOT(INDX),NDPLOT(NDTOT)
      DIMENSION NSHAP(NBOUN),NDIS(5)
      DIMENSION LCRN(8)
      DIMENSION XW(2),YW(2)
      INTEGER*2 ISTATUS,ISTYLE
      CHARACTER*20         list
      INTEGER*2 MAXX,MAXY,XPOS,YPOS
      INTEGER*4            ifont
      CHARACTER*10         options(6)
      RECORD/WXYCOORD/POSITION
      RECORD/XYCOORD/XYS
      CHARACTER*255 BUFFER
      COMMON /FNTS/NFONTS,IFONT,OPTIONS,MAXX,MAXY
C
      PI=3.14159265359D0
      TOL=1.0E-6
      NOD=3
C     INTERPOLATE WITH QUADRATIC SHAPE FUNCTIONS, TO FIND DATA OF THE
C     STRESSES IN MORE NODES
      CALL MOREDAT(XCR,YCR,SR1,RATE1,XCE,YCE,KONN,N1,N3,N4,
     &        NSUB,SLN1,LDIR1,NPLOT,NTOT,KPLOT,INDX)
C     FIND THE SCALING STRESSES AT EVERY NODE
      CALL NODEDAT(XCR,YCR,SR1,RATE1,XCN,YCN,NONN,
     &             KONN,N1,N3,N4,N1)
      CALL MAXIMA(XCE,YCE,XE1MIN,YE1MIN,XE1MAX,YE1MAX,N3*(NSUB+1))
      XYMIN=AMIN1(XE1MIN,YE1MIN)
      XYMAX=AMAX1(XE1MAX,YE1MAX)
      XW(1)=1.3*XYMIN
      YW(1)=1.3*XYMIN
      XW(2)=1.3*XYMAX
      YW(2)=1.3*XYMAX
C      CALL GLIMIT(XYMIN,XYMAX,XYMIN,XYMAX,0.0,0.0)
      ISTATUS=SETWINDOW(.TRUE.,XW(1),YW(1),XW(2),YW(2))

      NDIAK=3
C     SET LINE COLOR TO WHITE
      ISTATUS=SETCOLOR(7)
      CALL PLOTDOM(XCR,YCR,NNODEB,NBOUN,N1,NDIAK,
     &      XYMIN,XYMAX,NSHAP,NDIS,LCRN)
CC     SET LINE WIDTH AND COLOR
C      CALL GWICOL(1.0,2)
C      ISTATUS=SETCOLOR(2)
      ISTATUS=SETCOLOR(4)
CC     SET LINESTYLE
C      IPL=10
      ISTYLE=#555
C     CALL GDASH(IPL)
      KK=1
      DO 35 K=1,NBOUN
        K0=KK
        NB1=NELEMB(K)
        DO 39 JCL=1,NB1
C          CALL GVECT(XCE(KK,1),YCE(KK,1),0)
          CALL MOVETO_W(XCE(KK,1),YCE(KK,1),POSITION)
          CALL SETLINESTYLE(ISTYLE)
C          DO 49 IS=1,NSUB
          DO 49 IS=1,NSUB+1
C           SET LINESTYLE
C            CALL GDASH(IPL)
C            CALL GVECT(XCE(KK,IS),YCE(KK,IS),1)
            ISTATUS=LINETO_W(XCE(KK,IS),YCE(KK,IS))
  49      CONTINUE
          KK=KK+1
  39    CONTINUE
C       FOR OPEN SURFACES OR OPEN FREE REFLECTED SURFACES 
C       DON'T CLOSE THE CURVE
        IF((NREGI(K).EQ.3).OR.(NREGI(K).EQ.4)) GO TO 35
C        CALL GVECT(XCE(K0,1),YCE(K0,1),1)
        ISTATUS=LINETO_W(XCE(K0,1),YCE(K0,1))
  35  CONTINUE
C     PLOT THE STRESSES ON THE NODES AND WRITE THE AMOUNT ON THE LINE
      KK=1
      DO 45 K=1,NBOUN
C       SET LINE WIDTH AND DIFFERENT COLOR FOR EVERY BOUNDARY
C       SET LINESTYLE
        IPL=K
C       SET LINE WIDTH AND COLOR (COLOR NUMBER 2..8)
        NCOLR=IPL
        ICOLR=(1+NCOLR)/9
        IF(ICOLR.GT.0) NCOLR=IPL-7
C        CALL GWICOL(0.5,2+NCOLR)
        ISTYLE=#FFF
C         ISTYLE=#FFFF
        CALL SETLINESTYLE(ISTYLE)
C        ISTATUS=SETCOLOR(2+NCOLR)
c        ISTATUS=SETCOLOR(1+NCOLR)
C        K0=KK
C        NB1=NNODEB(K)
        NB1=NELEMB(K)
        DO 30 JCL=1,NB1
          DO 32 I=1,NOD
            ISTATUS=SETCOLOR(1+NCOLR)
            LN=KONN(KK,I)
C            CALL MOVETO_W(XD(LN),YD(LN),POSITION)
            CALL MOVETO_W(XCR(LN),YCR(LN),POSITION)
C            CALL GDASH(IPL)
            CALL SETLINESTYLE(ISTYLE)
C            CALL GVECT(XCN(I,KK),YCN(I,KK),1)
            ISTATUS=LINETO_W(XCN(I,KK),YCN(I,KK))
C
C           WRITE THE AMOUNT OF STRESS ON THE LINE, IF KPLOT(1)=0.
C           IN CASE THAT KPLOT(1)=1 (NPLOT=26), WRITE THE VALUES OF
C           STRESSES, ONLY AT THE NODES SPECIFIED AT NODE.PLOTS
            IF(KPLOT(1).EQ.1) THEN
              KDIAK=0
C             CHECK TO FIND IF THE NODE LN IS IN THE ARRAY NDPLOT (HAS BEEN
C             INCLUDED IN MODULUS NODE.PLOTS)
              IF(NDTOT.GT.0) THEN
                DO 2 II=1,NDTOT
                  K1=NDPLOT(II)
                  IF(LN.EQ.K1) KDIAK=1
  2             CONTINUE
              ENDIF
            ENDIF
            IF((KPLOT(1).EQ.0).OR.((KPLOT(1).EQ.1).AND.(KDIAK.EQ.1)))
     &      THEN
C             SET LINE COLOR TO WHITE
              ISTATUS=SETCOLOR(7)
              list = options(ifont) // 'h20w22b'
              IF(SETFONT(LIST).GE.0) THEN
                CALL MOVETO_W(XCN(I,KK),YCN(I,KK),POSITION)
                CALL GETVIEWCOORD_W(XCN(I,KK),YCN(I,KK),XYS)
                CALL GETCURRENTPOSITION(XYS)
                WRITE(BUFFER,"(F9.1)") SR1(I,KK)
                CALL OUTGTEXT(BUFFER(1:LEN_TRIM(BUFFER)))
              ELSE
                CALL OUTTEXT('Error: cannot set font')
              ENDIF
            ENDIF
  32      CONTINUE
          KK=KK+1
  30    CONTINUE
  45  CONTINUE
      ISTATUS = settextcolor( 7 )
C     WRITE THE TITLE OF THE INPUT FILE
C      CALL RTXANG(0.)
      CALL SETGTEXTVECTOR(1,0)
C      CALL GSCAMM
C      CALL RTXHEI(5.)
C      list = options(ifont) // 'h50w24b'
C      CALL RTX(-1,'TIME STEP: ',30.,10.)
C      CALL RTXN(RI,0,70.,10.)
      XPOS=1
      YPOS=MAXY-40
      CALL MOVETO(XPOS,YPOS,XYS)
      WRITE(BUFFER,'(I3)') NCOUNT
      CALL OUTGTEXT('Time Step : '//BUFFER(1:LEN_TRIM(BUFFER)))
C      CALL RTXHEI(5.)
C      CALL RTX(-1,FNAMEIN,8.,1.)
C      CALL RTX(-1,TITLE,80.,1.)
C      list = options(ifont) // 'h50w24b'
      XPOS=1
      YPOS=MAXY-20
      CALL MOVETO(XPOS,YPOS,XYS)
      WRITE(BUFFER,'(A)') TITLE
      CALL OUTGTEXT(BUFFER(1:LEN_TRIM(BUFFER)))
C      CALL GSCALE
CC      CALL GSAVE(12)
C      CALL GDIAGC('WAIT')
      READ(*,*)
      RETURN
      END
