          DETJ=DETJ1*DETJ2
          RN1=RN(1)
          RN2=RN(2)

C         NOW AT GLOBAL QUADRATIC ELEMENT LEVEL
C
          XG=0.0D0
          YG=0.0D0
          SXYG1=0.0D0
          SXYG2=0.0D0
