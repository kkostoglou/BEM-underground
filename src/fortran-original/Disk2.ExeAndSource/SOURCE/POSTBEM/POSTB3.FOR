      ISTATUS=LINETO_W(X0,Y0)
      ISTATUS=LINETO_W(X2,Y2)

C^^^^^^^^^^^^^^^^^
C      CALL GWICOL(.01,1)
C     DRAW A NORMAL LINE FROM THE CENTER OF THE SHAPE TO WAVEFRONT LINE
C      CALL GVECT(XCEN1,YCEN1,0)
C      CALL GVECT(X0,Y0,1)

      ISTYLE=#AAA
C      ISTYLE=#FFFF
      CALL SETLINESTYLE(ISTYLE)

      CALL MOVETO_W(XCEN1,YCEN1,WXY)
      ISTATUS=LINETO_W(X0,Y0)
      ISTYLE=#AAA
C      ISTYLE=#FFFF
      CALL SETLINESTYLE(ISTYLE)
C     PLOT THE GLOBAL AXIS
  11  CONTINUE
