      RI=NCOUNT
C      CALL RTXANG(0.)
C      CALL GSCAMM
C      CALL RTXHEI(5.)
      CALL SETGTEXTVECTOR(1,0)
      CALL MOVETO_W(0.5D0,0.5D0,WXY)
      CALL GETVIEWCOORD_W(XC,YC,XYS)
