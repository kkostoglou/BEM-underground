      REAL*8 XTIME[ALLOCATABLE](:)
      REAL*8 SDINTX[ALLOCATABLE](:,:)
      REAL*8 SDINTY[ALLOCATABLE](:,:)
      INTEGER*4 LBCU[ALLOCATABLE](:)
      INTEGER*4 NDTYPE[ALLOCATABLE](:)
      INTEGER*2 STAT,IERR
      CHARACTER FNAMEIN*14,TITLE*45,TITLY*20
      CHARACTER FNAMEPRO*14,FNAMEPOS*14
C
      COMMON/CONTR/NNODE,NELEM,NTINT,NP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM
      COMMON/GEOM3/FAI,PSAI
