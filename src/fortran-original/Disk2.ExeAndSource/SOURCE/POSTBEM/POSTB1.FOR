C -----------------------------------------------
      SUBROUTINE DATAS(XCR,YCR,SLT1,SLT2,SLT3,SLD1,SLD2,
     &  KONN,NONN,MBCU,LBCU,NDTYPE,N1,N2,N3,N4,N7,N9,NTOT,
     &  NPLOT,NSHAP,NDIS,LCRN,NBOUN)
C
C       LOADING WILL BE READ LATER
C
      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION LCRN(8)
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION KONN(N3,N4),MBCU(N2)
      DIMENSION NONN(N1,N4)
      DIMENSION LBCU(N3),NDTYPE(N1)
      DIMENSION SLT1(N9,N4,N3),SLT2(N9,N4,N3),SLT3(N9,N4,N3)
      DIMENSION SLD1(N9,N4,N3),SLD2(N9,N4,N3)
      DIMENSION NPLOT(NTOT)
      DIMENSION NSHAP(NBOUN),NDIS(5)
      DIMENSION NREGI(5)
      COMMON/CONTR/NNODE,NELEM,NTINT,NP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM
      COMMON/FREE/NFFS,NFRE
      COMMON/PROBL/NDOMA,NREGI
      COMMON/HARM/INES
C     FREQUENCY FOR HARMONIC WAVE
      COMMON/FREQ/OFREQ
C     INTERNAL POINTS WITH THEIR CO-ORDINATES
      COMMON/INTERN/NINT,CINT(10,2)
      CALL CLRARR(SLT1,N9*N4*N3)
      CALL CLRARR(SLT2,N9*N4*N3)
      CALL CLRARR(SLT3,N9*N4*N3)
      CALL CLRARR(SLD1,N9*N4*N3)
      CALL CLRARR(SLD2,N9*N4*N3)
      CALL CLRARR(SDINTX,N9*NINT)
      CALL CLRARR(SDINTY,N9*NINT)
C
      READ(1,*) RLA,RMU,RNU,RHO,C1,C2,TIM,NFRE
      READ(1,*) XCR
      READ(1,*) YCR
      READ(1,*) KONN
      READ(1,*) NONN
      READ(1,*) MBCU
      READ(1,*) LBCU
      READ(1,*) NDTYPE
C     FREQUENCY FOR HARMONIC WAVE
      READ(1,*) OFREQ
      READ(1,*) NINT,CINT
C
      READ(4,*) NSHAP,NDIS,LCRN
      READ(4,*) INES
C     IN LAPLACE DOMAIN (TRANIENT OR STEADY STATE CASE,
C     READ ONLY THAT QUANTITIES THAT WERE DECLARED
C     IN THE ARRAY NPLOT. THESE QUANTITIES WERE INVERTRED AND SAVED IN
C     THE PROCESSING PHASE, FOR COMPUTER ECONOMY.
      IF((NDOMA.EQ.1).OR.(NDOMA.EQ.4)) THEN
        KDIAK1=0
        KDIAK2=0
        KDIAK3=0
        KDIAK4=0
        KDIAK5=0
        DO 20 L=1,NTOT
C         CASE OF HOOP STRESSES PLOTS 
C         NORMAL STRESS IN RADIAL DIRECTION SYSTEM (NPLOT=1)
C         OR IN CARTESIAN SYSTEM (NPLOT=11)
          IF(((NPLOT(L).EQ.1).OR.(NPLOT(L).EQ.11)).AND.(KDIAK1.NE.1))
     &    THEN
            KDIAK1=1
            READ(3,*) SLT1
          ENDIF
C         TANGENTIAL STRESS IN RADIAL DIRECTION SYSTEM (NPLOT=2)
C         OR IN CARTESIAN SYSTEM (NPLOT=12)
          IF(((NPLOT(L).EQ.2).OR.(NPLOT(L).EQ.12)).AND.(KDIAK2.NE.1))
     &    THEN
            KDIAK2=1
            READ(3,*) SLT2
          ENDIF
C         SHEAR STRESS IN RADIAL DIRECTION SYSTEM (NPLOT=3)
C         OR IN CARTESIAN SYSTEM (NPLOT=13)
          IF(((NPLOT(L).EQ.3).OR.(NPLOT(L).EQ.13)).AND.(KDIAK3.NE.1))
     &    THEN
            KDIAK3=1
            READ(3,*) SLT3
          ENDIF
C         CASE OF DEFORMED SHAPE PLOT IN RADIAL DIRECTION (NPLOT=5)
C         OR X DISPLACEMENTS PLOT IN CARTESIAN SYSTEM(NPLOT=21)
          IF(((NPLOT(L).EQ.5).OR.(NPLOT(L).EQ.21)).AND.(KDIAK4.NE.1))
     &    THEN
C           X DISPLACEMENTS
            KDIAK4=1
            READ(3,*) SLD1
          ENDIF
C         CASE OF DEFORMED SHAPE PLOT IN RADIAL DIRECTION (NPLOT=5)
C         OR Y DISPLACEMENTS PLOT IN CARTESIAN SYSTEM(NPLOT=22)
          IF(((NPLOT(L).EQ.5).OR.(NPLOT(L).EQ.22)).AND.(KDIAK5.NE.1))
     &    THEN
C           Y DISPLACEMENTS
            KDIAK5=1
            READ(3,*) SLD2
          ENDIF
  20    CONTINUE
      ENDIF
C     IN TIME DOMAIN OR IN ELASTOSTATIC CASE, READ ALL QUANTITIES EVEN
C     IF THEY WERE NOT DECLARED IN THE ARRAY NPLOT. 
      IF((NDOMA.EQ.2).OR.(NDOMA.EQ.3)) THEN
        READ(3,*) SLT1
        READ(3,*) SLT2
        READ(3,*) SLT3
        READ(3,*) SLD1
        READ(3,*) SLD2
      ENDIF
      RETURN
      END

C------------------------------------------------------------------------
C     ************* PLOTING ROUTINES ************************************
