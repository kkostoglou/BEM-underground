      REAL*8 SARR[ALLOCATABLE](:)
      REAL*8 SARX[ALLOCATABLE](:)
      REAL*8 SLT1[ALLOCATABLE](:)
      REAL*8 SLT2[ALLOCATABLE](:)
      REAL*8 SLT3[ALLOCATABLE](:)
      REAL*8 SLD1[ALLOCATABLE](:)
      REAL*8 SLD2[ALLOCATABLE](:)
      REAL*8 XCE[ALLOCATABLE](:)
      REAL*8 YCE[ALLOCATABLE](:)
      REAL*8 XCN[ALLOCATABLE](:)
      REAL*8 YCN[ALLOCATABLE](:)
      INTEGER*4 NNONN[ALLOCATABLE](:)
      REAL*8 SLN1[ALLOCATABLE](:)
      INTEGER*4 LDIR1[ALLOCATABLE](:)
