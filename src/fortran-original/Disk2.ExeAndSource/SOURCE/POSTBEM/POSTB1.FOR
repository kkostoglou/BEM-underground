      DIMENSION SLT1(N9,N4,N3),SLT2(N9,N4,N3),SLT3(N9,N4,N3)
      DIMENSION SLD1(N9,N4,N3),SLD2(N9,N4,N3)
      DIMENSION SR1(N4,N3),SR2(N4,N3)
      DIMENSION SA1(N9)
      DIMENSION XTIME(N9)
      DIMENSION KONN(N3,N4)
      DIMENSION NONN(N1,N4)
      DIMENSION XCE(N3,NSUB+1),YCE(N3,NSUB+1)
      DIMENSION XCN(N4,N3),YCN(N4,N3)
      DIMENSION NREGI(5)
      DIMENSION NDPLOT(NDTOT),LEPLOT(LETOT),KPLOT(INDX)
      DIMENSION LDIR1(N1),SLN1(N1)
      DIMENSION NSHAP(NBOUN),NDIS(5)
      DIMENSION XW(2),YW(2)
      DIMENSION LBCU(N3),NDTYPE(N1)
      DIMENSION SDINTX(N9,NINT),SDINTY(N9,NINT)
C     FREQUENCY FOR HARMONIC WAVE
      COMMON/FREQ/OFREQ
C     INTERNAL POINTS WITH THEIR CO-ORDINATES
      COMMON/INTERN/NINT,CINT(10,2)
      DIMENSION LCRN(8)
      INTEGER*2 ISTATUS,MAXX,MAXY,MMAX
      INTEGER*2 XV(2),YV(2),XHALF,YHALF
      INTEGER*4 IDUMMY
      INTEGER*4            ifont
      CHARACTER*10         options(6)
      COMMON /FNTS/NFONTS,IFONT,OPTIONS,MAXX,MAXY
C
      PI=3.14159265359D0
      TOL=1.0E-6
      TOL1=1.0E-11
      NOD=3
C     IGNORE NODES OF THE ENCLOSING ELEMENTS BOUNDARY
      NNODE1=0
      NELEM1=0
      DO I=1,NNODE
        IF(NDTYPE(I).EQ.4) GO TO 35
C       NODES WITHOUT THE NODES OF THE ENCLOSING ELEMENTS BOUNDARY
C       (THE ENCLOSING NODES HAVE THE LAST NUMBERS IN THE SEQUENCE)
        NNODE1=NNODE1+1
  35  CONTINUE
      END DO
C     IGNORE ELEMENTS OF THE ENCLOSING ELEMENTS BOUNDARY
      DO I=1,NELEM
        IF(LBCU(I).EQ.4) GO TO 36
C       ELEMENTS WITHOUT THE ELEMENTS OF THE ENCLOSING ELEMENTS BOUNDARY
C       (THE ENCLOSING NODES HAVE THE LAST NUMBERS IN THE SEQUENCE)
        NELEM1=NELEM1+1
  36    CONTINUE
      END DO
      NA1=NNODE1
      NA2=2*NNODE1
      NA3=NELEM1
      NA5=3*NNODE1
C     CONVERT DOUBLE PRECISION TO REAL
      CA1=CA
      CB1=CB
      CP1=CP
      XCEN1=XCEN
      YCEN1=YCEN
      CALL MAXIMA(XCR,YCR,XMIN,YMIN,XMAX,YMAX,N1)
CC     SPARC STATION SCREEN
C      CALL GROUTE('SELECT MSVIEW;EXIT')
CC      VAX STATION
CC          CALL GROUTE('SELECT LT4207;EXIT')
CC      HP COLORPLOT
CC          CALL GROUTE('S PHP7475A;E')
CC          THIS GIVES A FILE WITH NAME HPGL, WHICH CAN BE PLOTED.
CC          IN EVERY RUN IT IS OVERWRITTEN, SO IT MUST BE RENAMED.
CC      HP PAINTJET
CC          CALL GROUTE('S GHP3630;E')
CC          THIS GIVES A FILE WITH NAME UNIRAS.RDB.  AFTER THIS
CC          RUN THE PROGRAM
CC          DHCPCL (OR CALL GHCPCL INCIDE OF A PROGRAM AT THE END)
CC       HOST RASTER MODE
CC      CALL GROUTE('SELECT MRASDR;EXIT')
CC      CALL GROUTE('SELECT MRASDR;EXIT')
C      CALL GOPEN
C      CALL GRPSIZ(XMMS,YMMS)
C      CALL GVPORT(XMMS*0.1,YMMS*0.1,XMMS*0.8,YMMS*0.8)
      XYMIN=AMIN1(XMIN,YMIN)
      XYMAX=AMAX1(XMAX,YMAX)
      CALL GRAPHICSMODE(MAXX,MAXY)
      XHALF=MAXX/2
      YHALF=MAXY/2
      MMAX=MIN0(MAXX,MAXY)
      CALL CLEARSCREEN($GCLEARSCREEN)
      XV(1)=0
      YV(1)=0
      XV(2)=MAXX
      YV(2)=MAXY
      CALL SETVIEWPORT(0,0,MAXX-1,MAXY-1)
      ISTATUS=SETCOLOR(4)
      ISTATUS=RECTANGLE_W($GBORDER,0,0,MAXX-1,MAXY-1)
      CALL SETVIEWPORT(XHALF-MMAX/2,YHALF-MMAX/2,
     &        XHALF+MMAX/2,YHALF+MMAX/2)
      XW(1)=1.4*XYMIN
      YW(1)=1.4*XYMIN
      XW(2)=1.4*XYMAX
      YW(2)=1.4*XYMAX
