      SUBROUTINE MAXIMA(X,Y,XMIN,YMIN,XMAX,YMAX,N1)
C
C     FINDS THE MINIMUM AND MAXIMUM VALUES OF TWO VECTORS X,Y OF
C     REAL VALUES
C
C     FIND THE SCALING FACTOR OF THE GEOMETRY TO PLOT.
C     X,Y    : COORDINATES OF NODAL POINTS
C     XMIN   : MINIMUM VALUE OF THE X COORDINATE
C     YMIN   : MINIMUM VALUE OF THE Y  -//-
C     XMAX   : MAXIMUM VALUE OF THE X  -//-
C     YMAX   : MAXIMUM VALUE OF THE Y  -//-
C
      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION X(N1),Y(N1)
C
C     SCALING OF THE GEOMETRY
C
      XMIN=1.0E11
      YMIN=1.0E11
      XMAX=-1.0E11
      YMAX=-1.0E11
      DO 102 I=1,N1
        XI=X(I)
        XMIN=AMIN1(XMIN,XI)
        XMAX=AMAX1(XMAX,XI)
        YI=Y(I)
        YMIN=AMIN1(YMIN,YI)
  102 YMAX=AMAX1(YMAX,YI)
      XSIZE=XMAX-XMIN
      YSIZE=YMAX-YMIN
      ASIZE=AMAX1(XSIZE,YSIZE)
      RETURN
      END 
C --------------------------------------------------------
      SUBROUTINE MAXIMA1(X,XMIN,XMAX,N1)
C
C     FINDS THE MINIMUM AND MAXIMUM VALUE OF THE VECTOR X OF
C     REAL VALUES
C
C     FIND THE SCALING FACTOR OF THE GEOMETRY TO PLOT.
C     X,Y    : COORDINATES OF NODAL POINTS
C     XMIN   : MINIMUM VALUE OF THE X COORDINATE
C     YMIN   : MINIMUM VALUE OF THE Y  -//-
C     XMAX   : MAXIMUM VALUE OF THE X  -//-
C     YMAX   : MAXIMUM VALUE OF THE Y  -//-
C
      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION X(N1)
C
C     SCALING OF THE GEOMETRY
C
      XMIN=1.0E11
      XMAX=-1.0E11
      DO 102 I=1,N1
        XI=X(I)
        XMIN=AMIN1(XMIN,XI)
        XMAX=AMAX1(XMAX,XI)
  102 CONTINUE
      XSIZE=XMAX-XMIN
      RETURN
      END 
C --------------------------------------------------------
C      SUBROUTINE MAXIMA2(AX,XMIN,XMAX,NA,NB)
      SUBROUTINE MAXIMA2(AX,XMIN,XMAX,N11)
C
C     FINDS THE MINIMUM AND MAXIMUM VALUE OF THE DOUBLE PRECISION ARRAY X
C     THE RETURN VALUES XMIN,YMIN ARE REAL
C
C     FIND THE SCALING FACTOR OF THE GEOMETRY TO PLOT.
C     X,Y    : COORDINATES OF NODAL POINTS
C     XMIN   : MINIMUM VALUE OF THE X COORDINATE
C     YMIN   : MINIMUM VALUE OF THE Y  -//-
C     XMAX   : MAXIMUM VALUE OF THE X  -//-
C     YMAX   : MAXIMUM VALUE OF THE Y  -//-
C
      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION AX(N11)
C
C     SCALING OF THE GEOMETRY
C
      XMIN=1.0E11
      XMAX=-1.0E11
      DO 102 I=1,N11
          XI=AX(I)
          XMIN=DMIN1(XMIN,XI)
          XMAX=DMAX1(XMAX,XI)
  102 CONTINUE
      XSIZE=XMAX-XMIN
      RETURN
      END 
