       SUBROUTINE BEM(XCR,YCR,KONN,NONN,MBCU,LBCU,NDTYPE,
     &   ZGM,ZFM,ZLOAD,ZTEMP,ZLOAD1,NHPOS,
     &   TIME,ZLT1,ZLT2,ZLT3,ZLD1,ZLD2,SLT1,
     &   SFDIAG,ZZ1,ZZ2,ZZ3,ZCOL,ZB,ZPQ,N1,N2,N3,N4,N5,N7,
     &   N8,N9,LINV,MINV,NTOT,NPLOT)
C
C      THE BEM SOLUTION BEGINS HERE
C
       IMPLICIT REAL*8 (A-H,O-Z)
       DIMENSION XCR(N1),YCR(N1),KONN(N3,N4),MBCU(N2)
       DIMENSION ZGM(N2,N2),ZFM(N2,N2),ZLOAD(N2),ZTEMP(N2)
       DIMENSION NONN(N1,N4)
       DIMENSION LBCU(N3),NDTYPE(N1)
       DIMENSION TIME(N9)
       DIMENSION ZLT1(N9,N4,N3),ZLT2(N9,N4,N3),ZLT3(N9,N4,N3)
       DIMENSION ZLD1(N9,N4,N3),ZLD2(N9,N4,N3),SLT1(N9,N4,N3)
       DIMENSION SFDIAG(N1,2,2)
       DIMENSION LINV(N2),MINV(N2)
       DIMENSION ZZ1(N4,N3),ZZ2(N4,N3),ZZ3(N4,N3)
       DIMENSION NHPOS(N3)
       DIMENSION ZLOAD1(N5)
       DIMENSION NPLOT(NTOT)
C
       COMMON/CONTR/NNODE,NELEM,NP
       COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
       COMMON/FREE/NFFS,NFRE
       DIMENSION ZCOL(N2),ZB(N2),ZPQ(N2)
C
       NTINT=N9
       CALL CLRARR(ZLT1,N9*N4*N3)
       CALL CLRARR(ZLT2,N9*N4*N3)
       CALL CLRARR(ZLT3,N9*N4*N3)
       CALL CLRARR(ZLD1,N9*N4*N3)
       CALL CLRARR(ZLD2,N9*N4*N3)
       DT=TIM/DFLOAT(NTINT)
       DO 2 NCOUNT=1,NTINT
         WRITE(*,*) '          TIME STEP : ', NCOUNT
         CALL CLRARR(ZZ1,N4*N3)
         CALL CLRARR(ZZ2,N4*N3)
         CALL CLRARR(ZZ3,N4*N3)
         IF (NCOUNT .EQ. 1) CALL CLRARR(SFDIAG,N1*4)
         TT=DT*DFLOAT(NCOUNT-1)
         TIME(NCOUNT)=TT
         CALL BMAIN(NCOUNT,XCR,YCR,KONN,N1,N2,N3,N4,N9,
     &             SFDIAG,LBCU,NDTYPE)
         CALL GENR(NCOUNT,KONN,MBCU,ZGM,ZFM,ZLOAD,ZTEMP,
     &    ZCOL,ZB,ZPQ,N1,N2,N3,N4,SFDIAG,LBCU,NDTYPE,LINV,MINV)
         CALL HOOP(KONN,NONN,ZLOAD,ZTEMP,ZLOAD1,XCR,YCR,
     &    N1,N2,N3,N4,N5,ZZ1,ZZ2,ZZ3)
C
C        TRACTIONS
         NP1=NP/3
         DO 4 J=1,NP1
           IF(NP1.EQ.NELEM) NJ=J
C          CASE NP<NNODE, RESULTS OF HOOP STRESSES FOR SOME NODES
           IF(NP1.LT.NELEM) NJ=NHPOS(J)
C          LOOP FOR THE 3 NODES OF THE QUADRATIC ELEMENT
           DO 15 L=1,N4
             ZLT1(NCOUNT,L,J)=ZZ1(L,NJ)
             ZLT2(NCOUNT,L,J)=ZZ2(L,NJ)
             ZLT3(NCOUNT,L,J)=ZZ3(L,NJ)
  15       CONTINUE
  4      CONTINUE
C
C        DISPLACEMENTS
         DO 21 JCL=1,NELEM
           DO 21 I=1,N4
             LN2=KONN(JCL,I)
             JREF=2*(LN2-1)
             ZLD1(NCOUNT,I,JCL)=ZTEMP(JREF+1)
             ZLD2(NCOUNT,I,JCL)=ZTEMP(JREF+2)
  21     CONTINUE
  2    CONTINUE
C      CALCULATE AND SAVE IN FILE 13, THE HOOP STRESSES AND X,Y GLOBAL
C      DISPLACEMENTS FOR PLOTING WITH POSTBEM
C
       NP1=NP/3
       DO 1 I=1,NP1
C        LOOP FOR THE 3 NODES OF THE QUADRATIC ELEMENT
         DO 1 J=1,N4
           DO 6 K=1,NTINT
             SLT1(K,J,I)=ZLT1(K,J,I)
  6        CONTINUE
  1    CONTINUE
       WRITE(13,*) SLT1
       DO 11 I=1,NP1
C        LOOP FOR THE 3 NODES OF THE QUADRATIC ELEMENT
         DO 11 J=1,N4
           DO 61 K=1,NTINT
             SLT1(K,J,I)=ZLT2(K,J,I)
  61       CONTINUE
  11   CONTINUE
       WRITE(13,*) SLT1
       DO 12 I=1,NP1
C        LOOP FOR THE 3 NODES OF THE QUADRATIC ELEMENT
         DO 12 J=1,N4
           DO 62 K=1,NTINT
             SLT1(K,J,I)=ZLT3(K,J,I)
  62       CONTINUE
  12   CONTINUE
       WRITE(13,*) SLT1
       DO 13 I=1,N3
C        LOOP FOR THE 3 NODES OF THE QUADRATIC ELEMENT
         DO 13 J=1,N4
           DO 63 K=1,NTINT
             SLT1(K,J,I)=ZLD1(K,J,I)
  63     CONTINUE
  13   CONTINUE
       WRITE(13,*) SLT1
       DO 14 I=1,N3
C        LOOP FOR THE 3 NODES OF THE QUADRATIC ELEMENT
         DO 14 J=1,N4
           DO 64 K=1,NTINT
             SLT1(K,J,I)=ZLD2(K,J,I)
  64       CONTINUE
  14   CONTINUE
       WRITE(13,*) SLT1
       RETURN
       END
C----------------------------------------------------------------------
C
       SUBROUTINE BMAIN(NCOUNT,XCR,YCR,KONN,N1,N2,N3,N4,N9,SFDIAG,
     &                   LBCU,NDTYPE)
C
C      START NODAL COLLOCATION SCHEME AND SUBDIVISION INTO SUBELEMENT
C
       IMPLICIT REAL*8 (A-H,O-Z)
       DIMENSION XCR(N1),YCR(N1),KONN(N3,N4)
       DIMENSION SFDIAG(N1,2,2)
       DIMENSION LBCU(N3),NDTYPE(N1)
       DIMENSION XY(3,2),LDIR(3),RLNA(3),SHP(3),DSHP(3),RN(2)
       COMMON/CONTR/NNODE,NELEM,NP
       COMMON/GAUSS/GPN(10,10),WTN(10,10),GPS(10,10),WTS(10,10)
       COMMON/FREE/NFFS,NFRE
C
       NOD=3
       TOL1=1.0D-02
       TOL2=1.0D-04
C
       DO 2 ICL=1,NNODE
       XPT=XCR(ICL)
       YPT=YCR(ICL)
       DO 3 JCL=1,NELEM
       DO 4 I=1,NOD
       LN=KONN(JCL,I)
       LDIR(I)=LN
       XY(I,1)=XCR(LN)
       XY(I,2)=YCR(LN)
  4    CONTINUE
C
C      CHECK FOR SINGULAR ELEMENTS
C
       IN=0
       NSUB=1
       DO 6 I=1,NOD
       RLNA(I)=DSQRT((XY(I,1)-XPT)**2+(XY(I,2)-YPT)**2)
       IF (RLNA(I) .LT. TOL1) IN=I
  6    CONTINUE
       IF (IN .EQ. 0) GO TO 10
C
C      SINGULAR CASE SUBDIVISION
C
       NSUB=4
       NPS=6
       CALL INTEGR(NCOUNT,NPS,ICL,JCL,IN,NSUB,NOD,XPT,
     &        YPT,XY,SFDIAG,N1,N2,N3,N9,LBCU,NDTYPE)
       GO TO 3
C
C      NONSINGULAR CASE SUBDIVISION
C
  10   CONTINUE
       RMIN=RLNA(1)
       DO 7 I=2,NOD
       IF (RMIN .GT. RLNA(I)) RMIN=RLNA(I)
  7    CONTINUE
C
       NGP=6
       ELEG=0.0D0
       DO 8 IX=1,NGP
       EK=GPN(NGP,IX)
       WT=WTN(NGP,IX)
       CALL CSHAPE(EK,NOD,XY,SHP,DSHP,RN,DETJ)
       ELEG=ELEG+DETJ*WT
  8    CONTINUE
C
       RATIO=RMIN/ELEG
       IF (RATIO .LT. 1.0D0) NSUB=3
       IF (RATIO .GE. 1.0D0 .AND. RATIO .LE. 2.0D0) NSUB=2
C
       ELEG=ELEG/NSUB
       RAT1=TOL2*ELEG
       RAT2=ELEG/(4.0D0*RMIN)
       RPN=0.5D0*DLOG(RAT1)/DLOG(RAT2)+1.0D0
       NPN=IDINT(RPN)
       IF (NPN .LT. 2) NPN=2
       IF (NPN .GT. 10) NPN=10
       CALL INTEGR(NCOUNT,NPN,ICL,JCL,IN,NSUB,NOD,XPT,
     &        YPT,XY,SFDIAG,N1,N2,N3,N9,LBCU,NDTYPE)
  3    CONTINUE
  2    CONTINUE
       RETURN
       END
C---------------------------------------------------------------
       SUBROUTINE INTEGR(NCOUNT,NGP,ICL,JCL,IN,NSUB,NOD,
     &     XPT,YPT,XY,SFDIAG,N1,N2,N3,N9,LBCU,NDTYPE)
C
C      FORMATION OF 2*2 SUBMATRICES VIA NUMERICAL INTEGRATION
C
       IMPLICIT REAL*8 (A-H,O-Z)
       DIMENSION XY(3,2),YX(3,2),SHP(3),DSHP(3),RN(2)
       DIMENSION ZKU(3,2,2),ZKT(3,2,2),ZU(2,2),ZT(2,2),RRN(3)
       DIMENSION SKT(3,2,2),SU(2,2),ST(2,2)
       DIMENSION SFDIAG(N1,2,2)
       DIMENSION LBCU(N3),NDTYPE(N1)
       COMMON/GAUSS/GPN(10,10),WTN(10,10),GPS(10,10),WTS(10,10)
       COMMON/FREE/NFFS,NFRE
C
       CALL CLRARR(YX,6)
       CALL CLRARR(ZKU,12)
       CALL CLRARR(ZKT,12)
       CALL CLRARR(SKT,12)
       DO 10 IS=1,NSUB
       DO 10 IX=1,NGP
       IF (IN .GT. 0) GO TO 40
C
C      NONSINGULAR CASE
C
       EK=GPN(NGP,IX)
       WT=WTN(NGP,IX)
       GO TO 41
C
C      SINGULAR CASE
C
  40   EK=GPN(NGP,IX)
       WT=WTN(NGP,IX)
  41   CONTINUE
C
C      START AT LINEAR SUBELEMENT LEVEL
C
       RINC=2.0D0/DFLOAT(NSUB)
       YX(1,1)=-1.0D0+RINC*DFLOAT(IS-1)
       YX(2,1)=YX(1,1)+RINC
       CALL CSHAPE(EK,2,YX,SHP,DSHP,RN,DETJ1)
C
C      CONTINUE WITH LOCAL QUADRATIC ELEMENT LEVEL
C
       EKS=0.0D0
       DO 11 I=1,2
       EKS=EKS+YX(I,1)*SHP(I)
  11   CONTINUE
C
       CALL CSHAPE(EKS,NOD,XY,SHP,DSHP,RN,DETJ2)
       DETJ=DETJ1*DETJ2
C
C      NOW AT GLOBAL QUADRATIC ELEMENT LEVEL
C
       XG=0.0D0
       YG=0.0D0
       DO 12 I=1,NOD
       XG=XG+XY(I,1)*SHP(I)
       YG=YG+XY(I,2)*SHP(I)
  12   CONTINUE
       RRN(1)=RN(1)
       RRN(2)=RN(2)
       RRN(3)=0.0D0
       ABC=0.0D0
       DEF=0.0D0
       CALL KERNEL(NCOUNT,XPT,YPT,ABC,XG,YG,DEF,RRN,ZU,ZT,N9)
       IF (NCOUNT .EQ. 1) CALL ZERNEL(XPT,YPT,XG,YG,RN,SU,ST)
       IF (IN .NE. 0) GO TO 18
C
C      NUMERICAL INTEGRATION - NONSINGULAR CASE
C
       DO 16 K1=1,NOD
       AMUL=SHP(K1)*DETJ*WT
       DO 17 K2=1,2
       DO 17 K3=1,2
       ZKU(K1,K2,K3)=ZKU(K1,K2,K3)+ZU(K2,K3)*AMUL
       ZKT(K1,K2,K3)=ZKT(K1,K2,K3)+ZT(K2,K3)*AMUL
       IF (NCOUNT .EQ. 1)
     &    SKT(K1,K2,K3)=SKT(K1,K2,K3)+ST(K2,K3)*AMUL
  17   CONTINUE
  16   CONTINUE
       GO TO 10
  18   CONTINUE
C
C      NUMERICAL INTEGRATION - SINGULAR CASE
C
       DO 19 K1=1,NOD
       AMUL=SHP(K1)*DETJ*WT
       DO 20 K2=1,2
       DO 20 K3=1,2
       ZKU(K1,K2,K3)=ZKU(K1,K2,K3)+ZU(K2,K3)*AMUL

       IF (K1 .EQ. IN .AND. NCOUNT .EQ. 1) GO TO 21
       IF (NCOUNT .NE. 1) GO TO 99
       SKT(K1,K2,K3)=SKT(K1,K2,K3)+ST(K2,K3)*AMUL
  99   ZKT(K1,K2,K3)=ZKT(K1,K2,K3)+ZT(K2,K3)*AMUL
       GO TO 20
  21   ZKT(K1,K2,K3)=ZKT(K1,K2,K3)+
     &          (ZT(K2,K3)-ST(K2,K3))*AMUL
  20   CONTINUE
  19   CONTINUE
  10   CONTINUE
C
C      SUBMATRICES ARE STORED ON TAPES FOR LATER ASSEMBLY
C
       DO 28 K1=1,NOD
       WRITE(7,*) ((ZKU(K1,K2,K3),K2=1,2),K3=1,2)
  28   CONTINUE
       DO 29 K1=1,NOD
       WRITE(8,*) ((ZKT(K1,K2,K3),K2=1,2),K3=1,2)
  29   CONTINUE
C
C      DIAGONAL TERMS
C
       IF (NCOUNT .GT. 1) RETURN
       DO 30 K1=1,NOD
       IF (K1 .EQ. IN) GO TO 30
       DO 31 K2=1,2
       DO 31 K3=1,2
       SFDIAG(ICL,K2,K3)=SFDIAG(ICL,K2,K3)
     &                       -SKT(K1,K2,K3)
  31   CONTINUE
  30   CONTINUE
       RETURN
       END
C------------------------------------------------
       SUBROUTINE CSHAPE(EK,NOD,XY,SHP,DSHP,RN,DETJ)
C
C      SHAPE FUNCTIONS, OUTWARD NORMAL, AND DET. OF JACOBIAN FOR LINE
C      ELEMENTS LINEAR AND QUADRATIC TYPES
C
       IMPLICIT REAL*8 (A-H,O-Z)
       DIMENSION XY(3,2),SHP(3),DSHP(3),RN(2),AJAC(2)
C
       TOL=1.0E-9
       IF (NOD .EQ. 3) GO TO 1
C
C      LINEAR
C
       SHP(1)=0.5D0*(1.0D0-EK)
       SHP(2)=0.5D0*(1.0D0+EK)
C
       DSHP(1)=-0.5D0
       DSHP(2)=0.5D0
       GO TO 2
C
C      QUADRATIC
C
  1    CONTINUE
       SHP(1)=-0.5D0*EK+0.5D0*EK**2
       SHP(2)=1.0D0-EK**2
       SHP(3)=0.5D0*EK+0.5D0*EK**2
C
       DSHP(1)=-0.5D0+EK
       DSHP(2)=-2.0D0*EK
       DSHP(3)=0.5D0+EK
  2    CONTINUE
C
C      JACOBIAN MATRIX, DETERMINANT, NORMAL VECTOR
C
       DO 10 I=1,2
       AJAC(I)=0.0D0
       DO 10 J=1,NOD
       AJAC(I)=AJAC(I)+DSHP(J)*XY(J,I)
  10   CONTINUE
C
       DETJ=DSQRT(AJAC(1)**2+AJAC(2)**2)
       AJ1=AJAC(1)
       AJ2=AJAC(2)
C      DETJ ALWAYS POSSITIVE OR 0
       IF(DETJ.LT.TOL)THEN
         IF (DETJ.EQ.0.0D0) THEN
           IF (AJ2.GT.0.0D0) RN(1)=0.0D0
           IF (AJ2.LT.0.0D0) RN(1)=0.0D0
           IF (AJ1.LT.0.0D0) RN(2)=1.0D0
           IF (AJ2.GT.0.0D0) RN(2)=-1.0D0
           GO TO 34
         ENDIF
       ENDIF
       RN(1)=AJ2/DETJ
       RN(2)=-AJ1/DETJ
  34   CONTINUE
       RETURN
       END
