C************************************************
      PROGRAM BEMTD
C
C     A 2-D BEM PROGRAM IN TIME DOMAIN
C     WITH TIME STEPPING
C
C     MST : TOTAL TIME STEPS
C     MND : TOTAL NODES OF THE MESH
C     MEL : TOTAL ELEMENTS OF THE MESH
C     MBD : TOTAL BOUNDARIES IN THE MESH
C     MPL : NUMBER OF TOTAL PLOT CATEGORIES
C     MZN : NUMBER OF TOTAL ZONES OF DIFFERENT MATERIAL
C     MDM : DIMENSIONS OF THE PROBLEM (2D HERE)
      PARAMETER(MST=100,MND=100,MEL=50,MBD=5,MPL=30,MZN=5,MDM=2)

      IMPLICIT REAL*8 (A-H,O-Z)
      COMMON/CONTR/NNODE,NELEM,NP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/FREE/NFFS,NFRE
      DIMENSION NHPOS(MEL)
      DIMENSION NPLOT(MPL)
      REAL*8 ZARR[ALLOCATABLE](:)
      REAL*8 RARR[ALLOCATABLE](:)
      INTEGER*4 IARR[ALLOCATABLE](:)
      REAL*8 TIMELAP[ALLOCATABLE](:)
      REAL*8 ZLT1[ALLOCATABLE](:)
      REAL*8 ZLT2[ALLOCATABLE](:)
      REAL*8 ZLT3[ALLOCATABLE](:)
      REAL*8 ZLD1[ALLOCATABLE](:)
      REAL*8 ZLD2[ALLOCATABLE](:)
      REAL*8 SLT1[ALLOCATABLE](:)
      REAL*8 SFARR[ALLOCATABLE](:)
      REAL*8 ZZARR[ALLOCATABLE](:)
      INTEGER*4 LINV[ALLOCATABLE](:)
      INTEGER*4 MINV[ALLOCATABLE](:)
      REAL*8 ZLOAD1[ALLOCATABLE](:)
      REAL*8 ZCOL[ALLOCATABLE](:)
      REAL*8 ZB[ALLOCATABLE](:)
      REAL*8 ZPQ[ALLOCATABLE](:)
      OPEN (UNIT=1,FILE='BEMTDDAT',STATUS='UNKNOWN')
      OPEN (UNIT=2,FILE='BEMTDSTR',STATUS='UNKNOWN')
      OPEN (UNIT=3,FILE='BEMTDTRA',STATUS='UNKNOWN')
      OPEN (UNIT=4,FORM='UNFORMATTED',STATUS='UNKNOWN')
      OPEN (UNIT=7,STATUS='UNKNOWN')
      OPEN (UNIT=8,STATUS='UNKNOWN')
      OPEN (UNIT=9,FORM='UNFORMATTED',STATUS='UNKNOWN')
      OPEN (UNIT=10,STATUS='UNKNOWN')
      OPEN (UNIT=11,STATUS='UNKNOWN')
      OPEN (UNIT=12,STATUS='UNKNOWN')
      OPEN (UNIT=14,STATUS='UNKNOWN')
C     FILE TO SAVE HOOP STRESSES FOR POSTBEM PLOTING
      OPEN (UNIT=13,FILE='BEMTDHOO',STATUS='UNKNOWN')
C     FILE TO READ PLOT INFORMATIONS SAVED IN PREPROCESSING
      OPEN (UNIT=23,FILE='POSTDAT',STATUS='UNKNOWN')
C
      REWIND 1
      REWIND 2
      REWIND 3
      REWIND 4
      REWIND 7
      REWIND 8
      REWIND 9
      REWIND 10
      REWIND 11
      REWIND 12
      REWIND 13
      REWIND 14
      REWIND 23
      WRITE(*,900)
  900 FORMAT(2X,//2X,'2-D TIME DOMAIN BEM PROGRAM'//)
C
      IMAX=860
      JMAX=210
      LMAX=80500
      MMAX=201
      MLMAX=301
C

      READ(1,*) NNODE,NELEM,NTINT,NP1,NDOMA,NFFS,NUNIT
C     CASE THAT DOMAIN NOT TIME, WRITE A MESSAGE AND STOP THE PROGRAM
      IF(NDOMA.NE.2) THEN
        WRITE(6,142)NDOMA
  142   FORMAT(1X,'THIS PROGRAM IS ONLY FOR TIME DOMAIN NDOMA=',
     &       I3)
        GO TO 101
      ENDIF
      IF(NP1.LT.NELEM) THEN
        READ(1,*)(NHPOS(K),K=1,NP1)
      ENDIF
      NP=3*NP1
      N1=NNODE
      N2=2*NNODE
      N3=NELEM
C     QUADRATIC ELEMENTS
      N4=3
      N5=3*NNODE
      N6=4*NELEM
      N7=NP
      N8=5
      N9=NTINT
C
C     DYNAMIC STORAGE ALLOCATION
C

      ALLOCATE (ZARR(1+8*N1*N1+4*N1),STAT=IERR)
      ALLOCATE (RARR(1+2*N1),STAT=IERR)
      ALLOCATE (IARR(1+N3*N4+N1*N4+N2+N3+N1),STAT=IERR)
      ALLOCATE (TIMELAP(N9),STAT=IERR)
      ALLOCATE (ZLT1(3*N9*N3),STAT=IERR)
      ALLOCATE (ZLT2(3*N9*N3),STAT=IERR)
      ALLOCATE (ZLT3(3*N9*N3),STAT=IERR)
      ALLOCATE (ZLD1(3*N9*N3),STAT=IERR)
      ALLOCATE (ZLD2(3*N9*N3),STAT=IERR)
      ALLOCATE (SLT1(3*N9*N3),STAT=IERR)
      ALLOCATE (SFARR(4*N1),STAT=IERR)
      ALLOCATE (ZZARR(1+9*N3),STAT=IERR)
      ALLOCATE (LINV(N2),STAT=IERR)
      ALLOCATE (MINV(N2),STAT=IERR)
      ALLOCATE (ZLOAD1(3*N1),STAT=IERR)
      ALLOCATE (ZCOL(2*N1),STAT=IERR)
      ALLOCATE (ZB(2*N1),STAT=IERR)
      ALLOCATE (ZPQ(2*N1),STAT=IERR)
C
      I1=1
      I2=I1+N3*N4
      I3=I2+N1*N4
      I4=I3+N2
      I5=I4+N3
      I6=I5+N1
C
      J1=1
      J2=J1+N1
      J3=J2+N1
      L1=1
      L2=L1+N2*N2
      L3=L2+N2*N2
      L4=L3+N2
      L5=L4+N2
C
      M1=1
      M2=M1+N6
C
      ML1=1
      ML2=ML1+N4*N3
      ML3=ML2+N4*N3
      ML4=ML3+N4*N3
      CALL DATAS(RARR(J1),RARR(J2),IARR(I1),IARR(I2),IARR(I3),
     &   IARR(I4),IARR(I5),NTOT,NPLOT,N1,N2,N3,N4,N9,MPL)

C
      CALL GAUSWE
C
      CALL BEM(RARR(J1),RARR(J2),IARR(I1),IARR(I2),IARR(I3),
     &    IARR(I4),IARR(I5),ZARR(L1),ZARR(L2),ZARR(L3),ZARR(L4),
     &    ZLOAD1,NHPOS,TIMELAP,ZLT1,ZLT2,
     &    ZLT3,ZLD1,ZLD2,SLT1,SFARR,ZZARR(ML1),
     &    ZZARR(ML2),ZZARR(ML3),ZCOL,ZB,ZPQ,N1,N2,N3,N4,N5,N7,N8,N9,
     &    LINV,MINV,NTOT,NPLOT)
C
      CLOSE (1)
      CLOSE (2)
      CLOSE (3)
      CLOSE (4)
      CLOSE (6)
      CLOSE (7)
      CLOSE (8)
      CLOSE (9)
      CLOSE (10)
      CLOSE (11)
      CLOSE (12)
      CLOSE (13)
      CLOSE (14)
      CLOSE (23)
C
      GO TO 101
  101 STOP
      END
