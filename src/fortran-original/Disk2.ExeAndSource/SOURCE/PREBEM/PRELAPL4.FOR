C---------------------------------------------------------------------------
      SUBROUTINE ZTRACT(ZSXX,ZSYY,ZSXY,COSF,SINF,ZTXX,ZTYY)
C
C     CALCULATES THE TRACTIONS ON A PLANE WITH UNIT NORMAL TO IT
C     VECTOR (COSF,SINF) (DIRECTION COSINES WITH X AND Y AXIS RESPECTIVELY)
C     THE STRESSES AND TRACTIONS ARE COMPLEX DOUBLE PRECISION NUMBERS
C
C     ZSXX,ZSYY,ZSXY: AXIAL STRESSES IN DIRECTIONS X,Y OF THE ACTUAL 
C                  COORDINATE SYSTEM AND SHEAR
C     COSF,SINF  : THE COS AND SIN OF THE AXIS X OF THE ACTUAL X AXIS
C                  (DIRECTIONAL COSINES)
C     ZTXX,ZTYY    : EQUEVELANT TRACTIONS IN X AND Y DIRECTIONS
C                  OF THE SAME COORDINATE SYSTEM
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      ZTXX=ZSXX*COSF+ZSXY*SINF
      ZTYY=ZSXY*COSF+ZSYY*SINF
      RETURN
      END
