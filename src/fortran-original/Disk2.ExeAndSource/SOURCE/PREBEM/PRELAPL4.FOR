C---------------------------------------------------------------------------
      SUBROUTINE ZSTRLOC(ZSXX,ZSYY,ZSXY,COSF,SINF,
     &                      ZSXX1,ZSYY1,ZSXY1)
C
C     TRANSFORMATION OF THE COMPLEX STRESSES ZSXX,ZSYY,ZSXY FROM THE GLOBAL
C     COORDINATE SYSTEM TO THE LOBAL COORDINATE SYSTEM
C     ZSXX,ZSYY,ZSXY    : AXIAL STRESSES IN X,Y DIRECTION AND SHEAR,
C                         IN GLOBAL SYSTEM
C     COSF,SINF         : COS AND SIN OF THE ANGLE F OF THE GLOBAL X AXIS,
C                         WITH THE LOCAL AXIS (DIRECTIONAL COSINES)
C     ZSXX1,ZSYY1,ZSXY1 : RETURN VALUES OF THE AXIAL STRESSES IN X1,Y1 
C                         DIRECTIONS AND SHEAR, IN LOCAL SYSTEM
C     SIGN CONVENTION   : TENSION STRESSES POSITIVE (+)
C                         COMPRESSION STRESSES NEGATIVE (-)
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)

      ZSXX1=ZSXX*COSF**2+2.0D0*ZSXY*COSF*SINF+ZSYY*SINF**2
      ZSYY1=ZSXX*SINF**2-2.0D0*ZSXY*COSF*SINF+ZSYY*COSF**2
      ZSXY1=(ZSYY-ZSXX)*COSF*SINF+ZSXY*(COSF**2-SINF**2)
      RETURN
      END
