      SUBROUTINE ZREFSTRSV(THEP,THANP,THANSV,THCR,RK,KANGL,
     &  ZC11P,ZC22P,ZC12P,ZC11SV,ZC22SV,ZC12SV,ZRAT1,ZRAT2,ZK)
C
C     CALCULATES THE STRESS REFLECTION COEFFICIENTS, TAKING INTO ACCOUNT
C     THE VISCOELASTICITY, FOR AN
C     INCIDENT SV-HARMONIC WAVE, IN A CORDINATE SYSTEM X1,Y1, WITH AXES
C     OUTWARD NORMAL AND TANGENT TO THE FREE SURFACE
C     THEP  : ANGLE OF INCIDENT SV-WAVE WITH THE X1 AXIS (ANTICLOCKWISE)
C     THANP : ANGLE OF REFLECTED P-WAVE WITH THE X1 AXIS (ANTICLOCKWISE)
C     THANSV: ANGLE OF REFLECTED  SV-WAVE WITH THE X1 AXIS (ANTICLOCKWISE)
C     THCR  : CRITICAL ANGLE OF INCIDENCE
C     KANGL : INDEX FOR POSITION OF AXES
C     RK : K COEFFICIENT=C1/C2=SQRT(2*(1.0D0-RNU)/(1-2*RNU))
C     ZC11P : STRESS REFLECTION COEFFICIENT OF P-REFLECTED WAVE
C                   FOR AXIAL STRESS IN X1 AXIS (RETURN VALUE)
C     C22P : STRESS REFLECTION COEFFICIENT OF P-REFLECTED WAVE
C                   FOR AXIAL STRESS IN X2 AXIS (RETURN VALUE)
C     C12P : STRESS REFLECTION COEFFICIENT OF P-REFLECTED WAVE
C                   FOR SHEAR STRESS (RETURN VALUE)
C     C11SV : STRESS REFLECTION COEFFICIENT OF SV-REFLECTED WAVE
C                   FOR AXIAL STRESS IN X1 AXIS (RETURN VALUE)
C     C22SV : STRESS REFLECTION COEFFICIENT OF SV-REFLECTED WAVE
C                   FOR AXIAL STRESS IN X2 AXIS (RETURN VALUE)
C     C12P : STRESS REFLECTION COEFFICIENT OF SV-REFLECTED WAVE
C                   FOR SHEAR STRESS (RETURN VALUE)
C
C    SPECIAL CASES FOR REFLECTION OF SV INCIDENT WAVE
C        1. REFLECTION AS AN SV WAVE ONLY IN THE FOLLOWING CASES
C             A. FOR KANGL=1  THEP=(PI/2),3PI/4,PI 
C             B. FOR KANGL=2  THEP=(3P/2),5PI/4,PI
C        2. REFLECTION AS A P WAVE ONLY
C             FOR (RAT2=0) 
C               DSIN(2.0D0*THANP)*(DSIN(2.0D0*THEP)+
C                 RK*RK*(DCOS(2.0D0*THANSV)**2))=0
C        3. CRITICAL ANGLE 
C             A. FOR KANGL=1 THCR=PI-ARC(SIN(1/K)) 
C                (1). THEP>THCR USUAL CASE TH1 REAL VALUED
C                (2). THEP=THCR :
C                       TH1=PI/2, THANP=3PI/2, 
C                       A1/A0=4*SQRT(K**2-1)/(K*(2-K**2)), A2/A0=-1
C                (3). THEP<THCR :
C                       P REFLECTED WAVE : IS A SURFACE WAVE DECAYING WITH
C                           DEPTH IN THE MATERIAL (IGNORE IT)
C                       SV REFLECTED WAVE: UNDERGOES A CHANGE IN PHASE OF
C                            PI+2*TH2
C                            RAT1=0 (NOT IN REALLITY)
C                            RAT2=A2/A0=1
C                            C11SV=C22SV=C12SV=-1
C                            C11P=C22P=C12P=0 (NOT IN REALLITY)
C             B. FOR KANGL=2 THCR=PI+ARC(SIN(1/K))
C                (1). THEP<THCR USUAL CASE TH1 REAL VALUED
C                (2). THEP=THCR :
C                       TH1=PI/2, THANP=3PI/2, 
C                       A2/A0=-1
C                (3). THEP>THCR :
C                       P REFLECTED WAVE : IS A SURFACE WAVE DECAYING WITH
C                           DEPTH IN THE MATERIAL (IGNORE IT)
C                       SV REFLECTED WAVE: UNDERGOES A CHANGE IN PHASE OF
C                            PI+2*TH2
C                            RAT1=0 (NOT IN REALLITY)
C                            RAT2=A2/A0=1
C                            C11SV=C22SV=C12SV=-1
C                            C11P=C22P=C12P=0 (NOT IN REALLITY
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
C
C     TOLERANCE 
      TOL=1.0E-11
      TOL1=1.0D-3
C

C     VISCOLASTISCITY
      CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
      ZRK=ZC1/ZC2
      SINAN2P=DSIN(2.0D0*THANP)
      SINAN2SV=DSIN(2.0D0*THANSV)
      COSAN2SV=DCOS(2.0D0*THANSV)
      SINEP2  =DSIN(2.0D0*THEP)
C
      IF(KANGL.EQ.1) THEN
C       CASE 3.A.(1) THEP>THCR
        IF(THEP.GT.THCR) ISRC=1
C       CASE 3.A.(2) THEP=THCR
        IF(THEP.EQ.THCR) ISRC=2
C       CASE 3.A.(3) THEP<THCR
        IF(THEP.LT.THCR) ISRC=3
C       CASE THAT THCR NEAR THEP
        IF(DABS(DABS(THCR)-DABS(THEP)).LT.TOL1) ISRC=2
      ENDIF
C
      IF(KANGL.EQ.2) THEN
C       CASE 3.B.(1) THEP<THCR
        IF(THEP.GT.THCR) ISRC=1
C       CASE 3.B.(2) THEP=THCR
        IF(THEP.EQ.THCR) ISRC=2
C       CASE 3.B.(3) THEP>THCR
        IF(THEP.LT.THCR) ISRC=3
C       CASE THAT THCR NEAR THEP
        IF(DABS(DABS(THCR)-DABS(THEP)).LT.TOL1) ISRC=2
      ENDIF
C
C     USUAL CASE 
      IF(ISRC.EQ.1) THEN
        GCOS=DCOS(2.0D0*THEP)
C       FOR XX :
C       FOR THEP=3PI/4 AND PI THE REFLECTED WAVE IS SV
        IF(DABS(GCOS).LT.TOL) THEN
          ZC11P=DCMPLX(0.0D0,0.0D0)
          GO TO 63
        ENDIF
        ZC11P=ZRK*COSAN2SV/SINEP2
  63    CONTINUE
        ZC11SV=DCMPLX(1.0D0,0.0D0)
C       FOR YY :
C       FOR THEP=3PI/4 AND PI THE REFLECTED WAVE IS SV
        IF(DABS(GCOS).LT.TOL) THEN
          ZC22P=DCMPLX(0.0D0,0.0D0)
          GO TO 65
        ENDIF
        SINANP=DSIN(THANP)
        ZC22P=-(ZLA+2.0D0*ZMU*SINANP**2)/
     &          (ZRK*ZMU*SINEP2)
  65    CONTINUE
        ZC22SV=DCMPLX(1.0D0,0.0D0)
C       FOR XY :
C       FOR THEP=3PI/4 AND PI THE REFLECTED WAVE IS SV
        IF(DABS(GCOS).LT.TOL) THEN
          ZC12P=DCMPLX(0.0D0,0.0D0)
          GO TO 67
        ENDIF
        ZC12P=-SINAN2P/(ZRK*GCOS)
  67    CONTINUE
        ZC12SV=DCMPLX(-1.0D0,0.0D0)
      ENDIF
C             
      IF((ISRC.EQ.2).OR.(ISRC.EQ.3)) THEN
        ZRAT1=DCMPLX(0.0D0,0.0D0)
        ZRAT2=DCMPLX(1.0D0,0.0D0)
        ZC11SV=DCMPLX(-1.0D0,0.0D0)
        ZC22SV=DCMPLX(-1.0D0,0.0D0)
        ZC12SV=DCMPLX(-1.0D0,0.0D0)
C        C11SV=1.0D0
C        C22SV=1.0D0
C        C12SV=1.0D0
        ZC11P=DCMPLX(0.0D0,0.0D0)
        ZC22P=DCMPLX(0.0D0,0.0D0)
        ZC12P=DCMPLX(0.0D0,0.0D0)
C
      ENDIF
C
      RETURN
      END
