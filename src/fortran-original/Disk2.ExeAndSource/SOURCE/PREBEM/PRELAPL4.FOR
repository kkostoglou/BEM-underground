      SUBROUTINE ZSTRGLOB(ZSXX1,ZSYY1,ZSXY1,COSF,SINF,
     &                      ZSXX,ZSYY,ZSXY)
C
C     TRANSFORMATION OF THE COMPLEX STRESSES SXX1,SYY1,SXY1 FROM THE LOCAL
C     COORDINATE SYSTEM TO THE GLOBAL COORDINATE SYSTEM
C     ZSXX1,ZSYY1,ZSXY1 : AXIAL STRESSES IN X1,Y1 DIRECTION AND SHEAR,
C                      IN LOCAL SYSTEM
C     COSF,SINF      : COS AND SIN OF THE ANGLE F OF THE LOCAL X1 AXIS,
C                      WITH THE GLOBAL X AXIS (DIRECTIONAL COSINES)
C     ZSXX,ZSYY,ZSXY    : RETURN VALUES OF THE AXIAL STRESSES IN X,Y
C                      DIRECTIONS AND SHEAR, IN GLOBAL SYSTEM.
C     SIGN CONVENTION: TENSION STRESSES POSITIVE (+)
C                      COMPRESSION STRESSES NEGATIVE (-)
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)

      ZSXX=ZSXX1*COSF**2-2.0D0*ZSXY1*COSF*SINF+ZSYY1*SINF**2
      ZSYY=ZSXX1*SINF**2+2.0D0*ZSXY1*COSF*SINF+ZSYY1*COSF**2
      ZSXY=(ZSXX1-ZSYY1)*COSF*SINF+ZSXY1*(COSF**2-SINF**2)
      RETURN
      END
