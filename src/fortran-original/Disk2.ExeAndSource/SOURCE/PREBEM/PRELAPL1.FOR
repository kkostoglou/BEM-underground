      SUBROUTINE WINTRAC(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &  N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &  XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,TRACX,TRACY,NBOUN,
