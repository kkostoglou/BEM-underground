      SUBROUTINE WINSURF(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &  N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &  XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,PSURFX,PSURFY,NBOUN,
     &  NSHAP,LCRN,LBOUN,NDTYPE,KONN,LDIR1)
C
C   CALCULATES THE INCIDENT FIELD IN LAPLACE TRANSFORM DOMAIN, FOR THE
C   PRESSURE ON THE ELEMENTS CASE. THE CALCULATIONS ARE
C   PERFORMED FOR ALL THE NODES OF THE MESH, AND THE OPPOSITE TRACTIONS 
C   TO THE INCIDENT ONES ARE RETURNED IN ARRAY ZLOAD WHILE THE INCIDENT
C   STRESSES IN THE ARRAY ZLOAD1. THESE TRACTIONS ZLOAD ARE REFERED
C   TO A GLOBAL COORDINATE SYSTEM AND ARE READ IN THE PROCESSING PHASE IN 
C   SUBROUTINE GENR. THE INCIDENT STRESSES ON THE PERIPHERY OF THE BOUNDARY 
C   ZLOAD1(NORMA, TANGENTIL AND SHEAR STRESSES), ARE REFERED TO A LOCAL 
C   COORDINATE SYSTEM WITH X AXIS THE NORMAL AND Y AXIS THE TANGENT TO THE 
C   PERIPHERY UNIT VECTORS, AND ARE READ IN SUBROUTINE HOOP OF PROCESSING PHASE.  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   NB2: GLOBAL NUMBER OF THE LAST NODE OF THE BOUNDARY
C   ZTSXX,ZTSYY,ZTSXY: TOTAL INCOMING STRESS WAVE (WITH THE ADDITIONAL VERTICAL
C                 STRESSES FROM UNIAXIAL STRAIN CONDITION ON THE WAVEFRONT.
C                 ON THE FREE SURFACE WE HAVE ONLY INCOMING SXX STRESSES, 
C                 BUT IT DOESN'T MUTTER, BECAUSE FINALY THEY VANISHES.) 
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C	       NODES OF DISCONTINUTY
C    LBOUN   : NUMBER OF EXAMINING BOUNDARY

C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/BLKEX/IEXIT
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/FREE/NFFS,NSIMU
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &		  EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
      COMMON/PRESS/KINSI,PINSI
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1),ZLOAD(N2)
      DIMENSION ZLOAD1(N5),SPOINT(3)
      DIMENSION XY(3,2),RN(2)
      DIMENSION NREGI(5)
      DIMENSION NSIMU(5)
      DIMENSION LCRN(8)
      DIMENSION NSHAP(NBOUN)
      DIMENSION PINSI(5)
      DIMENSION NDTYPE(N1)
      DIMENSION LDIR(3)
      DIMENSION PSURFX(N3),PSURFY(N3)
      DIMENSION KONN(N3,N4)
      DIMENSION LDIR1(N1)
      INTEGER*2 STAT,IERR
      DATA SPOINT/-1.,0.,1./
      TOL=1.0D-11
      NOD=3
C     FIND HOW MANY TIMES EACH NODE APPEARS IN ELEMENTS WITH SURFACE
C     PRESSURE, IN ORDER TO FIND LATER A MEAN VALUE OF THE PRESSURE
C     AT THE NODE (MEAN VALUE OF THE PRESSURES OF ALL THE JOINING AT
C     THAT NODE ELEMENTS
      DO 63 I=1,N1
        LDIR1(I)=0
  63  CONTINUE
      DO 65 JCL=1,NELEM
        DO 65 I=1,NOD
          LNC=KONN(JCL,I)
          IF((DABS(PSURFX(JCL)).GT.TOL).OR.
     &       (DABS(PSURFY(JCL)).GT.TOL))THEN
            L1=LDIR1(LNC)
            LDIR1(LNC)=L1+1
          ENDIF
  65  CONTINUE
      ZAL=DCMPLX(0.0D0,0.0D0)
      ZDELAY=CDEXP(-ZAL*ZK)
C     LOOP FOR ALL THE ELEMENTS
      DO 67 JCL=1,NELEM
C       FIND THE CONFINING STRESSES AS COMPLEX, TAKING VISCOELASTIC
C	MATERIAL BEHAVIOUR
        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
        DO 4 II=1,NOD
          LNC=KONN(JCL,II)
          LDIR(II)=LNC
  4     CONTINUE
        DO 69 I=1,NOD
          IF((DABS(PSURFX(JCL)).GT.TOL).OR.
     &       (DABS(PSURFY(JCL)).GT.TOL))THEN
            JREF=2*(LDIR(I)-1)
            ZLOAD(JREF+1)=ZLOAD(JREF+1)+PSURFX(JCL)*ZDELAY/ZK
            ZLOAD(JREF+2)=ZLOAD(JREF+2)+PSURFY(JCL)*ZDELAY/ZK
         ENDIF
  69    CONTINUE
  67    CONTINUE
C       FIND THE MEAN VALUE AT THE NODE
        DO 74 II=1,NNODE
          JREF=2*II
C         FOR LDIR1=0 (AS IN THE CASE OF ENCLOSING ELEMENTS)
          IF(LDIR1(II).EQ.0) LDIR1(II)=1
          ZLOAD(JREF-1)=ZLOAD(JREF-1)/LDIR1(II)
          ZLOAD(JREF)=ZLOAD(JREF)/LDIR1(II)
  74    CONTINUE
  99  CONTINUE
      RETURN
      END
