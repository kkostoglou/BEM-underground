C -----------------------------------------------------------------------
      SUBROUTINE DATALAP(XCR,YCR,KONN,NONN,NNODEB,LBCU,
     &        ZLOAD,ZLOAD1,ZLOADF,ZLOAD2,ZRXX,ZRYY,ZRXY,
     &        SXX,SYY,SXY,
     &        N1,N2,N3,N4,N5,CA,CB,CP,
     &        NBOUN,JKODE,NSHAP,NELEMB,NSEGM,SEG,NBNT,XCEN,YCEN,
     &        DRSTRE,DRNSTRE,DRNORM,TH0,TH3,TH4,KEXPL,
     &        KSURF,PSURFX,PSURFY,KTRAC,TRACX,TRACY,
     &        MBCU,NDTYPE,LCRN)
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS IN THE LAPLACE TRANSFORM,
C   ON THE SURFACE OF THE GEOMETRICAL SHAPE (ANY SHAPE) 
C     ZLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     ZLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLINDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   KEXPL=1: THE LOADS ARE FROM EXPLOSION POINT
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      COMMON/BLKEX/IEXIT
      COMMON/PRESS/KINSI,PINSI
      COMMON/FREQ/OFREQ
      DIMENSION XCR(N1),YCR(N1),ZLOAD(N2)
      DIMENSION ZLOAD1(N5)
      DIMENSION PSAI(5)
      DIMENSION KONN(N3,N4),NONN(N1,N4)
      DIMENSION NSIMU(5)
      DIMENSION LBCU(N3)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION NREGI(5)
      DIMENSION NNODEB(NBOUN)
      DIMENSION NSHAP(NBOUN)
      DIMENSION JKODE(NBNT)
      DIMENSION NELEMB(NBOUN)
      DIMENSION NSEGM(NBOUN)
      DIMENSION SEG(NBNT*7)
      DIMENSION ZLOADF(N2)
      DIMENSION ZLOAD2(N5)
      DIMENSION ZRXX(N1),ZRYY(N1),ZRXY(N1)
      DIMENSION MBCU(N2)
      DIMENSION TH0(N1),TH3(N1),TH4(N1)
      DIMENSION LCRN(8)
      DIMENSION PINSI(5)
      DIMENSION NDTYPE(N1)
      DIMENSION PSURFX(N3),PSURFY(N3)
      DIMENSION TRACX(N1),TRACY(N1)
      INTEGER*4 LDIR1[ALLOCATABLE](:)
      PI=3.14159265359D0
      TOL=1.0D-11
      TOL1=1.0E-6
C
      ALLOCATE (LDIR1(N1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      IF(OFREQ.GT.TOL) THEN
        TIM=2.0*PI/OFREQ
      ENDIF
      AK=6.0D0/TIM
      OMEGA=2.0D0*PI/TIM
      REWIND 11
C
C     PRINT THE CONFINING STRESSES
      IF(DRSTRE.LT.0.0D0) THEN
        DRNSTRE1=DRSTRE*RNU/(1.0D0-RNU)
        WRITE(6,324)
  324   FORMAT('SP(AX)*N/(1-N).........')
        WRITE(6,*) DRNSTRE1
      ENDIF
C     VERTICAL INCOMING STRESS
      IF(DRNSTRE.LT.0.0D0) THEN
        DRSTRE1=DRNSTRE*RNU/(1.0D0-RNU)
        WRITE(6,326)
  326   FORMAT('SP(VER)*N/(1-N).........')
        WRITE(6,*) DRSTRE1
      ENDIF
C
C     CALCULATE THE LOADS IN LAPLACE TRANSFORM 
      DO 31 K=1,NSTEP
        CALL CLRZRR(ZRXX,N1)
        CALL CLRZRR(ZRYY,N1)
        CALL CLRZRR(ZRXY,N1)
        CALL CLRZRR(ZLOAD,N2)
        CALL CLRZRR(ZLOADF,N2)
        CALL CLRZRR(ZLOAD1,N5)
        CALL CLRZRR(ZLOAD2,N5)
        AKMG=OMEGA*DFLOAT(K-1)
        ZK=DCMPLX(AK,AKMG)
C       FIND THE CONFINING STRESSES AS COMPLEX, TAKING VISCOELASTIC
C       MATERIAL BEHAVIOUR
        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
        IF(DRSTRE.LT.0.0D0) THEN
          ZDRNSTRE1=DRSTRE*ZNU/(1.0D0-ZNU)
        ENDIF
C       VERTICAL INCOMING STRESS
        IF(DRNSTRE.LT.0.0D0) THEN
          ZDRSTRE1=DRNSTRE*ZNU/(1.0D0-ZNU)
        ENDIF
C       INCOMING STRESSES WITH THE ADDITIONAL VERTICAL STRESSES
        ZDTRSTRE=DRSTRE+ZDRSTRE1
        ZDTRNSTRE=DRNSTRE+ZDRNSTRE1
        ZDTRNORM=DRNORM
C       TRANSFORMATION OF INCIDENT STRESSES FROM DIRECTION ANGL (WITH X AXIS)
C       TO THE GLOBAL COORDINATE SYSTEM
        FN1=DCOS(FAI)
        FN2=DSIN(FAI)
        CALL ZSTRGLOB(ZDTRSTRE,ZDTRNSTRE,ZDTRNORM,
     &              FN1,FN2,ZTSXX,ZTSYY,ZTSXY)
C
C       LOOP FOR ALL THE BOUNDARY SHAPES
        NB0=0
        NB2=0
        DO 61 L=1,NBOUN
C         CHECK FOR THE EXISTENCE OF A FREE SURFACE
          NFRE=0
          DO 46 I=1,NBOUN
            IF(NREGI(I).EQ.4) NFRE=1
  46      CONTINUE
C         COUNTER FOR THE STARTING NUMBER OF NODE OF A BOUNDARY
C         FOR FREE SURFACE PROBLEM THE LOADS ARE ALL 0
          IF(L.EQ.1) THEN
            NB0=1
            GO TO 54
          ENDIF
          NB0=NB0+NNODEB(L-1)
   54     NB1=NNODEB(L)
          NCOUNT=L
C         NUMBER OF LAST NODE IN THE BOUNDARY
          NB2=NB2+NB1
C          INSIDE PRESSURE WAVE (P WAVE)
C	   ====================
           IF(KINSI.EQ.1) THEN
             WVEL=C1
	     CALL WINPRES(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,
     &          NSHAP,LCRN,L,NDTYPE)
              IF (IEXIT.EQ.1) GO TO 999
	      GO TO 61
	    ENDIF
C          PRESSURE ON THE ELEMENTS CASE
C          =============================
           IF(KSURF.EQ.1) THEN
             WVEL=C1
             CALL WINSURF(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,PSURFX,PSURFY,NBOUN,
     &          NSHAP,LCRN,L,NDTYPE,KONN,LDIR1)
	      IF (IEXIT.EQ.1) GO TO 999
	      GO TO 61
            ENDIF
C          TRACTION ON THE NODES CASE
C          ==========================
           IF(KTRAC.EQ.1) THEN
             WVEL=C1
             CALL WINTRAC(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,TRACX,TRACY,NBOUN,
     &          NSHAP,LCRN,L,NDTYPE,KONN,LDIR1)
	      IF (IEXIT.EQ.1) GO TO 999
	      GO TO 61
	    ENDIF
C           FOR ALL THE CASES
C           INCIDENT WAVE
C           =============
C           P-WAVE
C           ------
C           CASE THAT 
C             PLANE WAVE : THERE IS AXIAL STRESS IN THE DIRECTION OF RAYS OR
C             EXPLOSIVE POINT
            IF((DABS(DRSTRE).GT.TOL).OR.(KEXPL.EQ.1))THEN
              WVEL=C1
              KPS=1
              CALL WINCID(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,
     &          NSHAP,LCRN,KPS,NDTYPE)
              IF (IEXIT.EQ.1) GO TO 999
            ENDIF
C
C           SV-WAVE
C           -------
C           CASE THAT 
C             PLANE WAVE : THERE IS SHEAR STRESS IN THE DIRECTION OF RAYS OR
C             EXPLOSIVE POINT WITH SV WAVE
            IF((DABS(DRNORM).GT.TOL).OR.
     &         ((KEXPL.EQ.1).AND.(DABS(EXPLSV).GT.TOL)))THEN
              WVEL=C2
              KPS=2
              CALL WINCID(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,
     &          NSHAP,LCRN,KPS,NDTYPE)
              IF (IEXIT.EQ.1) GO TO 999
            ENDIF
C         CASE OF NFFS=1, CALCULATION OF THE FREE FIELD WITH REFLECTION FORMS
C         OF HARMONIC WAVES
          IF(NFFS.EQ.1) THEN
C           REFLECTED WAVE
C           ==============
C           CASE OF EXISTENCE OF FREE SURFACE
            IF(NFRE.EQ.1) THEN
C             FIND THE REFLECTED STRESSES AT EVERY NODE WITH DELAYS 
C             ZRXX,ZRYY,ZRXY (REFLECTIONS OF SXX,SYY,SXY)
C             FOR CALCULATING THE INCIDENT STRESSES, TAKE THE INCOMING ONLY
C             STRESSES ZTSXX,ZTSYY,ZTSXY (WITHOUT THE ADDITIONAL VERTICAL 
C             STRESSES)
C             P-WAVE
C             ------
C           CASE THAT 
C             PLANE WAVE : THERE IS AXIAL STRESS IN THE DIRECTION OF RAYS OR
C             EXPLOSION POINT
            IF((DABS(DRSTRE).GT.TOL).OR.(KEXPL.EQ.1))THEN
                WVEL=C1
C               CASE OF EXPLOSION POINT WAVE
                IF(KEXPL.EQ.1) GO TO 72
C               CASE OF PLANE WAVE
                CALL REFP(XCR,YCR,SXX,SYY,SXY,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            ZRXX,ZRYY,ZRXY,DRSTRE,DRNSTRE,NDTYPE)
                IF (IEXIT.EQ.1) GO TO 999
                GO TO 69
  72            CONTINUE
C               CASE OF EXPLOSION POINT WAVE
                CALL REFEXP(XCR,YCR,SXX,SYY,SXY,WVEL,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            ZRXX,ZRYY,ZRXY,TH0,TH3,TH4,K,KEXPL,NDTYPE)
                IF (IEXIT.EQ.1) GO TO 999
  69            CONTINUE
              ENDIF
C             SV-WAVE
C             -------
C           CASE THAT 
C             PLANE WAVE : THERE IS SHEAR STRESS NORMAL THE DIRECTION OF RAYS
              IF(DABS(DRNORM).GT.TOL)THEN
                CALL REFSV(XCR,YCR,SXX,SYY,SXY,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            ZRXX,ZRYY,ZRXY,DRNORM,NDTYPE)
              ENDIF
C             EXPLOSION POINT SV WAVE
              IF(DABS(EXPLSV).GT.TOL)THEN
                CALL REFEXSV(XCR,YCR,SXX,SYY,SXY,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            ZRXX,ZRYY,ZRXY,DRNORM,NDTYPE)
              ENDIF
C             CALCULATE THE EQUIVELANT TO ZRXX,ZRYY,ZRXY INCIDENT STRESSES
C             AND TRACTIONS,LOADS WITHOUT DELAYS 
C             (DELAYS ALREADY APPLIED IN SUBROUTINE REFEX)
              CALL REFLECT(XCR,YCR,ZLOADF,ZLOAD2,ZRXX,ZRYY,ZRXY,
     &          N1,N2,N3,N4,N5,CA,CB,NB0,NB1,NCOUNT,NB2,NBOUN,
     &          NSHAP,LCRN,NDTYPE)
            ENDIF
          ENDIF
   61    CONTINUE
C       ADD THE INCIDENT AND REFLECTED STRESSES
        DO 42 I=1,N5
          ZLOAD1(I)=ZLOAD1(I)+ZLOAD2(I)
  42    CONTINUE
C       ADD THE INCIDENT AND REFLECTED TRACTIONS
        DO 44 I=1,N2
          ZLOAD(I)=ZLOAD(I)+ZLOADF(I)
  44    CONTINUE
C       INCIDENT TRACTIONS OR FREE FIELD TRACTIONS(IF THERE IS FREE SURFACE)
        WRITE(3,*) ZLOAD
C       RADIAL, TANGENTIAL AND SHEAR PERIPHERAL INCIDENT STRESSES
C       OR FREE FIELD STRESSES (IF THERE IS FREE SURFACE)
        WRITE(2,*) ZLOAD1
  31  CONTINUE
  999 CONTINUE
      GO TO 998
 988  STOP '....Not enough storage for data, aborting...'
 998  CONTINUE
      RETURN
      END
C
C ----------------------------------------------------------------------
      SUBROUTINE WINCID(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &  N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,XCEN,
     &  YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,NSHAP,
     &  LCRN,KPS,NDTYPE)
C
C   CALCULATES THE INCIDENT FIELD IN LAPLACE TRANSFORM DOMAIN, FOR THE 
C   PLANE WAVE AND EXPLOSIVE POINT WAVE ALSO. THE CALCULATIONS ARE 
C   PERFORMED FOR ALL THE NODES OF THE MESH, AND THE OPPOSITE TRACTIONS 
C   TO THE INCIDENT ONES ARE RETURNED IN ARRAY ZLOAD WHILE THE INCIDENT
C   STRESSES IN THE ARRAY ZLOAD1. THESE TRACTIONS ZLOAD ARE REFERED
C   TO A GLOBAL COORDINATE SYSTEM AND ARE READ IN THE PROCESSING PHASE IN 
C   SUBROUTINE GENR. THE INCIDENT STRESSES ON THE PERIPHERY OF THE BOUNDARY 
C   ZLOAD1(NORMA, TANGENTIL AND SHEAR STRESSES), ARE REFERED TO A LOCAL 
C   COORDINATE SYSTEM WITH X AXIS THE NORMAL AND Y AXIS THE TANGENT TO THE 
C   PERIPHERY UNIT VECTORS, AND ARE READ IN SUBROUTINE HOOP OF PROCESSING PHASE.  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   NB2: GLOBAL NUMBER OF THE LAST NODE OF THE BOUNDARY
C   ZTSXX,ZTSYY,ZTSXY: TOTAL INCOMING STRESS WAVE (WITH THE ADDITIONAL VERTICAL
C                 STRESSES FROM UNIAXIAL STRAIN CONDITION ON THE WAVEFRONT.
C                 ON THE FREE SURFACE WE HAVE ONLY INCOMING SXX STRESSES, 
C                 BUT IT DOESN'T MUTTER, BECAUSE FINALY THEY VANISHES.) 
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
C
C   KPS=1   : EXPLOSIVE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C   KPS=2   : EXPLOSIVE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)
C
C   THE RETURN VALUES OF SXX,SYY,SXY,ZTSXX,ZTSYY,ZTSXY ARE ICREASED BY
C      THE ACTUAL EXPLOSION STRESSES. IN CASE OF EXPLOSION THERE ARE
C      ONLY EXPLOSION STRESSES
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/BLKEX/IEXIT
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/FREE/NFFS,NSIMU
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1),ZLOAD(N2)
      DIMENSION ZLOAD1(N5),SPOINT(3)
      DIMENSION XY(3,2),RN(2)
      DIMENSION NREGI(5)
      DIMENSION LN(3)
      DIMENSION NSIMU(5)
      DIMENSION LCRN(8)
      DIMENSION NSHAP(NBOUN)
      DIMENSION NDTYPE(N1)
      DATA SPOINT/-1.,0.,1./
C
C         TO CALCULATE THE UNIT VECTOR NORMAL TO THE SURFACE OF THE ELEMENT
C         WE TAKE THE CURRENT NODE I AND THE PREVIUS AND NEXT NODE TO HAVE
C         AN ELEMENT. FROM THIS ELEMENT WITH SHAPE FUNCTIONS WE CALCULATE
C         THE NORMAL TO THE SURFACE VECTORS AT THE NODE I(MIDDLE)
      NOD=3
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
      DO 41 I=1,NB1
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 36
        ZTSXX1=DCMPLX(0.0D0,0.0D0)
        ZTSYY1=DCMPLX(0.0D0,0.0D0)
        ZTSXY1=DCMPLX(0.0D0,0.0D0)
        ZTSXX1E=DCMPLX(0.0D0,0.0D0)
        ZTSYY1E=DCMPLX(0.0D0,0.0D0)
        ZTSXY1E=DCMPLX(0.0D0,0.0D0)
C       ESTABLISH A TEMPORARY QUADRATIC ELEMENT WITH MIDDLE NODE I.
        DO 51 II=1,NOD
          JCL1=I
          II1=II  
C         PREVIOUS AND NEXT NODE
          CALL COORD3(NCN,JCL1,NB0,NB1,NCOUNT,
     &                 II1,KCL,NB2,NBOUN,NSHAP,LCRN)
          XY(II,1)=XCR(KCL)
          XY(II,2)=YCR(KCL)
          LN(II)=KCL
  51    CONTINUE
C       INTERPOLATION TO FIND THE OUTWARD TO THE MATERIAL NORMAL UNIT 
C       VECTOR FOR THE MIDDLE NODE (EKS=0)
        CALL SINTERP(XY,LN,RN)
C       TAKE THE OPPOSITE SIGN, BECAUSE WE WANT INWARD TO THE MATERIAL 
C       UNIT NORMAL VECTOR.
        RN1=-RN(1)
        RN2=-RN(2)
        XCR1=XCR(NCN)
        YCR1=YCR(NCN)
C       EXPLOSION POINT WAVE
C       --------------------
C       IN CASE OF EXPLOSION POINT SOURCE, CALCULATE FOR NODE I, THE
C       STRESSES IN THE TRANSFORMED DOMAIN. THESE STRESSES ARE DECAYING 
C       BY TIME
        IF(KEXPL.EQ.1) THEN
          CALL WAVEXPL(XCR1,YCR1,WVEL,NCOUNT,
     &           ZTSXX1E,ZTSYY1E,ZTSXY1E,ZK,K,KPS)
          IF(IEXIT.EQ.1) GO TO 99
          GO TO 33
        ENDIF
C       PLANE WAVE
C       ----------
C       CALCULATE THE TRANSFORMED STRESSES WITH DELAYS AND LAPLACE TRANFORMATION
C       ON THE NODE I, IN A GLOBAL SYSTEM
        CALL WAVPLAN(XCR1,YCR1,XCEN,YCEN,CA,CB,CP,WVEL,NCOUNT,ZK,
     &      SXX,SYY,SXY,ZTSXX,ZTSYY,ZTSXY,ZTSXX1,ZTSYY1,ZTSXY1)
  33    CONTINUE
        ZTSXX1=ZTSXX1+ZTSXX1E
        ZTSYY1=ZTSYY1+ZTSYY1E
        ZTSXY1=ZTSXY1+ZTSXY1E
        J=2*NCN
C
C       CALCULATE THE EQUEVELANT TRACTIONS IN A TANGENTIAL PLANE WITH
C       INWARD TO THE MATERIAL UNIT NORMAL VECTOR.
        CALL ZTRACT(ZTSXX1,ZTSYY1,ZTSXY1,RN1,RN2,ZTXX,ZTYY)
C       SUPERIMPOSE P AND SV TRACTIONS
        ZLOAD(J-1)=ZLOAD(J-1)+ZTXX
        ZLOAD(J)  =ZLOAD(J)+ZTYY
C-------------------------------------------------------
C       RADIAL,HOOP AND SHEAR INCIDENT STRESSES IN L.T.
C-------------------------------------------------------
        J=3*NCN
C
C       TRANSFORMATION OF STRESSES FROM THE GLOBAL COORDINATE
C       SYSTEM TO THE LOCAL WITH AXES X1,Y1 NORMAL AND TANGENTIAL 
C       TO THE BOUNDARY SURFACE AT NODE POINT. THE ANGLE OF AXIS
C       X (NORMAL), WITH THE GLOBAL SYSTEM HAS COS AND SIN, RN1 AND
C       RN2 RESPECTIVELLY.
C
        CALL ZSTRLOC(ZTSXX1,ZTSYY1,ZTSXY1,RN1,RN2,
     &                 ZTSXX11,ZTSYY11,ZTSXY11)
C       SUPERIMPOSE P AND SV STRESSES
        ZLOAD1(J-2)=ZLOAD1(J-2)+ZTSXX11
        ZLOAD1(J-1)=ZLOAD1(J-1)+ZTSYY11
        ZLOAD1(J)=ZLOAD1(J)+ZTSXY11
        GO TO 36
  36   CONTINUE
        NCN=NCN+1
  41  CONTINUE
  99  CONTINUE
      RETURN
      END
C
C-----------------------------------------------------------------------
      SUBROUTINE WINPRES(XCR,YCR,ZLOAD,ZLOAD1,ZTSXX,ZTSYY,ZTSXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,
     &          NSHAP,LCRN,LBOUN,NDTYPE)
C
C   CALCULATES THE INCIDENT FIELD IN LAPLACE TRANSFORM DOMAIN, FOR THE
C   PRESSURE WAVE INSIDE A CAVITY. THE CALCULATIONS ARE
C   PERFORMED FOR ALL THE NODES OF THE MESH, AND THE OPPOSITE TRACTIONS 
C   TO THE INCIDENT ONES ARE RETURNED IN ARRAY ZLOAD WHILE THE INCIDENT
C   STRESSES IN THE ARRAY ZLOAD1. THESE TRACTIONS ZLOAD ARE REFERED
C   TO A GLOBAL COORDINATE SYSTEM AND ARE READ IN THE PROCESSING PHASE IN 
C   SUBROUTINE GENR. THE INCIDENT STRESSES ON THE PERIPHERY OF THE BOUNDARY 
C   ZLOAD1(NORMA, TANGENTIL AND SHEAR STRESSES), ARE REFERED TO A LOCAL 
C   COORDINATE SYSTEM WITH X AXIS THE NORMAL AND Y AXIS THE TANGENT TO THE 
C   PERIPHERY UNIT VECTORS, AND ARE READ IN SUBROUTINE HOOP OF PROCESSING PHASE.  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   NB2: GLOBAL NUMBER OF THE LAST NODE OF THE BOUNDARY
C   ZTSXX,ZTSYY,ZTSXY: TOTAL INCOMING STRESS WAVE (WITH THE ADDITIONAL VERTICAL
C                 STRESSES FROM UNIAXIAL STRAIN CONDITION ON THE WAVEFRONT.
C                 ON THE FREE SURFACE WE HAVE ONLY INCOMING SXX STRESSES, 
C                 BUT IT DOESN'T MUTTER, BECAUSE FINALY THEY VANISHES.) 
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C	       NODES OF DISCONTINUTY
C    LBOUN   : NUMBER OF EXAMINING BOUNDARY
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/BLKEX/IEXIT
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/FREE/NFFS,NSIMU
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &		  EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
      COMMON/PRESS/KINSI,PINSI
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1),ZLOAD(N2)
      DIMENSION ZLOAD1(N5),SPOINT(3)
      DIMENSION XY(3,2),RN(2)
      DIMENSION NREGI(5)
      DIMENSION LN(3)
      DIMENSION NSIMU(5)
      DIMENSION LCRN(8)
      DIMENSION NSHAP(NBOUN)
      DIMENSION PINSI(5)
      DIMENSION NDTYPE(N1)
      DATA SPOINT/-1.,0.,1./
      TOL=1.0D-11
C
C         TO CALCULATE THE UNIT VECTOR NORMAL TO THE SURFACE OF THE ELEMENT
C         WE TAKE THE CURRENT NODE I AND THE PREVIUS AND NEXT NODE TO HAVE
C         AN ELEMENT. FROM THIS ELEMENT WITH SHAPE FUNCTIONS WE CALCULATE
C         THE NORMAL TO THE SURFACE VECTORS AT THE NODE I(MIDDLE)
      NOD=3
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
      DO 41 I=1,NB1
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 89
        ZTSXX1=DCMPLX(0.0D0,0.0D0)
        ZTSYY1=DCMPLX(0.0D0,0.0D0)
	ZTSXY1=DCMPLX(0.0D0,0.0D0)
C       ESTABLISH A TEMPORARY QUADRATIC ELEMENT WITH MIDDLE NODE I.
        DO 51 II=1,NOD
          JCL1=I
          II1=II  
C         PREVIOUS AND NEXT NODE
          CALL COORD3(NCN,JCL1,NB0,NB1,NCOUNT,
     &                 II1,KCL,NB2,NBOUN,NSHAP,LCRN)
          XY(II,1)=XCR(KCL)
          XY(II,2)=YCR(KCL)
          LN(II)=KCL
  51    CONTINUE
C       INTERPOLATION TO FIND THE OUTWARD TO THE MATERIAL NORMAL UNIT
C       VECTOR FOR THE MIDDLE NODE (EKS=0)
        CALL SINTERP(XY,LN,RN)
C       TAKE THE OPPOSITE SIGN, BECAUSE WE WANT INWARD TO THE MATERIAL 
C       UNIT NORMAL VECTOR.
         RN1=-RN(1)
	 RN2=-RN(2)
        XCR1=XCR(NCN)
	YCR1=YCR(NCN)
C       THE INSIDE PRESSURE AT EVERY NODE, IS DIRECTED IN THE DIRECTION
C	OF THE UNIT NORMAL TO THE SURFACE VECTOR, AND IS THE SAME
C	FOR ALL THE NODES OF THE BOUNDARY (PINSI(LBOUN))
C	TRANSFORMATION OF INCIDENT STRESSES FROM UNIT OUTWARD TO
C	THE MATERIAL DIRECTION FI (WITH X AXIS)
C	TO THE GLOBAL COORDINATE SYSTEM
C	RSTE: INCIDENT AXIAL STRESS (P)
C	RNSTE:	-//-   STRESS (P), IN DIRECTION VERTICAL TO AXIS OF INCIDENCE
C	RNORME: -//-	SHEAR STRESS
        RSTE=PINSI(LBOUN)
        GO TO 88
        RNSTE=0.0D0
	RNORME=0.0D0
        KDIAK=0
        IF(DABS(RSTE).LT.TOL) THEN
          DO II=1,NBOUN
            KDIAK=1
            INBOUN=II
            RSTE=-PINSI(II)
            IF (DABS(RSTE).GT.TOL) GO TO 63
          END DO
        ENDIF
  63    CONTINUE
C       FIND THE CONFINING STRESSES AS COMPLEX, TAKING VISCOELASTIC
C	MATERIAL BEHAVIOUR
        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
          ZRSTRE1=RSTE*ZNU/(1.0D0-ZNU)   !!!! IT SHOULD BE ZRSTRE1
          RNSTE=RNSTE+ZRSTRE1
        FN1=RN(1)
        FN2=RN(2)
        IF(KDIAK.EQ.0) THEN
          FN1=-RN(1)
          FN2=-RN(2)
        ENDIF
C       TRANSFORMATION OF THE INCOMING STRESSES
C	(WITH THE ADDITIONAL VERTICAL STRESSES)
	CALL STRGLOB(RSTE,RNSTE,RNORME,FN1,FN2,SXXE,
     &	  SYYE,SXYE)
C        PLANE WAVE
C       ----------
C       CALCULATE THE TRANSFORMED STRESSES WITH DELAYS AND LAPLACE TRANFORMATION
C       ON THE NODE I, IN A GLOBAL SYSTEM
	CALL WAVINS(XCR1,YCR1,XCEN,YCEN,CA,CB,CP,WVEL,NCOUNT,ZK,
     &      SXXE,SYYE,SXYE,ZTSXX,ZTSYY,ZTSXY,ZTSXX1,ZTSYY1,ZTSXY1,
     &      KDIAK,INBOUN)
  33	CONTINUE
        J=2*NCN
C
C       CALCULATE THE EQUEVELANT TRACTIONS IN A TANGENTIAL PLANE WITH
C       INWARD TO THE MATERIAL UNIT NORMAL VECTOR.
	CALL ZTRACT(ZTSXX1,ZTSYY1,ZTSXY1,RN1,RN2,ZTXX,ZTYY)
C       SUPERIMPOSE P AND SV TRACTIONS
        ZLOAD(J-1)=ZLOAD(J-1)+ZTXX
        ZLOAD(J)  =ZLOAD(J)+ZTYY
C-------------------------------------------------------
C       RADIAL,HOOP AND SHEAR INCIDENT STRESSES IN L.T.
C-------------------------------------------------------
        J=3*NCN
C
C       TRANSFORMATION OF STRESSES FROM THE GLOBAL COORDINATE
C       SYSTEM TO THE LOCAL WITH AXES X1,Y1 NORMAL AND TANGENTIAL 
C       TO THE BOUNDARY SURFACE AT NODE POINT. THE ANGLE OF AXIS
C       X (NORMAL), WITH THE GLOBAL SYSTEM HAS COS AND SIN, RN1 AND
C       RN2 RESPECTIVELLY.
C
        CALL ZSTRLOC(ZTSXX1,ZTSYY1,ZTSXY1,RN1,RN2,
     &                 ZTSXX11,ZTSYY11,ZTSXY11)

C       ATTENTION !!!!!!!!!!!
C       SUPERIMPOSE P AND SV STRESSES
        ZLOAD1(J-2)=ZLOAD1(J-2)+ZTSXX11
        ZLOAD1(J-1)=ZLOAD1(J-1)+ZTSYY11
        ZLOAD1(J)=ZLOAD1(J)+ZTSXY11
        IF(KDIAK.EQ.0) THEN
          ZLOAD1(J-2)=DCMPLX(0.0D0,0.0D0)
          ZLOAD1(J-1)=DCMPLX(0.0D0,0.0D0)
          ZLOAD1(J)=DCMPLX(0.0D0,0.0D0)
        ENDIF
C       FOR FREE SURFACE BOUNDARY, TAKE 0 TRACTIONS-STRESSES
        IF(NREGI(LBOUN).EQ.4) THEN
          J=2*NCN
          ZLOAD(J-1)=DCMPLX(0.0D0,0.0D0)
          ZLOAD(J)  =DCMPLX(0.0D0,0.0D0)
          J=3*NCN
          ZLOAD1(J-2)=DCMPLX(0.0D0,0.0D0)
          ZLOAD1(J-1)=DCMPLX(0.0D0,0.0D0)
          ZLOAD1(J)=DCMPLX(0.0D0,0.0D0)
        ENDIF
       GO TO 89
  88    CONTINUE
C       FIND THE CONFINING STRESSES AS COMPLEX, TAKING VISCOELASTIC
C	MATERIAL BEHAVIOUR
        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
        ZAL=DCMPLX(0.0D0,0.0D0)
        ZDELAY=CDEXP(-ZAL*ZK)
        J=2*NCN
        ZLOAD(J-1)=RSTE*RN1*ZDELAY/ZK
        ZLOAD(J)=RSTE*RN2*ZDELAY/ZK
        J=3*NCN
        ZRNSTE=RSTE*ZNU/(1.0D0-ZNU)
        ZLOAD1(J-2)=RSTE*ZDELAY/ZK
        ZLOAD1(J-1)=ZRNSTE*ZDELAY/ZK
        ZLOAD1(J)=DCMPLX(0.0D0,0.0D0)
  89    CONTINUE
        NCN=NCN+1
  41  CONTINUE
  99  CONTINUE
      RETURN
      END


