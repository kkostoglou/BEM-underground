      DIMENSION NSHAP(NBOUN)
      DIMENSION PINSI(5)
      DIMENSION NDTYPE(N1)
      DIMENSION LDIR(3)
      DIMENSION TRACX(N1),TRACY(N1)
      DIMENSION KONN(N3,N4)
      DIMENSION LDIR1(N1)


      INTEGER*2 STAT,IERR


      DATA SPOINT/-1.,0.,1./
      TOL=1.0D-11
      NOD=3
      ZAL=DCMPLX(0.0D0,0.0D0)
      ZDELAY=CDEXP(-ZAL*ZK)
C     LOOP FOR ALL THE NODES
      DO 67 JCL=1,NNODE
C       FIND THE CONFINING STRESSES AS COMPLEX, TAKING VISCOELASTIC
C	MATERIAL BEHAVIOUR
        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
          IF((DABS(TRACX(JCL)).GT.TOL).OR.
     &       (DABS(TRACY(JCL)).GT.TOL))THEN
            JREF=2*(JCL-1)
C           LAPLACE TRANSFORM    P*(e**(-as)/s)*(1-e**(-cs)/cs)
C           FOR THE EXAMINING PROBLEM IS c=0.20 msec = TIM/6
            CTIM=TIM/6.0D0
            ZC=CDEXP(-CTIM*ZK)
            ZLOAD(JREF+1)=ZLOAD(JREF+1)+TRACX(JCL)*(ZDELAY/ZK)*
     &                      (1.0D0-ZC)/(CTIM*ZK)
            ZLOAD(JREF+2)=ZLOAD(JREF+2)+TRACY(JCL)*(ZDELAY/ZK)*
     &                      (1.0D0-ZC)/(CTIM*ZK)
         ENDIF
  67    CONTINUE
  99  CONTINUE
      RETURN
      END
