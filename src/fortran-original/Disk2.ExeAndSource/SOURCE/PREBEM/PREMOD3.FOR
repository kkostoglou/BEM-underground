C -----------------------------------------------------------------
      SUBROUTINE FREESURF(NDTYPE,N1,N2,NBOUN,NNODEB)
C
C     FOR THE NODES OF AN INCLUSION CASE, SET VALUE OF NDTYPE=1
C     FOR THE NODES OF A FREE SURFACE, SET VALUE OF NDTYPE=2
C     FOR THE NODES OF A SIMULATION SURFACE, SET VALUE OF NDTYPE=3
C     FOR THE NODES OF AN ENCLOSING BOUNDARY, SET VALUE OF NDTYPE=4
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      DIMENSION NDTYPE(N1)
      DIMENSION NNODEB(NBOUN)
      DIMENSION NREGI(5)
      DIMENSION NSIMU(5)
C
      CALL ICLRIRR(NDTYPE,N1)
      DO 10 L=1,NBOUN
        KDIAK=0
C       FIND IF THE NUMBER OF THE BOUNDARY L, IS IN THE ARRAY NSIMU
C       (SIMUALTION CASE)
        DO 2 K=1,NBOUN
          K1=NSIMU(K)
          IF(L.EQ.K1) KDIAK=1
   2    CONTINUE
C       COUNTER FOR THE STARTING NUMBER OF NODE OF A BOUNDARY
        IF(L.EQ.1) THEN
          NB0=1
          GO TO 54
        ENDIF
        NB0=NB0+NNODEB(L-1)
  54    NB1=NNODEB(L)
C
C       FOR THE NODES OF A FREE SURFACE BOUNDARY
        IF(NREGI(L).EQ.4) THEN
C         COUNTER FOR NODE NUMBERING
          NCN=NB0
          DO 41 I=1,NB1
            NDTYPE(NCN)=2
            NCN=NCN+1
  41      CONTINUE
        ENDIF
C       FOR THE NODES OF A SIMULATION CASE BOUNDARY
        IF(KDIAK.EQ.1) THEN
          NCN=NB0
          DO 50 I=1,NB1
            NDTYPE(NCN)=3
            NCN=NCN+1
  50      CONTINUE
        ENDIF
C
C       FOR THE NODES OF AN ENCLOSING BOUNDARY
        IF((NREGI(L).EQ.5).OR.(NREGI(L).EQ.6)) THEN
          NCN=NB0
          DO 52 I=1,NB1
            NDTYPE(NCN)=4
            NCN=NCN+1
  52      CONTINUE
        ENDIF
C
C       FOR THE NODES OF AN INCLUSION BOUNDARY
        IF(NREGI(L).EQ.2) THEN
          NCN=NB0
          DO 51 I=1,NB1
            NDTYPE(NCN)=1
            NCN=NCN+1
  51      CONTINUE
        ENDIF
  10  CONTINUE
      RETURN
      END    
