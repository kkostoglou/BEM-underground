C ----------------------------------------------------------------
      SUBROUTINE FAILMOD(SKEYW,RSIGC,RFM,RFS)
C ----------------------------------------------------------------
C  MODULE : FAIL, READS THE CONSTANTS FOR HOOK & BROWN FAILURE CRITERIA
C                SIGC : UNIAXIAL COMPRESSIVE STRENGTH
C                M,S: MATERIAL CONSTANTS (M,S)
C           THIS MODULE IS NOT NECESERY
C           DEFAULT VALUES SIGC=0.0, M=0.0, S=0.0
C ----------------------------------------------------------------
      COMMON/BLKEX/IEXIT
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      DIMENSION SUBTITL(10)
      CHARACTER SUBTITL*4
      DIMENSION SKEYW(59)
      CHARACTER SKEYW*4
C     READ THE SECOND TITLE SIGC M S
      CALL READTITL(SUBTITL,NT)
      WRITE(6,412)
  412 FORMAT('FAILURE.CRITERIA')
      K0=0
      DO 844 IK=1,NT
        IF (SUBTITL(IK).EQ.SKEYW(30)) THEN
C         READ THE RSIGC                              [RSIGC]
          CALL READER(RSIGC,IDUMMY,IREAD,1,K0)
          IF (RSIGC.LT.0.0) THEN
            WRITE(6,502)RSIGC
            IEXIT=1
          ENDIF
          WRITE(6,413)RSIGC
  413     FORMAT('SIGC...............',F12.3)
        ENDIF
        IF (SUBTITL(IK).EQ.SKEYW(31)) THEN
C         READ THE M                                   [RFM]
          CALL READER(RFM,IDUMMY,IREAD,1,K0)
          IF (RFM.LT.0.0) THEN
            WRITE(6,502)RFM
            IEXIT=1
          ENDIF
          WRITE(6,414)RFM
  414     FORMAT('M.................',F12.3)
        ENDIF
        IF (SUBTITL(IK).EQ.SKEYW(32)) THEN
C         READ THE S                                 [RFS]
          CALL READER(RFS,IDUMMY,IREAD,1,K0)
          IF (RFS.LT.0.0) THEN
            WRITE(6,502)RFS
            IEXIT=1
          ENDIF
          IF (RFS.GT.1.0) THEN
            WRITE(6,566)RFS
            IEXIT=1
          ENDIF
          WRITE(6,416)RFS
  416     FORMAT('S.................',F12.3)
        ENDIF
  844 CONTINUE
  502  FORMAT(/,10X,'  ERROR - NEGATIVE VALUE ',F12.3,
     &             ' NOT PERMITED')
  566  FORMAT(/,10X,'  ERROR - MATERIAL CONSTANT S = ',F12.3,
     &             ' MUST BE <= 1.0')
      RETURN
      END
