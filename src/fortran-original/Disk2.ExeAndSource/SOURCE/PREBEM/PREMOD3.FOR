      SUBROUTINE VALJP1(JP1,N8)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
C
C     IN THE CASE THAT THE 3 NUMBERS JP1 FOR LAPLACE TRANSFORM ARE NOT
C     GIVEN, CHECK THE VALIDITY OF STEP NUMBER AND CALCULATE AUTOMATICALLY
C     THE 3 NUMBERS JP1: RETURN VALUE
C
C           ATTENTION     !!!!!!!!!!!!!!!!!!!!!!!!!
C                         #########################
C     THE POINT THAT NEEDS MORE INVESTIGATIO IS IF
C     THE 3 NUMBERS  CAN HAVE ANY VALUE, OR THE ONE
C     OF THEM MUST BE 2. AFTER THE ANSWER TO THIS QUESTION
C     THE NUMBERS IN THE LIBRARY MUST BE AULTERED
      DIMENSION JP1(N8)
C     IN LAPLACE TRANSFORM DOMAIN IF THE 3 NUMBERS JP1 ARE NOT GIVEN,
C     THEN NSTEP MUST BE
C     THE PRODUCT OF 3 NUMBERS, FROM WHICH THE ONE IS 2,
C     AND AUTOMATICALLY GIVE THESE VALUES
C     E.G.2X1X2=4,    2X1X3=6,    2X2X2=8,   2X1X5=10    2X2X3=12,
C         2X2X4=16,   2X3X3=18,   2X2X5=20,  2X3X4=24,   2X3X5=30, 
C         2X3X6=36,   2X4X5=40,   2X4X6=48,  2X5X5=50,   2X4X7=56, 
C         2X5X6=60,   2X4X8=64,   2X5X7=70,  2X5X8=80,   2X5X9=90,
C         2X5X10=100, 2X6X9=108, 2X6X10=120, 2X7X9=126, 2X7X10=140,
C         2X8X10=160,2X9X10=180,2X10X10=200
C     THE MULTIPLIERS ARE THE VALUES FOR THE JP1 IN SUBROUTINE
C     TRIGO OF THE BEM PROGRAM E.G. FOR NSTEP=20 THEN JP1(1)=2,
C     JP1(2)=2, JP1(3)=5
C
              IF  
     & ((NSTEP.EQ.4)  .OR. (NSTEP.EQ.6)  .OR. (NSTEP.EQ.8)  .OR. 
     &  (NSTEP.EQ.10) .OR. (NSTEP.EQ.12) .OR. (NSTEP.EQ.16) .OR.
     &  (NSTEP.EQ.18) .OR. (NSTEP.EQ.20) .OR. (NSTEP.EQ.24)) 
     &     KODIK=1
        IF 
