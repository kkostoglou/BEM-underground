C ----------------------------------------------------------------------
      SUBROUTINE REFP(XCR,YCR,SXX,SYY,SXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &          ZRXX,ZRYY,ZRXY,DRSTRE,DRNSTRE,NDTYPE)
C
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS IN THE LAPLACE TRANSFORM, 
C   ON THE SURFACE OF THE GEOMETRICAL SHAPE (ANY SHAPE) 
C   SXX,SYY,SXY: INCIDENT STRESSES IN GLOBAL COORDINATE SYSTEM (WITHOUT
C                THE ADDITIONAL VERTIACAL STRESSES) 
C     ZLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     ZLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLIDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   ZRXX,ZRYY,ZRXY: RETURNED VALUES OF REFLECTED STRESSES AT EVERY NODE
C                   WITH DELAYS OF ARRIVING WAVE, IN THE GLOBAL COORDINATE 
C                   SYSTEM
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION RN(2)
      DIMENSION NREGI(5)
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &         TYPELY(5),NDIS(5)
      DIMENSION JKODE(NBNT)
      DIMENSION NSHAP(NBOUN)
      DIMENSION NSEGM(NBOUN)
      DIMENSION SEG(NBNT*7)
      DIMENSION ZRXX(N1),ZRYY(N1),ZRXY(N1)
      DIMENSION NDTYPE(N1)
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
C
      ZSRXXP=DCMPLX(0.0D0,0.0D0)
      ZSRXXSV=DCMPLX(0.0D0,0.0D0)
      ZSRYYP=DCMPLX(0.0D0,0.0D0)
      ZSRYYSV=DCMPLX(0.0D0,0.0D0)
      ZSRXYP=DCMPLX(0.0D0,0.0D0)
      ZSRXYPV=DCMPLX(0.0D0,0.0D0)
      ZSRXYSV=DCMPLX(0.0D0,0.0D0)
C
C
C     FAI: ANGLE OF AXIS OF WAVEFRONT WITH X-AXIS (0<=FAI<=PI)
C     WAI: ANGLE OF LINE OF FREE SURFACE WITH X-AXIS (0<=WAI<=PI)
C     FIND THE ANGLE WAI
C     COUNTER TO FIND THE COORDINATES OF THE NODES IN ARRAY SEG (ONLY
C     COMBOUND SHAPES)
      FAI1=FAI
      JL=0
      IBI=0
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
C     CALCULATE THE REFLECTING STRESSES
      DO 46 IB=1,NBOUN 
C       FOR COMBOUND BOUNDARY, OR STRAIGHT LINE REFLECTION FREE SURFACES
        IF((NSHAP(IB).LT.0).OR.(NSHAP(IB).EQ.4)) THEN
            J=1
            JL=JL+7*(J-1)
            IBI=IBI+1
            JKODE1=JKODE(IBI)
            NREGI1=NREGI(IB)
C           FREE SURFACE BOUNDARY
            IF(NREGI1.EQ.4) THEN
C             STRAIGHT LINE COMBOUND BOUNDARY
              NRF=0
C             STRAIGHT LINE REFLECTION FREE SURFACES
              IF(NSHAP(IB).EQ.4) NRF=1
C
C             CALCULATE THE EQUATION OF THE LINE OF THE FREE SURFACE
C                 CE*X+CF*Y-CQ=0
C             AND THE DIRECTION COSINES RN OF THE UNIT NORMAL VECTOR
              CALL SURFLINE(JKODE1,SEG,JL,RN,THN1,CE,CF,CQ,NBNT,
     &                       IB,NRF)
              RN1=RN(1)
              RN2=RN(2)
C             CHECK IF THE REFLECTION CONDITION IS FULLFILED
              CALL REFLCOND(FAI1,THN1,KREFL,KANGL)
C             ANGLES OF REFLECTION
C             CASE NOT REFLECTION CONDITIONS
              IF(KREFL.EQ.0) GO TO 49
C             ABSOLUTE VALUE IS TAKEN ( 0<=TH0<=PI/2 )
              TH0=DABS(PI-DABS(FAI1-THN1))
C             P-WAVE
C             ------
C             CALCULATE THE ANGLE TH2 (ANGLE OF REFLECTED SHEAR SV WAVE WITH
C             THE NORMAL TO THE FREE SURFACE)
C             SIN(TH2)=SIN(TH0)/RK
              RK=DSQRT(2.0D0*(1.0D0-RNU)/(1.0D0-2.0D0*RNU))
C             OR RK=C1/C2
              IF(DABS(RK).LT.TOL) RK=TOL
              SINTH2=DSIN(TH0)/RK
C             TH2 ALWAYS POSITIVE AND 0<=TH2<=PI/2
              TH2=DABS(DASIN(SINTH2))
C
C             ANGLES OF INCIDENT AND REFLECTED WAVE IN LOCAL SYSTEM WITH 
C             CENTER AT POINT B
              THEP=PI-TH0
              THANP=PI+TH0
              THANSV=PI+TH2
              IF(KANGL.EQ.2) THEN
                THEP=PI+TH0
                THANP=PI-TH0
                THANSV=PI-TH2
              ENDIF
              FN1=DCOS(FAI1)
              FN2=DSIN(FAI1)
C
C             FIND THE REFLECTED STRESSES FIELD
              CALL REFLD(THEP,THANP,THANSV,RK,DRSTRE,DRNSTRE,
     &           XBB,YBB,XDD,YDD,K,FN1,FN2,RN1,RN2,ZRAT1,ZRAT2,
     &           ZSRXXP,ZSRYYP,ZSRXYP,ZSRXXCP,ZSRYYCP,ZSRXYCP,ZK)
            ENDIF
  49      CONTINUE
        ENDIF
  46  CONTINUE
C     CASE NOT REFLECTION CONDITIONS
      IF(KREFL.EQ.0) GO TO 99
C     CASE THAT THE INCIDENT WAVE IS PARALLEL TO THE FREE SURFACE,
C     IT CANOT BE REFLECTED.
C     BUT EVEN IF THE FREE SURFACE IS TRACTION FREE, THERE IS
C     TANGENTIAL INCIDENT STRESSES  EQUAL TO THE INCIDENT(CALCULATED
C     IN SUBROUTINE WINCID)
C
      IF(KREFL.EQ.2) GO TO 99
      DO 50 I=1,NB1
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 89
        INRF1=0
        INRF2=0
        XCR1=XCR(NCN)
        YCR1=YCR(NCN)
C       FIND THE DELAY OF PATERN OF THE RAYS OF THE REFLECTED WAVE 
C           ABE AND CDE
        CALL PATP(XCR1,YCR1,CE,CF,CQ,TH0,TH2,KANGL,THN1,
     &       XCEN,YCEN,CA,CB,CP,INRF1,INRF2,ZALP,ZALSV,ZK)
C       DELAY FOR ARRIVING AT NODE NCN OF THE REFLECTED WAVE
C       P-REFLECTED WAVE
        ZDELAY1=CDEXP(-ZALP*ZK)
C       SV-REFLECTED WAVE
        ZDELAY2=CDEXP(-ZALSV*ZK)
C       FIND THE REFLECTED STRESSES FIELD
C       REFLECTED STRESSES AT EVERY NODE
C       IN LOCAL COORDINATE AXIS, WITH X AXIS OUTWORD RADIAL TO FREE 
C       SURFACE (AS UNIT VECTORS N:RADIAL, Q:TANGENT) 
C       AND ORIGIN ON THE FREE SURFACE
C       TOTAL SXX FROM P AND SV REFLECTED STRESSES, WITH DELAY
C       FOR BOUNDARY OTHER THAN THE FREE SURFACE, TAKE THE INCREASED 
C       FROM THE CONFINEMENT STRESS
        IF(NREGI(NCOUNT).NE.4) THEN
          ZSRXXP=ZSRXXCP
          ZSRYYP=ZSRYYCP
          ZSRXYP=ZSRXYCP
        ENDIF
C
C       REFLECTED STRESSES 
        ZTRXXP=ZSRXXP*ZRAT1
        ZTRXXSV=ZSRXXSV*ZRAT2
        ZTRYYP=ZSRYYP*ZRAT1
        ZTRYYSV=ZSRYYSV*ZRAT2
        ZTRXYP=ZSRXYP*ZRAT1
        ZTRXYSV=ZSRXYSV*ZRAT2
C       CASE B OR D BEHIND THE WAVEFRONT, THE CONTRIBUTION IN THE ACTUAL
C       STRESSES IS 0
        IF(INRF1.EQ.1) THEN
          ZTRXXP=DCMPLX(0.0D0,0.0D0)
          ZTRYYP=DCMPLX(0.0D0,0.0D0)
          ZTRXYP=DCMPLX(0.0D0,0.0D0)
         ENDIF
        IF(INRF2.EQ.1) THEN
          ZTRXXSV=DCMPLX(0.0D0,0.0D0)
          ZTRYYSV=DCMPLX(0.0D0,0.0D0)
          ZTRXYSV=DCMPLX(0.0D0,0.0D0)
         ENDIF
C       TOTAL REFLECTED STRESSES OF P AND SV REFLECTED WAVE, WITH DELAYS
        ZRXX1=ZTRXXP*ZDELAY1/ZK+ZTRXXSV*ZDELAY2/ZK
        ZRYY1=ZTRYYP*ZDELAY1/ZK+ZTRYYSV*ZDELAY2/ZK
        ZRXY1=ZTRXYP*ZDELAY1/ZK+ZTRXYSV*ZDELAY2/ZK
C
C       TRANSFORMATION OF THESE STRESSES BACK TO THE GLOBAL COORDINATE SYSTEM
        CALL ZSTRGLOB(ZRXX1,ZRYY1,ZRXY1,RN1,RN2,
     &                     ZRXX11,ZRYY11,ZRXY11)
C       SUPERIMPOSE P AND SV TRACTIONS
        ZRXX(NCN)=ZRXX(NCN)+ZRXX11
        ZRYY(NCN)=ZRYY(NCN)+ZRYY11
        ZRXY(NCN)=ZRXY(NCN)+ZRXY11
  89    CONTINUE
        NCN=NCN+1
  50  CONTINUE
  99  CONTINUE
      RETURN
      END
C
C ----------------------------------------------------------------------
      SUBROUTINE PATP(XCR1,YCR1,CE,CF,CQ,TH0,TH2,KANGL,THN1,
     &       XCEN,YCEN,CA,CB,CP,INRF1,INRF2,ZALP,ZALSV,ZK)
C
C     CALCULATES THE DISTANCE OF PATERN OF THE RAYS OF THE REFLECTED WAVE 
C           ABE AND CDE
C     XCR1,YCR1: COORDINATES OF THE NODE NCN IN THE GLOBAL SYSTEM
C     EQUATION OF THE LINE OF THE FREE SURFACE
C                 CE*X+CF*Y-CQ=0
C     TH0      : ANGLE OF INCIDENT AND REFLECTED P-WAVE
C     TH2      : ANGLE OF REFLECTED SV-WAVE
C     KANGL    : INDEX FOR CALCULATING THE ANGLES OF INCIDENT AND REFLECTED
C                RETURN VALUE
C                  1: TH0=TH0,     TH2=TH2
C                  2: TH0=2PI-TH0, TH2=2PI-TH2
C     THN1     : ANGLE OF X GLOBAL AXIS WITH THE UNIT NORMAL VECTOR
C     XCEN,YCEN: COORDINATES OF THE CENTER OF THE MESH (OF ALL THE BOUNDARIES)
C     CA,CB,CP : VALUES OF THE CONSTANTS OF THE EQUATION OF LINE OF WAVE FRONT
C                    CA*XCR(I)+CB*YCR(I)-CP=0
C     INRF1,INRF2: INDEX WHEN =1, THE POINTS B OR D ARE BEHIND THE 
C     WAVEFRONT (THIS ESPECIALLY HAPPENS IN CASES OF SV WAVES,
C     WITH ANGLE OF INCIDENCE NEAR THE CRITICAL ANGLE). IN THIS CASE THE
C     ACTUAL REFLECTED STRESS IS 0.
C
C     ALP      : TOTAL DELAY OF PATERN P-WAVE RAY, RETURN VALUE
C                    ABE=PWAV AB + PWAV  BE
C     ALSV     : TOTAL DELAY OF PATERN P,SV-WAVE RAY , RETURN VALUE
C                    CDE=PWAV CD + SVWAV DE 

      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      PI=3.14159265359D0
C       DISTANCE OF NODE I FROM THE LINE OF FREE SURFACE
C       POSITIVE IF NODE I AND THE ORIGIN XCR0,YCR0 ARE IN THE OPOSITE SIDE,
C       NEGATIVE, IF THEY ARE IN THE SAME SIDE
C       ALWAYS IT IS NEGATIVE
C        CH=XCR(I)*DCOS(WAI)+YCR(I)*DSIN(WAI)-CQ
C        CH=XCR1*CE+YCR1*CF-CQ
C
        CH=XCR1*CE+YCR1*CF-CQ
C       TAKE ABSOLUTE VALUE, FREE SURFACE ALWAYS ABOVE NODES
        CH=DABS(CH)
C
C       ATTENTION      0 DEGREES !!!!!!!!!!!!!!!!!!!!!!!
C       NOT PERMITED FROM THIS PROGRAM
C       DISTANCE OF NODE E FROM THE LINE OF FREE SURFACE BEL: REFLECTED P-WAVE
C                                                        DEL: REFLECTED SV-WAVE
C       IN LOCAL COORDINATE SYSTEM WITH ORIGIN AT THE ACTUAL NODE, AND 
C       AXES X',Y' PARALLEL TO N,Q  (N: UNIT VECTOR NORMAL TO FREE SURFACE
C                                   (Q: UNIT VECTOR TANGENT TO FREE SURFACE)
C       ANGLES TH0 AND TH2 IN LOCAL SYSTEM
        THT0=TH0
        THT2=TH2
        IF(KANGL.EQ.2) THEN
          THT0=2*PI-TH0
          THT2=2*PI-TH2
        ENDIF
        BEL=CH/DCOS(THT0)
        DEL=CH/DCOS(THT2)
C       COORDINATES IN LOCAL SYSTEM
        YBB1=BEL*DSIN(THT0)
        XBB1=CH
        YDD1=DEL*DSIN(THT2)
        XDD1=CH
C       XBB1,XDD1: POSITIVE FOR TH0=TH0
C                  NEGATIVE FOR TH0=2PI-TH0
C       YBB1,YDD1: ALWAYS POSITIVE
C       TRANSFORMATION OF COORDINATES FROM LOCAL SYSTEM WITH ORIGIN 
C       AT THE ACTUAL NODE AND AXES PARALLEL TO N,Q, 
C       TO A SYSTEM WITH ORIGIN AGAIN AT THE NODE AND
C       AXES PARALLEL TO AXES OF GLOBAL SYSTEM
C       POINT B
C
        WAI=THN1
        WN1=DCOS(WAI)
        WN2=DSIN(WAI)
        XBB=XBB1*WN1-YBB1*WN2
        YBB=XBB1*WN2+YBB1*WN1
C       POINT D
        XDD=XDD1*WN1-YDD1*WN2
        YDD=XDD1*WN2+YDD1*WN1
C
     
C       COORDINATES IN THE GLOBAL SYSTEM
        XBB=XCR1+XBB
        YBB=YCR1+YBB
        XDD=XCR1+XDD
        YDD=YCR1+YDD
C
C       SAVE THESE DISTANCES FOR DRAWING LATER IN SUBROUTINE RAYPLANL
        WRITE(11,*) XBB,YBB,XDD,YDD

C
C       THE DISTANCE OF THE NODE FROM THE WAVEFRONT IS TAKEN ALWAYS
C       POSSITIVE. 
C       THIS MEANS THAT THE WAVEFRONT AT TIME T=0, IS ALWAYS OUT OF THE
C       MESH, AND THIS IS TRUE, SINCE THE PROGRAM AUTOMATICALLY PUTS
C       THE WAVEFRONT OUTSIDE THE MESH (EXCEPT FOR THE BOUNDARY OF THE
C       FREE SURFACE THAT IS NOT TAKEN INTO ACCOUNT)
C       IF WE WANT THE WAVE AT T=0 INCIDE THE MESH, THEN THE DELAYS BEHIND
C       THE MESH MUST BE =0
C       DISTANCE OF POINTS B,D (ON THE LINE OF FREE SURFACE) FROM 
C       THE WAVEFRONT LINE CA*X+CB*Y-CP=0 (POSITION AT T=0)
C       POSITIVE IF NODE I AND THE ORIGIN XCR0,YCR0 ARE IN THE OPPOSITE
C       SIDE OF THE LINE, NEGATIVE IF THEY ARE IN THE SAME SIDE
        XBBG=XBB-XCEN
        YBBG=YBB-YCEN
        XDDG=XDD-XCEN
        YDDG=YDD-YCEN
C
C
        ABL=XBBG*CA+YBBG*CB-CP
        CDL=XDDG*CA+YDDG*CB-CP
C       IF ABL OR CDL IS POSSITIVE, IT MEANS THAT THE POINT B OR D IS
C       BEHIND THE WAVEFRONT (THIS IS ESPECIALLY HAPPEN IN CASE OF SV WAVES,
C       WITH ANGLE OF INCIDENCE NEAR THE CRITICAL ANGLE). IN THIS CASE THE 
C       ACTUAL REFLECTED STRESS IS 0.
        IF(ABL.GT.0.0D0) INRF1=1
        IF(CDL.GT.0.0D0) INRF2=1
C       DISTANCES ALWAYS POSSITIVE
        ABL=DABS(ABL)
        CDL=DABS(CDL)
C
        BEL=DABS(BEL)
        DEL=DABS(DEL)
C
C       VISCOELASTIC BEHAVIOR
        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
C       TOTAL DISTANCE OF THE PATERN OF RAYS
        ZALP=(ABL+BEL)/ZC1
        ZALSV=CDL/ZC1+DEL/ZC2
       RETURN
       END
C
C ----------------------------------------------------------------------
       SUBROUTINE REFLD(THEP,THANP,THANSV,RK,DRSTRE,DRNSTRE,
     &   XBB,YBB,XDD,YDD,K,FN1,FN2,RN1,RN2,ZRAT1,ZRAT2,
     &   ZSRXXP,ZSRYYP,ZSRXYP,ZSRXXCP,ZSRYYCP,ZSRXYCP,ZK)
C     CALCULATES THE REFLECTED STRESS FIELD
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY

C             FIND THE REFLECTED STRESSES FIELD
C             P-WAVE
C             ------
C             AMPLITUDE REFLECTION COEFFICIENTS FOR P-WAVE
              CALL ZREFAMP(THEP,THANP,THANSV,RK,ZRAT1,ZRAT2,ZK)
C             TRANSFORNATION OF THE INCIDENT P STRESSES FROM ANGLE
C             OF INCIDENCE FAI1 TO THE GLOBAL COORDINATE SYSTEM FIRST
C             P-WAVE (NORMAL STRESSES ONLY WITHOUT SHEAR
              TSXX1=DRSTRE
              TSYY1=DRNSTRE
              TSXY1=0.0D0
              CALL STRGLOB(TSXX1,TSYY1,TSXY1,FN1,FN2,
     &                        SXXP,SYYP,SXYP)
C
C             TRANSFORNATION OF THESE INCIDENT P STRESSES FROM THE
C             GLOBAL COORDINATE SYSTEM TO THE LOCAL SYSTEM WITH X1,X2 AXIS 
C             OUTWORD NORMAL AND TANGENTIAL UNIT VECTORS,(-RQ,RN) TO THE 
C             FREE SURFACE
C             P-WAVE 
              CALL STRLOC(SXXP,SYYP,SXYP,RN1,RN2,S11P,S22P,S12P)
C
C             STRESS REFLECTION COEFFICIENTS IN LOCAL COORDINATE SYSTEM
C             WITH AXES NORMAL AND TANGENT TO THE FREE SURFACE (UNIT VECTORS
C             N AND Q)
C
C             P-WAVE
C             ------
              CALL ZREFSTRP(THEP,THANP,THANSV,RK,
     &          ZC11P,ZC22P,ZC12P,ZC11SV,ZC22SV,ZC12SV,ZK)
              ZSRXXP=ZC11P*S11P
              ZSRXXSV=ZC11SV*S11P
              ZSRYYP=ZC22P*S22P
              ZSRYYSV=ZC22SV*S22P
              ZSRXYP=ZC12P*S12P
              ZSRXYSV=ZC12SV*S12P
C
C             FOR NODES NOT LYING ON THE FREE SURFACE, ADD THE CONFINING
C             STRESSES DUE TO THE REFLECTED P-WAVE.
C             TRANSFORMATION OF THE STRESSES SRXXP,SRYYP,SRXYP FROM THE
C             LOCAL(GLOBAL) COORDINATE SYSTEM (AXES NORMAL AND TANGENT 
C             TO THE FREE SURFACE), TO A SYSTEM WITH X AXIS THE REFLECTED 
C             P-WAVE WHICH MAKES AN ANGLE THANP
C
C
              RNT1=DCOS(THANP)
              RNT2=DSIN(THANP)
C
              CALL ZSTRLOC(ZSRXXP,ZSRYYP,ZSRXYP,RNT1,RNT2,
     &                       ZSRXXP1,ZSRYYP1,ZSRXYP1)
C
C             VISCOELASTIC BEHAVIOR
              CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
C
              ZSRXXCP=ZSRYYP1*ZNU/(1.0D0-ZNU)
              ZSRYYCP=ZSRXXP1*ZNU/(1.0D0-ZNU)
C             ZSUM OF CONFINING AND OTHER STRESSES:
              ZSRXXP1=ZSRXXP1+ZSRXXCP
              ZSRYYP1=ZSRYYP1+ZSRYYCP
C              SRXYP1=SRXYP1
C             TRANSFORMATION OF THESE TOTAL PRESSURES FROM THE DIRECTION
C             WITH ANGLE THANP, BACK TO THE LOCAL(GLOBAL)  COORDINATE SYSTEM
              CALL ZSTRGLOB(ZSRXXP1,ZSRYYP1,ZSRXYP1,RNT1,RNT2,
     &                        ZSRXXCP,ZSRYYCP,ZSRXYCP)

              RETURN
              END
C
C ----------------------------------------------------------------------
      SUBROUTINE REFSV(XCR,YCR,SXX,SYY,SXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &          ZRXX,ZRYY,ZRXY,DRNORM,NDTYPE)
C
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS IN THE LAPLACE TRANSFORM, 
C   ON THE SURFACE OF THE GEOMETRICAL SHAPE (ANY SHAPE) 
C   SXX,SYY,SXY: INCIDENT STRESSES IN GLOBAL COORDINATE SYSTEM (WITHOUT
C                THE ADDITIONAL VERTIACAL STRESSES) 
C     ZLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     ZLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLIDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   ZRXX,ZRYY,ZRXY: RETURNED VALUES OF REFLECTED STRESSES AT EVERY NODE
C                   WITH DELAYS OF ARRIVING WAVE, IN THE GLOBAL COORDINATE 
C                   SYSTEM
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION RN(2)
      DIMENSION NREGI(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &      TYPELY(5),NDIS(5)
      DIMENSION JKODE(NBNT)
      DIMENSION NSHAP(NBOUN)
      DIMENSION NSEGM(NBOUN)
      DIMENSION SEG(NBNT*7)
      DIMENSION ZRXX(N1),ZRYY(N1),ZRXY(N1)

      DIMENSION NDTYPE(N1)
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
C
      ZSRXXP=DCMPLX(0.0D0,0.0D0)
      ZSRXXSV=DCMPLX(0.0D0,0.0D0)
      ZSRYYP=DCMPLX(0.0D0,0.0D0)
      ZSRYYSV=DCMPLX(0.0D0,0.0D0)
      ZSRXYP=DCMPLX(0.0D0,0.0D0)
      ZSRXYPV=DCMPLX(0.0D0,0.0D0)
      ZSRXYSV=DCMPLX(0.0D0,0.0D0)
C
C
C          FAI: ANGLE OF AXIS OF WAVEFRONT WITH X-AXIS (0<=FAI<=PI)
C          WAI: ANGLE OF LINE OF FREE SURFACE WITH X-AXIS (0<=WAI<=PI)
C
      RK=DSQRT(2.0D0*(1.0D0-RNU)/(1.0D0-2.0D0*RNU))
C     OR RK=C1/C2
      IF(DABS(RK).LT.TOL) RK=TOL
C     FIND THE ANGLE WAI
C     COUNTER TO FIND THE COORDINATES OF THE NODES IN ARRAY SEG (ONLY
C     COMBOUND SHAPES)
      FAI1=FAI
      JL=0
      IBI=0
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
C     CALCULATE FIRST THE EQUATION OF THE LINE OF THE FREE SURFACE
C     AND THE ANGLES OF REFLECTION
      DO 46 IB=1,NBOUN 
C       FOR COMBOUND BOUNDARY
        IF((NSHAP(IB).LT.0).OR.(NSHAP(IB).EQ.4)) THEN
C          DO 49 J=1,NS
            J=1
            JL=JL+7*(J-1)
            IBI=IBI+1
            JKODE1=JKODE(IBI)
            NREGI1=NREGI(IB)
C           FREE SURFACE BOUNDARY
            IF(NREGI1.EQ.4) THEN
C             STRAIGHT LINE COMBOUND BOUNDARY
              NRF=0
C             STRAIGHT LINE REFLECTION FREE SURFACES
              IF(NSHAP(IB).EQ.4) NRF=1
C
C             CALCULATE THE EQUATION OF THE LINE OF THE FREE SURFACE
C                 CE*X+CF*Y-CQ=0
C             AND THE DIRECTION COSINES RN OF THE UNIT NORMAL VECTOR
              CALL SURFLINE(JKODE1,SEG,JL,RN,THN1,CE,CF,CQ,NBNT,
     &                       IB,NRF)
              RN1=RN(1)
              RN2=RN(2)
C             CHECK IF THE REFLECTION CONDITION IS FULLFILED
              CALL REFLCOND(FAI1,THN1,KREFL,KANGL)
C             CASE NOT REFLECTION CONDITIONS
              IF(KREFL.EQ.0) GO TO 49
C
C             ANGLES OF REFLECTION
C             ABSOLUTE VALUE IS TAKEN ( 0<=TH0<=PI/2
              TH0=DABS(PI-DABS(FAI1-THN1))
C             SV-WAVE
C             ------
C             CALCULATE THE ANGLE TH1 (ANGLE OF REFLECTED SHEAR SV WAVE WITH
C             THE NORMAL TO THE FREE SURFACE)
C             SIN(TH2)=SIN(TH0)/RK
              TH2=TH0
              RK=DSQRT(2.0D0*(1.0D0-RNU)/(1.0D0-2.0D0*RNU))
              IF(DABS(RK).LT.TOL) RK=TOL
              SINTH1=RK*DSIN(TH0)
C             CASE TH0>=THCR THEN SINTH1>1. BUT THE REFLECTED P-WAVE 
C             IS PARALLEL TO THE FREE SURFACE, SO TH1=PI/2
              IF(SINTH1.GT.1.0D0) THEN 
                TH1=PI/2.0D0
                GO TO 69
              ENDIF
C             TH1 ALWAYS POSITIVE AND 0<=TH1<=PI/2
              TH1=DABS(DASIN(SINTH1))
  69          CONTINUE
C
C             ANGLES OF INCIDENT AND REFLECTED WAVE IN LOCAL SYSTEM WITH 
C             CENTER AT POINT B
              THEP=PI-TH0
              THANP=PI+TH1
              THANSV=PI+TH0
C             CRITICAL ANGLE OF INCIDENT FOR SV WAVE
              IF(DABS(RK).LT.TOL) RK=TOL
              GASIN=DASIN(1.0D0/RK)
              THCR=PI-GASIN
              IF(KANGL.EQ.2) THEN
                THEP=PI+TH0
                THANP=PI-TH1
                THANSV=PI-TH0
                THCR=PI+GASIN
              ENDIF
              FN1=DCOS(FAI1)
              FN2=DSIN(FAI1)
C
C             FIND THE REFLECTED STRESSES FIELD
              CALL REFLDSV(THEP,THANP,THANSV,THCR,RK,DRNORM,
     &          XBB,YBB,XDD,YDD,K,FN1,FN2,RN1,RN2,ZRAT1,ZRAT2,
     &          ZSRXXP,ZSRYYP,ZSRXYP,ZSRXXCP,ZSRYYCP,ZSRXYCP,ZK,KANGL)

            ENDIF
  49      CONTINUE
        ENDIF
  46  CONTINUE
C     CASE NOT REFLECTION CONDITIONS
      IF(KREFL.EQ.0) GO TO 99
C     CASE THAT THE INCIDENT WAVE IS PARALLEL TO THE FREE SURFACE,
C     IT CANOT BE REFLECTED.
C     BUT EVEN IF THE FREE SURFACE IS TRACTION FREE, THERE IS
C     TANGENTIAL INCIDENT STRESSES  EQUAL TO THE INCIDENT(CALCULATED
C     IN SUBROUTINE WINCID)
C
      IF(KREFL.EQ.2) GO TO 99
      DO 50 I=1,NB1
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 89
        INRF1=0
        INRF2=0
        XCR1=XCR(NCN)
        YCR1=YCR(NCN)
C       FIND THE DELAY OF PATERN OF THE RAYS OF THE REFLECTED WAVE 
C           ABE AND CDC
        CALL PATSV(XCR1,YCR1,CE,CF,CQ,TH0,TH1,KANGL,THN1,
     &       XCEN,YCEN,CA,CB,CP,INRF1,INRF2,ZALP,ZALSV,ZK)
C       DELAY FOR ARRIVING AT NODE NCN OF THE REFLECTED WAVE
C       P-REFLECTED WAVE
        ZDELAY1=CDEXP(-ZALP*ZK)
C       SV-REFLECTED WAVE
        ZDELAY2=CDEXP(-ZALSV*ZK)
C       FIND THE REFLECTED STRESSES FIELD
C       REFLECTED STRESSES AT EVERY NODE
C       IN LOCAL COORDINATE AXIS, WITH X AXIS OUTWORD RADIAL TO FREE 
C       SURFACE (AS UNIT VECTORS N:RADIAL, Q:TANGENT) 
C       AND ORIGIN ON THE FREE SURFACE
C       TOTAL SXX FROM P AND SV REFLECTED STRESSES, WITH DELAY
C       FOR BOUNDARY OTHER THAN THE FREE SURFACE, TAKE THE INCREASED 
C       FROM THE CONFINEMENT STRESSES
        IF(NREGI(NCOUNT).NE.4) THEN
          ZSRXXP=ZSRXXCP
          ZSRYYP=ZSRYYCP
          ZSRXYP=ZSRXYCP
        ENDIF
C
C       REFLECTED STRESSES 
C           TRIIP =SRIIP*A1/A0 =SRIIP*RAT1
C           TRIISV=SRIISV*A2/A0=SRIISV*RAT2
        ZTRXXP=ZSRXXP*ZRAT1
        ZTRXXSV=ZSRXXSV*ZRAT2
        ZTRYYP=ZSRYYP*ZRAT1
        ZTRYYSV=ZSRYYSV*ZRAT2
        ZTRXYP=ZSRXYP*ZRAT1
        ZTRXYSV=ZSRXYSV*ZRAT2
C       CASE B OR D BEHIND THE WAVEFRONT, THE CONTRIBUTION IN THE ACTUAL
C       STRESSES IS 0
        IF(INRF1.EQ.1) THEN
          ZTRXXP=DCMPLX(0.0D0,0.0D0)
          ZTRYYP=DCMPLX(0.0D0,0.0D0)
          ZTRXYP=DCMPLX(0.0D0,0.0D0)
        ENDIF
        IF(INRF2.EQ.2) THEN
          ZTRXXSV=DCMPLX(0.0D0,0.0D0)
          ZTRYYSV=DCMPLX(0.0D0,0.0D0)
          ZTRXYSV=DCMPLX(0.0D0,0.0D0)
        ENDIF
C       TOTAL REFLECTED STRESSES OF P AND SV REFLECTED
        ZRXX1=ZTRXXP*ZDELAY1/ZK+ZTRXXSV*ZDELAY2/ZK
        ZRYY1=ZTRYYP*ZDELAY1/ZK+ZTRYYSV*ZDELAY2/ZK
        ZRXY1=ZTRXYP*ZDELAY1/ZK+ZTRXYSV*ZDELAY2/ZK
C
C       TRANSFORMATION OF THESE STRESSES BACK TO THE GLOBAL COORDINATE SYSTEM
        CALL ZSTRGLOB(ZRXX1,ZRYY1,ZRXY1,RN1,RN2,
     &                    ZRXX11,ZRYY11,ZRXY11)
C       SUPERIMPOSE P AND SV TRACTIONS
        ZRXX(NCN)=ZRXX(NCN)+ZRXX11
        ZRYY(NCN)=ZRYY(NCN)+ZRYY11
        ZRXY(NCN)=ZRXY(NCN)+ZRXY11

  89    CONTINUE
        NCN=NCN+1
  50  CONTINUE
  99  CONTINUE
      RETURN
      END
