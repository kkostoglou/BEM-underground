      SUBROUTINE WAVINS(XCR1,YCR1,XCEN,YCEN,CA,CB,CP,WVEL,NCOUNT,ZK,
     &      SXX,SYY,SXY,ZTSXX,ZTSYY,ZTSXY,ZTSXX1,ZTSYY1,ZTSXY1,
     &      KDIAK,INBOUN)
C
C     CALCULATES THE TRANSFORMED STRESSES ON A NODE, IN A GLOBAL SYSTEM
C     (DELAYS AND LAPLACE TRANSFORMATION), FOR THE CASE OF A PRESSURE
C     WAVE INSIDE THE BOUNDARY.
C     XCR1,YCR1 : COORDINATES OF THE NODE
C     XCEN,YCEN : COORDINATES OF THE CENTER OF THE MESH (OF ALL THE BOUNDARIES)
C     EQUATION OF LINE OF WAVEFRONT 
C           CA=COS(FAI), CB=SIN(FAI)
C           CA*XCR(I)+CB*YCR(I)-CP=0
C     WAVEL     : SEISMIC WAVE VELOCITY
C
C     KDIAK: 0: THE CURRENT BOUNDARY IS UNDER INTERNAL PRESSURE
C            1:       -//-         IS NOT     -//-
C     INBOUN: NUMBER OF THE BOUNDARY THAT IS UNDER INTARNAL PRESSURE
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION NREGI(5),NSIMU(5)

      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &         TYPELY(5),NDIS(5)


C
C     TOLERANCE 
      TOL=1.0E-9
C     COORDINATES IN SYSTEM WITH ORIGIN THE GLOBAL CENTER OF ALL
C     THE BOUNDARIES
      XCG=XCR1-XCEN
      YCG=YCR1-YCEN
C     VISCOELASTIC BEHAVIOR
       CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
C     CASE OF NOT INSIDE PRESSURE IN THE CURRENT BOUNDARY
      IF(KDIAK.EQ.1) THEN
C       DISTANCE OF THE NODES OF THE CURRENT BOUNDARY FROM THE NODES OF
C       THE BOUNDARY UNDER PRESSURE
C       ATTENTION !!!!!!  THE BOUNDARY UNDER INTERNAL PRESSURE IS SUPPOSED
C                         TO BE CIRCULAR
        CDP=DSQRT((XCR1-XCR0(INBOUN))**2+(YCR1-YCR0(INBOUN))**2)
C       THE PRESSURE AT t=0 IS APPLIED ON THE BOUNDARY, SO
        CDP=CDP-RAD(INBOUN)
        AL=CDP/WVEL
        WVC1=WVEL-C1
        WVC2=WVEL-C2
C       CASE OF P WAVE
        IF(DABS(WVC1).LT.TOL) ZAL=CDP/ZC1
C       CASE OF SV WAVE
        IF(DABS(WVC2).LT.TOL) ZAL=CDP/ZC2
        GO TO 66
      ENDIF
      ZAL=DCMPLX(0.0D0,0.0D0)
  66  CONTINUE
      ZDELAY=CDEXP(-ZAL*ZK)
C     FOR FREE SURFACE TAKE THE REDUCED STRESSES SXX,SYY,SXY
C     INSTEAD OF HAVING THE SUM OF INCIDENT AND REFLECTED
C     STRESSES 0. THIS IS TEMPORALY FOR CHECK AND CAN BE REMOVED
C     BY SETTING IN DATALAP TRACTIONS ON FREE SURFACE 0
CC     CASE OF NFFS=1, CALCULATION OF THE FREE FIELD WITH REFLECTION FORMS
C      IF(NFFS.EQ.1) THEN
C     FOR ALL THE CASES
      ZTSXX1=SXX*ZDELAY/ZK
      ZTSYY1=SYY*ZDELAY/ZK
      ZTSXY1=SXY*ZDELAY/ZK

      RETURN
      END
