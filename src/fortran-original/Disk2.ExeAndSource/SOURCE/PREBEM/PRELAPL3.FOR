      SUBROUTINE EXPLMOR(XI,YI,ZRSTE,ZRNSTE,ZRNORME,ZSXXE,ZSYYE,
     &         ZSXYE,ZTSXXE,ZTSYYE,ZTSXYE)
C     CALCULATES IN THE LAPLACE TRANSFORMED DOMAIN, THE STRESSES AT
C     A NODE OF THE MESH, DUE TO A POINT
C     EXPLOSION SOURCE, IN THE GLOBAL COORDINATE SYSTEM
C     XI,YI:COORDINATES OF NODE I
C     SXXE,SYYE,SXYE: STRESSES AT NODE I, IN GLOBAL COORDINATE SYSTEM
C                     WITHOUT THE ADDITIONAL CONFINING STRESSES
C                     RETURN VALUE
C     TSXXE,TSYYE,TSXYE: STRESSES AT NODE I, IN GLOBAL COORDINATE SYSTEM
C                     WITH THE ADDITIONAL CONFINING STRESSES
C                     RETURN VALUE
C     RSTE   : INCOMING STRESSES IN THE DIRECTION OF RAYS
C     RNSTE  : INCOMING STRESSES IN THE DIRECTION NORMAL TO THE RAYS(HERE=0)
C     RNORME : INCOMING SHEAR STRESSES (HERE =0)
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
C     TOLERANCE 
      TOL=1.0E-11
      PI=3.14159265359D0
C     PEAK PRESSURE
      XE=EXPLX
      YE=EXPLY
C
      ZTRSTE=ZRSTE
C     FIND THE STRESS S*N/(1-N) IN THE NORMAL DIRECTION
C     VISCOELASTIC BEHAVIOR
      CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
C
      ZTRNSTE=ZTRSTE*ZNU/(1.0D0-ZNU)
C     SHEAR STRESS IN THE INCOMING DIRECTION
      ZTRNORME=ZRNORME
      X1=XI-XE
      Y1=YI-YE
      IF(DABS(X1).LT.TOL) X1=TOL
      FI=DATAN2(Y1,X1)
      IF(FI.LT.0.0D0) FI=2.0D0*PI+FI
C     TRANSFORMATION OF INCIDENT STRESSES FROM DIRECTION FI (WITH X AXIS)
C     TO THE GLOBAL COORDINATE SYSTEM
C     ZRSTE: INCIDENT AXIAL STRESS (P)
C     ZRNSTE:  -//-   STRESS (P), IN DIRECTION VERTICAL TO AXIS OF INCIDENCE
C     ZRNORME: -//-   SHEAR STRESS
      FN1=DCOS(FI)
      FN2=DSIN(FI)
C     TRANSFORMATION OF THE INCOMING STRESSES ONLY
C     (WITHOUT THE ADDITIONAL VERTICAL STRESSES)
      CALL ZSTRGLOB(ZRSTE,ZRNSTE,ZRNORME,FN1,FN2,ZSXXE,ZSYYE,
     &            ZSXYE)
C     TRANSFORMATION OF THE INCOMING STRESSES 
C     (WITH THE ADDITIONAL VERTICAL STRESSES)
      CALL ZSTRGLOB(ZTRSTE,ZTRNSTE,ZTRNORME,FN1,FN2,ZTSXXE,
     &    ZTSYYE,ZTSXYE)
      RETURN
      END
