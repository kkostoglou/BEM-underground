C
C ----------------------------------------------------------------------
      SUBROUTINE REFEXP(XCR,YCR,SXX,SYY,SXY,WVEL,
     &   N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,JKODE,NSHAP,
     &   NBOUN,NSEGM,SEG,NBNT,
     &   XCEN,YCEN,ZRXX,ZRYY,ZRXY,TH0,TH3,TH4,K,KEXPL,NDTYPE)
C
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS IN THE LAPLACE TRANSFORM, 
C   ON THE SURFACE OF THE GEOMETRICAL SHAPE (ANY SHAPE) 
C   SXX,SYY,SXY: INCIDENT STRESSES IN GLOBAL COORDINATE SYSTEM (WITHOUT
C                THE ADDITIONAL VERTIACAL STRESSES) 
C     ZLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     ZLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLIDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   ZRXX,ZRYY,ZRXY: RETURNED VALUES OF REFLECTED STRESSES AT EVERY NODE
C                   WITH DELAYS OF ARRIVING WAVE, IN THE GLOBAL COORDINATE 
C                   SYSTEM
C   KEXPL=1: THE LOADS ARE FROM EXPLOSION POINT
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
      COMMON/BLKEX/IEXIT
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION RN(2)
      DIMENSION NREGI(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &     TYPELY(5),NDIS(5)
      DIMENSION JKODE(NBNT)
      DIMENSION NSHAP(NBOUN)
      DIMENSION NSEGM(NBOUN)
      DIMENSION SEG(NBNT*7)
      DIMENSION ZRXX(N1),ZRYY(N1),ZRXY(N1)
      DIMENSION NDTYPE(N1)
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
      ZSRXXP=DCMPLX(0.0D0,0.0D0)
      ZSRXXSV=DCMPLX(0.0D0,0.0D0)
      ZSRYYP=DCMPLX(0.0D0,0.0D0)
      ZSRYYSV=DCMPLX(0.0D0,0.0D0)
      ZSRXYP=DCMPLX(0.0D0,0.0D0)
      ZSRXYPV=DCMPLX(0.0D0,0.0D0)
C
C     WAI: ANGLE OF LINE OF FREE SURFACE WITH X-AXIS (0<=WAI<=PI)
C
      RK=DSQRT(2.0D0*(1.0D0-RNU)/(1.0D0-2.0D0*RNU))
C     OR RK=C1/C2
      IF(DABS(RK).LT.TOL) RK=TOL
C     CALCULATE THE EQUATION OF THE LINE OF THE FREE SURFACE
C             CE*X+CF*Y-CQ=0
C     AND THE DIRECTION COSINES RN OF THE UNIT NORMAL VECTOR
C     COUNTER TO FIND THE COORDINATES OF THE NODES IN ARRAY SEG (ONLY
C     COMBOUND SHAPES)
      JL=0
      IBI=0
C     LOOP FOR ALL THE BOUNDARIES
      DO 15 IB=1,NBOUN 
C       FOR COMBOUND BOUNDARY
        IF((NSHAP(IB).LT.0).OR.(NSHAP(IB).EQ.4)) THEN
C         ATTENTION
C         ********** RESTRICTION OF THE PROGRAM *************
C         THE PROGRAM ACCEPTS ONLY ONE LINE FREE SURFACE(SO NS=1)
C         NS=NSEGM(IB)
          J=1
          JL=JL+7*(J-1)
          IBI=IBI+1
          JKODE1=JKODE(IBI)
          NREGI1=NREGI(IB)
C         FREE SURFACE BOUNDARY
          IF(NREGI1.EQ.4) THEN
C             STRAIGHT LINE COMBOUND BOUNDARY
              NRF=0
C             STRAIGHT LINE REFLECTION FREE SURFACES
              IF(NSHAP(IB).EQ.4) NRF=1
C
C           CALCULATE THE EQUATION OF THE LINE OF THE FREE SURFACE
C                   CE*X+CF*Y-CQ=0
C           AND THE DIRECTION COSINES RN OF THE UNIT NORMAL VECTOR
            CALL SURFLINE(JKODE1,SEG,JL,RN,THN1,CE,CF,CQ,NBNT,
     &                       IB,NRF)
            RN1=RN(1)
            RN2=RN(2)
C           EXAMINE THE REFLECTION CONDITIONS, AND CALCULATE THE
C           DISTANCE CHA (ABSOLUTE VALUE) OF EXPLOSION POINT A FROM THE 
C           LINE OF FREE SURFACE
            CALL REFCONEX(CE,CF,CQ,KREFL,CHA)
            IF(IEXIT.EQ.1) GO TO 99        
C           CASE NOT REFLECTION CONDITIONS
            IF(KREFL.EQ.0) GO TO 99
          ENDIF
        ENDIF
  15  CONTINUE
C     CASE NOT REFLECTION CONDITIONS
      IF(KREFL.EQ.0) GO TO 99
C     CASE THAT THE INCIDENT WAVE IS PARALLEL TO THE FREE SURFACE,
C     IT CANOT BE REFLECTED.
C     BUT EVEN IF THE FREE SURFACE IS TRACTION FREE, THERE IS
C     TANGENTIAL INCIDENT STRESSES  EQUAL TO THE INCIDENT(CALCULATED
C     IN SUBROUTINE WINCID)
C
      IF(KREFL.EQ.2) GO TO 99
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
C     LOOP FOR ALL THE NODES OF THE BOUNDARY
      DO 50 I=1,NB1
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 89
        XCR1=XCR(NCN)
        YCR1=YCR(NCN)
        CALL PATEXP(XCR1,YCR1,CE,CF,CQ,CHA,TH00,TH33,TH44,THN1,RK,
     &    BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,INRF1,INRF2,
     &    ZALP,ZALSV,FAI1,FAI2,XBB,YBB,XDD,YDD,KANGL,ZK)
C       FIND THE REFLECTED STRESSES FIELD FOR POINT B
        THEP=BTHEP
        THANP=BTHANP
        THANSV=BTHANSV
        XBD=XBB
        YBD=YBB
        FN1=DCOS(FAI1)
        FN2=DSIN(FAI1)
        KPS=1
        CALL REFLDEX(THEP,THANP,THANSV,RK,XBD,YBD,K,
     &   FN1,FN2,RN1,RN2,ZRAT1,ZRAT2,ZSRXXP,ZSRYYP,ZSRXYP,
     &   ZSRXXCP,ZSRYYCP,ZSRXYCP,ZK,KPS)
        IF(IEXIT.EQ.1) GO TO 99
        ZBRAT1=ZRAT1
        ZBRAT2=ZRAT2
        ZBSRXXP=ZSRXXP
        ZBSRYYP=ZSRYYP
        ZBSRXYP=ZSRXYP
        ZBSRXXCP=ZSRXXCP
        ZBSRYYCP=ZSRYYCP
        ZBSRXYCP=ZSRXYCP
C       FIND THE REFLECTED STRESSES FIELD FOR POINT D
        THEP=DTHEP
        THANP=DTHANP
        THANSV=DTHANSV
        XBD=XDD
        YBD=YDD
        FN1=DCOS(FAI2)
        FN2=DSIN(FAI2)
        KPS=1
        CALL REFLDEX(THEP,THANP,THANSV,RK,XBD,YBD,K,
     &   FN1,FN2,RN1,RN2,ZRAT1,ZRAT2,ZSRXXP,ZSRYYP,ZSRXYP,
     &   ZSRXXCP,ZSRYYCP,ZSRXYCP,ZK,KPS)
        IF(IEXIT.EQ.1) GO TO 99
        ZDRAT1=ZRAT1
        ZDRAT2=ZRAT2
        ZDSRXXP=ZSRXXP
        ZDSRYYP=ZSRYYP
        ZDSRXYP=ZSRXYP
        ZDSRXXCP=ZSRXXCP
        ZDSRYYCP=ZSRYYCP
        ZDSRXYCP=ZSRXYCP
C       DELAY FOR ARRIVING AT NODE NCN OF THE REFLECTED WAVE
C       P-REFLECTED WAVE
        ZDELAY1=CDEXP(-ZALP*ZK)
C       SV-REFLECTED WAVE
        ZDELAY2=CDEXP(-ZALSV*ZK)
C
C       FIND THE REFLECTED STRESSES FIELD
C       REFLECTED STRESSES AT EVERY NODE
C       IN LOCAL COORDINATE AXIS, WITH X AXIS OUTWORD RADIAL TO FREE 
C       SURFACE (AS UNIT VECTORS N:RADIAL, Q:TANGENT) 
C       AND ORIGIN ON THE FREE SURFACE
C       TOTAL SXX FROM P AND SV REFLECTED STRESSES, WITH DELAY
C       FOR BOUNDARY OTHER THAN THE FREE SURFACE, TAKE THE INCREASED 
C       FROM THE CONFINEMENT STRESSES
        IF(NREGI(NCOUNT).NE.4) THEN
C         POINT B
          ZBSRXXP=ZBSRXXCP
          ZBSRYYP=ZBSRYYCP
          ZBSRXYP=ZBSRXYCP
C         POINT D
          ZDSRXXP=ZDSRXXCP
          ZDSRYYP=ZDSRYYCP
          ZDSRXYP=ZSRXYCP
        ENDIF
C
C       REFLECTED STRESSES 
C       POINT B
        ZBTRXXP=ZBSRXXP*ZBRAT1
        ZBTRXXSV=ZBSRXXSV*ZBRAT2
        ZBTRYYP=ZBSRYYP*ZBRAT1
        ZBTRYYSV=ZBSRYYSV*ZBRAT2
        ZBTRXYP=ZBSRXYP*ZBRAT1
        ZBTRXYSV=ZBSRXYSV*ZBRAT2
C       POINT D
        ZDTRXXP=ZDSRXXP*ZDRAT1
        ZDTRXXSV=ZDSRXXSV*ZDRAT2
        ZDTRYYP=ZDSRYYP*ZDRAT1
        ZDTRYYSV=ZDSRYYSV*ZDRAT2
        ZDTRXYP=ZDSRXYP*ZDRAT1
        ZDTRXYSV=ZDSRXYSV*ZDRAT2
C       CASE B OR D BEHIND THE WAVEFRONT, THE CONTRIBUTION IN THE ACTUAL
C       STRESSES IS 0
        IF(DREAL(ZALP).GT.1.0D0) THEN
C         POINT B
          ZBTRXXP=DCMPLX(0.0D0,0.0D0)
          ZBTRYYP=DCMPLX(0.0D0,0.0D0)
          ZBTRXYP=DCMPLX(0.0D0,0.0D0)
C         POINT D
          ZDTRXXP=DCMPLX(0.0D0,0.0D0)
          ZDTRYYP=DCMPLX(0.0D0,0.0D0)
          ZDTRXYP=DCMPLX(0.0D0,0.0D0)
         ENDIF
        IF(DREAL(ZALSV).EQ.1.0D0) THEN
C         POINT B
          ZBTRXXSV=DCMPLX(0.0D0,0.0D0)
          ZBTRYYSV=DCMPLX(0.0D0,0.0D0)
          ZBTRXYSV=DCMPLX(0.0D0,0.0D0)
C         POINT D
          ZDTRXXSV=DCMPLX(0.0D0,0.0D0)
          ZDTRYYSV=DCMPLX(0.0D0,0.0D0)
          ZDTRXYSV=DCMPLX(0.0D0,0.0D0)
         ENDIF
C       TOTAL REFLECTED STRESSES OF P AND SV REFLECTED WAVE, WITH DELAYS
C       AT NODE E
C     NO DECAY IN TIME
      IF(NDECAY.EQ.0) THEN
C       LAPLACE TRANSFORMATION OF THE FORCING FUNCTION
C       L[P*H(T-A)]=[P*1/S]*E**(-TA*S),     H(T-A): HEAVISIDE FUNCTION
        ZRXX1=ZBTRXXP*ZDELAY1/ZK+ZDTRXXSV*ZDELAY2/ZK
        ZRYY1=ZBTRYYP*ZDELAY1/ZK+ZDTRYYSV*ZDELAY2/ZK
        ZRXY1=ZBTRXYP*ZDELAY1/ZK+ZDTRXYSV*ZDELAY2/ZK
      ENDIF
C     NDECAY=0: NO DECAY, NDECAY=1: DECAY
C     DECAY IN TIME BY EXPRESSION E**T/TA
      IF(NDECAY.EQ.1) THEN
C       LAPLACE TRANSFORMATION OF THE FORCING FUNCTION
C       L[E**-T/TA]=[TA/(1+S*TA)]*E**(-TA*S)
        ZRXX1=(ZBTRXXP*ZALP/(1+ZK*ZALP))*ZDELAY1+
     &        (ZDTRXXSV*ZALSV/(1+ZK*ZALSV))*ZDELAY2
        ZRYY1=(ZBTRYYP*ZALP/(1+ZK*ZALP))*ZDELAY1+
     &        (ZDTRYYSV*ZALSV/(1+ZK*ZALSV))*ZDELAY2
        ZRXY1=(ZBTRXYP*ZALP/(1+ZK*ZALP))*ZDELAY1+
     &        (ZDTRXYSV*ZALSV/(1+ZK*ZALSV))*ZDELAY2
      ENDIF
C
C       TRANSFORMATION OF THESE STRESSES BACK TO THE GLOBAL COORDINATE SYSTEM
        CALL ZSTRGLOB(ZRXX1,ZRYY1,ZRXY1,RN1,RN2,
     &                     ZRXX11,ZRYY11,ZRXY11)
C       SUPERIMPOSE P AND SV TRACTIONS
        ZRXX(NCN)=ZRXX(NCN)+ZRXX11
        ZRYY(NCN)=ZRYY(NCN)+ZRYY11
        ZRXY(NCN)=ZRXY(NCN)+ZRXY11
  89    CONTINUE
        NCN=NCN+1
  50  CONTINUE
  99  CONTINUE
      RETURN
      END
C
C ----------------------------------------------------------------------
      SUBROUTINE PATEXP(XCR1,YCR1,CE,CF,CQ,CHA,TH0,TH3,TH4,THN1,RK,
     &   BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,INRF1,INRF2,
     &   ZALP,ZALSV,FAI1,FAI2,XBB,YBB,XDD,YDD,KANGL,ZK)
C
C     CALCULATES THE DISTANCE OF PATERN OF THE RAYS OF THE REFLECTED WAVE 
C           ABE AND CDE
C     XCR1,YCR1: COORDINATES OF THE NODE NCN IN THE GLOBAL SYSTEM
C     EQUATION OF THE LINE OF THE FREE SURFACE
C                 CE*X+CF*Y-CQ=0
C     CHA      : DISTANCE CHA (ABSOLUTE VALUE) OF EXPLOSION POINT A FROM THE 
C                LINE OF FREE SURFACE
C     TH1=TH0  : ANGLE OF INCIDENT P-WAVE AT POINT B
C     TH2=TH0  : ANGLE OF REFLECTED SV-WAVE AT POINT B
C     TH3      : ANGLE OF INCIDENT P-WAVE AT POINT D
C     TH4      : ANGLE OF REFLECTED SV-WAVE AT POINT D
C
C     KANGL    : INDEX FOR CALCULATING THE ANGLES OF INCIDENT AND REFLECTED
C                RETURN VALUE
C                  1: TH0=TH0,     TH2=TH2
C                  2: TH0=2PI-TH0, TH2=2PI-TH2
C     THN1     : ANGLE OF X GLOBAL AXIS WITH THE UNIT NORMAL VECTOR
C     RK       = C1/C2
C     XCEN,YCEN: COORDINATES OF THE CENTER OF THE MESH (OF ALL THE BOUNDARIES)
C     CA,CB,CP : VALUES OF THE CONSTANTS OF THE EQUATION OF LINE OF WAVE FRONT
C                    CA*XCR(I)+CB*YCR(I)-CP=0
C
C     ALP      : TOTAL DELAY OF PATERN P-WAVE RAY, RETURN VALUE
C                    ABE=PWAV AB + PWAV  BE
C     ALSV     : TOTAL DELAY OF PATERN P,SV-WAVE RAY , RETURN VALUE
C                    CDE=PWAV CD + SVWAV DE 
C     FAI1,FAI2: ANGLE OF ATTACK OF P-P, P-SV WAVE RESPECTIVELLY.
C                IT IS THE ANGLE OF X GLOBAL AXIS WITH THE TAIL OF THE WAVE 
C     XBB,YBB,XDD,YDD: COORDINATES OF B AND D POINTS IN GLOBAL COORD SYSTEM,
C                      RETURN VALUE
C     WHEN THE POINTS B OR D ARE BEHIND THE WAVEFRONT
C             ALP=2.0   ALSV=2.0
C     (THIS ESPECIALLY HAPPENS IN CASES OF SV WAVES,
C     WITH ANGLE OF INCIDENCE NEAR THE CRITICAL ANGLE). IN THIS CASE THE
C     ACTUAL REFLECTED STRESS IS 0.
C
C     DISTANCE OF NODE E FROM THE LINE OF FREE SURFACE BEL: REFLECTED P-WAVE
C                                                      DEL: REFLECTED SV-WAVE
C     IN LOCAL COORDINATE SYSTEM WITH ORIGIN AT THE ACTUAL NODE, AND 
C     AXES X',Y' PARALLEL TO N,Q  (N: UNIT VECTOR NORMAL TO FREE SURFACE
C                                 (Q: UNIT VECTOR TANGENT TO FREE SURFACE)
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
C
C     DISTANCE OF NODE E FROM THE LINE OF FREE SURFACE
C     POSITIVE IF NODE I AND THE ORIGIN XCR0,YCR0 ARE IN THE OPOSITE SIDE,
C     NEGATIVE, IF THEY ARE IN THE SAME SIDE
C     ALWAYS IT IS NEGATIVE
      CH=XCR1*CE+YCR1*CF-CQ
C     TAKE ABSOLUTE VALUE, FREE SURFACE ALWAYS ABOVE NODES
      CH=DABS(CH)
C
C     CALCULATION OF ANGLES TH1=TH2=TH0, TH3 AND TH4
      CALL REFANGEX(XCR1,YCR1,RK,CH,CHA,THT0,THT3,THT4,
     &  BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,THN1,KANGL)
        BEL=CH/DCOS(THT0)
        DEL=CH/DCOS(THT4)
C       COORDINATES IN LOCAL SYSTEM
        YBB1=BEL*DSIN(THT0)
        XBB1=CH
        YDD1=DEL*DSIN(THT4)
        XDD1=CH
C       TRANSFORMATION OF COORDINATES FROM LOCAL SYSTEM WITH ORIGIN
C       AT THE ACTUAL NODE AND AXES PARALLEL TO N,Q, 
C       TO A SYSTEM WITH ORIGIN AGAIN AT THE NODE AND
C       AXES PARALLEL TO AXES OF GLOBAL SYSTEM
C       POINT B
C        XBB=XBB1*DCOS(WAI)-YBB1*DSIN(WAI)+XCEN
C        YBB=XBB1*DSIN(WAI)+YBB1*DCOS(WAI)+YCEN
C
        WAI=THN1
        WN1=DCOS(WAI)
        WN2=DSIN(WAI)
        XBB=XBB1*WN1-YBB1*WN2
        YBB=XBB1*WN2+YBB1*WN1
C       POINT D
C        XDD=XDD1*DCOS(WAI)-YDD1*DSIN(WAI)+XCEN
C        YDD=XDD1*DSIN(WAI)+YDD1*DCOS(WAI)+YCEN
        XDD=XDD1*WN1-YDD1*WN2
        YDD=XDD1*WN2+YDD1*WN1
C
C       COORDINATES IN THE GLOBAL SYSTEM
        XBB=XCR1+XBB
        YBB=YCR1+YBB
        XDD=XCR1+XDD
        YDD=YCR1+YDD
C
C       SAVE THESE DISTANCES FOR DRAWING LATER IN SUBROUTINE RAYEXPL
        WRITE(11,*) XBB,YBB,XDD,YDD
C
C       THE DISTANCE OF THE NODE FROM THE EPLOSIVE POINT A, IS TAKEN ALWAYS
C       POSSITIVE. 
C       ************** USER'S RESPONSIBILITY ***************
C       THIS MEANS THAT THE EXPLOSIVE POINT A, IS ALWAYS OUT OF THE
C       MESH, AND THIS IS RESPONSIBILITY OF THE USER.
C       IF WE WANT THE WAVE AT T=0 INCIDE THE MESH, THEN THE DELAYS BEHIND
C       THE MESH MUST BE =0
C       DISTANCE OF POINTS B,D (ON THE LINE OF FREE SURFACE) FROM 
C       THE EXPLOSION POINT A.
        ABL=DSQRT((EXPLX-XBB)**2+(EXPLY-YBB)**2)
        ADL=DSQRT((EXPLX-XDD)**2+(EXPLY-YDD)**2)
C       DISTANCES ALWAYS POSSITIVE
        ABL=DABS(ABL)
        ADL=DABS(ADL)
C
        BEL=DABS(BEL)
        DEL=DABS(DEL)
C
C       VISCOELASTIC BEHAVIOR
        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
C
C       TOTAL DISTANCE OF THE PATERN OF RAYS
        ZALP=(ABL+BEL)/ZC1
        ZALSV=ADL/ZC1+DEL/ZC2
C       IF ABL OR ADL IS POSSITIVE, IT MEANS THAT THE POINT B OR D IS
C       BEHIND THE WAVEFRONT, GIVE ALP,ALS THE VALUE OF 2.0D0
        IF(INRF1.EQ.1) THEN ZALP=2.0D0
        IF(INRF2.EQ.1) THEN ZALSV=2.0D0
C
C      CALCULATE THE FAI1,FAI2
C      GLOBAL COORD. OF B : XBB,YBB
C      GLOBAL COORD. OF D : XDD,YDD
C      FAI1
       DIFX=EXPLX-XBB
       DIFY=EXPLY-YBB
       IF(DABS(DIFX).LT.TOL) DIFX=TOL
       FAI1=DATAN2(DIFY,DIFX)
       IF(FAI1.LT.0.0D0) FAI1=2.0D0*PI+FAI1
C      FAI2
       DIFX=EXPLX-XDD
       DIFY=EXPLY-YDD
       IF(DABS(DIFX).LT.TOL) DIFX=TOL
       FAI2=DATAN2(DIFY,DIFX)
       IF(FAI2.LT.0.0D0) FAI2=2.0D0*PI+FAI2
       RETURN
       END
C
C ----------------------------------------------------------------------
       SUBROUTINE REFLDEX(THEP,THANP,THANSV,RK,XBD,YBD,K,
     &   FN1,FN2,RN1,RN2,ZRAT1,ZRAT2,ZSRXXP,ZSRYYP,ZSRXYP,
     &   ZSRXXCP,ZSRYYCP,ZSRXYCP,ZK,KPS)
C     CALCULATES THE REFLECTED STRESS FIELD, FOR EXPLOSION POINT WAVE
C
C   KPS=1   : EXPLOSIVE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C   KPS=2   : EXPLOSIVE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/BLKEX/IEXIT
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
C     FIND THE REFLECTED STRESSES FIELD
C     P-WAVE
C     ------
C     AMPLITUDE REFLECTION COEFFICIENTS FOR P-WAVE
      CALL ZREFAMP(THEP,THANP,THANSV,RK,ZRAT1,ZRAT2,ZK)
C
C     SPECIAL CASE NOT TAKEN INTO ACCOUNT
C     STRESSES WITH OUT DECAYING
      CALL ZEXPLOSQ(XBD,YBD,ZRSTE,ZRNSTE,ZRNORME,K,0,ZK,KPS)
      IF(IEXIT.EQ.1) GO TO 99
      ZTSXX1=ZRSTE
      ZTSYY1=ZRNSTE
      ZTSXY1=DCMPLX(0.0D0,0.0D0)
C     TRANSFORMATION OF THE INCIDENT P STRESSES FROM ANGLE 
C     OF INCIDENCE FAI1 TO THE GLOBAL COORDINATE SYSTEM FIRST
C     P-WAVE (NORMAL STRESSES ONLY WITHOUT SHEAR
      CALL ZSTRGLOB(ZTSXX1,ZTSYY1,ZTSXY1,FN1,FN2,
     &       ZSXXP,ZSYYP,ZSXYP)
C
C     TRANSFORNATION OF THESE INCIDENT P STRESSES FROM THE
C     GLOBAL COORDINATE SYSTEM TO THE LOCAL SYSTEM WITH X1,X2 AXIS 
C     OUTWORD NORMAL AND TANGENTIAL UNIT VECTORS,(-RQ,RN) TO THE 
C     FREE SURFACE
C     P-WAVE 
      CALL ZSTRLOC(ZSXXP,ZSYYP,ZSXYP,RN1,RN2,ZS11P,ZS22P,ZS12P)
C
C     STRESS REFLECTION COEFFICIENTS IN LOCAL COORDINATE SYSTEM
C     WITH AXES NORMAL AND TANGENT TO THE FREE SURFACE (UNIT VECTORS
C     N AND Q)
C
C     P-WAVE
C     ------
      CALL ZREFSTRP(THEP,THANP,THANSV,RK,
     &  ZC11P,ZC22P,ZC12P,ZC11SV,ZC22SV,ZC12SV,ZK)
      ZSRXXP=ZC11P*ZS11P
      ZSRXXSV=ZC11SV*ZS11P
      ZSRYYP=ZC22P*ZS22P
      ZSRYYSV=ZC22SV*ZS22P
      ZSRXYP=ZC12P*ZS12P
      ZSRXYSV=ZC12SV*ZS12P
C
C     FOR NODES NOT LYING ON THE FREE SURFACE, ADD THE CONFINING
C     STRESSES DUE TO THE REFLECTED P-WAVE.
C     TRANSFORMATION OF THE STRESSES SRXXP,SRYYP,SRXYP FROM THE
C     LOCAL(GLOBAL) COORDINATE SYSTEM (AXES NORMAL AND TANGENT 
C     TO THE FREE SURFACE), TO A SYSTEM WITH X AXIS THE REFLECTED 
C     P-WAVE WHICH MAKES AN ANGLE THANP
C
C
      RNT1=DCOS(THANP)
      RNT2=DSIN(THANP)
C
      CALL ZSTRLOC(ZSRXXP,ZSRYYP,ZSRXYP,RNT1,RNT2,
     &  ZSRXXP1,ZSRYYP1,ZSRXYP1)
C
C     VISCOELASTIC BEHAVIOR
      CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
C
      ZSRXXCP=ZSRYYP1*ZNU/(1.0D0-ZNU)
      ZSRYYCP=ZSRXXP1*ZNU/(1.0D0-ZNU)
C     SUM OF CONFINING AND OTHER STRESSES:
      ZSRXXP1=ZSRXXP1+ZSRXXCP
      ZSRYYP1=ZSRYYP1+ZSRYYCP
C     TRANSFORMATION OF THESE TOTAL PRESSURES FROM THE DIRECTION
C     WITH ANGLE THANP, BACK TO THE LOCAL(GLOBAL)  COORDINATE SYSTEM
      CALL ZSTRGLOB(ZSRXXP1,ZSRYYP1,ZSRXYP1,RNT1,RNT2,
     &  ZSRXXCP,ZSRYYCP,ZSRXYCP)
  99  CONTINUE
      RETURN
      END
C
C------------------------------------------------------------------------
      SUBROUTINE ZEXPLOSQ(XI,YI,ZRSTE,ZRNSTE,ZRNORME,K,KDIAK,ZK,KPS)
C     CALCULATES THE STRESSES AT A NODE OF THE MESH, IN LAPLACE DOMAIN,
C     DUE TO A POINT EXPLOSION SOURCE, WITH OR WITHOUT DELAYS
C     THE DELAYS ARE INTRODUCED LATER IN SUBROUTINE DECEXPL
C     XI,YI:COORDINATES OF NODE I
C     K    : NUMBER OF CURRENT TIME STEP
C     SXXE,SYYE,SXYE: STRESSES AT NODE I, IN GLOBAL COORDINATE SYSTEM
C                     WITHOUT THE ADDITIONAL CONFINING STRESSES
C                     RETURN VALUE
C     TSXXE,TSYYE,TSXYE: STRESSES AT NODE I, IN GLOBAL COORDINATE SYSTEM
C                     WITH THE ADDITIONAL CONFINING STRESSES
C                     RETURN VALUE
C     RSTE : INCOMING STRESSES IN THE DIRECTION OF RAYS, RETURN VALUE
C     RNSTE  : INCOMING STRESSES IN THE DIRECTION NORMAL TO THE RAYS (HERE=0)
C                    RETURN VALUE
C     RNORME : INCOMING SHEAR STRESSES (HERE =0), RETURN VALUE
C
C   KPS=1   : EXPLOSIVE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C   KPS=2   : EXPLOSIVE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/BLKEX/IEXIT
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C      DIMENSION XY(3,2),RN(2)
C
C
C     TOLERANCE 
      TOL=1.0E-11
C     VISCOLASTISCITY
      CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
      ZRK=ZC1/ZC2
C     PEAK PRESSURE
      XE=EXPLX
      YE=EXPLY
      R=DSQRT((XE-XI)**2+(YE-YI)**2)
C     CASE THAT THE DISTANCE IS 0, ERROR, PRINT A MESSAGE
      IF(R.LT.TOL) THEN
        WRITE(6,566) EXPLX,EXPLY,NCN,XI,YI
        IEXIT=1
      ENDIF
      W=EXPLW
      EN=EXPLN
      EN1=EXPLN1
      B=EXPLB
      F=EXPLF
C     FOR P WAVE, MULTIPLY BY THE RATE EXPLP
      IF(KPS.EQ.1) ZC12=ZC1*EXPLP
C     FOR SV WAVE, MULTIPLY BY THE RATE EXPLSV
      IF(KPS.EQ.2) ZC12=ZC2*EXPLSV
C     CASE OF QUBIC ROOT FORMULA
      IF(NFORM.EQ.1) THEN
        ZP0=B*F*RHO*ZC12*(R/W**(1.0D0/3.0D0))**(-EN)
      ENDIF
C     CASE OF SQUARE ROOT FORMULA
      IF(NFORM.EQ.2) THEN
        ZP0=B*F*RHO*ZC12*(R/W**(1.0D0/2.0D0))**(-EN)
      ENDIF
C     CASED OF OTHER TYPE FORMULA
      IF(NFORM.EQ.3) THEN
        ZP0=B*F*W**EN/R**EN1
      ENDIF
C
      ZP=ZP0
C     THE DECAY OF THE WAVE 
C       A. IN THE ANALALYTICAL METHOD IS INSIDE THE LAPLACE TRANSFORMATION
C           (THE TRASFORMATION OF A DECAYING FUNCTION WAS TAKEN, IN 
C           SUBROUTINE DECEXPLF(S) FOR THE INCIDENT WAVE, AND IN 
C           SUBROUTINE REFEXP FOR THE REFLECTED WAVE, VALUE FOR P=1)
C           SO THE LAPLACE TRANSFORM IS P0*F(S)
C       B. IN THE NUMERICAL METHOD THE VALUES OF THE FUNCTION IN TIME DOMAIN
C           ARE NEEDED.
C     DECAY OF WAVE IN TIME
C     NDECAY=0: NO DECAY, NDECAY=1: DECAY
      IF((KDIAK.EQ.1).AND.(NDECAY.EQ.1)) THEN
C       ARRIVAL TIME
        ZTA=R/ZC12
        DT=TIM/DFLOAT(NSTEP)
        TIME1=DT*DFLOAT(K-1)
          ZTIME2=TIME1-ZTA
          IF(DREAL(ZTIME2).LT.0.0D0) THEN
            ZTIME2=DCMPLX(0.0D0,0.0D0)
            ZP=DCMPLX(0.0D0,0.0D0)
            GO TO 41
          ENDIF
        ZP=ZP0*EXP(-ZTIME2/ZTA)
  41    CONTINUE
      ENDIF
C     THE INCOMING STRESSES OF P-WAVE ARE ALWAYS COMPRESSIONAL(-)
      ZRSTE=-ZP
      ZRNSTE=DCMPLX(0.0D0,0.0D0)
      ZRNORME=DCMPLX(0.0D0,0.0D0)
      ZTRSTE=ZRSTE
C     FOR SV EXPLOSIVE WAVE
      IF(KPS.EQ.2) THEN
        ZRSTE=DCMPLX(0.0D0,0.0D0)
        ZRNORME=-ZP
      ENDIF
      TRNORME=0.0D0
  566  FORMAT(/,10X,'  ERROR - DISTANCE BETWEEN EXPLOSION POINT '
     &        /,10X,'(',F12.3,F12.3') AND NODE ',I3,' (',F12.3,F12.3,')'
     &        /,10X,' FOUND 0, NOT PERMITED. CHECK THE COORDINATES '
     &        /,10X,' OF EXPLOSION POINT IN MODULUS LOADS')
      RETURN
      END
C
