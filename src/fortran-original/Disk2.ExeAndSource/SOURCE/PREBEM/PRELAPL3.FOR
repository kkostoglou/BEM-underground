      SUBROUTINE DECEXPL(XI,YI,WVEL,RE,ZF1,ZF2,ZF3,ZK,K,KPS)
C
C     CALCULATE THE TRANSFORMED DECAYING STRESSES IN LOCAL SYSTEM (RAY X AXIS)
C
C   NODE I, CURRENT TIME STEP
C     FD1=RSTE   : INCOMING STRESS IN THE DIRECTION OF RAYS
C     FD2=RNSTE  : INCOMING STRESS IN THE DIRECTION NORMAL TO THE RAYS (HERE=0)
C     FD3=RNORME : INCOMING SHEAR STRESS (HERE =0)
C   NODE I, PREVIOUS TIME STEP
C     FB1=RSTE   : INCOMING STRESS IN THE DIRECTION OF RAYS
C     FB2=RNSTE  : INCOMING STRESS IN THE DIRECTION NORMAL TO THE RAYS (HERE=0)
C     FB3=RNORME : INCOMING SHEAR STRESS (HERE =0)
C
C   KPS=1   : EXPLOSIVE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C   KPS=2   : EXPLOSIVE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)
C
C     THE TRANSFORM STRESS FOR E.G. RSTRE IS:
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/BLKEX/IEXIT
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
      DT=TIM/DFLOAT(NSTEP)
      TIMEB=DT*DFLOAT(K+1)
      TIMED=DT*DFLOAT(K)
C     VISCOELASTIC BEHAVIOR
       CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
      IF(KPS.EQ.1) ZAL=RE/ZC1
      IF(KPS.EQ.2) ZAL=RE/ZC2
C     E**-AS
      ZDELAY=CDEXP(-ZAL*ZK)
      ZF1=DCMPLX(0.0D0,0.0D0)
      ZF2=DCMPLX(0.0D0,0.0D0)
      ZF3=DCMPLX(0.0D0,0.0D0)
C       STRESSES WITH OUT DECAYING
        CALL ZEXPLOSQ(XI,YI,ZRSTE,ZRNSTE,ZRNORME,IST,0,ZK,KPS)
C        IF(I.EQ.K) THEN
          ZFA=ZRSTE
          ZFB=ZRNSTE
          ZFC=ZRNORME
C     NDECAY=0: NO DECAY, NDECAY=1: DECAY
C     DECAY IN TIME BY EXPRESSION E**T/TA
      IF(NDECAY.EQ.1) THEN
C       LAPLACE TRANSFORMATION OF THE FORCING FUNCTION
C       L[E**-T/TA]=[TA/(1+S*TA)]*E**(-TA*S)
        ZF1=(ZFA*ZAL/(1+ZK*ZAL))*ZDELAY
        ZF2=(ZFB*ZAL/(1+ZK*ZAL))*ZDELAY
        ZF3=(ZFC*ZAL/(1+ZK*ZAL))*ZDELAY
      ENDIF
C     NO DECAY IN TIME
      IF(NDECAY.EQ.0) THEN
C       LAPLACE TRANSFORMATION OF THE FORCING FUNCTION
C       L[P*H(T-A)]=[P*1/S]*E**(-TA*S),     H(T-A): HEAVISIDE FUNCTION
        ZF1=ZFA*ZDELAY/ZK
        ZF2=ZFB*ZDELAY/ZK
        ZF3=ZFC*ZDELAY/ZK
      ENDIF


  99  CONTINUE
      RETURN
      END
C
C ----------------------------------------------------------------------
      SUBROUTINE REFEXSV(XCR,YCR,SXX,SYY,SXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,ZK,NCOUNT,
     &          JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &          ZRXX,ZRYY,ZRXY,DRNORM,NDTYPE)
C
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS OF AN EXPLOSIVE WAVE, 
C   IN THE LAPLACE TRANSFORM, ON THE SURFACE OF THE GEOMETRICAL SHAPE
C   (ANY SHAPE) 
C   SXX,SYY,SXY: INCIDENT STRESSES IN GLOBAL COORDINATE SYSTEM (WITHOUT
C                THE ADDITIONAL VERTIACAL STRESSES) 
C     ZLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     ZLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLIDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   ZRXX,ZRYY,ZRXY: RETURNED VALUES OF REFLECTED STRESSES AT EVERY NODE
C                   WITH DELAYS OF ARRIVING WAVE, IN THE GLOBAL COORDINATE 
C                   SYSTEM
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON/BLKEX/IEXIT
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION RN(2)
      DIMENSION NREGI(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &      TYPELY(5),NDIS(5)
      DIMENSION JKODE(NBNT)
      DIMENSION NSHAP(NBOUN)
      DIMENSION NSEGM(NBOUN)
      DIMENSION SEG(NBNT*7)
      DIMENSION ZRXX(N1),ZRYY(N1),ZRXY(N1)
      DIMENSION NDTYPE(N1)
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
C
      ZSRXXP=DCMPLX(0.0D0,0.0D0)
      ZSRXXSV=DCMPLX(0.0D0,0.0D0)
      ZSRYYP=DCMPLX(0.0D0,0.0D0)
      ZSRYYSV=DCMPLX(0.0D0,0.0D0)
      ZSRXYP=DCMPLX(0.0D0,0.0D0)
      ZSRXYPV=DCMPLX(0.0D0,0.0D0)                       
C
C
C          FAI: ANGLE OF AXIS OF WAVEFRONT WITH X-AXIS (0<=FAI<=PI)
C          WAI: ANGLE OF LINE OF FREE SURFACE WITH X-AXIS (0<=WAI<=PI)
C
      RK=DSQRT(2.0D0*(1.0D0-RNU)/(1.0D0-2.0D0*RNU))
C     OR RK=C1/C2
      IF(DABS(RK).LT.TOL) RK=TOL
C     FIND THE ANGLE WAI
C     COUNTER TO FIND THE COORDINATES OF THE NODES IN ARRAY SEG (ONLY
C     COMBOUND SHAPES)
      FAI1=FAI
      JL=0
      IBI=0
C     CALCULATE FIRST THE EQUATION OF THE LINE OF THE FREE SURFACE
C     AND THE ANGLES OF REFLECTION
      DO 15 IB=1,NBOUN
C       FOR COMBOUND BOUNDARY
        IF((NSHAP(IB).LT.0).OR.(NSHAP(IB).EQ.4)) THEN
C          ATTENTION
C          ********** RESTRICTION OF THE PROGRAM *************
C          THE PROGRAM ACCEPTS ONLY ONE LINE FREE SURFACE(SO NS=1)
          J=1
          JL=JL+7*(J-1)
          IBI=IBI+1
          JKODE1=JKODE(IBI)
          NREGI1=NREGI(IB)
C         FREE SURFACE BOUNDARY
          IF(NREGI1.EQ.4) THEN
C           STRAIGHT LINE COMBOUND BOUNDARY
            NRF=0
C           RAIGHT LINE REFLECTION FREE SURFACES
            IF(NSHAP(IB).EQ.4) NRF=1
C
C           CALCULATE THE EQUATION OF THE LINE OF THE FREE SURFACE
C               CE*X+CF*Y-CQ=0
C           AND THE DIRECTION COSINES RN OF THE UNIT NORMAL VECTOR
            CALL SURFLINE(JKODE1,SEG,JL,RN,THN1,CE,CF,CQ,NBNT,
     &                     IB,NRF)
            RN1=RN(1)
            RN2=RN(2)
C           EXAMINE THE REFLECTION CONDITIONS, AND CALCULATE THE
C           DISTANCE CHA (ABSOLUTE VALUE) OF EXPLOSION POINT A FROM THE 
C           LINE OF FREE SURFACE
            CALL REFCONEX(CE,CF,CQ,KREFL,CHA)
            IF(IEXIT.EQ.1) GO TO 99        
C           CASE NOT REFLECTION CONDITIONS
            IF(KREFL.EQ.0) GO TO 99
          ENDIF
        ENDIF
  15  CONTINUE

C     CASE NOT REFLECTION CONDITIONS
      IF(KREFL.EQ.0) GO TO 99
C     CASE THAT THE INCIDENT WAVE IS PARALLEL TO THE FREE SURFACE,
C     IT CANOT BE REFLECTED.
C     BUT EVEN IF THE FREE SURFACE IS TRACTION FREE, THERE IS
C     TANGENTIAL INCIDENT STRESSES  EQUAL TO THE INCIDENT(CALCULATED
C     IN SUBROUTINE WINCID)
C
      IF(KREFL.EQ.2) GO TO 99
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
C     LOOP FOR ALL THE NODES OF THE BOUNDARY
      DO 50 I=1,NB1
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 89
        XCR1=XCR(NCN)
        YCR1=YCR(NCN)
        CALL PATEXSV(XCR1,YCR1,CE,CF,CQ,CHA,TH00,TH33,TH44,THN1,RK,
     &    BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,INRF1,INRF2,
     &    ZALP,ZALSV,FAI1,FAI2,XBB,YBB,XDD,YDD,KANGL,ZK,ISRC)
C      CASE OF ANGLE GREATER THAN CRITICAL
       IF(ISRC.EQ.3) GO TO 50
C
C       FIND THE REFLECTED STRESSES FIELD FOR POINT B
        THEP=BTHEP
        THANP=BTHANP
        THANSV=BTHANSV
        XBD=XBB
        YBD=YBB
        FN1=DCOS(FAI1)
        FN2=DSIN(FAI1)
        KPS=2
        CALL REFLDEX(THEP,THANP,THANSV,RK,XBD,YBD,K,
     &   FN1,FN2,RN1,RN2,ZRAT1,ZRAT2,ZSRXXP,ZSRYYP,ZSRXYP,
     &   ZSRXXCP,ZSRYYCP,ZSRXYCP,ZK,KPS)
        IF(IEXIT.EQ.1) GO TO 99
        ZBRAT1=ZRAT1
        ZBRAT2=ZRAT2
        ZBSRXXP=ZSRXXP
        ZBSRYYP=ZSRYYP
        ZBSRXYP=ZSRXYP
        ZBSRXXCP=ZSRXXCP
        ZBSRYYCP=ZSRYYCP
        ZBSRXYCP=ZSRXYCP
C
C       FIND THE REFLECTED STRESSES FIELD FOR POINT D
        THEP=DTHEP
        THANP=DTHANP
        THANSV=DTHANSV
        XBD=XDD
        YBD=YDD
        FN1=DCOS(FAI2)
        FN2=DSIN(FAI2)
        KPS=2
        CALL REFLDEX(THEP,THANP,THANSV,RK,XBD,YBD,K,
     &   FN1,FN2,RN1,RN2,ZRAT1,ZRAT2,ZSRXXP,ZSRYYP,ZSRXYP,
     &   ZSRXXCP,ZSRYYCP,ZSRXYCP,ZK,KPS)
        IF(IEXIT.EQ.1) GO TO 99
        ZDRAT1=ZRAT1
        ZDRAT2=ZRAT2
        ZDSRXXP=ZSRXXP
        ZDSRYYP=ZSRYYP
        ZDSRXYP=ZSRXYP
        ZDSRXXCP=ZSRXXCP
        ZDSRYYCP=ZSRYYCP
        ZDSRXYCP=ZSRXYCP
C       DELAY FOR ARRIVING AT NODE NCN OF THE REFLECTED WAVE
C       P-REFLECTED WAVE
        ZDELAY1=CDEXP(-ZALP*ZK)
C       SV-REFLECTED WAVE
        ZDELAY2=CDEXP(-ZALSV*ZK)

C  43    CONTINUE
C
C       FIND THE REFLECTED STRESSES FIELD
C       REFLECTED STRESSES AT EVERY NODE
C       IN LOCAL COORDINATE AXIS, WITH X AXIS OUTWORD RADIAL TO FREE 
C       SURFACE (AS UNIT VECTORS N:RADIAL, Q:TANGENT) 
C       AND ORIGIN ON THE FREE SURFACE
C       TOTAL SXX FROM P AND SV REFLECTED STRESSES, WITH DELAY
C       FOR BOUNDARY OTHER THAN THE FREE SURFACE, TAKE THE INCREASED 
C       FROM THE CONFINEMENT STRESSES
        IF(NREGI(NCOUNT).NE.4) THEN
C         POINT B
          ZBSRXXP=ZBSRXXCP
          ZBSRYYP=ZBSRYYCP
          ZBSRXYP=ZBSRXYCP
C         POINT D
          ZDSRXXP=ZDSRXXCP
          ZDSRYYP=ZDSRYYCP
          ZDSRXYP=ZSRXYCP
        ENDIF
C       REFLECTED STRESSES
C       POINT B
        ZBTRXXP=ZBSRXXP*ZBRAT1
        ZBTRXXSV=ZBSRXXSV*ZBRAT2
        ZBTRYYP=ZBSRYYP*ZBRAT1
        ZBTRYYSV=ZBSRYYSV*ZBRAT2
        ZBTRXYP=ZBSRXYP*ZBRAT1
        ZBTRXYSV=ZBSRXYSV*ZBRAT2
C       POINT D
        ZDTRXXP=ZDSRXXP*ZDRAT1
        ZDTRXXSV=ZDSRXXSV*ZDRAT2
        ZDTRYYP=ZDSRYYP*ZDRAT1
        ZDTRYYSV=ZDSRYYSV*ZDRAT2
        ZDTRXYP=ZDSRXYP*ZDRAT1
        ZDTRXYSV=ZDSRXYSV*ZDRAT2
C       CASE B OR D BEHIND THE WAVEFRONT, THE CONTRIBUTION IN THE ACTUAL
C       STRESSES IS 0
        IF(DREAL(ZALP).GT.1.0D0) THEN
C         POINT B
          ZBTRXXP=DCMPLX(0.0D0,0.0D0)
          ZBTRYYP=DCMPLX(0.0D0,0.0D0)
          ZBTRXYP=DCMPLX(0.0D0,0.0D0)
C         POINT D
          ZDTRXXP=DCMPLX(0.0D0,0.0D0)
          ZDTRYYP=DCMPLX(0.0D0,0.0D0)
          ZDTRXYP=DCMPLX(0.0D0,0.0D0)
         ENDIF
        IF(DREAL(ZALSV).EQ.1.0D0) THEN
C         POINT B
          ZBTRXXSV=DCMPLX(0.0D0,0.0D0)
          ZBTRYYSV=DCMPLX(0.0D0,0.0D0)
          ZBTRXYSV=DCMPLX(0.0D0,0.0D0)
C         POINT D
          ZDTRXXSV=DCMPLX(0.0D0,0.0D0)
          ZDTRYYSV=DCMPLX(0.0D0,0.0D0)
          ZDTRXYSV=DCMPLX(0.0D0,0.0D0)
         ENDIF
C       TOTAL REFLECTED STRESSES OF P AND SV REFLECTED WAVE, WITH DELAYS
C       AT NODE E
C     NO DECAY IN TIME
      IF(NDECAY.EQ.0) THEN
C       LAPLACE TRANSFORMATION OF THE FORCING FUNCTION
C       L[P*H(T-A)]=[P*1/S]*E**(-TA*S),     H(T-A): HEAVISIDE FUNCTION
        ZRXX1=ZBTRXXP*ZDELAY1/ZK+ZDTRXXSV*ZDELAY2/ZK
        ZRYY1=ZBTRYYP*ZDELAY1/ZK+ZDTRYYSV*ZDELAY2/ZK
        ZRXY1=ZBTRXYP*ZDELAY1/ZK+ZDTRXYSV*ZDELAY2/ZK
      ENDIF
C     NDECAY=0: NO DECAY, NDECAY=1: DECAY
C     DECAY IN TIME BY EXPRESSION E**T/TA
      IF(NDECAY.EQ.1) THEN
C       LAPLACE TRANSFORMATION OF THE FORCING FUNCTION
C       L[E**-T/TA]=[TA/(1+S*TA)]*E**(-TA*S)
        ZRXX1=(ZBTRXXP*ZALP/(1+ZK*ZALP))*ZDELAY1+
     &        (ZDTRXXSV*ZALSV/(1+ZK*ZALSV))*ZDELAY2
        ZRYY1=(ZBTRYYP*ZALP/(1+ZK*ZALP))*ZDELAY1+
     &        (ZDTRYYSV*ZALSV/(1+ZK*ZALSV))*ZDELAY2
        ZRXY1=(ZBTRXYP*ZALP/(1+ZK*ZALP))*ZDELAY1+
     &        (ZDTRXYSV*ZALSV/(1+ZK*ZALSV))*ZDELAY2
      ENDIF
C
C       TRANSFORMATION OF THESE STRESSES BACK TO THE GLOBAL COORDINATE SYSTEM
        CALL ZSTRGLOB(ZRXX1,ZRYY1,ZRXY1,RN1,RN2,
     &                     ZRXX11,ZRYY11,ZRXY11)
C       SUPERIMPOSE P AND SV TRACTIONS
        ZRXX(NCN)=ZRXX(NCN)+ZRXX11
        ZRYY(NCN)=ZRYY(NCN)+ZRYY11
        ZRXY(NCN)=ZRXY(NCN)+ZRXY11
  89    CONTINUE
        NCN=NCN+1
  50  CONTINUE
  99  CONTINUE
      RETURN
      END
