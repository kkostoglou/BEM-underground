      SUBROUTINE WAVEXPL(XCR1,YCR1,WVEL,NCOUNT,
     &  ZTSXX1E,ZTSYY1E,ZTSXY1E,ZK,K,KPS)
C
C   KPS=1   : EXPLOSIVE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C   KPS=2   : EXPLOSIVE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)



C     &    DRSTE,DRNSTE,DRNORME,BRSTE,BRNSTE,BRNORME
C
C     CALCULATES THE TRANSFORMED STRESSES ON A NODE, IN A GLOBAL SYSTEM
C     (DELAYS AND LAPLACE TRANSFORMATION)
C     XCR1,YCR1 : COORDINATES OF THE NODE
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/BLKEX/IEXIT
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      DIMENSION NREGI(5),NSIMU(5)
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
C     DISTANCE OF NODE FROM EXPLOSION POINT
      XE=EXPLX
      YE=EXPLY
      RE=DSQRT((XE-XCR1)**2+(YE-YCR1)**2)

C     CALCULATE THE TRANSFORMED DECAYING STRESSES IN LOCAL SYSTEM (RAY X AXIS)
      CALL DECEXPL(XCR1,YCR1,WVEL,RE,ZRSTE,ZRNSTE,ZRNORME,ZK,K,KPS)
      IF(IEXIT.EQ.1) GO TO 99
C
      CALL EXPLMOR(XCR1,YCR1,ZRSTE,ZRNSTE,ZRNORME,ZSXXE,ZSYYE,ZSXYE,
     &      ZTSXXE,ZTSYYE,ZTSXYE)
C      VISCOELASTIC BEHAVIOR
       CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
      IF(KPS.EQ.1) ZAL=RE/ZC1
      IF(KPS.EQ.2) ZAL=RE/ZC2
      ZDELAY=CDEXP(-ZAL*ZK)
C
      ZTSXX1E=ZTSXXE
      ZTSYY1E=ZTSYYE
      ZTSXY1E=ZTSXYE
C     FOR FREE SURFACE TAKE THE REDUCED STRESSES SXX,SYY,SXY
C     INSTEAD OF HAVING THE SUM OF INCIDENT AND REFLECTED
C     STRESSES 0. THIS IS TEMPORALY FOR CHECK AND CAN REMOVED
C     BY SETTING IN DATALAP TRACTIONS ON FREE SURFACE 0
C     FOR ALL THE CASES
  99  CONTINUE
      RETURN
      END
