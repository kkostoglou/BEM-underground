      SUBROUTINE COORD3(NCN,NNOD,NB0,NB1,NCOUNT,
     &            KNOD,KCL,NB2,NBOUN,NSHAP,LCRN)
C
C     FOR THE NODE NNOD,
C     FINDS THE NUMBER OF THE PREVIUS,CURRENT AND NEXT NODE
C     NCN: CURRENT NODE IN THE GLOBAL MESH (FROM 1 TO NNODE)
C                 NNODE: NODES OF ALL THE MESH
C     NNOD: NUMBER OF NODE IN THE BOUNDARY (FROM 1 TO NB1), 
C                 NB1: NODES OF BOUNDARY
C     NCOUNT: NUMBER OF THE BOUNDARY
C     KNOD: 1,2 OR 3 (PREVIUS,CURRENT OR NEXT NODE)
C     KCL: RETURN REFERENCE NUMBER OF THE NODE IN THE GLOBAL MESH
C     NB1: NUMBER OF THE NODES OF THE BOUNDARY
C     NB2: GLOBAL NUMBER OF THE LAST NODE OF THE BOUNDARY
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY

      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION NREGI(5)
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &          TYPELY(5),NDIS(5)
      DIMENSION LCRN(8)
      DIMENSION NSHAP(NBOUN)

      NB11=NB1
      NB22=NB2
      KDIAK=0
C     FOR SQUARE OR RECTANGLE AND 
C     IN CASE OF DISCONTINUITY THE CORNERS HAVE BEEN DUPLICATED,  
C     SO THE REAL NUMBER OF NODES IS THE NUMBER OF TOTAL NODES 
C     MINUS 4
      IF(((NSHAP(NCOUNT).EQ.2).OR.(NSHAP(NCOUNT).EQ.3)).AND.
     &       (NDIS(NCOUNT).EQ.2)) THEN
C       TOTAL NUMBER OF THE NODES OF THE CURRENT BOUNDARY
        NB11=NB1-4
C       LAST NODE
        NB22=NB2-4
        KDIAK=1
      ENDIF
C
C     FIND THE COORDINATES OF THE PREVIUS,CURRENT AND NEXT NODE.
C     GLOBAL NUMBER OF NODE NNOD-1,NNOD,NNOD+1
      KCL=NCN+(KNOD-2)
C     FOR THE FIRST NODE 
      IF((NNOD.EQ.1).AND.(KNOD.EQ.1)) KCL=NB22
C     FOR THE LAST NODE 
      IF((NNOD.EQ.NB11).AND.(KNOD.EQ.3)) KCL=NB0

C     IN THE CASE OF OPEN SURFACES AND FOR THE FIRST (AND LAST) NODE,
C     WE USE LINEAR INTRERPOLATION, INSTEAD OF QUADRATIC

C     FREE OR OPEN SURFACES
      IF((NREGI(NCOUNT).EQ.4).OR.(NREGI(NCOUNT).EQ.3)) THEN
C       FIRST NODE
        IF(NNOD.EQ.1) THEN
C         PREVIUS NODE IS THE CURRENT NODE
          IF(KNOD.EQ.1)KCL=NCN
C         CURRENT NODE IS THE FIRST NODE
          IF(KNOD.EQ.2) THEN
            KCL=NCN
          ENDIF
C         NEXT NODE IS THE SECOND NODE
          IF(KNOD.EQ.3) THEN
            KCL=NCN+1
C            KDIAK=1
          ENDIF
        ENDIF
C       LAST NODE
        IF(NNOD.EQ.NB11) THEN

C         PREVIUS NODE IS THE CURRENT BUT ONE NODE
          IF(KNOD.EQ.1)KCL=NCN-1
C         CURRENT NODE IS THE SECOND NODE
          IF(KNOD.EQ.2) THEN
            KCL=NCN
          ENDIF
C         NEXT NODE IS THE CURRENT (LAST) NODE
          IF(KNOD.EQ.3) THEN
            KCL=NCN
          ENDIF
        ENDIF   
      ENDIF
C     FOR SQUARE OR RECTANGLE AND 
C     IN CASE OF DISCONTINUITY THE CORNERS HAVE BEEN DUPLICATED
      IF(KDIAK.EQ.1) THEN
C       CHECK TO SEE IF NCN IS A CORNER NODE (NOT THE DUPLICATED NODE)
        DO 20 I=1,4
          IF(NCN.EQ.LCRN(I)) THEN
C           NEXT NODE IS THE CURRENT (LAST) NODE
            IF(KNOD.EQ.3) THEN
              KCL=NCN
            ENDIF
         ENDIF
  20    CONTINUE
C       FOR THE DUPLICATED CORNER NODES
        DO 25 I=1,4
C         CASE THAT FOUND
          IF(NCN.EQ.LCRN(I+4)) THEN
C           PREVIUS NODE IS THE CURRENT NODE
            IF(KNOD.EQ.1)KCL=NCN
C           NEXT NODE IS THE NEXT TO THE CORNER NODE PLUS 1
            IF(KNOD.EQ.3) THEN
C              KCL=NCN
              KCL=LCRN(I)+1
            ENDIF
          ENDIF
  25    CONTINUE
C       CHECK TO SEE IF NCN HAS AS PREVIOUS NODE A DUPLICATED CORNER NODE
        DO 30 I=1,4
C         CASE THAT FOUND, THIS IS ALWAYS THE LAST NODE IN THE ELEMENT
          IF((NCN-1).EQ.LCRN(I)) THEN
C           PREVIUS NODE IS THE DUPLICATED CORNER NODE
            IF(KNOD.EQ.1) KCL=LCRN(I+4)
          ENDIF
  30    CONTINUE

      ENDIF
      RETURN
      END
