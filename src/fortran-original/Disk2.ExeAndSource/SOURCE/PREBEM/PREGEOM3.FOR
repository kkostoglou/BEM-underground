C-----------------------------------------------------------
       SUBROUTINE CORNESQ(XSQ,YSQ,ALEN)
C   CALCULATES FOR A SQUARE IN A LOCAL SYSTEM  WITH CENTER THE 
C   CENTER OF THE SQUARE THE 
C   COORDINATES OF THE 4 ORIGINS AND 4 MIDDLE POINTS OF SIDES  
C   X(1),X(3),X(5),X(7): ORIGINS
C   X(2),X(4),X(6),X(8): MIDDLE POINTS
C   FIRST NODE UPPER RIGHT CORNER
C   ANTI-CLOCKWISE
C   ALEN: LENGTH OF THE SIDE OF THE SQUARE
C
       IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
C      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XCR0,YCR0
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
       DIMENSION XSQ(8),YSQ(8)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION NREGI(5)
       PI=3.14159265359D0
       HSID=ALEN/2.0D0
       PI4=PI/4.0D0
       PI2=PI/2.0D0
C      ORIGINS OF THE SQUARE:
       DO 100 I=1,4
         K=2*(I-1)+1
C        COORDINATES WITHOUT ROTATION OR TRANSLATION OF THE AXES
         THETA=DFLOAT(K)*PI4
         XSQ(K)=HSID*DSQRT(2.0D0)*DCOS(THETA)
         YSQ(K)=HSID*DSQRT(2.0D0)*DSIN(THETA)
C        COORDINATES WITH ROTATION OR TRANSLATION OF THE AXES
  100 CONTINUE
C     MIDDLE POINTS OF THE SIDES: 
      DO 110 I=1,4
         K=2*I
C        COORDINATES WITHOUT ROTATION OR TRANSLATION OF THE AXES
         THETA=DFLOAT(K)*PI4
         XSQ(K)=HSID*DCOS(THETA)
         YSQ(K)=HSID*DSIN(THETA)
  110 CONTINUE
       RETURN
       END
