       SUBROUTINE CORNEREC(XSQ,YSQ,ALENX,ALENY)
C   CALCULATES FOR A RECTANGLE IN A LOCAL SYSTEM  WITH CENTER THE 
C   CENTER OF THE RECTANGLE THE 
C   COORDINATES OF THE 4 ORIGINS AND 4 MIDDLE POINTS OF SIDES  
C   X(1),X(3),X(5),X(7): ORIGINS
C   X(2),X(4),X(6),X(8): MIDDLE POINTS
C   ANTI-CLOCKWISE
C   ALENX,ALENY: LENGTH OF THE SIDES OF RECTANGLE
C
       IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
       DIMENSION XSQ(8),YSQ(8)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION NREGI(5)
        PI=3.14159265359D0
C       CALCULATE THE COORDINATES OF THE 4 NODES WITH RESPECT TO A
C       HALF SIDES
        HXSID=ALENX/2.0D0
        HYSID=ALENY/2.0D0
C   COORDINATES OF THE NODES IN THE TOPIC AXIS M,N, STARTING 
C   FROM THE RIGH UPPER 
C   1,3,5,7 : CORNER NODES
C   2,4,6,8 : MIDDLE NODES
C       POINT P1, RIGHT UP CORNER
        XSQ(1)=HXSID
        YSQ(1)=HYSID
C       POINT P2, MIDDLE UP NODE
        XSQ(2)=0.0
        YSQ(2)=HYSID
C       POINT P3, LEFT UP CORNER
        XSQ(3)=-HXSID
        YSQ(3)=HYSID
C       POINT P4, LEFT MIDDLE NODE
        XSQ(4)=-HXSID
        YSQ(4)=0.0
C       POINT P5, LEFT DOWN CORNER
        XSQ(5)=-HXSID
        YSQ(5)=-HYSID
C       POINT P6, MIDDLE DOWN NODE
        XSQ(6)=0.0
        YSQ(6)=-HYSID
C       POINT P7, RIGHT DOWN CORNER
        XSQ(7)=HXSID
        YSQ(7)=-HYSID
C       POINT P8, RIGHT MIDDLE NODE
        XSQ(8)=HXSID
        YSQ(8)=0.0
        RETURN 
        END
