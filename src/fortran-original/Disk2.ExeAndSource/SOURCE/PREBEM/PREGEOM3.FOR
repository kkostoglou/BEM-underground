         SUBROUTINE PRODUCT(A,B,N,DOT)
C
C   PRODUCT OF TWO VECTORS A AND B
C
        IMPLICIT REAL*8 (A-H,O-Z)
        DIMENSION A(N),B(N)
C
        DOT=0.0D0
        DO 10 I=1,N
        DOT=DOT+A(I)*B(I)
  10    CONTINUE
