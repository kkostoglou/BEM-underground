       SUBROUTINE GLOBSYS(XCR,YCR,N1,PSI,XCEN,YCEN)
C  TRANFORMS THE COORDINATES FROM THE LOCAL TO GLOBAL SYSTEM
C  TRANSLATION AND ROTATION OF THE LOCAL AXIS
C       XCR,YCR  : COORDINATES FOR TRANSFORMATION
C       PSAI     : ANGLE OF ROTATION
C       XCR0,YCR0: CENTER OF THE LOCAL SYSTEM
C
        IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION NREGI(5)
        DO 11 I=1,N1
          TEMP1=XCR(I)*DCOS(PSI)-YCR(I)*DSIN(PSI)+XCEN
          TEMP2=XCR(I)*DSIN(PSI)+YCR(I)*DCOS(PSI)+YCEN
          XCR(I)=TEMP1
          YCR(I)=TEMP2
   11   CONTINUE     
        RETURN
        END
