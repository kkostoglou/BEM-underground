         SUBROUTINE SINTERP(XY,LN,RN)
C
C       INTERPOLATION TO FIND THE NORMAL UNIT VECTOR FOR THE 
C       MIDDLE NODE OF AN ELEMENT(EKS=0), BY CALLING SUBROUTINE CSHAPE
C       XY: COORDINATES OF THE 3 NODES OF THE ELEMENT
C       LN: NUMBERS OF THE NODES OF THE MESH
C       RN: DIRECTION COSINES OF THE UNIT NORMAL VECTOR, RETURN VALUES
C
        IMPLICIT REAL*8 (A-H,O-Y)
        DIMENSION LN(3)
        DIMENSION XY(3,2),SPOINT(3),SHP(3),DSHP(3),RN(2)
C        LDIR(3),
        DATA SPOINT/-1.,0.,1./
C
        NOD=3
C
        LN1=LN(1)
        LN2=LN(2)
        LN3=LN(3)
C       INTERPOLATION IN THE MIDDLE NODE ONLY FOR QUADRATIC ELEMENTS (EKS=0)
        EKS=SPOINT(2)
C       IN THE CASE THAT THE NUMBER OF THE FIRST (OR LAST) NODE, IS THE
C       SAME WITH THE NUMBER OF THE CURRENT NODE (E.G. EDGE NODES IN 
C       OPEN SURFACES, POINTS OF DISCONTINUYTIES AT THE NODES OF A SQARE
C       OR RECATNGLE
C       INDEX FOR LINEAR INTERPOLATION
        IF(LN1.EQ.LN2) THEN
          NOD=2
C         INTERPOLATION IN THE FIRST NODE FOR LINEAR ELEMENT
          EKS=SPOINT(1)
        ENDIF
C       CASE THAT THE LAST NODE IS EQUAL WITH THE CURRENT
C       INDEX FOR LINEAR INTERPOLATION
        IF(LN2.EQ.LN3) THEN
          NOD=2
C         INTERPOLATION IN THE 2ND NODE FOR LINEAR ELEMENT
          EKS=SPOINT(3)
C         LDIR(2)=LN3  
        ENDIF
C       IF NOD=3: QUADRATIC INTERPOLATION
C          NOD=2: LINEAR       -//-
C       IN CASE OF LINEAR INTERPOLATION, TAKE THE COORDINATES OF THE 
C       TWO EDGE NODES (PREVIUS AND NEXT, NOT MIDDLE)
        IF(NOD.EQ.2) THEN 
          XY(2,1)=XY(3,1)
          XY(2,2)=XY(3,2)
        ENDIF
        CALL CSHAPE(EKS,NOD,XY,SHP,DSHP,RN,DETJ)
        RETURN
        END
C
C ----------------------------------------------------------------------
      SUBROUTINE SURFLINE(JKODE1,SEG,JL,RN,THN1,CE,CF,CQ,NBNT,
     &                     IB,NRF)

C     CALCULATES
C         A. THE EQUATION OF THE LINE OF THE FREE SURFACE 
C                CE*X+CF*Y-CQ=0
C         B. RN : THE DIRECTION COSINES OF THE UNIT NORMAL VECTOR
C         C. THN1: ANGLE OF X GLOBAL AXIS WITH THE UNIT NORMAL VECTOR
C         NRF : 0 STRAIGHT LINE COMBOUND SUSFACE
C               1 STRAIGHT LINE FREE REFLECTING SURFACE
C
C     UNIT VECTORS FOR THE MIDDLE NODE, WHICH ARE THE SAME FOR ALL THE LINE
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5),XCR0(5),YCR0(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &        TYPELY(5),NDIS(5)
      DIMENSION SEG(NBNT*7)
      DIMENSION XY(3,2),SPOINT(3),SHP(3),DSHP(3),RN(2),RQ(2)
      DATA SPOINT/-1.0D0,0.0D0,1.0D0/
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
C     STRAIGHT LINE COMBOUND SEGEMENT
      IF(JKODE1.EQ.1) THEN
C       COORDINATES OF THE ENDS OF THE LINE OF THE FREE BOUNDARY
C       START X COORD.
        RSX1=SEG(JL+1)
C       START Y COORD.
        RSY1=SEG(JL+2)
C       END X COORD.
        RSX2=SEG(JL+3)
C       END Y COORD.
        RSY2=SEG(JL+4)
      ENDIF
C     CASE OF STRAIGHT LINE FREE REFLECTING SURFACE
      IF(NRF.EQ.1) THEN
C       START X COORD.
        RSX1=XSTA(IB)
C       START Y COORD.
        RSY1=YSTA(IB)
C       END X COORD.
        RSX2=XLAS(IB)
C       END Y COORD.
        RSY2=YLAS(IB)
      ENDIF
      NOD=3
      XY(1,1)=RSX1
      XY(1,2)=RSY1
      XY(3,1)=RSX2
      XY(3,2)=RSY2
C     COOORDINATES OF THE MIDDLE OF THE LINE
      XY(2,1)=(RSX1+RSX2)/2.0D0
      XY(2,2)=(RSY1+RSY2)/2.0D0
C     INTERPOLATION FOR THE MIDDLE NODE (EKS=0)
      EKS=SPOINT(2)
      CALL CSHAPE(EKS,NOD,XY,SHP,DSHP,RN,DETJ)
C     FIND THE NORMAL AND TANGENT UNIT VECTORS FOR THE MIDDLE NODE 
C     WHICH ARE THE SAME FOR ALL THE LINE
      RQ(1)=-RN(2)
      RQ(2)=RN(1)
      RN1=RN(1)
      RN2=RN(2)
      RQ1=RQ(1)
      RQ2=RQ(2)
C
C     CALCULATE THE ANGLE THN1, OF X GLOBAL AXIS WITH THE UNIT 
C     NORMAL VECTOR
      RN11=RN1
      IF(DABS(RN11).LT.TOL)THEN
        IF (RN11.LT.0.0D0) RN11=-TOL
        IF (RN11.GT.0.0D0) RN11=TOL
        IF (RN11.EQ.0.0D0) THEN
          IF (RQ1.LT.0.0D0) THN1=PI/2.0D0
          IF (RQ1.GT.0.0D0) THN1=3.0D0*PI/2.0D0
          GO TO 34
        ENDIF
      ENDIF
      THN1=DATAN2(RN2,RN11)
  34  CONTINUE
      IF(THN1.LT.0.0D0) THN1=2.0D0*PI+THN1
C     EQUATION OF THE LINE OF THE FREE SURFACE, IN GLOBAL SYSTEM
C     PASSING THROUGH POINTS (RSX1,RSY1),(RSX2,RSY2)
C     (Y2-Y1)*X+(X1-X2)*Y-(X1Y2-Y1X2)=0
C     OR DIAG=SQRT((Y2-Y1)**2+(X2-X1)**2)
C     ((Y2-Y1)/DIAG)*X+((X2-X1)/DIAG)*Y-(X1Y2-Y1X2)/DIAG=0
C     SIN(WAI)*X+COS(WAI)*Y-CQ=0
C     CE*X+CF*Y-CQ=0
      CE=RN1
      CF=RN2
      DIAG=DSQRT((RSY2-RSY1)**2+(RSX2-RSX1)**2)
      IF(DABS(DIAG).LT.TOL) DIAG=TOL
      CQ=(RSX1*RSY2-RSY1*RSX2)/DIAG
      RETURN 
      END
