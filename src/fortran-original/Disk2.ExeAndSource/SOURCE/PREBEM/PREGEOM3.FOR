      SUBROUTINE NODECON(NNODEB,NBOUN,NONN,NONZON,NSHAP,LCRN,
     &                   N1,N4)

C
C     CREATES AN ARAY NNODE THAT CONTAINS FOR EVERY NODE 
C     THE NUMBERS OF THE PREVIOUS,CURRENT AND NEXT NODE.
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      DIMENSION NREGI(5)
      DIMENSION NNODEB(NBOUN)
      DIMENSION NONN(N1,N4)
      DIMENSION NONZON(N1,N4)
      DIMENSION LCRN(8)
      DIMENSION NSHAP(NBOUN)
      DIMENSION NSIMU(5),LDIAK(5)
C
C     LOOP FOR ALL THE BOUNDARY SHAPES
      NB0=0
      NB2=0
C     INDEX FOR THE SIMULATION BOUNDARY
      CALL ICLRIRR(LDIAK,5)
      DO 1 KK=1,5
        K1=NSIMU(KK)
        DO 2 II=1,NBOUN
          IF(II.EQ.K1) LDIAK(II)=1
  2     CONTINUE
  1   CONTINUE

      DO 61 L=1,NBOUN
C       CHECK FOR THE EXISTENCE OF A FREE SURFACE
        NFRE=0
        DO 46 I=1,NBOUN
          IF(NREGI(I).EQ.4) NFRE=1
  46    CONTINUE
        IZDIAK=0
        IF((NREGI(L).EQ.2).OR.(NREGI(L).EQ.5).OR.
     &                   (LDIAK(L).EQ.1)) IZDIAK=1
C       COUNTER FOR THE STARTING NUMBER OF NODE OF A BOUNDARY
        IF(L.EQ.1) THEN
          NB0=1
          GO TO 54
        ENDIF
        NB0=NB0+NNODEB(L-1)
   54   NB1=NNODEB(L)
        NCOUNT=L
C       NUMBER OF LAST NODE IN THE BOUNDARY
        NB2=NB2+NB1
C
        NOD=3
C       COUNTER FOR NODE NUMBERING
        NCN=NB0
C       IN CASE OF INCLUSIONS OR SIMULATION, CREATE ALSO TWO NEW 
C       CONNECTIVITY ARRAY (WITH NEW NUMBERING), ONE FOR THE 
C       ZONE NODES AND ONE FOR THE NON ZONE NODES
C            IF((NREGI(L).EQ.2).OR.(LDIAK.EQ.1)) THEN
C
C       FOR THE ZONE NODES
        IF(IZDIAK.EQ.1) THEN
          LZ=LZ+1
          IF(LZ.EQ.1) THEN
            NB0Z=1
            GO TO 64
          ENDIF
          NONZON(NCN,II)=KCL
C         FOR FUTURE VERSION: HERE WE SUPPOSE THAT ALL THE BOUNDARY
C         IS AN INCLUSION OR SIMULTATION. IF WE WANT ONLY A PART OF
C         IT, WE MUST MODIFY
          NB0Z=NB0Z+NNODEB(L-1)
   64     NB1Z=NNODEB(L)
          NB2Z=NB2Z+NB1Z
          NCNZ=NB0Z
        ENDIF
C       FOR THE NON ZONE NODES
        IF(IZDIAK.EQ.0) THEN
          LN=LN+1
          IF(LN.EQ.1) THEN
            NB0N=1
            GO TO 65
          ENDIF
C         FOR FUTURE VERSION: HERE WE SUPPOSE THAT ALL THE BOUNDARY
C         IS AN INCLUSION OR SIMULTATION. IF WE WANT ONLY A PART OF
C         IT, WE MUST MODIFY
          NB0N=NB0N+NNODEB(L-1)
   65     NB1N=NNODEB(L)
          NB2N=NB2N+NB1N
          NCNN=NB0N
        ENDIF
        DO 41 I=1,NB1
          DO 51 II=1,NOD
            JCL1=I
            II1=II  
             CALL COORD3(NCN,JCL1,NB0,NB1,NCOUNT,
     &                  II1,KCL,NB2,NBOUN,NSHAP,LCRN)
            NONN(NCN,II)=KCL
C           IN CASE OF INCLUSIONS OR SIMULATION, CREATE ALSO A NEW 
C           CONNECTIVITY ARRAY (WITH NEW NUMBERING)
C            IF((NREGI(L).EQ.2).OR.(LDIAK.EQ.1)) THEN
C           FOR THE ZONE NODES
            IF(IZDIAK.EQ.1) THEN
             CALL COORD3(NCNZ,JCL1,NB0Z,NB1Z,NCOUNT,
     &                  II1,KCL,NB2Z,NBOUN,NSHAP,LCRN)
C             NCN IS THE GLOBAL NODE NUMBER
              NONZON(NCN,II)=KCL 
            ENDIF
  51      CONTINUE
          NCN=NCN+1
C         FOR THE ZONE NODES
          IF(IZDIAK.EQ.1) NCNZ=NCNZ+1
C         FOR THE NON ZONE NODES
          IF(IZDIAK.EQ.0) NCNN=NCNN+1
  41    CONTINUE
  61  CONTINUE
      RETURN
      END
