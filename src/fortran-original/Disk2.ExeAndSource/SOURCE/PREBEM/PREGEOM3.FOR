      SUBROUTINE CHANGEND(XCR,YCR,XT,YT,N1,NS,NT,NDIS1,LCRN)
C FROM AN EXISTING CLOSE MESH WITH NN NODES NUMBERED IN ANTICLOCKWISE 
C DIRECTION CREATE ANOTHER CLOSE MESH WITH THE FIRST NODE IN THE PLACE 
C OF NODE NS AND IN CLOCKWISE OR ANTICLOCKWISE, DEPENDING ON  
C THE VALUE OF NT
C       NT=1, ANTICLOCKWISE (INTERNAL PROBLEM)
C       NT=2, CLOCKWISE     (EXTERNAL PROBLEM)
C       NDIS1:1 NO DISCONTINUITY AT THE CORNERS OF THE SQUARE OR RECTANGLEC     C             :2 YES  -//-
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
C
      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION XT(N1),YT(N1)
      DIMENSION LCRN(8),LT(4)
        J=NS
        DO 10 I=1,4
          LT(I)=0
  10    CONTINUE
C FOR EXTERIOR PROBLEM, CLOCKWISE
C OR CLOCKWISE ENCLOSING ELEMENTS BOUNDARY (LIKE INCLUSION)
      IF ((NT.EQ.1).OR.(NT.EQ.6)) THEN
        DO 1 I=1,N1
          XT(I)=XCR(J)
          YT(I)=YCR(J)
C         FOR SQUARE OR RECTANGLE AND
C         IN CASE OF DISCONTINUITY AT THE CORNERS, CHANGE THE NUMBERING
C         OF THE LAST NODES OF THE SIDES (CORNER NODES)
C          IF(((NSHAP(K).EQ.2).OR.(NSHAP(K).EQ.3)).AND.
C     &          (NDIS(K).EQ.2)) THEN
          IF (NDIS1.EQ.2) THEN
C           FIND IF THE I NODE IS ONE OF THE 4 CORNER NODES, AND IF SO
C           CHANGE THE NODE NUMBERING OF THE CORNER ALSO
            DO 20 II=1,4
              IF(J.EQ.LCRN(II)) LT(II)=I
  20        CONTINUE
            J=J-1
            IF (J.EQ.0) J=N1-4
            IF (J.EQ.NS) J=N1-3
            GO TO 1
          ENDIF

          J=J-1
          IF (J.EQ.0) J=N1
          IF (J.EQ.NS) GO TO 3
  1     CONTINUE
      ENDIF
C FOR INTERIOR PROBLEM, ANTICLOCKWISE
C       OR ANTICLOCKWISE ENCLOSING ELEMENTS BOUNDARY (LIKE INCLUSION)
      IF ((NT.EQ.2).OR.(NT.EQ.5)) THEN

        KDIAK=0
        DO 2 I=1,N1
          XT(I)=XCR(J)
          YT(I)=YCR(J)
C         FOR SQUARE OR RECTANGLE AND
C         IN CASE OF DISCONTINUITY AT THE CORNERS, CHANGE THE NUMBERING
C         OF THE LAST NODES OF THE SIDES (CORNER NODES)
          IF (NDIS1.EQ.2) THEN
C           FIND IF THE I NODE IS ONE OF THE 4 CORNER NODES, AND IF SO
C           CHANGE THE NODE NUMBERING OF THE CORNER ALSO
            DO 30 II=1,4
              IF(J.EQ.LCRN(II)) LT(II)=I
  30        CONTINUE
            J=J+1
            IF (J.GT.(N1-4)) THEN
              IF(KDIAK.EQ.0) J=1
              KDIAK=1
            ENDIF
            IF (J.EQ.NS) J=N1-3
            GO TO 2
          ENDIF
          J=J+1
c          IF (J.EQ.N1) J=1
          IF (J.GT.N1) J=1
          IF (J.EQ.NS) GO TO 3    
  2     CONTINUE
      ENDIF
  3   CONTINUE
      DO 4 I=1,N1
        XCR(I)=XT(I)
        YCR(I)=YT(I)
  4   CONTINUE
      DO 6 I=1,4
        LCRN(I)=LT(I)
  6   CONTINUE
      RETURN
      END
