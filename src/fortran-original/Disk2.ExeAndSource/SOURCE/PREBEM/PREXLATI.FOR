      SUBROUTINE REFANGEX(XCR1,YCR1,RK,CH,CHA,THT0,THT3,THT4,
     &   BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,THN1,KANGL)
C
C     FOR THE CASE OF EXPLOSION POINT WAVE,
C     CALCULATES THE ANGLES TH1=TH2=TH0 OF P-P WAVE
C                       AND TH3,TH4 OF P-SV WAVE
C     TH0,TH3,TH4 : ANGLES IN RANGE 0,PI/2 (KANGL=1)
C     TH0: ANGLE OF INCIDENT=ANGLE OF REFLECTED P WAVE AT POINT B
C     TH3: ANGLE OF INCIDENT P WAVE AT POINT D
C     TH4: ANGLE OF REFLECTED SV WAVE AT POINT D
C     TH5: ANGLE OF REFLECTED SV WAVE AT POINT B
C
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
      KANGL=0
C     ANGLES TH1=TH2=TH0
C     ------------------
C     DISTANCE AE OF EXPLOSION POINT A FROM NODE E
      AE=DSQRT((XCR1-EXPLX)**2+(YCR1-EXPLY)**2)
C     ANGLE PSI OF LINE EA IN LOCAL COORDINATE SYSTEM (WITH ORIGIN 
C     AT THE ACTUAL NODE E AND AXES PARALLEL TO UNIT VECTORS
C     OF THE FREE SURFACE N,Q
C     COORDINATES OF POINT A IN A SYSTEM WITH ORIGIN AT THE ACTUAL NODE E,
C     AND AXES PARALLEL TO AXES OF GLOBAL SYSTEM
      XEX1=EXPLX-XCR1
      YEX1=EXPLY-YCR1
C     TRANSFORMATION OF COORDINATES OF POINT A FROM GLOBAL SYSTEM
C     WITH ORIGIN AT THE ACTUAL NODE E AND AXES PARALLEL TO AXES OF GLOBAL
C     SYSTEM, TO A LOCAL SYSTEM WITH ORIGIN AGAIN AT THE NODE E AND AXES 
C     PARALLEL TO N,Q 
C       POINT A
C
        WAI=THN1
        WN1=DCOS(WAI)
        WN2=DSIN(WAI)
        XEX=XEX1*DCOS(WAI)+YEX1*DSIN(WAI)
        YEX=-XEX1*DSIN(WAI)+YEX1*DCOS(WAI)
      IF(DABS(XEX).LT.TOL) XEX=TOL
      PSI=DATAN2(YEX,XEX)
      IF(PSI.LT.0.0D0) PSI=2.0D0*PI+PSI
C     KANGL    : INDEX FOR CALCULATING THE ANGLES 
C                  1: TH0=TH0,     TH3=TH3,     TH4=TH4
C                  2: TH0=2PI-TH0, TH3=2PI-TH3, TH4=2PI-TH4
C     0<=PSI<=PI
      IF((PSI.GE.0.0D0).AND.(PSI.LE.PI)) KANGL=1
C     PI<PSI<2PI
      IF((PSI.GT.PI).AND.(PSI.LT.2.0D0*PI)) KANGL=2

C     LENGTH OF PROJECTION OF AE TO THE FREE SURFACE
      AE2=AE*DSIN(PSI)
      AB2=AE2*CHA/(CH+CHA)
      AB2=DABS(AB2)
      TH0=DATAN2(AB2,CHA)
      IF(TH0.LT.0.0D0) TH0=2.0D0*PI+TH0
C     ANGLE OF REFLECTED SV WAVE AT B
C     FOR A GIVEN TH0, CALCULATE TH5:  K=SIN(TH0)/SIN(TH5)
      X1=DSIN(TH0)/RK
      TH5=DABS(DASIN(X1))
C     ANGLES TH3,TH4
C     --------------
      KPS=1
      CALL TH34EX(RK,AE2,CH,CHA,TH3,TH4,KPS)
C        
C  20  CONTINUE
C
C     ANGLES THT0,THT3,THT4,THT5
C     --------------------------
      THT0=TH0
      IF(KANGL.EQ.2) THT0=2*PI-TH0
      THT3=TH3
      THT4=TH4
      THT5=TH5
      IF(KANGL.EQ.2) THEN
        THT3=2.0D0*PI-TH3
        THT4=2.0D0*PI-TH4
        THT5=2.0D0*PI-TH5
      ENDIF
C
C     ANGLES BTHEP, BTHANP, DTHEP, DTHANSV
C     ------------------------------------
C     ANGLES OF INCIDENT AND REFLECTED WAVE IN LOCAL SYSTEM WITH 
C     CENTER AT POINT B
      BTHEP=PI-TH0
      BTHANP=PI+TH0
      BTHANSV=PI+TH5
      IF(KANGL.EQ.2) THEN
        BTHEP=PI+TH0
        BTHANP=PI-TH0
        BTHANSV=PI-TH5
      ENDIF
C     CENTER AT POINT D
      DTHEP=PI-TH3
      DTHANP=PI+TH3
      DTHANSV=PI+TH4
      IF(KANGL.EQ.2) THEN
        DTHEP=PI+TH3
        DTHANP=PI-TH3
        DTHANSV=PI-TH4
      ENDIF
      RETURN
      END
