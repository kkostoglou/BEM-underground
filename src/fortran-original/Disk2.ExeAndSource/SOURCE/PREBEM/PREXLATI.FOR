      SUBROUTINE REFAEXSV(XCR1,YCR1,RK,CH,CHA,THT0,THT1,THT4,
     &  BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,THN1,KANGL,ISRC)
C
C     FOR THE CASE OF EXPLOSION POINT WAVE,
C     CALCULATES THE ANGLES TH1=TH2=TH0 OF SV-P WAVE
C                       AND TH3,TH4 OF SV-SV WAVE
C     TH0,TH3,TH4 : ANGLES IN RANGE 0,PI/2 (KANGL=1)
C     TH0: ANGLE OF INCIDENT=ANGLE OF REFLECTED P WAVE AT POINT D
C     TH1: ANGLE OF INCIDENT P WAVE AT POINT B
C     TH2: ANGLE OF REFLECTED SV WAVE AT POINT B
C     TH5: ANGLE OF REFLECTED P WAVE AT POINT D
C     THESE ANGLES ARE IN LOCAL SYSTEM AND HAVE VALUES BETWEEN 0 AND PI/2
C
C
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
      KANGL=0
C     ANGLES TH3=TH4=TH0
C     ------------------
C     DISTANCE AE OF EXPLOSION POINT A FROM NODE E
      AE=DSQRT((XCR1-EXPLX)**2+(YCR1-EXPLY)**2)
C     ANGLE PSI OF LINE EA IN LOCAL COORDINATE SYSTEM (WITH ORIGIN 
C     AT THE ACTUAL NODE E AND AXES PARALLEL TO UNIT VECTORS
C     OF THE FREE SURFACE N,Q
C     COORDINATES OF POINT A IN A SYSTEM WITH ORIGIN AT THE ACTUAL NODE E,
C     AND AXES PARALLEL TO AXES OF GLOBAL SYSTEM
      XEX1=EXPLX-XCR1
      YEX1=EXPLY-YCR1
C     TRANSFORMATION OF COORDINATES OF POINT A FROM GLOBAL SYSTEM
C     WITH ORIGIN AT THE ACTUAL NODE E AND AXES PARALLEL TO AXES OF GLOBAL
C     SYSTEM, TO A LOCAL SYSTEM WITH ORIGIN AGAIN AT THE NODE E AND AXES 
C     PARALLEL TO N,Q 
C       POINT A
C        XEX=XEX1*DCOS(WAI)+YEX1*DSIN(WAI)+XCEN
C        YEX=-XEX1*DSIN(WAI)+YEX1*DCOS(WAI)+YCEN
C
        WAI=THN1
        WN1=DCOS(WAI)
        WN2=DSIN(WAI)
        XEX=XEX1*DCOS(WAI)+YEX1*DSIN(WAI)
        YEX=-XEX1*DSIN(WAI)+YEX1*DCOS(WAI)
      IF(DABS(XEX).LT.TOL) XEX=TOL
      PSI=DATAN2(YEX,XEX)
      IF(PSI.LT.0.0D0) PSI=2.0D0*PI+PSI
C     0<=PSI<=PI
      IF((PSI.GE.0.0D0).AND.(PSI.LE.PI)) KANGL=1
C     PI<PSI<2PI
      IF((PSI.GT.PI).AND.(PSI.LT.2.0D0*PI)) KANGL=2
C     CRITICAL ANGLE OF INCIDENT FOR SV WAVE
      IF(DABS(RK).LT.TOL) RK=TOL
        GASIN=DASIN(1.0D0/RK)
        THCR=PI-GASIN
        IF(KANGL.EQ.2) THEN
        THCR=PI+GASIN
      ENDIF
C     LENGTH OF PROJECTION OF AE TO THE FREE SURFACE
      AE2=AE*DSIN(PSI)
      AD2=AE2*CHA/(CH+CHA)
      AD2=DABS(AD2)
      TH0=DATAN2(AD2,CHA)
      IF(TH0.LT.0.0D0) TH0=2.0D0*PI+TH0
C     FOR ANGLE GREATER THAN CRITICAL
      IF(TH0.GT.THCR) THEN
        ISRC=3
        GO TO 99
      ENDIF
      X1=RK*DSIN(TH0)
      TH5=DABS(DASIN(X1))
C     ANGLES TH1,TH2
C     --------------
      KPS=2
      CALL TH34EX(RK,AE2,CH,CHA,TH1,TH2,KPS)
C     ANGLES THT0,THT1,THT2,THT5
C     --------------------------
      THT0=TH0
      IF(KANGL.EQ.2) THT0=2*PI-TH0
      THT4=TH4
      THT1=TH1
      THT2=TH2
      THT5=TH5
      IF(KANGL.EQ.2) THEN
        THT4=2.0D0*PI-TH4
        THT1=2.0D0*PI-TH1
        THT2=2.0D0*PI-TH2
        THT5=2.0D0*PI-TH5
      ENDIF
C
C     ANGLES BTHEP, BTHANP, DTHEP, DTHANSV
C     ------------------------------------
C     ANGLES OF INCIDENT AND REFLECTED WAVE IN LOCAL SYSTEM WITH 
C     CENTER AT POINT D
      BTHEP=PI-TH0
      BTHANP=PI+TH5
      BTHANSV=PI+TH0
      IF(KANGL.EQ.2) THEN
        BTHEP=PI+TH0
        BTHANP=PI-TH5
        BTHANSV=PI-TH0
      ENDIF
C     CENTER AT POINT B
      DTHEP=PI-TH1
      DTHANP=PI+TH2
      DTHANSV=PI+TH1
      IF(KANGL.EQ.2) THEN
        DTHEP=PI+TH1
        DTHANP=PI-TH1
        DTHANSV=PI-TH2
      ENDIF
  99  CONTINUE
      RETURN
      END
