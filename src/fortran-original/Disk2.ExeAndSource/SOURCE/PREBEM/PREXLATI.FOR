C -----------------------------------------------------------------------
      SUBROUTINE REFCONEX(CE,CF,CQ,KREFL,CHA)
C
C     EXAMINES THE REFLECTION CONDITIONS OF EXPLOSIVE WAVE
C     AND THE POSITION OF THE EXPLOSION POINT TO THE NODE
C
C     XCR1,YCR1: COORDINATES OF THE NODE
C     EQUATION OF THE LINE OF THE FREE SURFACE
C             CE*X+CF*Y-CQ=0
C     WITH THE X AXIS
C     KREFL: RETURN VALUE
C            0: NO REFLECTION
C            1: REFLECTION
C            2: CASE THAT THE INCIDENT WAVE IS PARALLEL TO THE FREE SURFACE,
C               IT CANOT BE REFLECTED.
C     CHA  : DISTANCE OF EXPLOSION POINT A FROM THE FREE SURFACE, 
C            RETURN ABSOLUTE VALUE
C
C      COMMON/GEOM3/FAI,PSAI
C
C      DIMENSION PSAI(5)
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/BLKEX/IEXIT
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-6
C     REFLECTION CONDITION
C     IN CASE OF EXPLOSION POINT, WHEN THE POINT IS UNDER
C     THE FREE SURFACE, WE HAVE ALWAYS REFLECTION
C     IF(KEXPL.EQ.1) THEN
C     DISTANCE OF EXPLOSION POINT ( FROM THE LINE OF FREE SURFACE)
C     NEGATIVE IF EXPLOSION POINT AND THE ORIGIN XCR0,YCR0 ARE IN 
C     THE SAME SIDE, POSITIVE IF THEY ARE IN THE OPPOSITE SIDE
C     ALWAYS IT IS NEGATIVE
C     CH=EXPLX*DCOS(WAI)+EXPLY*DSIN(WAI)-CQ
C     CH=XCE*CE+YCE*CF-CQ
C
      XCE=EXPLX
      YCE=EXPLY
      CHA=XCE*CE+YCE*CF-CQ
C     CASE THAT CHA IS POSITIVE, THE POINT IS OVER THE FREE
C     SURFACE, ERROR
      IF(CHA.GT.0.0D0) THEN
        WRITE(6,502)CHA
        IEXIT=1
        GO TO 99
      ENDIF
  502 FORMAT(/,10X,'  ERROR - THE EXPLOSION POINT IS OVER THE FREE', 
     &         10X,' SURFACE ',F12.3,' DISTANCE, NOT PERMITED')
      KREFL=1
C     CASE THAT THE EXPLOSION POINT IS ON THE FREE SURFACE, THE WAVES CANOT
C     BE REFLECTED
      IF(DABS(CHA).LT.TOL) KREFL=2
C     TAKE ABSOLUTE VALUE
      CHA=DABS(CHA)
  99  CONTINUE
      RETURN
      END
