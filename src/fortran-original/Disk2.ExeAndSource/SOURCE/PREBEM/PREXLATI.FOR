C ----------------------------------------------------------------------
      SUBROUTINE TH34EX(RK,AE2,CH,CHA,TH3,TH4,KPS)
C
C     CALCULATES THE ANGLES TH3,TH4 OF INCIDENT AND REFLECTED P-SV WAVE
C     KPS=1   : EXPLOSIVE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C     KPS=2   : EXPLOSIVE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)
C     NUMERICALLY (BISECTION METHOD)
      IMPLICIT REAL*8 (A-H,O-Y)
C
C      PI=3.14159265359D0
C     TOLERANCE 
      XACC=0.001
C     INITIAL VALUES
      DS=DABS(AE2)
C     START FROM TH3=0
      TH3=0.0D0
C     KDIAK=0 : INCREASES THE ANGLE TH3 CONTINUSLY WITH STEP 0.1 RAD,
C               (STARTING FROM 0), UNTIL THE DIFFERENCE DIF=DS-DS1<0
      KDIAK=0 
      CALL CONVERG(RK,DS,CH,CHA,TH3,TH4,FDIF,KDIAK,KPS)
      IF(DABS(FDIF).LT.XACC) GO TO 30
C     KDIAK=1 : DECREASES THE ANGLE TH3 CONTINUSLY WITH STEP 0.01 RAD,
C               (STARTING FROM THE PREVIOUS VALUE), UNTIL THE DIFFERENCE
C               DIF=DS-DS1>=0
      KDIAK=1 
      CALL CONVERG(RK,DS,CH,CHA,TH3,TH4,FDIF,KDIAK,KPS)
      IF(DABS(FDIF).LT.XACC) GO TO 30
C     KDIAK=2 : INCREASES AGAIN THE ANGLE TH3 CONTINUSLY WITH STEP 0.001 RAD,
C               (STARTING FROM THE PREVIOUS VALUE), UNTIL THE DIFFERENCE
C               DIF=DS-DS1<0
      KDIAK=2
      CALL CONVERG(RK,DS,CH,CHA,TH3,TH4,FDIF,KDIAK,KPS)
  30  CONTINUE
      RETURN
      END
C
C ----------------------------------------------------------------------
      SUBROUTINE CONVERG(RK,DS,CH,CHA,TH3,TH4,FDIF,KDIAK,KPS)
C
C     FOR THE GIVEN VALUE OF ANGLE TH3, CALCULATES THE ANGLE TH4 BY
C     FINDING THE DIFFERENCE DIF=DS-DS1 AND DEPENDING ON THE SIGN OF DIF
C
C     KDIAK=0 : INCREASES THE ANGLE TH3 CONTINUSLY WITH STEP 0.1 RAD,
C               (STARTING FROM 0), UNTIL THE DIFFERENCE DIF=DS-DS1<=0
C     KDIAK=1 : DECREASES THE ANGLE TH3 CONTINUSLY WITH STEP 0.01 RAD,
C               (STARTING FROM THE PREVIOUS VALUE), UNTIL THE DIFFERENCE
C               DIF=DS-DS1>=0
C     KDIAK=2 : INCREASES AGAIN THE ANGLE TH3 CONTINUSLY WITH STEP 0.001 RAD,
C               (STARTING FROM THE PREVIOUS VALUE), UNTIL THE DIFFERENCE
C               DIF=DS-DS1<=0
C     KPS=1   : EXPLOSE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C     KPS=2   : EXPLOSE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)
 
C     THE WHOLE PROCESS STOPS WHEN EITHER |FDIF|<XACC, OR AFTER FINISHING
C     THE ABOVE 3 STEPS WITH ESTIMATED ACCURACE NOT FAR FROM 0.001.

      IMPLICIT REAL*8 (A-H,O-Y)
C     FOR THE GIVEN VALUE TH3, CALCULATE TH4 AND NEW DISTANCE AE=DS1
      PI=3.14159265359D0
C     TOLERANCE 
      XACC=0.0005
      IF(KDIAK.EQ.0) RAC=0.1D0
      IF(KDIAK.EQ.1) RAC=-0.01D0
      IF(KDIAK.EQ.2) RAC=0.001D0
  20  CONTINUE
C
C     FOR A GIVEN TH3, CALCULATE TH4
C     CASE OF ICIDENT-REFL. IS P-SV WAVE
      IF(KPS.EQ.1) THEN
        X1=DSIN(TH3)/RK
        TH4=DABS(DASIN(X1))
      ENDIF
C     CASE OF ICIDENT-REFL. IS SV-P WAVE, TH3=TH4
      IF(KPS.EQ.2) THEN
C        X1=RK*DSIN(TH3)
        TH4=TH3
      ENDIF
C     TH4 ALWAYS POSITIVE AND 0<=TH4<=PI/2
      AD2=CHA*DTAN(TH3)
      ED1=CH*DTAN(TH4)
C     NEW DISTANCE AE=DS1
      DS1=AD2+ED1
C     DEFFERENCE BETWEEN THE OLD AND NEW DISTANCE OF POINTS A AND E
      FDIF=DS-DS1
C
      IF(DABS(FDIF).LT.XACC) GO TO 30
      IF((KDIAK.EQ.0).OR.(KDIAK.EQ.2)) THEN
        IF(FDIF.LE.0.0D0) GO TO 30
      ENDIF
      IF(KDIAK.EQ.1) THEN
        IF(FDIF.GE.0.0D0) GO TO 30
      ENDIF
      TH3=TH3+RAC
      GO TO 20
  30  CONTINUE
      RETURN
      END
