      SUBROUTINE TWAVPLAN(XCR1,YCR1,XCEN,YCEN,CA,CB,CP,WVEL,NCOUNT,T1,
     &      SXX,SYY,SXY,TSXX,TSYY,TSXY,TSXX1,TSYY1,TSXY1)
C
C     CALCULATES THE TRANSFORMED STRESSES ON A NODE, IN A GLOBAL SYSTEM
C     (DELAYS AND LAPLACE TRANSFORMATION)
C     XCR1,YCR1 : COORDINATES OF THE NODE
C     XCEN,YCEN : COORDINATES OF THE CENTER OF THE MESH (OF ALL THE BOUNDARIES)
C     EQUATION OF LINE OF WAVEFRONT 
C           CA=COS(FAI), CB=SIN(FAI)
C           CA*XCR(I)+CB*YCR(I)-CP=0
C     WAVEL     : SEISMIC WAVE VELOCITY
C
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      DIMENSION NREGI(5),NSIMU(5)
C
C     TOLERANCE 
      TOL=1.0E-9
C
C     DISTANCE OF NODE NCN FROM 
C     THE WAVEFRONT LINE CA*X+CB*Y-CP=0 (POSITION AT T=0)
C     NEGATIVE IF NODE I AND THE ORIGIN OF ALL THE BOUNDARIES, XCEN,YCEN
C     ARE IN THE SAME SIDE OF THE LINE, POSSITIVE IF THEY ARE IN THE 
C     OPPOSITE SIDE
C     COORDINATES IN SYSTEM WITH ORIGIN THE GLOBAL CENTER OF ALL
C     THE BOUNDARIES
      XCG=XCR1-XCEN
      YCG=YCR1-YCEN
      CD=XCG*CA+YCG*CB-CP
C     THE DISTANCE OF THE NODE FROM THE WAVEFRONT IS TAKEN ALWAYS
C     POSSITIVE. 
C     THIS MEANS THAT THE WAVEFRONT AT TIME T=0, IS ALWAYS OUT OF THE
C     MESH, AND THIS IS TRUE, SINCE THE PROGRAM AUTOMATICALLY PUTS
C     THE WAVEFRONT OUTSIDE THE MESH (EXCEPT FOR THE BOUNDARY OF THE
C     FREE SURFACE THAT IS NOT TAKEN INTO ACCOUNT)
C     IF WE WANT THE WAVE AT T=0 INCIDE THE MESH, THEN THE DELAYS BEHIND
C     THE MESH MUST BE =0
C     DELAY FOR THE ARIVING OF WAVE FRONT AT NODE I
C
C     CD ALWAYS POSSITIVE
      CD=DABS(CD)
      WVC1=WVEL-C1
      WVC2=WVEL-C2
      IF(DABS(WVC1).LT.TOL) T2=CD/C1
C     CASE OF SV WAVE
      IF(DABS(WVC2).LT.TOL) T2=CD/C2
  66  CONTINUE   
      SDELAY=0.0D0
      IF (T1.GE.T2) SDELAY=1.0D0
      IF(DABS(T1-T2).LT. TOL) SDELAY=1.0D0
C
      TSXX1=TSXX
      TSYY1=TSYY
      TSXY1=TSXY
C     FOR FREE SURFACE TAKE THE REDUCED STRESSES SXX,SYY,SXY
C     INSTEAD OF HAVING THE SUM OF INCIDENT AND REFLECTED
C     STRESSES 0. THIS IS TEMPORALY FOR CHECK AND CAN REMOVED
C     BY SETTING IN DATALAP TRACTIONS ON FREE SURFACE 0
      TSXX1=TSXX1*SDELAY
      TSYY1=TSYY1*SDELAY
      TSXY1=TSXY1*SDELAY
      RETURN
      END
