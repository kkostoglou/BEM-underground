C
C   --------------------------------------------------------------------
      PROGRAM PREBEM
C   --------------------------------------------------------------------
C
C   PREPROCCESSING OF THE DATA FOR THE MAIN BEM PROGRAM
C   IN LAPLACE DOMAIN AND IN TIME DOMAIN
C
C   FUNCTIONS -
C
C       1. READS THE DATA FROM A USERS DEFINED FILE AND PREPROCCESSES THEM.
C          SAVES THE DATA WITH ERROR MESSAGES IN A USERS DEFINED FILE
C          FOR CHECKING.
C
C       2. SAVES DATA IN FILES BEMLTDAT, BEMLTTRA AND BEMLTSTR
C                    FOR LAPLACE DOMAIN
C              OR IN FILES BEMTDDAT, BEMTDTRA AND BEMLTSTR FOR TIME DOMAIN
C          FOR USE FROM THE MAIN BEM PROGRAMS.
C
C       3. SAVES DATA IN FILE POSTDAT, FOR USE FROM POSTPROCCESSING 
C          PROGRAM POSTDAT.
C
C        READS AND DIRECTS EXECUTION OF COMMANDS.
C
C   --------------------------------------------------------------------
C
C       PSAI: ANGLE OF AXIS OF SECTION WITH X AXIS
C       FAI : ANGLE OF AXIS OF INCIDENT WAVE WITH X AXIS
C       MST : TOTAL TIME STEPS
C       MND : TOTAL NODES OF THE MESH
C       MEL : TOTAL ELEMENTS OF THE MESH
C       MBD : TOTAL BOUNDARIES IN THE MESH
C       MPL : NUMBER OF TOTAL PLOT CATEGORIES
C       MZN : NUMBER OF TOTAL ZONES OF DIFFERENT MATERIAL
C       MDM : DIMENSIONS OF THE PROBLEM (2D HERE)
C       MSG : TOTAL SEGMENTS FOR ALL THE BOUNDARIES
C       MIN : TOTAL NUMBER OF INTERNAL NODES
      PARAMETER(MST=100,MND=100,MEL=50,MBD=5,MPL=30,MZN=5,MDM=2,
     &    MSG=10,MIN=10)
C     TYPE OF BOUNDARY CONDITION (1:TRACTION 2:DISPLACEMENT)
      DIMENSION MMBCU(MND*MDM)
      DIMENSION NHPOS(MEL)
      DIMENSION SEG(MEL*7)
      DIMENSION NCELE(MEL)
      DIMENSION JKODE(MEL)
      DIMENSION JP1(5)
      DIMENSION NSHAP(MBD),NSEGM(MBD)
      DIMENSION NELEMB(MBD),NNODEB(MBD)
C     CODE FOR FREE SURFACE ELEMENTS
      COMPLEX*16 ZARR[ALLOCATABLE](:)
      REAL*8 RARR[ALLOCATABLE](:)
      REAL*8 SARR[ALLOCATABLE](:)
      REAL*8 RARRB[ALLOCATABLE](:)
      REAL*8 RIGR[ALLOCATABLE](:)
      REAL*8 TH0[ALLOCATABLE](:)
      REAL*8 TH3[ALLOCATABLE](:)
      REAL*8 TH4[ALLOCATABLE](:)
      INTEGER*4 KKONN[ALLOCATABLE](:)
      INTEGER*4 KKONZON[ALLOCATABLE](:)
      INTEGER*4 NNDTYPE[ALLOCATABLE](:)
      INTEGER*4 NNONN[ALLOCATABLE](:)
      INTEGER*4 NNONZON[ALLOCATABLE](:)
      INTEGER*4 LLBCU[ALLOCATABLE](:)
      INTEGER*2 STAT,IERR
      DIMENSION NREGI(5)
      DIMENSION NPLOT(MPL)
      DIMENSION NDPLOT(MND),LEPLOT(2*MND)
      DIMENSION PSURFX(MEL),PSURFY(MEL)
      DIMENSION TRACX(MND),TRACY(MND)
C
C     ******ALL THE COMMON BLOCKS USED IN THIS PROGRAM********
      COMMON /BLK20/DATE,TIME,SNAME,FNAMEIN,FNAMEPRE,
     &              FNAMEPRO,FNAMEPOS
      COMMON /CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON /MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON /BLKEX/IEXIT
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON /GEOM3/FAI,PSAI
      COMMON /GEOM4/NXELE,NYELE
      COMMON /PROBL/NDOMA,NREGI,NUNIT
      COMMON /FREE/NFFS,NSIMU
      COMMON/PRESS/KINSI,PINSI
C      COMMON /EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
C     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
C     DIMENSIONS OF COMMON BLOCKS,  5=MBD
C     CHANGING MBD, NUMBER 5 MUST BE SHANGED IN ALL THE SUBROUTINES FOR
C     THESE ARRAYS
      DIMENSION RAD(5),RATIO(5),SID(5),XSID(5),YSID(5)
      DIMENSION XCR0(5),YCR0(5),PSAI(5)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION NSIMU(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &	  TYPELY(5),NDIS(5)
      DIMENSION PINSI(5)
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE.
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
      DIMENSION LCRN(8)
      DIMENSION SGTYP(MSG)
      REAL*8 SGTYP
      CHARACTER FNAMEIN*14,FNAMEPRE*14,DATE*35
      CHARACTER FNAMEPRO*14,FNAMEPOS*14
      CHARACTER TIME*15,SNAME*35
      REAL*8 RLA,RMU,RNU,RHO,C1,C2,TIM
      REAL*8 SXX,SYY,SXY
      REAL*8 RAD,SID,XSID,YSID,RATIO,XCR0,YCR0
      REAL*8 XSTA,YSTA,XLAS,YLAS,TYPELX,TYPELY
      REAL*8 FAI,PSAI,SEG,CA,CB,CP
      REAL*8 WAVX,WAVY,WAVCEN
      REAL*8 XCEN,YCEN
      REAL*8 FVISC,SIGC,FM,FS
      REAL*8 PTH
      REAL*8 DRSTRE,DRNSTRE,DRNORM
      REAL*8 FN1,FN2
      REAL*8 PINSI
      REAL*8 PSURFX,PSURFY
      REAL*8 TRACX,TRACY
C
C      FOR UNIX SYSTEM
C      FOR TARAPING IEE FLOATINGIPOINT EXCEPTIONS
C      EXTERNAL COMMON_HANDLER
C      III=IEEE_HANDLER("SET", "COMMON", COMMON_HANDLER)
C      III=IEEE_HANDLER("SET", "ALL", COMMON_HANDLER)
C      IF(III.NE.0) THEN
C        PRINT*, "COULD NOT ESTABLISH FP SIGNAL HANDLER"
C        WRITE(12,100)
C 100    FORMAT("COULD NOT ESTABLISH FP SIGNAL HANDLER")
C      ENDIF
C
      TOL=1.0E-11
      PI=3.14159265359
      N8=5
C
C--------------------------------------------------------------
C     CALL THE SUBROUTINE FOR INPUT DATA (MODULES)
C
      CALL MODULES(MMBCU,NHPOS,SEG,NCELE,JKODE,JP1,NSHAP,
     &  NSEGM,NELEMB,NNODEB,RSTRE,RNSTRE,RNORM,NBOUN,NANAL,
     &  NTSG,RYOUN,RPOIS,RDENS,RTIME,RANGL,RPX,RPY,
     &  LWAV,RSIGC,RFM,RFS,NTOT,NPLOT,NDTOT,NDPLOT,LETOT,LEPLOT,
     &  KEXPL,KSURF,PSURFX,PSURFY,KTRAC,TRACX,TRACY,MST,MND,MEL,
     &  MBD,MPL,MDM,N8,INES,SGTYP,MSG,MIN)
C           INES : INDEX 0: NUMBER OF ELEMENTS IN A SEGMENT WERE 0
C                        1: THERE WERE NOT 0 NUMBER OF ELEMENTS IN ANY SEGMENT
C-----------------------------------------------------------
C     IF  THERE IS ERROR IN THE DATA STOP THE PROGRAM
C-----------------------------------------------------------
  222   IF (IEXIT.NE.0) THEN
        WRITE(6,372)
  372   FORMAT(/
     &	   10X,'******************************************'/
     &	   10X,'****  ERROR IN THE VALIDATION OF DATA ****'/
     &     10X,'****       CHECK YOUR DATAFILE        ****'/
     &     10X,'****     PROGRAM TERMINATED           ****'/
     &	   10X,'******************************************'/)
        GO TO 999
      ENDIF
C-----------------------------------------------------------
C     SAVE VALUES TO DATA FILE BEMLTDAT AND BEMLTLOD
C ----------------------------------------------------------
 19   CONTINUE
C-----------------------------------------------------------
C     OPEN FILES FOR WRITING DATA FOR THE MAIN BEM PROGRAM
C     FOR LAPLACE DOMAIN (ELASTODYNAMIC CASE) THE FILES ARE
C         BEMLTDAT : DATAFILE
C         BEMLTTRA : DATA OF INCIDENT TRACTIONS ON THE BOUNDARIES, 
C                    IN X AND Y GLOBAL COORDINATES (OPPOSITE SIGN OF INCOMING)
C                    PRODUCED BY SUBROUTINE DATALAP
C         BEMLTSTR : DATA OF INICIAL HOOP STRESSES, USED IN
C                    SUBROUTINE HOOP OF THE BEM MAIN PROGRAM.
C     FOR TIME DOMAIN (ELASTODYNAMIC CASE) THE FILES ARE
C         BEMTDDAT : DATAFILE
C         BEMTDTRA : DATA OF INCIDENT TRACTIONS ON THE BOUNDARIES, 
C                    IN X AND Y GLOBAL COORDINATES (OPPOSITE SIGN OF INCOMING)
C                    PRODUCED BY SUBROUTINE DATATIM
C         BEMTDSTR : DATA OF INICIAL HOOP STRESSES, USED IN
C                    SUBROUTINE HOOP OF THE BEM MAIN PROGRAM.
C     FOR ELASTOSTATIC CASE THE FILES ARE
C         BEMELDAT : DATAFILE
C         BEMELTRA : DATA OF INCIDENT TRACTIONS ON THE BOUNDARIES, 
C                    IN X AND Y GLOBAL COORDINATES (OPPOSITE SIGN OF INCOMING)
C                    PRODUCED BY SUBROUTINE DATATIM
C         BEMELSTR : DATA OF INICIAL HOOP STRESSES, USED IN
C                    SUBROUTINE HOOP OF THE BEM MAIN PROGRAM.
C     FOR ALL THE CASES 
C         POSTDAT  : FILE FOR WRITING DATA PLOTING DATA USED IN
C                    PROCESSING AND POSTPROCESSING
C------------------------------------------------------------
C     LAPLACE DOMAIN (ELASTODYNAMIC CASE), TRANSIENT AND STEADY STATE CASE
      IF((NDOMA.EQ.1).OR.(NDOMA.EQ.4))THEN
        OPEN (UNIT=1,FILE='BEMLTDAT',STATUS='UNKNOWN')
        OPEN (UNIT=2,FILE='BEMLTSTR',STATUS='UNKNOWN')
        OPEN (UNIT=3,FILE='BEMLTTRA',STATUS='UNKNOWN')
      ENDIF
C     TIME DOMAIN (ELASTODYNAMIC CASE)
      IF(NDOMA.EQ.2)THEN
        OPEN (UNIT=1,FILE='BEMTDDAT',STATUS='UNKNOWN')
        OPEN (UNIT=2,FILE='BEMTDSTR',STATUS='UNKNOWN')
        OPEN (UNIT=3,FILE='BEMTDTRA',STATUS='UNKNOWN')
      ENDIF
C     ELASTOSTATIC CASE
      IF(NDOMA.EQ.3)THEN
        OPEN (UNIT=1,FILE='BEMELDAT',STATUS='UNKNOWN')
        OPEN (UNIT=2,FILE='BEMELSTR',STATUS='UNKNOWN')
        OPEN (UNIT=3,FILE='BEMELTRA',STATUS='UNKNOWN')
      ENDIF
C     FILE FOR WRITING DATA USED IN POSTBEM PLOTING 
C     ROUTINE
      OPEN (UNIT=4,FILE='POSTDAT',STATUS='UNKNOWN')
C     FILE FOR WRITING TEMPORARY DATA FOR EXPLOSION POINT WAVE 
      OPEN (UNIT=11,STATUS='SCRATCH')
C
      REWIND 1
      REWIND 2
      REWIND 3
      REWIND 4
      REWIND 11
C
C     IF HOOP MODULE IS NOT PRESENT, THEN NUMBER OF ELEMENTS FOR
C     CALCULATING THE HOOP STRESSES IS THE NUMBER OF ALL THE NODES
      IF(NHOOP.EQ.0) NHOOP=NELEM
C
C     IN ELESTOSTATIC CASE, NSTEP IS 1 INSTEAD OF 20
      IF(NDOMA.EQ.3) NSTEP=1
C
      WRITE(1,*)NNODE,NELEM,NSTEP,NHOOP,NDOMA,NFFS,NUNIT
C     CASE THAT NHOOP<NNODE WRITE THE POSITION ELEMENTS (HOOP STRESSES
C     AT EACH NODE)
      IF(NHOOP.LT.NELEM) WRITE(1,*)(NHPOS(K),K=1,NHOOP)
C
C     FOR LAPLACE DOMAIN ONLY, WRITE THE PARAMETER AND MODEL FOR VOSCOCITY
C     TRANSIENT AND STEADY STATE CASE
      IF((NDOMA.EQ.1).OR.(NDOMA.EQ.4)) THEN
        WRITE(1,*)FVISC,NMODE
      ENDIF
C
C     FOR LAPLACE TRANSFORM DOMAIN CASE, WRITE THE 3 NECESERY NUMBERS
C     FOR FFT (TRANSIENT AND STEADY STATE CASE)
      IF((NDOMA.EQ.1).OR.(NDOMA.EQ.4))WRITE(1,*)(JP1(K),K=1,5)
C
C     CONVERT TO DOUBLE-PRECISION
      FAI=RANGL
      RNU=RPOIS 
      RHO=RDENS
      TIM=RTIME
      SIGC=RSIGC
      FM=RFM
      FS=RFS
C     COORDINATES OF THE FIRST WAVE ARRIVAL POINT
      WAVX=RPX
      WAVY=RPY
C
      DRSTRE=RSTRE
      DRNSTRE=RNSTRE
      DRNORM=RNORM
      FN1=DCOS(FAI)
      FN2=DSIN(FAI)
      CALL STRGLOB(DRSTRE,DRNSTRE,DRNORM,FN1,FN2,SXX,SYY,SXY)
C     CALCULATE THE L LAME'S CONSTANT FROM E: YOUNG'S MODULUS RYOUN
C                                     AND POISSON'S RATIO RPOIS
C     RMU=E/(2(1+NU))
      RMU=RYOUN/(2.0D0*(1.0D0+RNU))
      RLA=RNU*RYOUN/((1.0D0+RNU)*(1.0D0-2.0D0*RNU))
C---------------------------------------------------
C     FOR PLANE STRESS V=V/(1+V), L'=2*L*MU/(L+2*MU)
C---------------------------------------------------
      IF (NANAL.EQ.2) THEN
        RNU=RNU/(1.0D0+RNU)
        RLA=2.0D0*RLA*RMU/(RLA+2.0D0*RMU)
      ENDIF
      JMAX=MND*2+1
      LMAX=MND*13+1
      JILMAX=MND*2+1
      JERMAX=MND*2+1
      JRIGMAX=MND*2+1
      N1=NNODE
      N2=2*NNODE
      N3=NELEM
      N4=3
      N5=3*NNODE
C
C    DYNAMIC STORAGE ALLOCATION
C
      ALLOCATE (RARR(2*N1+1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (ZARR(1+3*N1+2*N2+2*N5),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (SARR(1+3*N1+2*N2+2*N5),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (RARRB(4*N1+1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (RIGR(2*N1+1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (TH0(N1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (TH3(N1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (TH4(N1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (KKONN(3*N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (KKONZON(3*N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (NNDTYPE(N1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (NNONN(3*N1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (NNONZON(3*N1),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (LLBCU(N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
        J1=1
        J2=J1+N1
        J3=J2+N1
        L1=1
        L2=L1+N2
        L3=L2+N5
        L4=L3+N2
        L5=L4+N5
        L6=L5+N1
        L7=L6+N1
        L8=L7+N1
        JER1=1
        JER2=JER1+N1
        JER3=JER2+N1
C
        JRIG1=1
        JRIG2=JRIG1+N1
        JRIG3=JRIG2+N1
C
        JRAR1=1
        JRAR2=JRAR1+N1
        JRAR3=JRAR2+N1
        JRAR4=JRAR3+N1
        JRAR5=JRAR4+N1
C
        IF(J3.GT.JMAX) GO TO 700
        IF(L8.GT.LMAX) GO TO 700
        IF(JRIG3.GT.JRIGMAX) GO TO 700
        IF(JER3.GT.JERMAX) GO TO 700
C
C         CREATE THE GEOMETRY OF THE SECTION
          CALL PROGEOM(RARR(J1),RARR(J2),RARRB(JRAR1),RARRB(JRAR2),
     &      RARRB(JRAR3),RARRB(JRAR4),KKONN,KKONZON,NNODEB,NELEMB,
     &      NSEGM,NSHAP,SEG,JKODE,NCELE,N1,N3,N4,NBOUN,NTSG,
     &      LLBCU,MND,MBD,MDM,LCRN,INES,SGTYP)
C        CREATE AN ARRAY NONN WITH THE  NUMBERS OF THE PREVIOUS,CURRENT
C        AND NEXT NODE (AS KONN, FOR CONNECTIVITY OF ELEMENTS)
C        AND NEW ARRAY FOR THE NODES OF THE ZONE
         CALL NODECON(NNODEB,NBOUN,NNONN,NNONZON,NSHAP,LCRN,
     &                N1,N4)
C-----------------------------------------------------------
C     IF  THERE IS ERROR IN THE GEOMETRY STOP THE PROGRAM
C-----------------------------------------------------------
      IF (IEXIT.EQ.1) THEN
        WRITE(6,373)
  373   FORMAT(1H1,/
     &	   10X,'*******************************************'/
     &	   10X,'**** ERROR IN THE CREATION OF GEOMETRY ****'/
     &     10X,'****       CHECK YOUR DATAFILE         ****'/
     &     10X,'****       PROGRAM TERMINATED          ****'/
     &	   10X,'*******************************************'/)
        WRITE(*,374) FNAMEPRE
  374   FORMAT(/
     &	   10X,'*******************************************'/
     &	   10X,'**** ERROR IN THE CREATION OF GEOMETRY  ***'/
     &     10X,'****    CHECK FOR ERRORS IN THE FILE :  ***'/,A,
     &     10X,'****       PROGRAM TERMINATED           ***'/
     &	   10X,'**************************************** **'/)
        GO TO 999
      ENDIF
C     FOR THE NODES OF AN INCLUSION CASE, SET VALUE OF NDTYPE=1
C     FOR THE NODES OF A FREE SURFACE, SET VALUE OF NDTYPE=2
C     FOR THE NODES OF A SIMULATION SURFACE, SET VALUE OF NDTYPE=3
C     FOR THE NODES OF AN ENCLOSING BOUNDARY, SET VALUE OF NDTYPE=4
      CALL FREESURF(NNDTYPE,N1,N2,NBOUN,NNODEB)
C
C     FIND THE POSITION OF THE WAVE FRONT WHEN IT FIRST ARRIVES
C     AT THE SURFACE OF THE MESH
C     FIND THE CENTER OF THE MESH (OF ALL THE BOUNDARIES)
      XCEN=0.0D0
      YCEN=0.0D0
      KOUNT=0
C   DON'T IGNORE THE BOUNDARY OF THE FREE SURFACE, BECAUSE IT
C   IS NEEDED IN CALCULATING THE DELAYS AND INCIDENT STRESSES ON
C   IT (WAVEFRONT PARALLEL TO THE FREE SURFACE, OR NOT)
C
      DO 110 IB=1,NBOUN
C       IN CASE OF 0 ELEMENTS ON A FREE SURFACE BOUNDARY
        IF((NREGI(IB).EQ.4).AND.(INES.EQ.0)) GO TO 110
        KOUNT=KOUNT+1
        XCEN=XCEN+XCR0(IB)
        YCEN=YCEN+YCR0(IB)
 110  CONTINUE
      XCEN=XCEN/DFLOAT(KOUNT)
      YCEN=YCEN/DFLOAT(KOUNT)
C     CASE THAT FOUND SUBMODULUS XDISTANCE OR YDISTANCE IN
C     MODULUS LOAD.STRESES
      IF(LWAV.EQ.1) THEN
C       CHECK IF THE POLAR ANGLE OF THE POINT ON  THE WAVE FRONT
C       IS EQUAL TO ANGLE OF ATTACK FAI
        WAVCEN=WAVX-XCEN
        IF(DABS(WAVCEN).LT.TOL) WAVCEN=TOL
        PTH=DATAN2((WAVY-YCEN),(WAVCEN))
        IF(PTH.LT.0.0D0) PTH=2.0D0*PI+PTH
        IF(DABS(PTH-FAI).LT.1.0D-6) THEN
          CP=DSQRT((WAVX-XCEN)**2+(WAVY-YCEN)**2)
          GO TO 234
        ENDIF
C       IN CASE THAT THE ANGLES PTH AND FAI ARE DIFFERENT, THE 
C       POINT (WAVX,WAVY) IS DETERMINED AS A POINT ON THE VERTICAL 
C       LINE ON THE WAVEAXIS (WITH ANGLE FAI).
C       THE DISTANCE OF THE CENTER OF THE AXIS FROM THE WAVEFRONT IS 
        CP=DSQRT((WAVX-XCEN)**2+(WAVY-YCEN)**2)*DCOS(PTH-FAI)
C       ONLY ABSOLUTE VALUES 
        CP=DABS(CP)
  234   CONTINUE
        CA=DCOS(FAI)
        CB=DSIN(FAI)
        GO TO 223
      ENDIF
      CALL WAVEFIR(RARR(J1),RARR(J2),RIGR(JRIG1),RIGR(JRIG2),
     &     CA,CB,CP,N1,XCEN,YCEN,NNODEB,NBOUN,INES)
  223 CONTINUE
      CALL WRITEDAT(RARR(J1),RARR(J2),KKONN,KKONZON,
     &  NNONN,NNONZON,MMBCU,LLBCU,NNDTYPE,NNODEB,NELEMB,NTOT,
     &  NPLOT,NDTOT,NDPLOT,LETOT,LEPLOT,CA,CB,CP,NBOUN,XCEN,YCEN,
     &  SIGC,FM,FS,KEXPL,NSHAP,LCRN,N1,N2,N3,N4,MND,MPL,MBD,INES)
       IF((NDOMA.EQ.1).OR.(NDOMA.EQ.4))
     &    CALL DATALAP(RARR(J1),RARR(J2),
     &       KKONN,NNONN,NNODEB,LLBCU,
     &       ZARR(L1),ZARR(L2),ZARR(L3),ZARR(L4),
     &       ZARR(L5),ZARR(L6),ZARR(L7),
     &       SXX,SYY,SXY,N1,N2,N3,N4,N5,
     &       CA,CB,CP,NBOUN,JKODE,NSHAP,NELEMB,NSEGM,SEG,NTSG,
     &       XCEN,YCEN,DRSTRE,DRNSTRE,DRNORM,TH0,TH3,TH4,
     &       KEXPL,KSURF,PSURFX,PSURFY,KTRAC,TRACX,TRACY,MMBCU,
     &       NNDTYPE,LCRN)
C       LOADS IN TIME DOMAIN
C       SLOAD: REAL 
        IF(NDOMA.EQ.2)
     &    CALL DATATIM(RARR(J1),RARR(J2),
     &       KKONN,NNONN,NNODEB,LLBCU,
     &       SARR(L1),SARR(L2),SARR(L3),SARR(L4),
     &       SARR(L5),SARR(L6),SARR(L7),
     &       SXX,SYY,SXY,N1,N2,N3,N4,N5,
     &       CA,CB,CP,NBOUN,JKODE,NSHAP,NELEMB,NSEGM,SEG,NTSG,
     &       XCEN,YCEN,DRSTRE,DRNSTRE,DRNORM,TH0,TH3,TH4,KEXPL,
     &       MMBCU,NNDTYPE,LCRN)
C                TSXX,TSYY,TSXY,
C       LOADS IN ELASTOSTATIC CASE
C       SLOAD: REAL
        IF(NDOMA.EQ.3) 
     &    CALL DATAEL(RARR(J1),RARR(J2),KKONN,NNONN,NNODEB,
     &      LLBCU,SARR(L1),SARR(L2),SXX,SYY,SXY,
     &      N1,N2,N3,N4,N5,NBOUN,XCEN,YCEN,NNDTYPE)
C
C
      IF (IEXIT.EQ.1) THEN
        WRITE(6,375)
  375   FORMAT(/
     &	   10X,'*******************************************'/
     &	   10X,'**** ERROR IN THE CALCULATIONS OF LOADS ***'/
     &     10X,'****       CHECK YOUR DATAFILE          ***'/
     &     10X,'****       PROGRAM TERMINATED           ***'/
     &	   10X,'**************************************** **'/)
        WRITE(*,377) FNAMEPRE
  377   FORMAT(/
     &	   10X,'*******************************************'/
     &	   10X,'**** ERROR IN THE CALCULATIONS OF LOADS ***'/
     &     10X,'****    CHECK FOR ERRORS IN THE FILE :  ***'/,A,
     &     10X,'****       PROGRAM TERMINATED           ***'/
     &	   10X,'**************************************** **'/)
        GO TO 999
      ENDIF
C---------------------------------------------
C       PLOTING OF THE MESH (USING UNIRAS FGL)
C---------------------------------------------
       CALL PLMESH(RARR(J1),RARR(J2),N1,CA,CB,CP,NNODEB,NBOUN,XCEN,
     &    YCEN,NNDTYPE,KEXPL,NTOT,NPLOT,NSHAP,LCRN,MPL,MBD,INES)

        GO TO 706
 700    CONTINUE
      STOP
 706  CONTINUE
      CLOSE (UNIT=1,STATUS='KEEP')
      CLOSE (UNIT=2,STATUS='KEEP')
      CLOSE (UNIT=3,STATUS='KEEP')
      CLOSE (UNIT=4,STATUS='KEEP')
      CLOSE (UNIT=6,STATUS='KEEP')
      CLOSE (UNIT=7)
      CLOSE (UNIT=11)
C
C     AT THIS POINT ASK THE USER IF HE WANTS TO CONTINUE THE PROCESSING
C     OR STOP THE PROGRAM
C
        WRITE(*,400) FNAMEPRE
  400   FORMAT(1H1,/
     &	   10X,'*******************************************'/
