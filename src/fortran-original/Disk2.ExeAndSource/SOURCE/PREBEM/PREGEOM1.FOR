C ----------------------------------------------------------------------
      SUBROUTINE PROGEOM(XCR,YCR,RARRBX,RARRBY,XT,YT,KONN,KONZON,
     &  NNODEB,NELEMB,NSEGM,NSHAP,SEG,JKODE,NCELE,N1,N3,N4,NBOUN,
     &  NTSG,LLBCU,MND,MBD,MDM,LCRN,INES,SGTYP)

C^^^^^^^^^^^^^^^^^^^^
C           INES : INDEX 0: NUMBER OF ELEMENTS IN A SEGMENT WERE 0
C                        1: THERE WERE NOT 0 NUMBER OF ELEMENTS IN ANY SEGMENT
C
C     XCR,YCR: RETURN VALUES OF COORDINATES OF ALL THE NODES 
C     NNODEB,NELEMB,NSEGM: TOTAL NODES,ELEMENTS,SEGMENTS OF ALL
C                          BOUNDARIES OF THE MESH
C     NSHAP,JKODE: NUMBERS OF SHAPE AND CODE
C     NCELE: NUMBER OF ELEMENTS OF EACH SEGEMENT
C     N1: TOTAL NODES OF THE MESH
C     NBOUN: NUMBER OF BOUNDARIES
C     NTSG: NUMBER OF TOTAL SEGMENTS OF THE MESH
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C     ********COMMONBLOCKS*******
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION RARRBX(N1),RARRBY(N1)
      DIMENSION XT(N1),YT(N1)
      DIMENSION NNODEB(NBOUN),NELEMB(NBOUN),NSEGM(NBOUN)
      DIMENSION NSHAP(NBOUN),JKODE(NTSG)
      DIMENSION NCELE(NTSG)
      DIMENSION SEG(NTSG*7)
      DIMENSION KONN(N3,N4),KONZON(N3,N4)
C            ,KONNOT(N3,N4)
      DIMENSION LLBCU(N3)
C     CHANGING MBD IN MAIN PROGRAM, NUMBER 5 MUST BE CHANGED TO NBD ALSO
      DIMENSION RAD(5),RATIO(5),SID(5),XSID(5),YSID(5)
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &         TYPELY(5),NDIS(5)
      DIMENSION PSAI(5)
      DIMENSION NSIMU(5)
      DIMENSION NREGI(5)  
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION KDIAK(5)
      DIMENSION LCRN(8)
      DIMENSION SGTYP(NTSG)
C
      KX=0
      KY=0
      KIB=0
      KIZ=0
      KIN=0
      NOD=3
C     INDEX FOR THE SIMULATION BOUNDARY
      CALL ICLRIRR(KDIAK,MBD)
      CALL ICLRIRR(LLBCU,N3)
      DO 1 KK=1,MBD
        K1=NSIMU(KK)
        DO 2 II=1,NBOUN
          IF(II.EQ.K1) KDIAK(II)=1
  2     CONTINUE
  1   CONTINUE
C     COUNTER FOR NUMBER OF OPEN SURFACES
      NOS=0
C     COUNTER FOR COMPLITING ARRAY SEG (ONLY COMBOUND BOUNDARIES)
      JL=1
C     COUNTER FOR NUMBER OF CURRENT SEGMENT
      IBI=0
C     LOOP FOR ALL THE BOUNDARIES
      DO 50 K=1,NBOUN
C       IN CASE OF 0 ELEMENTS ON A FREE SURFACE BOUNDARY
        IF((NREGI(K).EQ.4).AND.(INES.EQ.0)) GO TO 50
        IZDIAK=0
        NS=NSEGM(K)
        NB1=NNODEB(K)
        NB2=2*NNODEB(K)
        NB3=NELEMB(K)
C       CREATE THE GEOMETRY OF THE SECTION
        CALL GEOMETR(RARRBX,RARRBY,XT,YT,SEG,NCELE,JKODE,NSHAP,
     &    NB1,NB2,NB3,NS,K,NBOUN,NTSG,JL,IBI,LR,LCRN,INES,
     &    SGTYP)
        DO 55 II=1,NB1
          KX=KX+1
          XCR(KX)=RARRBX(II)
  55    CONTINUE
        DO 58 II=1,NB1
          KY=KY+1
          YCR(KY)=RARRBY(II)
  58     CONTINUE
C     CONNECTIVITY (TOPOGRAPHY)
C       OR ENCLOSING ELEMENTS BOUNDARY (LIKE INCLUSION)
        IF((NREGI(K).EQ.2).OR.(NREGI(K).EQ.5).OR.
     &       (KDIAK(K).EQ.1)) IZDIAK=1
C       CASE OF OPEN SURFACE
C       -------------------- 
        IF((NREGI(K).EQ.3).OR.(NREGI(K).EQ.4))THEN  
          DO 23 I=1,NELEMB(K)
            KIB=KIB+1
            KONN(KIB,1)=2*KIB-1+NOS 
            KONN(KIB,2)=2*KIB+NOS
            KONN(KIB,3)=2*KIB+1+NOS
C           IN CASE OF INCLUSIONS OR SIMULATION, CREATE ALSO TWO NEW 
C           CONNECTIVITY ARRAYS (WITH NEW NUMBERING), AND THE SAME 
C           DIMENSIONS AS KONN. THESE WILL BE USED IN THE ANALYSIS PROGRAM 
C           TO INDETIFY THE POSITION OF THE KERNELS IN THE LEFT HAND ARRAY
C           KONZON: FOR THE NODES OF ZONE
C           KONNOT: FOR THE NODES OF NON ZONE
C
C           FOR THE ZONE NODES
            IF(IZDIAK.EQ.1) THEN
              KIZ=KIZ+1
C             KIB IS THE GLOBAL ELEMENT NUMBER
C             ARRAY FOR THE ZONE NODES
              KONZON(KIB,1)=2*KIZ-1+NOZ
              KONZON(KIB,2)=2*KIZ+NOZ
              KONZON(KIB,3)=2*KIZ+1+NOZ
            ENDIF
C           IN CASE OF INCLUSION, GIVE THE ELEMENT A CODE NUMBER LLBCU=1
            IF(NREGI(K).EQ.2) LLBCU(KIB)=1
C           IN CASE OF FREE SURFACE, GIVE THE ELEMENT A CODE NUMBER LLBCU=2
            IF(NREGI(K).EQ.4) LLBCU(KIB)=2
C           SIMULATION CASE
            IF(KDIAK(K).EQ.1) LLBCU(KIB)=3
C           ELEMENT ON ENCLOSING BOUNDARY
            IF((NREGI(K).EQ.5).OR.(NREGI(K).EQ.6)) LLBCU(KIB)=4
  23      CONTINUE
          NOS=NOS+1
          KAKIB=KAKIB+2*NELEMB(K)+NOS
C         FOR THE ZONE NODES
          IF(IZDIAK.EQ.1) THEN
            NOZ=NOZ+1
            KAKIZ=KAKIZ+2*NELEMB(K)+NOZ
          ENDIF
C         FOR THE NON ZONE NODES
          IF(IZDIAK.EQ.0) THEN
            NON=NON+1
            KAKIN=KAKIN+2*NELEMB(K)+NON
          ENDIF
        ENDIF
C
C       CASE OF CLOSED SURFACE (NOT OPEN)
C       ---------------------------------
        IF ((NREGI(K).EQ.1).OR.(NREGI(K).EQ.2).OR.
     &          (NREGI(K).EQ.5).OR.(NREGI(K).EQ.6)) THEN
C         FIRST NODE OF THE BOUNDARY
          KAKIA=KAKIB+1
C         LAST NODE OF THE BOUNDARY
          KAKIB=KAKIB+2*NELEMB(K)
C         FOR THE ZONE NODES
          IF(IZDIAK.EQ.1) KAKIZ=KAKIZ+2*NELEMB(K)
C         FOR THE NON ZONE NODES
          IF(IZDIAK.EQ.0) KAKIN=KAKIN+2*NELEMB(K)
          DO 25 I=1,NELEMB(K)
C           CURRENT ELEMENT
            KIB=KIB+1
C           USUAL CASE OR CASE THAT THE Y SIDE (OF RECTANGLE SHAPE),
C           HAS ODD NUMBER OF 
C           ELEMENTS
            KONN(KIB,1)=2*KIB-2+NOS
            KONN(KIB,2)=2*KIB-1+NOS
            KONN(KIB,3)=2*KIB+NOS
C           FIRST ELEMENT
            IF(I.EQ.1)KONN(KIB,1)=KAKIB
C            ENDIF
C           IN CASE OF RECTANGLE OR SQUARE AND IN CASE THAT THE Y SIDE
C           (OF RECTANGLE SHAPE), HAS EVEN NUMBER OF ELEMENTS
            IF((NSHAP(K).EQ.2).OR.(NSHAP(K).EQ.3)) THEN
              IF(LR.EQ.0) THEN
                KONN(KIB,1)=2*KIB-1+NOS 
                KONN(KIB,2)=2*KIB+NOS
                KONN(KIB,3)=2*KIB+NOS+1
C               FIRST ELEMENT
               IF(I.EQ.1)KONN(KIB,1)=KAKIA
               IF(I.EQ.NELEMB(K))KONN(KIB,3)=KAKIA
              ENDIF
            ENDIF
C           IN CASE OF INCLUSIONS OR SIMULATION, CREATE ALSO A NEW
C           CONNECTIVITY ARRAY (WITH NEW NUMBERING)
C
C           FOR THE ZONE NODES
            IF(IZDIAK.EQ.1) THEN
              KIZ=KIZ+1
C             KIB IS THE GLOBAL ELEMENT NUMBER
              KONZON(KIB,1)=2*KIZ-2+NOZ 
              KONZON(KIB,2)=2*KIZ-1+NOZ
              KONZON(KIB,3)=2*KIZ+NOZ
C             FIRST ELEMENT
              IF(I.EQ.1)KONZON(KIB,1)=KAKIZ
            ENDIF
C            INCLUSION CASE
             IF(NREGI(K).EQ.2) LLBCU(KIB)=1
C            SIMULATION CASE
             IF(KDIAK(K).EQ.1) LLBCU(KIB)=3
C           ELEMENT ON ENCLOSING BOUNDARY
            IF((NREGI(K).EQ.5).OR.(NREGI(K).EQ.6)) LLBCU(KIB)=4
  25       CONTINUE
C          FOR SQUARE OR RECTANGLE AND
C          IN CASE OF DISCONTINUITY AT THE CORNERS, DUPLICATE THE CORNER 
C          NODE OF NUMBERING, BY GIVING TO THE ONE OF THE 2 JOINING
C          ELEMENTS MAXIMUM NODES PLUS 1)
C          NEW CONNECTIVITY NUMBER (NEMBER OF MTAKE THE NODES INCREASED
C          BY 1 (AT THE 4 CORNERS)
           IF(((NSHAP(K).EQ.2).OR.(NSHAP(K).EQ.3)).AND.
     &           (NDIS(K).EQ.2)) THEN
C            CURRENT ELEMENT
             KIB=0
C            MAXIMUM NUMBER OF NODES
             NMAX=N1-4
             DO 67 I=1,4
               KIB=0
               DO 68 J=1,NELEMB(K)
C                CURRENT ELEMENT
                 KIB=KIB+1
                   DO 69 II=1,NOD
                     LN=KONN(KIB,II)
C                    CASE THAT THE CONNECTIVITY NODE IS A CORNER NODE
                     IF(LN.EQ.LCRN(I)) THEN
C                      FIND THE REST OF THE ELEMENTS THAT HAVE THIS NODE 
C                      AS CONNECTIVITY NODE
C                      CURRENT NODE
                       JIB=0
                       DO 70 JJ=1,NELEMB(K)
                         JIB=JIB+1
                         DO 70 KK=1,NOD
                           LN=KONN(JIB,KK)
C                          CASE THAT THE CONNECTIVITY NODE IS A CORNER NODE
C                          AND IS DIFFERENT THAN KIB, CHANGE THE CONNECTIVITY
C                          NUMBER BY A NEW NUMBER EQUAL TO MAXIMUM NODE 
C                          NUMBERS PLUS ONE
                           IF((LN.EQ.LCRN(I)).AND.(JIB.NE.KIB)) THEN
                             NMAX=NMAX+1
                             KONN(JIB,KK)=NMAX
C                            COORDINATES OF THIS NODE THE SAME AS LCRN(I)
                             XCR(NMAX)=XCR(LCRN(I))
                             YCR(NMAX)=YCR(LCRN(I))
C                            KEEP THE NUMBER OF THIS DUPLICATED NODE IN THE
C                            ARRAY LCN, AT A POSITION I+4 (THE 4 FIRST NUMBERS
C                            IN LCN ARE THE NODE NODES AND THE 4 LAST NUMBERS
C                            ARE THE  DUPLICATED NODES)
                             LCRN(I+4)=NMAX
                           ENDIF
  70                   CONTINUE
                     ENDIF
  69               CONTINUE
C                  INCREASE CURRENT ELEMENT
  68           CONTINUE
  67         CONTINUE
           ENDIF
        ENDIF
  50  CONTINUE
      RETURN
      END
C -----------------------------------------------------------------------
      SUBROUTINE GEOMETR(XCR,YCR,XT,YT,SEG,NCELE,JKODE,NSHAP,
     &  N1,N2,N3,NS,IB,NBOUN,NTSG,JL,IBI,LR,LCRN,INES,
     &  SGTYP)

C   CALCULATES THE GEOMETRY OF THE MESH
C   (EMPTY CAVITY, OUTER PROBLEM)
C
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
C^^^^^^^^^^^^^^^^^^^^
C           INES : INDEX 0: NUMBER OF ELEMENTS IN A SEGMENT WERE 0
C                        1: THERE WERE NOT 0 NUMBER OF ELEMENTS IN ANY SEGMENT
C
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION XT(N1),YT(N1)
C     ******COMMONBLOCKS********
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      DIMENSION SEG(NTSG*7),NCELE(NTSG)
      DIMENSION JKODE(NTSG)
      DIMENSION NSHAP(NBOUN)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5),XCR0(5),YCR0(5)
      DIMENSION PSAI(5)
      DIMENSION NREGI(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &          TYPELY(5),NDIS(5)
      DIMENSION LCRN(8)
      DIMENSION SGTYP(NTSG)
      PI=3.14159265359D0
C     SIMPLE SHAPE
C     ============
C     CIRCLE ,ELLIPSE
C     ---------------
      IF (NSHAP(IB).EQ.1)  THEN
C       ANGLES OF START AND END POINTS OF THE ELLIPTICAL SEGMENT
C       AS START POINT WE WANT THE FIRST NODE OF THE MESH, ON THE LOCAL
C       AXIS WITH ANGLE PSAI(IB)
        TH1=PSAI(IB)
        TH2=2*PI+PSAI(IB)
C       PSAI(IB) HAS ALREADY CONVERTED IN RADIANS IN MODULUS SECT
C       BUT ATTENTION :ONLY FOR SIMPLE SECTIONS(NOT COMBOUND) 
        PSI=PSAI(IB)
        NELR=NXELE(IB)
        RAD1=RAD(IB)
        RATIO1=RATIO(IB)
C       NUMBER OF NODES ON THE SHAPE
        NODSEG=N1
        X0=XCR0(IB)
        Y0=YCR0(IB)
        NREGION=NREGI(IB)
        CALL GEOELL(XCR,YCR,X0,Y0,TH1,TH2,PSI,NELR,RAD1,
     &                   RATIO1,NODSEG,NREGION,XLAST,YLAST)
      ENDIF
C     SQUARE,RECTANGLE
C     ----------------
      IF ((NSHAP(IB).EQ.2).OR.(NSHAP(IB).EQ.3)) THEN
        PSI=PSAI(IB)
        NELX=NXELE(IB)
        NELY=NYELE(IB)
        ALEN=SID(IB)
        ALENX=XSID(IB)
        ALENY=YSID(IB)
        NSHAP1=NSHAP(IB)
        XCEN=XCR0(IB)
        YCEN=YCR0(IB)
        NREGION=NREGI(IB)
        CALL GEOBOX(XCR,YCR,XT,YT,N1,NELX,NELY,ALEN,ALENX,ALENY,
     &          NSHAP1,PSI,XCEN,YCEN,NREGION,IB,LR,LCRN)
      ENDIF
C     STRAIGHT LINE
C     -------------
      IF (NSHAP(IB).EQ.4) THEN
        NELX=NXELE(IB)
        XCEN=XCR0(IB)
        YCEN=YCR0(IB)
        CALL GEOSTRLN(XCR,YCR,N1,NELX,XCEN,YCEN,IB)
      ENDIF

C     COMBOUND SHAPE
C     ==============
      IF(NSHAP(IB).LT.0) THEN
        CALL GEOCOMB(XCR,YCR,SEG,NCELE,JKODE,NS,N1,IB,
     &           JL,IBI,SGTYP,NTSG)
C       FOR COMBOUND SHAPES FIND THE CENTER OF THE SHAPE AS
C       THE CENTER OF CENTROIDS
        XCR0(IB)=0.0D0
        YCR0(IB)=0.0D0
        DO 20 I=1,N1
          XCR0(IB)=XCR0(IB)+XCR(I)
          YCR0(IB)=YCR0(IB)+YCR(I)
   20   CONTINUE
        XCR0(IB)=XCR0(IB)/DFLOAT(N1)
        YCR0(IB)=YCR0(IB)/DFLOAT(N1)
      ENDIF
  38  CONTINUE
      RETURN
      END
C -----------------------------------------------------------------------
      SUBROUTINE GEOELL(XND,YND,X0,Y0,TH1,TH2,PSI,NELR,
     &               RAD1,RATIO1,NODSEG,NREGION,XLAST,YLAST)
C   CALCULATES THE CORDINATES OF THE NODES ON AN ELLIPTICAL (OR CIRCULAR)
C   SEGMENT, IN A GLOBAL COORDINATE SYSTEM.
C        XND,YND : COORDINATES OF NODES FOR CALCULATION, RETURN VALUE
C        X0,Y0   : COORDINATES OF THE CENTER OF ELLIPSE IN GLOBAL SYSTEM
C        TH1,TH2 : ANGLE OF START AND END OF ELLIPTICAL SEGMENT, 
C                  MEASURED IN  THE GLOBAL SYSTEM[RADIANS], ANTICLOCKWISE
C                  DIRECTION ALWAYS. 
C                  IN EXTERIOR PROBLEMS TH1 IS THE ANGLE 
C                  (ANTICLOCK. DIR.) OF THE FIRST POINT OF THE SEGMENT
C                  AND TH2 IS THE ANGLE(ANTICLOCK. DIR.) OF THE END POINT 
C                  OF THE SEGMENET IN CLOCKWISE DIR DISTANCE.
C                  IN INTERIOR PROBLEMS TH1 IS THE ANGLE 
C                  (ANTICLOCK. DIR.) OF THE FIRST POINT OF THE SEGMENT
C                  AND TH2 IS THE ANGLE(ANTICLOCK. DIR.) OF THE END POINT 
C                  OF THE SEGMENET IN ANTICLOCKWISE DIR DISTANCE.
C        PSI     : ANGLE OF ONE AXIS OF THE LOCAL SYSTEM WITH GLOBAL SYSTEM, 
C                  IN [RADIANS], MEASURED IN ANTICLOCKWISE DIRECTION.
C                  THIS LOCAL AXIS CAN BE ANY OF THE TWO AXIS. THE PROGRAM
C                  AUTOMATICALLY RECODNISE THE AXIS.
C        NELR    : NUMBER OF ELEMENTS ON THE SEGMENT
C        NODSEG  : NUMBER OF NODES ON THE SHAPE
C        XLAST,YLAST: RETURN VALUES OF THE COORDIANATES OF THE LAST NODE 
C                    (NEEDED FOR OPEN BOUNDARIES)
C
C   LOCAL VARIABLES:
C                XY(I,J), I=1,3: NODES OF ELEMENT, START,MIDDLE,END
C                         J=1,2: X,Y COORDINATES OF NODE I
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION XND(NODSEG),YND(NODSEG)
C      DIMENSION TH(NODSEG)
C     ******COMMONBLOCKS********
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/BLKEX/IEXIT
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON/GEOM4/NXELE,NYELE
      DIMENSION XB(3),SHP(3),XY(3,2)
      DIMENSION PROD(2)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5),XCR0(5),YCR0(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &       TYPELY(5),NDIS(5)
C
      PI=3.14159265359D0
      L1=0
      F1=TH1-PSI
      F2=TH2-PSI
      GD=1.0E-11
      TOL=1.0E-6
      GA=RATIO1*DCOS(F1)
      IF(DABS(GA).LT.GD)GA=GD
      GB=RATIO1*DCOS(F2)
      IF(DABS(GB).LT.GD)GB=GD
C     ------------------------
C     GLOBAL COORDINATE SYSTEM
C     ------------------------
C     VALUES OF GE (GLOBAL SYSTEM)
C       TH1: POLAR ANGLE OF START POINT P1 OF THE ELLIPTICAL SEGMENT
C       TH2: POLAR ANGLE OF THE END POINT P2 OF THE ELLIPTICAL SEGMENT
C     EXTERIOR PROBLEM (CLOCKWISE)
C       GE=-1: FOR TH1>TH2, THIS HAPPENS WHEN THE ELEMENT P1P2 IS NOT
C                           CROSSING THE X AXIS
C       GE=+1: FOR TH1<TH2, THIS HAPPENS WHEN THE ELEMENT P1P2 IS 
C                           CROSSING THE X AXIS
C     INTERIOR PROBLEM (ANTICLOCKWISE)
C       GE=+1: FOR TH2>TH1, THIS HAPPENS WHEN THE ELEMENT P1P2 IS NOT
C                           CROSSING THE X AXIS
C       GE=-1: FOR TH2<TH1, THIS HAPPENS WHEN THE ELEMENT P1P2 IS 
C                           CROSSING THE X AXIS
C     CHECK FOR EQUAL ANGLES OF START AND END OF ELEMENT
      IF(DABS(TH2-TH1).LT.TOL) THEN
        WRITE(6,500)TH1,TH2
        IEXIT=1
        GO TO 90
      ENDIF
      GE=(TH2-TH1)/(DABS(TH2-TH1))
C     -----------------------
C     LOCAL COORDIANTE SYSTEM
C     ----------------------- 
C     ANGLE OF THE START OF THE SEGMENT WITH LOCAL SYSTEM, ALWAYS 
C     IN ANTICLOCKWISE DIRECTION
C       CHI1=ARCTAN[SIN(TH1-PSI)/(B/A*COS(TH1-PSI)]
      CHI1=DATAN2(DSIN(F1),GA)
C     ANGLE OF THE END OF THE SEGMENT WITH LOCAL SYSTEM, ALWAYS
C     IN ANTICLOCKWISE DIRECTION
      CHI2=DATAN2(DSIN(F2),GB)
C     ANGLE BETWEEN START AND END OF ONE ELEMENT OF THE SEGMENT
C     WE ACCEPT THAT DIVIDE THE SEGMENT IN ELEMETS WITH EQUAL ANGLES 
C     BETWEEN THEM
      DCHI=(CHI2-CHI1)/(DFLOAT(NELR))
C     VALUES OF GC (LOCAL SYSTEM)
C     GC IS AN INTEGER NUMBER THAT TAKES VALUES 0,-2 OR +2 
C     IF OMEGA IS THE ANGLE BETWEEN THE START POINT P1 OF THE ELLIPTICAL
C     SEGMENT AND THE END POINT P2 AND
C     CHI1,CHI2 IS THE POLAR ANGLE OF START  P1 AND END  P2 POINT OF THE
C     SEGMENT IN THE LOCAL COORDINATE SYTEM THEN
C     EXTERIOR PROBLEM (CLOCKWISE)
C       GC=-1: FOR CHI1>CHI2,THIS HAPPENS WHEN THE ELEMENT P1P2 IS NOT
C                           CROSSING THE LOCAL M (X) AXIS
C       GC=+1: FOR CHI1<CHI2, THIS HAPPENS WHEN THE ELEMENT P1P2 IS 
C                           CROSSING THE LOCAL M (X) AXIS
C     INTERIOR PROBLEM (ANTICLOCKWISE)
C       GC=+1: FOR CHI2>CHI1, THIS HAPPENS WHEN THE ELEMENT P1P2 IS NOT
C                           CROSSING THE LOCAL M (X) AXIS
C       GC=-1: FOR CHI2<CHI1, THIS HAPPENS WHEN THE ELEMENT P1P2 IS 
C                           CROSSING THE LOCAL M (X) AXIS
      IF(DABS(DCHI).LT.GD)GO TO 6
      GC=DCHI/(DABS(DCHI))
      GO TO 5
C     EXTERIOR PROBLEM
    6 IF(NREGION.EQ.1) GC=1.0D0
C      OR ENCLOSING ELEMENTS BOUNDARY (ANTICLOCKWISE)
C      INTERIOR PROBLEM
       IF((NREGION.EQ.2).OR.(NREGION.EQ.5)) GC=-1.0D0
C       GC=-1.0D0
C       GF= 0  : THE LOCAL M (X) AXIS DOES NOT CUT THE SEGMENT 
C       GF= -2 : EXTERIOR PROBLEM(CLOCKWISE), THE LOCAL M (X) AXIS
C                CUTS THE SEGMENT
C       GF= +2 : INTERIOR PROBLEM(ANTICLOCKWISE), THE LOCAL M (X) AXIS
C                CUTS THE SEGMENT
    5 GF=0.0D0
C     EXTERIOR PROBLEM IF GC= 1, GE= 1 
C                      OR GC= 1, GE=-1 THEN GF=-2
C                      (THE SAME RESULT FOR ONLY GC=1, BUT IT MUST BE 
C                      CHECKED FOR ALL THE OCASIONS)
      IF(NREGION.EQ.1)THEN
        IF(((DABS(GC-1.0D0).LT.TOL).AND.(DABS(GE-1.0D0).LT.TOL)).OR.
     &     ((DABS(GC-1.0D0).LT.TOL).AND.(DABS(GE+1.0D0).LT.TOL))) 
     &    GF=-2.0D0
      ENDIF
C     INTERIOR PROBLEM IF GC=-1, GE=-1 
C                      OR GC=-1, GE= 1 THEN GF= 2
C                      (THE SAME RESULT FOR ONLY GC=-1, BUT IT MUST BE 
C                      CHECKED FOR ALL THE OCASIONS)
C          THEN GF=2
C       OR ENCLOSING ELEMENTS BOUNDARY (LIKE INCLUSION)
      IF((NREGION.EQ.2).OR.(NREGION.EQ.5))THEN
        IF(((DABS(GC+1.0D0).LT.TOL).AND.(DABS(GE+1.0D0).LT.TOL)).OR.
     &     ((DABS(GC+1.0D0).LT.TOL).AND.(DABS(GE-1.0D0).LT.TOL))) 
     &    GF=2.0D0
      ENDIF
      DCHI=DCHI+GF*PI/(DFLOAT(NELR))
C     ANGLE OF THE END OF THE SEGMENT
      CHI3=DCHI*DFLOAT(NELR)
C     CASE OF A CLOSED ELLIPTICAL SHAPE
      IF(DABS(DABS(CHI3)-2.0D0*PI).LT.TOL) THEN
        KCLOSE=1
        NELNODE=2*NELR 
      ELSE
C     CASE OF AN OPEN ELLIPTICAL SEGMENT
        KCLOSE=2
C        NELNODE=2*NELR+1
        NELNODE=2*NELR
      ENDIF
      DO 10 I=1,NELR
        CHI=CHI1+DFLOAT(I-1)*DCHI
C       EXTERIOR PROBLEM(CLOCKWISE DIRECTION)
        IF(NREGION.EQ.1) CHI=CHI+2*PI
C       COORDINATES OF START OF ELEMENT
        XY(1,2)=RAD1*(DCOS(CHI)*DSIN(PSI)+
     &                 DSIN(CHI)*DCOS(PSI)*RATIO1)
C                 +X0
        XY(1,1)=RAD1*(DCOS(CHI)*DCOS(PSI)-
     &                 DSIN(CHI)*DSIN(PSI)*RATIO1)
C       COORDINATES OF END OF ELEMENT
        CHI=CHI+DCHI
        XY(3,2)=RAD1*(DCOS(CHI)*DSIN(PSI)+
     &               DSIN(CHI)*DCOS(PSI)*RATIO1)
        XY(3,1)=RAD1*(DCOS(CHI)*DCOS(PSI)-
     &               DSIN(CHI)*DSIN(PSI)*RATIO1)
C
C       COORDINATES OF THE MIDDLE NODE OF THE ELLIPTICAL SEGMENT
C       --------------------------------------------------------
C       FIND FIRST THE COORDINATES OF THE MIDDLE NODE OF THE LINE CONNECTING
C       THE START AND END NODES OF THE ELEMENT
        NOD=2
        EKS=0.0D0
        CALL MORFH(EKS,NOD,SHP)
        DO 20 J=1,2
          XB(1)=XY(1,J)
          XB(2)=XY(3,J)
          CALL PRODUCT(XB,SHP,NOD,DOT)
          PROD(J)=DOT
   20   CONTINUE      
C       X,Y COORDINATES OF THE MIDDLE NODE ON THE STRAIGHT LINE
C       CONNECTING THE START AND END OF THE SEGMENT
        DO 50 J=1,2
          XY(2,J)=PROD(J)
   50   CONTINUE
C       PROJECT THE POINT FROM THE STREIGHT LINE, ON THE SURFACE OF THE
C       ELLIPSE
C       POLAR ANGLE IN THE GLOBAL SYSTEM
        IF(DABS(XY(2,1)).LT.GD) XY(2,1)=GD
        TH3=DATAN2(XY(2,2),XY(2,1))
C       POLAR ANGLE IN THE LOCAL SYSTEM
        TH3=TH3-PSI
C       POINT ON THE ELLIPSE WITH THIS POLAR ANGLE
        XY(2,2)=RAD1*(DCOS(TH3)*DSIN(PSI)+
     &               DSIN(TH3)*DCOS(PSI)*RATIO1)
        XY(2,1)=RAD1*(DCOS(TH3)*DCOS(PSI)-
     &               DSIN(TH3)*DSIN(PSI)*RATIO1)
C               +Y0
 
C
C       NUMBER OF THE FIRST NODE OF THE ELEMENT
C       FINAL COORDINATES IN GLOBAL COORDINATE SYSTEM (WITH TRANSLATION)
        DO 60 K=1,3
          L1=L1+1
C         LAST NODE IN A CLOSED BOUNDARY
          IF((I.EQ.NELR).AND.(KCLOSE.EQ.1).AND.(K.EQ.3))L1=1
C         IN AN OPEN BOUNDARY CALCULATE  THE COORDINATES OF THE LAST NODE
C
         IF(((I.EQ.NELR).AND.(KCLOSE.EQ.2).AND.(K.EQ.3)).AND.
     &             ((NREGION.EQ.3).OR.(NREGION.EQ.4))) GO TO 74
C
C         IN AN OPEN ELLIPTICAL SEGMENT DON'T TAKE INTO ACOUNT THE
C         LAST NODE. IT WILL BE CALCULATED WITH THE NEXT SEGMENT
          IF((I.EQ.NELR).AND.(KCLOSE.EQ.2).AND.(K.EQ.3))GO TO 60
          XND(L1)=XY(K,1)
          YND(L1)=XY(K,2)
          IF(K.EQ.3)L1=L1-1
          GO TO 60  
   74     XLAST=XY(K,1)
          YLAST=XY(K,2)
   60   CONTINUE 
   10 CONTINUE  
C     FINALLY IN GLOBAL SYSTEM
      DO 70 I=1,NELNODE  
        XND(I)=XND(I)+X0
        YND(I)=YND(I)+Y0
   70 CONTINUE
 500  FORMAT(/,10X,'  ERROR - THE ANGLES OF START ',I4,
     &             ' AND END ',I4
     &       /,10X,' OF THE ELEMENT ARE THE SAME ')
  90  CONTINUE
      RETURN
      END
C -----------------------------------------------------------------------
      SUBROUTINE GEOSTRLN(XCR,YCR,N1,NELX,XCEN,YCEN,IB)
C
C     IT CREATES THE GEOMETRICAL DATA FOR A STRAIGHT LINE, WITH EQUAL QUADRATIC
C     ELEMENTS. CALCULATES THE CORDINATES OF THE NODES IN A GLOBAL COORDIANTE
C     SYSTEM.
C     NUMBERING OF THE NODES FROM THE START GIVEN TO THE LAST GIVEN NODE
C     NELX: NUMBER OF ELEMENTS ON THE STRAIGHT LINE
C     XCR0,YCR0: COORDINATES OF THE CENTER OF THE STRAIGHT IN GLOBAL
C                CARTESIAN SYSTEM
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5),XCR0(5),YCR0(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &        TYPELY(5),NDIS(5)
      DIMENSION RSQ(6)
C
C     START X COORD.
      RSQ(1)=XSTA(IB)
C     START Y COORD.
      RSQ(2)=YSTA(IB)
C     END X COORD.
      RSQ(5)=XLAS(IB)
C     END Y COORD.
      RSQ(6)=YLAS(IB)
C     COORDINATES OF THE MIDDLE NODES OF THE LINE
      RSQ(3)=(RSQ(1)+RSQ(5))/2.0D0
      RSQ(4)=(RSQ(2)+RSQ(6))/2.0D0
C     INTERPOLATION BY QUADRATIC SHAPE FUNCTIONS
      NOD=3
C     ELEMENTS ON LINE, AFTER DIVIDING THE ORIGINAL ELEMENTS WITH
C     A MIDDLE NODE TO HAVE QUADRATIC ELEMENTS
      MX=2*NELX
C     NUMBER OF NODES ON THE LINE, FROM THE KNOWN NUMBER OF ELEMENTS
C     THE LAST NODE IS NOT TAKEN INTO ACCOUNT. IT WILL BE CALCULATED
C     IN THE NEXT SEGMENT(AS FIRST NODE)
      NODSEG=2*NELX
C     LINE TYPE
      PX=TYPELX(IB)
      CALL GEOLIN(XCR,YCR,RSQ,NOD,MX,PX,N1,NODSEG,XLAST,YLAST)
      XCR(MX+1)=XLAST
      YCR(MX+1)=YLAST
      RETURN
      END
C------------------------------------------------------------------------
      SUBROUTINE GEOLIN(XND,YND,RSQ,NOD,MX,PX,N1,NODSEG,
     &                 XLAST,YLAST)
C  STRAIGHT LINE BY INTERPOLATION, USING SHAPE FUNCTIONS.
C  CALCULATES THE COORDINATES IN GLOBAL SYSTEM(VALUES OF XB,YB ARE IN
C  GLOBAL SYSTEM).
C  EACH LINE HAS START,MIDDLE AND END, ELEMENTS
C  FOR THE LAST NODE OF THE LINE ARE NOT FOUND THE COORDINATES
C  THEY ARE FOUND IN THE NEXT SEGMENT(FIRST NODE OF NEXT SEGEMNT) 
C  ELEMENT(BLOCK) AND INTERPOLATION BETWEEN ORIGINS IS SUCCEDED
C  WITH SHAPE FUNCTIONS
C    XND,YND: COORDINATES OF NODAL POINTS, FOR CALCULATION, RETURN VALUE
C    RSQ    : COORDINATES OF THE START,MIDDLE AND END NODES OF A LINE
C    IJK    : ELEMENT CONNECTIVITIES, RETURN VALUE
C    NOD    : TOTAL NUMBERS OF NODAL POINTS IN AN ELEMENT 
C              2: FOR LINE ELEMENTS
C              3: FOR QUADRATIC ELEMENTS
C    MX     : NUMBER OF ELEMENTS IN THE LINE    
C    PX     : PARAMETER OF THE DIVISION 
C               PX=1   THE SIDES IN THE 1ST DIR. ARE EQUAL DIVIDED
C               PX=2   THE ELEMENTS IN THE 1ST DIR. ARE GRADUALLY LARGER
C               PX=0.5 THE ELEMENTS IN THE 1ST DIR. ARE GRADUALLY SMALLER 
CC    IJB    : BLOCK CONNECTIVITY (NUMBER OF  8 NODES THAT DEFINE 
C             THE BLOCK)
C    N1     : TOTAL NUMBER OF NODES
C  LOCAL VARIABLES 
C    XB,YB  : COORDINATES OF THE 3 NODES OF THE LINE, AS XSQ,YSQ
C        XLAST,YLAST: RETURN VALUES OF THE COORDIANATES OF THE LAST NODE 
C                    (NEEDED FOR OPEN BOUNDARIES)
C-------------------------------------------------------------------------
C
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      DIMENSION XND(NODSEG),YND(NODSEG)
      DIMENSION RSQ(6)
      DIMENSION XB(3),YB(3),SHP(3)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION NREGI(5)
      CALL CLRARR(XB,3)
      CALL CLRARR(YB,3)
      CALL CLRARR(SHP,3)
      MX1=MX+1
      ND=NOD
C     CONSTRUCT THE ELEMENT CONNECTIVITY
C     SET COORDINATES OF THE  3 NODES IN THE LINE(START,MIDDLE,END)
      DO 515 K=1,ND
        K1=2*K-1
        K2=2*K
        XB(K)=RSQ(K1)
        YB(K)=RSQ(K2)
  515 CONTINUE 
      KO1=0

      DO 102 I=1,MX
C       NUMBER OF FIRST NODE OF THE ELEMENT
         L1=I
C       FIND THE COORDINATES, IN THE LOCAL SYSTEM,
C       OF THE NODES FROM THE KNOWN COORDINATES 
C       OF THE ORIGINES, WITH INTERPOLATION BY SHAPE FUNCTIONS
C       CALL SUBROUTINE SYNTEL, WITH DIAK=0 (START EXAMINING FEOM THE 1ST
C       NODE OF THE LINE)
    5   CALL SYNTEL(I,MX,PX,FUN1,KO1,0)
C       INTERPOLATION WITH SHAPE FUNCTIONS FOR QUADRATIC 
C       ELEMENTS NOD=3, IT IS DETERMINED IN SUBROUTINE GEOBOX
C       FIRST NODE OF THE ELEMENT
        EKS=FUN1
        CALL MORFH(EKS,ND,SHP)
        CALL PRODUCT(XB,SHP,ND,DOT)
        XND(L1)=DOT
        CALL PRODUCT(YB,SHP,ND,DOT)
        YND(L1)=DOT
  102 CONTINUE
C     LAST NODE
      XLAST=XB(3)
      YLAST=YB(3)
      RETURN
      END
