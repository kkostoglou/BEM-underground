        IF(((NSHAP(K).EQ.2).OR.(NSHAP(K).EQ.3)).AND.
     &      (NDIS(K).EQ.2)) NB1=NB1-4
C        CALL GVECT(XD(KK),YD(KK),0)
	CALL MOVETO_W(XCR(KK),YCR(KK),POSITION)
C       SET A DOT
	ISTATUS=SETCOLOR(4)
	ISTATUS=SETPIXEL_W(XCR(KK),YCR(KK))
