          IF(((NSHAP(K).EQ.2).OR.(NSHAP(K).EQ.3)).AND.
     &        (NDIS(K).EQ.2)) THEN
C           CHECK IF THE CURRENT NODE IS A DUPLICATED CORNER
            KDIAK=0
            DO 25 II=1,4
              IF(I.EQ.LCRN(II+4)) KDIAK=1
