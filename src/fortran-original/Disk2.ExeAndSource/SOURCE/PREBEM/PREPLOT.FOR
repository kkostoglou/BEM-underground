      SUBROUTINE WAVFRONT(CP1,XCEN1,YCEN1,XMAX,YMAX,NCOUNT)
C     PLOT THE LINE OF THE WAVE FRONT
C     -------------------------------
C     EQUATION OF THE LINE IN POLAR COORDINATES 
C       R=R0/(COS(TH-FAI)), D0: DISTANCE FROM THE CENTER OF THE SHAPE XCR0,YCR0
C                           TO THE LINE OF THE WAVEFRONT
C                         TH: ANGLE OF A POINT P ON THE LINE OF WAVEFRONT
C                             WITH THE HORIZONTAL X GLOBAL AXIS
C                       FAI: ANGLE OF THE AXIS OF THE INCIDENT WAVE WITH X 
C                             GLOBAL AXIS
C     COORD OF A POINT ON THE LINE OF THE WAVE FRONT TO THE LEFT AND RIGHT
C     OF THE NODE KMIN 
C     COLLECT TH EQUAL TO +-PI/6
C     POLAR COORDINATES
C      IF(X0.NE.0.0) 
C
      IMPLICIT REAL*8 (A-H,O-Y)
      INCLUDE 'FGRAPH.FD'
      COMMON/GEOM3/FAI,PSAI
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      DIMENSION PSAI(5)
      DIMENSION NSIMU(5),NREGI(5)
      REAL*8 FAI,PSAI
      INTEGER*2 ISTATUS,ISTYLE
      INTEGER*2 MAXX,MAXY
      INTEGER*4            ifont
      CHARACTER*10         options(6)
      COMMON /FNTS/NFONTS,IFONT,OPTIONS,MAXX,MAXY
C
      RECORD/WXYCOORD/WXY
      RECORD/XYCOORD/XYS
C
      CHARACTER*255 BUFFER
C
      PI=3.14159265359D0
      TOL=1.0E-6
C     CHECK FOR THE EXISTENCE OF A FREE SURFACE
      NFRE=0
      DO 46 I=1,NBOUN
        IF(NREGI(I).EQ.4) NFRE=1
  46  CONTINUE
C     FIRST TIME STEP
      IF(NCOUNT.EQ.1) THEN
        FAI1=FAI
        TH1=FAI1+PI/6.0   
        TH2=FAI1+11.0*PI/6.0
C        R1=CP1/(DCOS(TH1-FAI1))
C        R2=CP1/(DCOS(TH2-FAI1))
      ENDIF
C     CARTESIAN COORDINATES
      X0=CP1*DCOS(FAI1)+XCEN1
      Y0=CP1*DSIN(FAI1)+YCEN1
C     TIME STEP GREATER THAN 1ST
      IF(NCOUNT.GT.1) THEN
        RLWF0=SQRT((X0-XCEN1)**2+(Y0-YCEN1)**2)
        IF(DABS(RLWF0).LT.TOL) RLWF0=TOL
        EFTH1=RLWF/(2.0*RLWF0)
        TH11=ATAN(EFTH1)
        TH1=FAI1+TH11
        TH2=FAI1+(2.0*PI-TH11)
      ENDIF
      R1=CP1/(DCOS(TH1-FAI1))
      R2=CP1/(DCOS(TH2-FAI1))
      X1=R1*DCOS(TH1)+XCEN1
      Y1=R1*DSIN(TH1)+YCEN1
      X2=R2*DCOS(TH2)+XCEN1
      Y2=R2*DSIN(TH2)+YCEN1
      RLWF=DSQRT((X1-X2)**2+(Y1-Y2)**2)
C        
C     SET WIDTH OF LINES
C      CALL GWICOL(1.,1)
C     DRAW THE LINE OF THE WAVE FRONT
C     IN CASE OF FREE SURFACE PLOT ONLY IN THE FIRST STEP
      IF((NFRE.EQ.1).AND.(NCOUNT.GT.1)) GO TO 11
C      CALL GVECT(X1,Y1,0)
C      CALL GVECT(X0,Y0,1)
C      CALL GVECT(X2,Y2,1)
      CALL MOVETO_W(X1,Y1,WXY)
      ISTATUS=LINETO_W(X0,Y0)
      ISTATUS=LINETO_W(X2,Y2)
C      CALL GWICOL(.01,1)
C     DRAW A NORMAL LINE FROM THE CENTER OF THE SHAPE TO WAVEFRONT LINE
C      CALL GVECT(XCEN1,YCEN1,0)
C      CALL GVECT(X0,Y0,1)
c      ISTYLE=#AA3C
      ISTYLE=#AA3
C      ISTYLE=#FFFF
      CALL SETLINESTYLE(ISTYLE)
C      CALL SETLINESTYLE(255)
      CALL MOVETO_W(XCEN1,YCEN1,WXY)
      ISTATUS=LINETO_W(X0,Y0)
C     PLOT THE GLOBAL AXIS
  11  CONTINUE
C      CALL GVECT(XCEN1,YCEN1,0)
C      CALL GVECT(XMAX,YCEN1,1)
C      CALL GVECT(XCEN1,YCEN1,0)
C      CALL GVECT(XCEN1,YMAX,1)
      CALL MOVETO_W(XCEN1,YCEN1,WXY)
      ISTATUS=LINETO_W(XMAX,YCEN1)
      ISTATUS=LINETO_W(XCEN1,YCEN1)
      ISTATUS=LINETO_W(XCEN1,YCEN1)
C      CALL RAXIS(1,0.0,2.,1)
C      CALL RAXIS(2,0.0,2.,1)
C
C     WRITE THE TITLE OF THE TIME STEP AND POSITION OF WAVEFRONT
C      RI=NCOUNT
c      CALL RTXANG(0.)
c      CALL GSCAMM
c      CALL RTXHEI(4.)
      CALL SETGTEXTVECTOR(1,0)
      CALL MOVETO_W(0.5,0.5,WXY)
      CALL GETVIEWCOORD_W(XC,YC,XYS)
      CALL GETCURRENTPOSITION(XYS)
C     COURIER FONTS
      IFONT=1
