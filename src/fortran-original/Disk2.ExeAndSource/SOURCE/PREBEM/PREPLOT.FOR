C
C      ***************************************
C      UNIRAS GRAPHICAL PACKAGE, UNIX SYSTEM
C      CALL GROUTE('SELECT LT4207;EXIT')
C      CALL GROUTE('SELECT MSVIEW;EXIT')
C      CALL GROUTE(' ')
C      HP COLORPLOT
