C               LINE OF WAVE FRONT
C               THE EQUATION OF THE WAVEFRONT, IS THE EQUATION OF A 
C               NORMAL TO A STRAIGHT LINE WITH ANGLE FAI WITH X AXIS
C               (AXIS OF INCIDENT WAVE)
C               CA=COS(FAI), CB=SIN(FAI)
C               CA*XCR(I)+CB*YCR(I)-CP=0
C
