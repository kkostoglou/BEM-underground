      SUBROUTINE PLMESH(XCR,YCR,N1,CA,CB,CP,NNODEB,
     &  NBOUN,XCEN,YCEN,NDTYPE,KEXPL,NTOT,NPLOT,NSHAP,LCRN,
     &  MPL,MBD,INES)
