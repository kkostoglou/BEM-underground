	  ISTATUS=LINETO_W(XCR(KK),YCR(KK))
C         SET A DOT
	  ISTATUS=SETCOLOR(4)
	  ISTATUS=SETPIXEL_W(XCR(KK),YCR(KK))
	  ISTATUS=SETCOLOR(7)
  30    CONTINUE
C        CALL GVECT(XD(K0),YD(K0),1)
        ISTATUS=LINETO_W(XCR(K0),YCR(K0))
  35  CONTINUE
      IF (NDIAK.GT.1) GO TO 60
C     PLOT DOTS AND NODE NUMBERS
      HIG1=DABS(XMAX-XMIN)*0.04
      HIG2=HIG1
C      MAKE THE DOTS BIG ENOUGH
C      CALL GWICOL(2.,1)
      KK=0
      DO 45 K=1,NBOUN
        NB1=NNODEB(K)
        DO 40 I=1,NB1
          BUFFER=' '
          KK=KK+1
          RI=KK
C          CALL GDOT(XD(KK),YD(KK),1)
C          XC=XCR(KK)-HIG1
C	   YC=YCR(KK)-HIG2
	   XC=XCR(KK)
	   YC=YCR(KK)
C         PLOT THE NODE NUMBERS
C          CALL RTXHEI(4.)
          list = options(ifont) // 'h20w20b'
          IF(SETFONT(LIST).GE.0) THEN
C
C         FOR SQUARE OR RECTANGLE AND 
C         IN CASE OF DISCONTINUITY AT THE CORNERS, CORNER NODES HAVE BEEN
