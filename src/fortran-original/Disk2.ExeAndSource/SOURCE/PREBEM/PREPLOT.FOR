C          RUN THE PROGRAM
C          DHEPEL (OR CALL GHEPEL INCIDE OF A PROGRAM AT THE END)     
C      CALL GOPEN
C      ***************************************
C
C     IN CASE OF EXPLOSION POINT, INCLUDE THE EXPLOSION POINT IN THE LIMITS
      IF(KEXPL.EQ.1) THEN
        XE=EXPLX
        YE=EXPLY
        XMIN=AMIN1(XMIN,XE)
        YMIN=AMIN1(YMIN,YE)
        XMAX=AMAX1(XMAX,XE)
        YMAX=AMAX1(YMAX,YE)
      ENDIF
      XYMIN=AMIN1(XMIN,YMIN)
      XYMAX=AMAX1(XMAX,YMAX)
C
C      ***************************************
C      UNIRAS GRAPHICAL PACKAGE, UNIX SYSTEM
C      CALL GRPSIZ(XMMS,YMMS)
C      CALL GLIMIT(XYMIN,XYMAX,XYMIN,XYMAX,0.0,0.0)
C      CALL GVPORT(XMMS*0.1,YMMS*0.1,XMMS*0.8,YMMS*0.8)
C      CALL GWBOX(1.0,1.0,0.0)
C      CALL GSCALE
C      ***************************************
C
      CALL GRAPHICSMODE(MAXX,MAXY)
      XHALF=MAXX/2
      YHALF=MAXY/2
      MMAX=MIN0(MAXX,MAXY)
      CALL CLEARSCREEN($GCLEARSCREEN)
C
      XV(1)=0
      YV(1)=0
      XV(2)=MAXX
      YV(2)=MAXY
      CALL SETVIEWPORT(0,0,MAXX-1,MAXY-1)
      ISTATUS=SETCOLOR(4)
      ISTATUS=RECTANGLE_W($GBORDER,0,0,MAXX-1,MAXY-1)
      CALL SETVIEWPORT(XHALF-MMAX/2,YHALF-MMAX/2,
     &        XHALF+MMAX/2,YHALF+MMAX/2)
      XW(1)=1.4*XYMIN
      YW(1)=1.4*XYMIN
      XW(2)=1.4*XYMAX
      YW(2)=1.4*XYMAX
      ISTATUS=SETWINDOW(.TRUE.,XW(1),YW(1),XW(2),YW(2))
      ISTATUS=SETCOLOR(7)
C     SELECT TEXT GRAPHICS FONTS
C
C     COURIER FONTS
      IFONT=1
      CALL FONTREG
      NDIAK=1
      KDIAK1=0
      IPSG=0
C     CHECK FOR DRAWING PLOTS IN PREPROCESSING (NPLOT=30)
      DO 26 IPL=1,NTOT
        KPL1=NPLOT(IPL)
        IF(KPL1.EQ.30) KDIAK1=1
  26  CONTINUE
      IF(KDIAK1.EQ.1) THEN
        IPSG=IPSG+1
C
C      ***************************************
C      UNIRAS GRAPHICAL PACKAGE, UNIX SYSTEM
C        CALL GSEGCR(IPSG)
C      ***************************************
C
      ENDIF
      CALL PLOTDOM(XCR,YCR,NNODEB,NBOUN,N1,NDIAK,
     &         XYMIN,XYMAX,NSHAP,LCRN,MBD,INES)
C
C      ***************************************
C      UNIRAS GRAPHICAL PACKAGE, UNIX SYSTEM
C      CALL GDIAGC('WAIT')
C      ***************************************
C
C     CASE OF INSIDE A BOUNDARY PRESSURE
      IF(KINSI.EQ.1) GO TO 999
      IF(KEXPL.EQ.0) THEN
C       PLANE WAVE CASE
C       ---------------
C       PLOT THE LINE OF THE WAVE FRONT
C       ELASTODYNAMIC CASE ONLY
        NCOUNT=1
        CP1=CP
        IF((NDOMA.EQ.1).OR.(NDOMA.EQ.2))THEN
          CALL WAVFRONT(CP1,XCEN1,YCEN1,XMAX,YMAX,NCOUNT)
C         DRAW AN ARROW ON THE CENTER OF WAVEFRONT
          CALL SETLINESTYLE(ISTYLE)
          CALL PLARROW(XCEN1,YCEN1,CP1,FAI1,XYMIN,XYMAX)
          READ(*,*)                      ! WAIT FOR A KEY TO BE PRESSED
          IF(KDIAK1.EQ.1) THEN
C           CREATE A SEGMENT FOR PLOTING WITH RASCON
            IPSG=IPSG+1
C            CALL GSEGCR(IPSG)
          ENDIF
C         DRAW THE RAYS OF THE INCIDENT WAVE
C         (NORMAL LINES FROM THE NODES TO WAVEFRONT)
          CALL RAYINCPL(XCR,YCR,NNODEB,NBOUN,FAI1,CA1,CB1,CP1,
     &       XCEN1,YCEN1,XYMIN,XYMAX,NSHAP,LCRN,MBD,N1,INES)

C
C      ***************************************
C      UNIRAS GRAPHICAL PACKAGE, UNIX SYSTEM
C         CLOSE THE SEGMENT
C          IF(KDIAK1.EQ.1) CALL GSEGCL(IPSG)
C         IN CASE OF EXISTENCE OF FREE SURFACE,
C         DRAW THE RAYS OF THE REFLECTED WAVE (ONLY FOR THE CASE OF 
C         REFLECTION BY THE LAWS OF HARMONIC WAVES)
C      ***************************************
C
          IF(NFFS.EQ.1) THEN
            IF(NFRE.EQ.1) THEN
              IF(KDIAK1.EQ.1) THEN
C               CREATE A SEGMENT FOR PLOTING WITH RASCON
                IPSG=IPSG+1
C                CALL GSEGCR(IPSG)
              ENDIF
              CALL RAYPLANE(XCR,YCR,FAI1,CA1,CB1,CP1,XCEN1,YCEN1,
     &          XYMIN,XYMAX,NNODEB,NDTYPE,NBOUN,NSHAP,LCRN,MBD,
     &          N1,INES)
C
C      ***************************************
C      UNIRAS GRAPHICAL PACKAGE, UNIX SYSTEM
C             CLOSE THE SEGMENT
C              IF(KDIAK1.EQ.1) CALL GSEGCL(IPSG)
C      ***************************************
C
            ENDIF
          ENDIF
        ENDIF
      ENDIF
C     EXPLOSIVE POINT WAVE CASE
C     -------------------------
      IF(KEXPL.EQ.1) THEN
C
C      ***************************************
C      UNIRAS GRAPHICAL PACKAGE, UNIX SYSTEM
C       CLOSE THE SEGMENT
C        IF(KDIAK1.EQ.1) CALL GSEGCL(IPSG)
        IF((NDOMA.EQ.1).OR.(NDOMA.EQ.2))THEN
          IF(KDIAK1.EQ.1) THEN
C           CREATE A SEGMENT FOR PLOTING WITH RASCON
            IPSG=IPSG+1
C            CALL GSEGCR(IPSG)
          ENDIF
C      ***************************************
C
C         DRAW THE RAYS OF THE INCIDENT WAVE
          CALL RAYINCEX(XCR,YXR,NNODEB,NBOUN,XCEN1,YCEN1,
     &            XYMIN,XYMAX,NSHAP,LCRN,MBD,N1,INES)

C         CLOSE THE SEGMENT
C         IN CASE OF EXISTENCE OF FREE SURFACE,
C         DRAW THE RAYS OF THE REFLECTED WAVE
          IF(NFRE.EQ.1) THEN
            IF(KDIAK1.EQ.1) THEN
C             CREATE A SEGMENT FOR PLOTING WITH RASCON
              IPSG=IPSG+1
C              CALL GSEGCR(IPSG)
            ENDIF
            CALL RAYEXPL(XCR,YCR,NNODEB,NDTYPE,NBOUN,XYMIN,XYMAX,
     &        NSHAP,LCRN,MBD,N1,INES)
C           CLOSE THE SEGMENT
C            IF(KDIAK1.EQ.1) CALL GSEGCL(IPSG)
          ENDIF
        ENDIF
      ENDIF
C
C      ***************************************
C      UNIRAS GRAPHICAL PACKAGE, UNIX SYSTEM
C      CLOSE UNIPICT FILES
C      CALL GSEGCF
C      CLOSE GRAPHICS
C      CALL GCLOSE
C      ***************************************
C
  999 CONTINUE
      READ(*,*)
      CALL UNREGISTERFONTS()
      IDUMMY=SETVIDEOMODE($DEFAULTMODE)
      RETURN
      END
