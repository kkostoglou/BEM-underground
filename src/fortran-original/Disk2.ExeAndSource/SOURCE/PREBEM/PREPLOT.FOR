C-----------------------------------------------------------
      SUBROUTINE ARROW(X1,Y1,X0,Y0,H,B)
C
C     DRAWS AN ARROW
C     X1,Y1: TAIL OF THE ARROW
C     X0,Y0: HEAD
C     H    : HEIGHT OF THE ARROW'S TRRIANGLE
C     B    : BASE OF THE ARROW'S TRIANGLE
C     FAI1 : ANGLE OF INCIDENCE OF THE PLANE WAVE (ANGLE OF THE
C            TAIL OF WAVE WITH X-AXIS
C
      IMPLICIT REAL*8 (A-H,O-Y)
      INCLUDE 'FGRAPH.FD'
      RECORD/WXYCOORD/WXY
      INTEGER*2 ISTATUS
C
      PI=3.14159265359D0
C     FAI1 : ANGLE OF INCIDENCE OF THE PLANE WAVE (ANGLE OF THE

C     TAIL OF WAVE WITH X-AXIS
      FAI1=DATAN2(Y1-Y0,X1-X0)
      IF(FAI1.LT.0.0D0) FAI1=2.0D0*PI+FAI1
C     HALF ANGLE OF THE HEAD ANGLE OF THE TRIANGLE
      WAI=DATAN2(B,2.0D0*H)
      IF(WAI.LT.0.0D0) WAI=2.0D0*PI+WAI
C     LENGTH OF THE SIDE OF THE HEAD TRIANGLE (DIAGONAL)
      EL=DABS(H*H+B*B/4.0D0)
C     COORDINATES OF THE NODE 1 OF THE BASE OF THE TRIANGLE
      XAR1=X0+EL*DCOS(FAI1+WAI)
      YAR1=Y0+EL*DSIN(FAI1+WAI)
C     COORDINATES OF THE NODE 2 OF THE BASE OF THE TRIANGLE
      XAR2=X0+EL*DCOS(FAI1-WAI)
      YAR2=Y0+EL*DSIN(FAI1-WAI)
      CALL MOVETO_W(X1,Y1,WXY)
      ISTATUS=LINETO_W(X1,Y1)
      ISTATUS=LINETO_W(X0,Y0)
      ISTATUS=LINETO_W(XAR1,YAR1)
      ISTATUS=LINETO_W(XAR2,YAR2)
      ISTATUS=LINETO_W(X0,Y0)
      RETURN
      END
