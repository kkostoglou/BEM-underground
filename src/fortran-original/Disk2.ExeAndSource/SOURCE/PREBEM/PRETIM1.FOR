C -----------------------------------------------------------------------
      SUBROUTINE DATATIM(XCR,YCR,KONN,NONN,NNODEB,LBCU,
     &       SLOAD,SLOAD1,SLOADF,SLOAD2,SRXX,SRYY,SRXY,
     &       SXX,SYY,SXY,N1,N2,N3,N4,N5,
     &       CA,CB,CP,NBOUN,JKODE,NSHAP,NELEMB,NSEGM,SEG,NBNT,
     &       XCEN,YCEN,DRSTRE,DRNSTRE,DRNORM,TH0,TH3,TH4,KEXPL,
     &       MBCU,NDTYPE,LCRN)
C                TSXX,TSYY,TSXY,
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS IN THE TIME DOMAIN ON THE
C   SURFACE OF THE GEOMETRICAL SHAPE (ANY SHAPE) 
C     SLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     SLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLIDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C -----------------------------------------------------------------------
      IMPLICIT REAL*8 (A-H,O-Y)
C     ******COMMONBLOCKS********
C
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      COMMON/BLKEX/IEXIT
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
      DIMENSION XCR(N1),YCR(N1),SLOAD(N2)
      DIMENSION SLOAD1(N5)
      DIMENSION PSAI(5)
      DIMENSION KONN(N3,N4),NONN(N1,N4)
      DIMENSION NSIMU(5)
      DIMENSION LBCU(N3)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION NREGI(5)
      DIMENSION NNODEB(NBOUN)
      DIMENSION NSHAP(NBOUN)
      DIMENSION JKODE(NBNT)
      DIMENSION NELEMB(NBOUN)
      DIMENSION NSEGM(NBOUN)
      DIMENSION SEG(NBNT*7)
      DIMENSION SLOADF(N2)
      DIMENSION SLOAD2(N5)
      DIMENSION SRXX(N1),SRYY(N1),SRXY(N1)
      DIMENSION MBCU(N2)
      DIMENSION TH0(N1),TH3(N1),TH4(N1)
      DIMENSION LCRN(8)
      DIMENSION NDTYPE(N1)
C
C      DATA SPOINT/-1.,0.,1./
      PI=3.14159265359D0
      TOL=1.0D-11
C--------------------------------------------------------
C       CALCULATE THE NORMAL UNIT VECTOR
C--------------------------------------------------------
      NOD=3
      DT=TIM/DFLOAT(NSTEP)
C     FIND THE CONFINING STRESSES
      IF(DRSTRE.LT.0.0D0) THEN
        DRNSTRE1=DRSTRE*RNU/(1.0D0-RNU)
        WRITE(6,328)DRNSTRE1
  328   FORMAT('SP(AX)*N/(1-N).........',F12.3)
      ENDIF
C     VERTICAL INCOMING STRESS
      IF(DRNSTRE.LT.0.0D0) THEN
        DRSTRE1=DRNSTRE*RNU/(1.0D0-RNU)
        WRITE(6,330)DRSTRE1
  330   FORMAT('SP(VER)*N/(1-N).........',F12.3)
      ENDIF
C     CALCULATE THE LOADS IN TIME DOMAIN
      DO 31 K=1,NSTEP
        CALL CLRARR(SRXX,N1)
        CALL CLRARR(SRYY,N1)
        CALL CLRARR(SRXY,N1)
        CALL CLRARR(SLOAD,N2)
        CALL CLRARR(SLOADF,N2)
        CALL CLRARR(SLOAD1,N5)
        CALL CLRARR(SLOAD2,N5)
        T1=DT*DFLOAT(K-1)
CC       FIND THE CONFINING STRESSES
C        IF(DRSTRE.LT.0.0D0) THEN
C          DRNSTRE1=DRSTRE*RNU/(1.0D0-RNU)
C          WRITE(6,328)DRNSTRE1
C  328     FORMAT('SP(AX)*N/(1-N).........',F12.3)
C        ENDIF
CC       VERTICAL INCOMING STRESS
C        IF(DRNSTRE.LT.0.0D0) THEN
C          DRSTRE1=DRNSTRE*RNU/(1.0D0-RNU)
C          WRITE(6,330)DRSTRE1
C  330     FORMAT('SP(VER)*N/(1-N).........',F12.3)
C        ENDIF

C       INCOMING STRESSES WITH THE ADDITIONAL VERTICAL STRESSES
        DTRSTRE=DRSTRE+DRSTRE1
        DTRNSTRE=DRNSTRE+DRNSTRE1
        DTRNORM=DRNORM
C       TRANSFORMATION OF INCIDENT STRESSES FROM DIRECTION ANGL (WITH X AXIS)
C       TO THE GLOBAL COORDINATE SYSTEM
        FN1=DCOS(FAI)
        FN2=DSIN(FAI)
        CALL STRGLOB(DTRSTRE,DTRNSTRE,DTRNORM,
     &              FN1,FN2,TSXX,TSYY,TSXY)
C
C       LOOP FOR ALL THE BOUNDARY SHAPES
        NB0=0
        NB2=0
        DO 61 L=1,NBOUN
C         CHECK FOR THE EXISTENCE OF A FREE SURFACE
          NFRE=0
          DO 46 I=1,NBOUN
            IF(NREGI(I).EQ.4) NFRE=1
  46      CONTINUE
C         COUNTER FOR THE STARTING NUMBER OF NODE OF A BOUNDARY
C         FOR FREE SURFACE PROBLEM THE LOADS ARE ALL 0
          IF(L.EQ.1) THEN
            NB0=1
            GO TO 54
          ENDIF
          NB0=NB0+NNODEB(L-1)
   54     NB1=NNODEB(L)
          NCOUNT=L
C         NUMBER OF LAST NODE IN THE BOUNDARY
          NB2=NB2+NB1
C         COUNTER FOR NODE NUMBERING
C         NCN=NB0
C         CALCULATE THE EQUIVALENT TO TSXX,TSYY,TSXY INCIDENT STRESSES 
C         AND TRACTIONS, WITH DELAYS (OPOSITE IN SIGN FROM THE INCOMING).
C         FOR CALCULATING THE INCIDENT STRESSES, TAKE THE TOTAL INCOMING
C         STRESSES TSXX,TSYY,TSXY (WITH THE ADDITIONAL VERTICAL STRESSES) 
C
CC         CASE OF NFFS=1, CALCULATION OF THE FREE FIELD WITH REFLECTION FORMS
CC         OF HARMONIC WAVES
C          IF(NFFS.EQ.1) THEN

C           FOR ALL THE CASES
C           INCIDENT WAVE
C           =============
C           P-WAVE
C           ------
C           CASE THAT 
C             PLANE WAVE : THERE IS AXIAL STRESS IN THE DIRECTION OF RAYS OR
C             EXPLOSIVE POINT
            IF((DABS(DRSTRE).GT.TOL).OR.(KEXPL.EQ.1))THEN
              WVEL=C1
              KPS=1
              CALL WINCIDIM(XCR,YCR,SLOAD,SLOAD1,TSXX,TSYY,TSXY,
     &           N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &           XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,
     &           NSHAP,LCRN,KPS,NDTYPE)
              IF (IEXIT.EQ.1) GO TO 999
            ENDIF
C
C           SV-WAVE
C           -------
C           CASE THAT 
C             PLANE WAVE : THERE IS SHEAR STRESS IN THE DIRECTION OF RAYS
C             EXPLOSIVE POINT WITH SV WAVE
            IF((DABS(DRNORM).GT.TOL).OR.
     &         ((KEXPL.EQ.1).AND.(DABS(EXPLSV).GT.TOL)))THEN
              WVEL=C2
              KPS=2
              CALL WINCIDIM(XCR,YCR,SLOAD,SLOAD1,TSXX,TSYY,TSXY,
     &           N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &           XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,
     &          NSHAP,LCRN,KPS,NDTYPE)
              IF (IEXIT.EQ.1) GO TO 999
            ENDIF
C
C         CASE OF NFFS=1, CALCULATION OF THE FREE FIELD WITH REFLECTION FORMS
C         OF HARMONIC WAVES
          IF(NFFS.EQ.1) THEN
C           REFLECTED WAVE
C           ==============
            IF(NFRE.EQ.1) THEN
C             FIND THE REFLECTED STRESSES AT EVERY NODE WITH DELAYS 
C             SRXX,SRYY,SRXY (REFLECTIONS OF SXX,SYY,SXY)
C             FOR CALCULATING THE INCIDENT STRESSES, TAKE THE INCOMING ONLY
C             STRESSES TSXX,TSYY,TSXY (WITHOUT THE ADDITIONAL VERTICAL STRESSES)
C             P-WAVE
C             ------
C           CASE THAT 
C             PLANE WAVE : THERE IS AXIAL STRESS IN THE DIRECTION OF RAYS OR
C             EXPLOSION POINT
            IF((DABS(DRSTRE).GT.TOL).OR.(KEXPL.EQ.1))THEN
                WVEL=C1
C               CASE OF EXPLOSION POINT WAVE
                IF(KEXPL.EQ.1) GO TO 72
C               CASE OF PLANE WAVE
                CALL REFPTIM(XCR,YCR,SXX,SYY,SXY,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            SRXX,SRYY,SRXY,DRSTRE,DRNSTRE,NDTYPE)
                IF (IEXIT.EQ.1) GO TO 999
                GO TO 69
  72            CONTINUE
C               CASE OF EXPLOSION POINT WAVE
                CALL TREFEXP(XCR,YCR,SXX,SYY,SXY,WVEL,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            SRXX,SRYY,SRXY,TH0,TH3,TH4,K,KEXPL,NDTYPE)
                IF (IEXIT.EQ.1) GO TO 999
  69            CONTINUE
              ENDIF
C             SV-WAVE
C             -------
C           CASE THAT 
C             PLANE WAVE : THERE IS SHEAR STRESS NORMAL THE DIRECTION OF RAYS
              IF(DABS(DRNORM).GT.TOL)THEN
                CALL REFSVTIM(XCR,YCR,SXX,SYY,SXY,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            SRXX,SRYY,SRXY,DRNORM,NDTYPE)
              ENDIF
C             EXPLOSION POINT SV WAVE
              IF(DABS(EXPLSV).GT.TOL)THEN
                CALL TREFEXSV(XCR,YCR,SXX,SYY,SXY,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            SRXX,SRYY,SRXY,DRNORM,NDTYPE)
              ENDIF
C             CALCULATE THE EQUIVALENT TO SRXX,SRYY,SRXY INCIDENT STRESSES
C             AND TRACTIONS,LOADS WITHOUT DELAYS 
C             (DELAYS ALREADY APPLIED IN SUBROUTINE REF)
              CALL REFLTIM(XCR,YCR,SLOADF,SLOAD2,SRXX,
     &          SRYY,SRXY,N1,N2,N3,N4,N5,CA,CB,NB0,NB1,NCOUNT,NB2,
     &          NBOUN,NSHAP,LCRN,NDTYPE)
            ENDIF
          ENDIF
   61    CONTINUE
C       ADD THE INCIDENT AND REFLECTED STRESSES
        DO 42 I=1,N5
          SLOAD1(I)=SLOAD1(I)+SLOAD2(I)
  42    CONTINUE
C       ADD THE INCIDENT AND REFLECTED TRACTIONS
        DO 44 I=1,N2
          SLOAD(I)=SLOAD(I)+SLOADF(I)
  44    CONTINUE
C       INCIDENT TRACTIONS OR FREE FIELD TRACTIONS(IF THERE IS FREE SURFACE)
        WRITE(3,*) SLOAD
C       RADIAL, TANGENTIAL AND SHEAR PERIPHERAL INCIDENT STRESSES
C       OR FREE FIELD STRESSES (IF THERE IS FREE SURFACE)
        WRITE(2,*) SLOAD1
  31  CONTINUE
  999 CONTINUE
      RETURN
      END
C ----------------------------------------------------------------------
      SUBROUTINE WINCIDIM(XCR,YCR,SLOAD,SLOAD1,TSXX,TSYY,TSXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &          XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,
     &          NSHAP,LCRN,KPS,NDTYPE)
C
C   CALCULATES THE INCIDENT FIELD IN TIME DOMAIN, FOR THE 
C   PLANE WAVE AND EXPLOSIVE POINT WAVE ALSO. THE CALCULATIONS ARE 
C   PERFORMED FOR ALL THE NODES OF THE MESH, AND THE OPPOSITE TRACTIONS 
C   TO THE INCIDENT ONES ARE RETURNED IN ARRAY SLOAD WHILE THE INCIDENT
C   STRESSES IN THE ARRAY SLOAD1. THESE TRACTIONS SLOAD ARE REFERED
C   TO A GLOBAL COORDINATE SYSTEM AND ARE READ IN THE PROCESSING PHASE IN 
C   SUBROUTINE GENR. THE INCIDENT STRESSES ON THE PERIPHERY OF THE BOUNDARY 
C   SLOAD1(NORMA, TANGENTIL AND SHEAR STRESSES), ARE REFERED TO A LOCAL 
C   COORDINATE SYSTEM WITH X AXIS THE NORMAL AND Y AXIS THE TANGENT TO THE 
C   PERIPHERY UNIT VECTORS, AND ARE READ IN SUBROUTINE HOOP OF PROCESSING PHASE.  

C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   NB2: GLOBAL NUMBER OF THE LAST NODE OF THE BOUNDARY
C   TSXX,TSYY,TSXY: TOTAL INCOMING STRESS WAVE (WITH THE ADDITIONAL VERTICAL
C                 STRESSES. ON THE FREE SURFACE WE HAVE ONLY INCOMING
C                 SXX STRESSES, BUT IT DOESN'T MUTTER, BECAUSE FINALY 
C                 THEY VANISHES.) 
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
C
C   KPS=1   : EXPLOSIVE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C   KPS=2   : EXPLOSIVE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)
C
C   THE RETURN VALUES OF SXX,SYY,SXY,TSXX,TSYY,TSXY ARE ICREASED BY
C      THE ACTUAL EXPLOSION STRESSES. IN CASE OF EXPLOSION THERE ARE
C      ONLY EXPLOSION STRESSES
C -----------------------------------------------------------------------
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/BLKEX/IEXIT
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/FREE/NFFS,NSIMU
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1),SLOAD(N2)
      DIMENSION SLOAD1(N5),SPOINT(3)
      DIMENSION XY(3,2),RN(2)
      DIMENSION NREGI(5)
      DIMENSION LN(3)
      DIMENSION NSIMU(5)
      DIMENSION LCRN(8)
      DIMENSION NSHAP(NBOUN)

      DIMENSION NDTYPE(N1)
      DATA SPOINT/-1.,0.,1./
C
C         TO CALCULATE THE UNIT VECTOR NORMAL TO THE SURFACE OF THE ELEMENT
C         WE TAKE THE CURRENT NODE I AND THE PREVIUS AND NEXT NODE TO HAVE
C         AN ELEMENT. FROM THIS ELEMENT WITH SHAPE FUNCTIONS WE CALCULATE
C         THE NORMAL TO THE SURFACE VECTORS AT THE NODE I(MIDDLE)
      NOD=3
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
      DO 41 I=1,NB1
C
C       FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
        IF(NDTYPE(I).EQ.4) GO TO 89
        TSXX1=0.0D0
        TSYY1=0.0D0
        TSXY1=0.0D0
        TSXX1E=0.0D0
        TSYY1E=0.0D0
        TSXY1E=0.0D0
        DO 51 II=1,NOD
          JCL1=I
          II1=II  
          CALL COORD3(NCN,JCL1,NB0,NB1,NCOUNT,
     &                 II1,KCL,NB2,NBOUN,NSHAP,LCRN)
            XY(II,1)=XCR(KCL)
            XY(II,2)=YCR(KCL)
            LN(II)=KCL
  51    CONTINUE
C       INTERPOLATION TO FIND THE OUTWARD TO THE MATERIAL NORMAL UNIT 
C       VECTOR FOR THE MIDDLE NODE (EKS=0)
        CALL SINTERP(XY,LN,RN)
C       TAKE THE OPPOSITE SIGN, BECAUSE WE WANT INWARD TO THE MATERIAL 
C       UNIT NORMAL VECTOR.
        RN1=-RN(1)
        RN2=-RN(2)
        XCR1=XCR(NCN)
        YCR1=YCR(NCN)
C       EXPLOSION POINT WAVE
C       --------------------
C       IN CASE OF EXPLOSION POINT SOURCE, CALCULATE FOR NODE I, THE
C       STRESSES IN THE TIME DOMAIN. THESE STRESSES ARE DECAYING 
C       BY TIME
        IF(KEXPL.EQ.1) THEN
          CALL TWAVEXPL(XCR1,YCR1,WVEL,NCOUNT,
     &           TSXX1E,TSYY1E,TSXY1E,T1,K,KPS)
          IF(IEXIT.EQ.1) GO TO 99
          GO TO 33
        ENDIF
C       PLANE WAVE
C       ----------
C       CALCULATE THE STRESSES WITH DELAYS
C       ON THE NODE I, IN A GLOBAL SYSTEM
        CALL TWAVPLAN (XCR1,YCR1,XCEN,YCEN,CA,CB,CP,WVEL,NCOUNT,T1,
     &      SXX,SYY,SXY,TSXX,TSYY,TSXY,TSXX1,TSYY1,TSXY1)
  33    CONTINUE
        TSXX1=TSXX1+TSXX1E
        TSYY1=TSYY1+TSYY1E
        TSXY1=TSXY1+TSXY1E
        J=2*NCN
C
C       CALCULATE THE EQUEVELANT TRACTIONS IN A TANGENTIAL PLANE WITH
C       INWARD TO THE MATERIAL UNIT NORMAL VECTOR.
        CALL TRACT(TSXX1,TSYY1,TSXY1,RN1,RN2,TXX,TYY)
C       SUPERIMPOSE P AND SV TRACTIONS
        SLOAD(J-1)=SLOAD(J-1)+TXX
        SLOAD(J)  =SLOAD(J)+TYY
C-------------------------------------------------------
C       RADIAL,HOOP AND SHEAR INCIDENT STRESSES IN T.D.
C-------------------------------------------------------
        J=3*NCN
C
C       TRANSFORMATION OF STRESSES FROM THE GLOBAL COORDINATE
C       SYSTEM TO THE LOCAL WITH AXES X1,Y1 NORMAL AND TANGENTIAL 
C       TO THE BOUNDARY SURFACE AT NODE POINT. THE ANGLE OF AXIS
C       X (NORMAL), WITH THE GLOBAL SYSTEM HAS COS AND SIN, RN1 AND
C       RN2 RESPECTIVELLY.
C
        CALL STRLOC(TSXX1,TSYY1,TSXY1,RN1,RN2,
     &                 TSXX11,TSYY11,TSXY11)
C       SUPERIMPOSE P AND SV STRESSES
        SLOAD1(J-2)=SLOAD1(J-2)+TSXX11
        SLOAD1(J-1)=SLOAD1(J-1)+TSYY11
        SLOAD1(J)=SLOAD1(J)+TSXY11
  89    CONTINUE
        NCN=NCN+1
  41  CONTINUE
  99  CONTINUE
      RETURN
      END
C
C ----------------------------------------------------------------------
      SUBROUTINE REFLTIM(XCR,YCR,SLOAD,SLOAD1,SRXX,SRYY,
     &          SRXY,N1,N2,N3,N4,N5,CA,CB,NB0,NB1,NCOUNT,NB2,
     &          NBOUN,NSHAP,LCRN,NDTYPE)
C
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS IN THE TIME DOMAIN, 
C   ON THE SURFACE OF THE GEOMETRICAL SHAPE (ANY SHAPE) 
C     SLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     SLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLIDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   SRXX,SRYY,SRXY: INCOMING STRESS WAVE 
C -----------------------------------------------------------------------
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1),SLOAD(N2)
      DIMENSION SLOAD1(N5)
      DIMENSION XY(3,2),RN(2),SPOINT(3)
      DIMENSION NREGI(5)
      DIMENSION SRXX(N1),SRYY(N1),SRXY(N1)
      DIMENSION LN(3)
      DIMENSION LCRN(8)
      DIMENSION NSHAP(NBOUN)
      DIMENSION NDTYPE(N1)
      DATA SPOINT/-1.,0.,1./
C
C         TO CALCULATE THE UNIT VECTOR NORMAL TO THE SURFACE OF THE ELEMENT
C         WE TAKE THE CURRENT NODE I AND THE PREVIUS AND NEXT NODE TO HAVE
C         AN ELEMENT. FROM THIS ELEMENT WITH SHAPE FUNCTIONS WE CALCULATE
C         THE NORMAL TO THE SURFACE VECTORS AT THE NODE I(MIDDLE)
      NOD=3
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
      DO 41 I=1,NB1
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 89
        DO 51 II=1,NOD
          JCL1=I
          II1=II  
          CALL COORD3(NCN,JCL1,NB0,NB1,NCOUNT,
     &                 II1,KCL,NB2,NBOUN,NSHAP,LCRN)
            XY(II,1)=XCR(KCL)
            XY(II,2)=YCR(KCL)
            LN(II)=KCL
  51    CONTINUE
C       INTERPOLATION TO FIND THE NORMAL UNIT VECTOR FOR THE 
C       MIDDLE NODE (EKS=0)
        CALL SINTERP(XY,LN,RN)
C         TAKE THE OPPOSITE SIGN, BECAUSE WE WANT THE STRESSES ON A TANGENTIAL
C         PLANE THAT THE UNIT NORMAL TO IT VECTOR (INWARD TO THE MATERIAL),
C         IS OPPOSITE FROM THE UNIT VECTOR RN (OUTWARD TO THE MATERIAL)
          RN1=-RN(1)
          RN2=-RN(2)
          J=2*NCN
C          SLOAD(J-1)=(SRXX(NCN)*RN1+SRXY(NCN)*RN2)
C          SLOAD(J)  =(SRXY(NCN)*RN1+SRYY(NCN)*RN2)
          SSXX=SRXX(NCN)
          SSYY=SRYY(NCN)
          SSXY=SRXY(NCN)
C         CALCULATE THE EQUEVELANT TRACTIONS
          CALL TRACT(SSXX,SSYY,SSXY,RN1,RN2,STXX,STYY)
C
C         SUPERIMPOSE P AND SV TRACTIONS
          SLOAD(J-1)=SLOAD(J-1)+STXX
          SLOAD(J)  =SLOAD(J)+STYY
C-------------------------------------------------------
C         RADIAL,HOOP(TANGENTIAL) AND SHEAR INCIDENT STRESSES IN L.T.
C-------------------------------------------------------
           J=3*NCN
C         TRANSFORMATION OF STRESSES FROM THE GLOBAL COORDINATE
C         SYSTEM TO THE LOCAL WITH AXES X1,Y1 NORMAL AND TANGENTIAL 
C         TO THE BOUNDARY SURFACE AT NODE POINT. THE ANGLE OF AXIS
C         X (NORMAL), WITH THE GLOBAL SYSTEM HAS COS AND SIN, RN1 AND
C         RN2 RESPECTIVELLY.
C
          SSXX=SRXX(NCN)
          SSYY=SRYY(NCN)
          SSXY=SRXY(NCN)
          CALL STRLOC(SSXX,SSYY,SSXY,RN1,RN2,
     &                   SSXX1,SSYY1,SSXY1)
