      SUBROUTINE TWAVEXPL(XCR1,YCR1,WVEL,NCOUNT,
     &  TSXX1E,TSYY1E,TSXY1E,T1,K,KPS)
C
C   KPS=1   : EXPLOSIVE P WAVE CASE (INCIDENT P - RFELECTED SV WAVE AT NODE D)
C   KPS=2   : EXPLOSIVE SV WAVE CASE (INCIDENT SV - RFELECTED P WAVE AT NODE B)
C
C     &    DRSTE,DRNSTE,DRNORME,BRSTE,BRNSTE,BRNORME
C
C     CALCULATES THE STRESSES ON A NODE, IN A GLOBAL SYSTEM
C     (DELAYS AND LAPLACE TRANSFORMATION)
C     XCR1,YCR1 : COORDINATES OF THE NODE
C
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/BLKEX/IEXIT
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/FREE/NFFS,NSIMU
      DIMENSION NREGI(5),NSIMU(5)
C      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
C      DIMENSION DRSTE(N1),DRNSTE(N1),DRNORME(N1)

C
C     DISTANCE OF NODE FROM EXPLOSION POINT
      TOL=1.0E-9
      XE=EXPLX
      YE=EXPLY
      RE=DSQRT((XE-XCR1)**2+(YE-YCR1)**2)
C     CALCULATE THE DECAYING STRESSES IN LOCAL SYSTEM (RAY X AXIS)
      CALL TDECEXPL(XCR1,YCR1,WVEL,RE,RSTE,RNSTE,RNORME,T1,K,KPS)
      IF(IEXIT.EQ.1) GO TO 99
      CALL TEXPLMOR(XCR1,YCR1,RSTE,RNSTE,RNORME,SXXE,SYYE,SXYE,
     &      TSXXE,TSYYE,TSXYE)
      IF(KPS.EQ.1) T2=RE/C1
      IF(KPS.EQ.2) T2=RE/C2
      SDELAY=0.0D0
      IF (T1.GE.T2) SDELAY=1.0D0
      IF(DABS(T1-T2).LT. TOL) SDELAY=1.0D0
      TSXX1E=TSXXE
      TSYY1E=TSYYE
      TSXY1E=TSXYE
  99  CONTINUE
      RETURN
      END
