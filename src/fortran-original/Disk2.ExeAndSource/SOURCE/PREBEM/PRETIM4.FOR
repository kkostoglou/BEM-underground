      SUBROUTINE STRGLOB(SXX1,SYY1,SXY1,COSF,SINF,SXX,SYY,SXY)
C
C     TRANSFORMATION OF THE DOUBLE PRECISION STRESSES SXX1,SYY1,SXY1 
C     FROM THE LOCAL COORDINATE SYSTEM TO THE GLOBAL COORDINATE SYSTEM
C     SXX1,SYY1,SXY1 : AXIAL STRESSES IN X1,Y1 DIRECTION AND SHEAR,
C                      IN LOCAL SYSTEM
C     COSF,SINF      : COS AND SIN OF THE ANGLE F OF THE LOCAL X1 AXIS,
C                      WITH THE GLOBAL X AXIS (DIRECTIONAL COSINES)
C     SXX,SYY,SXY    : RETURN VALUES OF THE AXIAL STRESSES IN X,Y
C                      DIRECTIONS AND SHEAR, IN GLOBAL SYSTEM.
C     SIGN CONVENTION: TENSION STRESSES POSITIVE (+)
C                      COMPRESSION STRESSES NEGATIVE (-)
C
      IMPLICIT REAL*8 (A-H,O-Y)
      SXX=SXX1*COSF**2-2.0D0*SXY1*COSF*SINF+SYY1*SINF**2
      SYY=SXX1*SINF**2+2.0D0*SXY1*COSF*SINF+SYY1*COSF**2
      SXY=(SXX1-SYY1)*COSF*SINF+SXY1*(COSF**2-SINF**2)
      RETURN
      END
C
C---------------------------------------------------------------------------
      SUBROUTINE STRLOC(SXX,SYY,SXY,COSF,SINF,SXX1,SYY1,SXY1)
C
C     TRANSFORMATION OF THE DOUBLE PRECISION STRESSES SXX,SYY,SXY FROM
C     THE GLOBAL COORDINATE SYSTEM TO THE LOBAL COORDINATE SYSTEM
C     SXX,SYY,SXY    : AXIAL STRESSES IN X,Y DIRECTION AND SHEAR,
C                      IN GLOBAL SYSTEM
C     COSF,SINF      : COS AND SIN OF THE ANGLE F OF THE GLOBAL X AXIS,
C                      WITH THE LOCAL AXIS (DIRECTIONAL COSINES)
C     SXX1,SYY1,SXY1 : RETURN VALUES OF THE AXIAL STRESSES IN X1,Y1 
C                      DIRECTIONS AND SHEAR, IN LOCAL SYSTEM
C     SIGN CONVENTION: TENSION STRESSES POSITIVE (+)
C                      COMPRESSION STRESSES NEGATIVE (-)
C
      IMPLICIT REAL*8 (A-H,O-Y)
      SXX1=SXX*COSF**2+2.0D0*SXY*COSF*SINF+SYY*SINF**2
      SYY1=SXX*SINF**2-2.0D0*SXY*COSF*SINF+SYY*COSF**2
      SXY1=(SYY-SXX)*COSF*SINF+SXY*(COSF**2-SINF**2)
      RETURN
      END
