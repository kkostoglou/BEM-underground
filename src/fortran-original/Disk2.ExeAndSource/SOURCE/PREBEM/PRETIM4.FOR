C---------------------------------------------------------------------------
      SUBROUTINE TRACT(SXX,SYY,SXY,COSF,SINF,TXX,TYY)
C     
C     CALCULATES THE EQUEVELANT DOUBLE PRECISION TRACTIONS
C     DUE TO DOUBLE PRECISION STRESSES, IN ANY COORDINATE SYSTEM
C     SXX,SYY,SXY: AXIAL STRESSES IN DIRECTIONS X,Y OF THE ACTUAL 
C                  COORDINATE SYSTEM AND SHEAR
C     COSF,SINF  : THE COS AND SIN OF THE AXIS X OF THE ACTUAL X AXIS
C                  (DIRECTIONAL COSINES)
C     TXX,TYY    : EQUEVELANT TRACTIONS IN X AND Y DIRECTIONS
C                  OF THE SAME COORDINATE SYSTEM
C
      IMPLICIT REAL*8 (A-H,O-Y)
      TXX=SXX*COSF+SXY*SINF
      TYY=SXY*COSF+SYY*SINF
      RETURN
      END
