C -----------------------------------------------------------------------
       SUBROUTINE GEOBOX(XCR,YCR,XT,YT,N1,NELX,NELY,ALEN,ALENX,
     &       ALENY,NSHAP1,PSI,XCEN,YCEN,NREGION,IB,LR,LCRN)
C   IT CREATES THE GEOMETRICAL DATA FOR A SQUARE, WITH EQUAL QUADRATIC
C   ELEMENTS. CALCULATES THE CORDINATES OF THE NODES ON A SQUARE, 
C   IN A GLOBAL COORDIANTE SYSTEM.
C   NUMBERING OF THE NODES IN CLOCKWISE DIRECTION FOR EXTERIOR PROBLEM 
C   (EMPTY SQUARE), AND IN ANTICLOCKWISE DIRECTION FOR INTERIOR PROBLEM
C   (SOLID SQUARE)
C   ALEN: LENGTH OF ONE SIDE OF SQUARE
C   ALENX,ALENY: LENGTH OF THE SIDES OF RECTANGLE
C   NSHAP1: NUMBER FOR THE SHAPE
C   NELX: NUMBER OF ELEMENTS ON ONE SIDE ONLY OF THE SQUARE
C   NELY:                    OF THE OTHER SIDE OF THE RECTANGLE
C   XCR0,YCR0: COORDINATES OF THE CENTER OF THE SQUARE IN GLOBAL
C                 CARTESIAN SYSTEM
C   PSAI     : ANGLE OF THE AXIS M OF SQUARE WITH X AXIS
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
C -----------------------------------------------------------------------
        IMPLICIT REAL*8 (A-H,O-Y)
C
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON/GEOM4/NXELE,NYELE
        DIMENSION XCR(N1),YCR(N1)
        DIMENSION XT(N1),YT(N1)
        DIMENSION XSQ(8),YSQ(8),IJB(8)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5),XCR0(5),YCR0(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &      TYPELY(5),NDIS(5)
      DIMENSION LCRN(8)
C
      PI=3.14159265359D0
C
C     INTERPOLATION FUNCTIONS
C  
C     SQUARE
      IF (NSHAP1.EQ.2) CALL CORNESQ(XSQ,YSQ,ALEN)
C     RECTANGLE
      IF (NSHAP1.EQ.3) CALL CORNEREC(XSQ,YSQ,ALENX,ALENY)
C     INTERPOLATION FOR THE NODES ON THE SIDES BETWEEN THE ORIGINS
C     NODES PER SIDE
C     NUMBER OF ELEMENTS PER SIDE 
      LEPSX=NELX
      LEPSY=NELY
C     SQUARE
      IF (NSHAP1.EQ.2) LEPSY=NELX
C     ELEMENTS PER SIDE AFTER DIVINDING THEM WITH A MIDDLE 
C     NODE, FOR QUADRATIC ELEMENTS 
      MX=2*LEPSX
      MY=2*LEPSY
C     INTERPOLATION WITH SHAPE FUNCTIONS OF INTERVAL -1,0,1
      NOD=3 
      PX=TYPELX(IB)
      PY=TYPELY(IB)
      DO 102 I=1,8
      IJB(I)=I
  102 CONTINUE
      NDC=1
C     INDEX FOR DISCONTINUITY AT THE CORNERS
      IF(NDIS(IB).EQ.2) NDC=2
C     CREATE THE MESH IN LOCAL COORDINATES, WITH ORIGIN THE CENTER
C     OF THE SQUARE
      CALL MESH4(XCR,YCR,XSQ,YSQ,NOD,MX,MY,PX,PY,N1,IJB,NDC,
     &           LCRN)
C     COORDINATES IN THE GLOBAL SYSTEM
      CALL GLOBSYS(XCR,YCR,N1,PSI,XCEN,YCEN)
C     CHANGE THE NUMBERING OF THE  NN NODES MESH, STARTING FROM NODE NST
C     AND IN DIRECTION DEPENDING ON NT=NREGION
C     NREGION=1, CLOCKWISE (EXTERIOR PROBLEM)
C     NREGION=2, ANTICLOCKWISE(INTERIOR PROBLEM)
C     STARTING NODE,
C     IF THE NUMBER OF ELEMENTS IN THE Y DIRECTION IS ODD THEN STARTING 
C     NODE IS THE NODE OF INTERSECTION OF X AXIS WITH THE 
C     ELSE FOR EVEN NUMEBR OF ELEMENTS IN Y DIR., STARTING NODE IS 1 LESS
C     VERTICAL RIGHT SIDE 
      L1=LEPSY
C     REMAINDER (DEVIDED BY 2) = L1-INT(L1/2)*2
      LR=MOD(L1,2)
C     L1 EVEN (LR.EQ.0)
C     L1 ODD (LR.NE.0)
C     IF(LR.NE.0) NST=2*MX+3*MY/2+1
      NST=2*MX+3*MY/2+1

      NT=NREGION
      NDIS1=NDIS(IB)
      CALL CHANGEND(XCR,YCR,XT,YT,N1,NST,NT,NDIS1,LCRN)
      RETURN
      END
C-------------------------------------------------------------------------
      SUBROUTINE MESH4(XCR,YCR,XSQ,YSQ,NOD,MX,MY,PX,PY,N1,IJB,NDC,
     &                 LCRN)
C  CREATE THE MESH IN LOCAL COORDINATES FOR A BLOCK (SQUARE OR RECTANGLE)
C  USING SHAPE FUNCTIONS. THE SQUARE IS CONSIDERED AS A CLOSED SHAPE
C  WITH 4 LINES AND NX NUMBER OF NODAL NODES. EACH LINE HAS START,MIDDLE 
C  AND END, ELEMENTS. 
C  INTERPOLATION BETWEEN ORIGINS IS SUCCEDED
C  WITH SHAPE FUNCTIONS
C    XCR,YCR: COORDINATES OF NODAL POINTS, FOR CALCULATION, RETURN VALUE
C    XSQ,YSQ: COORDINATES OF THE 8 NODES OF THE BLOCK
C    IJK    : ELEMENT CONNECTIVITIES, RETURN VALUE
C    NOD    : TOTAL NUMBERS OF NODAL POINTS IN AN ELEMENT 
C              2: FOR LINE ELEMENTS
C              3: FOR QUADRATIC ELEMENTS
C    MX     : NUMBER OF ELEMENTS  PER ONE SIDE IN 1ST DIRECTION 
C    MY     : NUMBER OF ELEMENTS  PER ONE SIDE IN 2ND DIRECTION     
C    PX     : PARAMETER OF THE DIVISION FOR THE 1ST DIRECTION
C    PY     : PARAMETER OF THE DIVISION FOR THE 2ND DIRECTION
C    IJB    : BLOCK CONNECTIVITY (NUMBER OF  8 NODES THAT DEFINE 
C             THE BLOCK)
C    N1     : TOTAL NUMBER OF NODES 
C    NDC    : INDEX FOR DISCONTINUITY AT THE CORNERS
C               1: NO DISCONDINUITY
C               2: YES    -//-      (DUPLICATED NODES AT THE CORNERS)
C
C  LOCAL VARIABLES 
C    XB,YB  : COORDINATES OF THE 8 NODES OF THE BLOCK, AS XSQ,YSQ
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY
C-------------------------------------------------------------------------
C
      IMPLICIT REAL*8 (A-H,O-Y)
C
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION XSQ(8),YSQ(8),IJB(8)
      DIMENSION XB(3),YB(3),XBA(3),YBA(3),SHP(3)
      DIMENSION NXELE(5),NYELE(5)
      DIMENSION NREGI(5)
      DIMENSION LCRN(8)
      TOL=1.0E-11
C
      CALL CLRARR(XB,3)
      CALL CLRARR(YB,3)
      CALL CLRARR(SHP,3)
      ND=NOD
C     IN CASE THAT ONE OF THE PX OR PY IS 0, FIND THE OTHER SO THAT 
C     AT THE CORNERS AT BOTH SIDES TO HAVE ABOUT UNIFORM DISCRETIZATION.
      KDIAK1=0
      KDIAK2=0
      DO 60 J=1,4
C       COORDINATES OF THE START, MIDDLE AND END OF THE CURRENT SIDE
        DO 65 K=1,ND
          J1=2*(J-1)+K
          IF(J1.GT.8) J1=1
          K1=IJB(J1)
          XB(K)=XSQ(K1)
          YB(K)=YSQ(K1)
  65   CONTINUE
        IF(((J.EQ.1).OR.(J.EQ.3)).AND.(KDIAK1.EQ.0)) THEN
          KDIAK1=1
C         COORDINATES OF THE START, MIDDLE AND END OF THE OTHER SIDE
          DO 67 K=1,ND
            J1=2*(J)+K
            IF(J1.GT.8) J1=1
            K1=IJB(J1)
            XBA(K)=XSQ(K1)
            YBA(K)=YSQ(K1)
  67      CONTINUE
          IF(DABS(PX).LT.TOL) THEN
C           CALCULATE PXY NUMERICALLY
            CALL RATENUM(XB,YB,XBA,YBA,ND,MX,PX,MY,PY,PXYA)
            PX=PXYA
            WRITE(6,367)
            WRITE(6,361) PX
          ENDIF
        ENDIF
C
        IF(((J.EQ.2).OR.(J.EQ.4)).AND.(KDIAK2.EQ.0))  THEN
          KDIAK2=1
C         COORDINATES OF THE START, MIDDLE AND END OF THE OTHER SIDE
          DO 69 K=1,ND
            J1=2*(J-2)+K
            IF(J1.GT.8) J1=1
            K1=IJB(J1)
            XBA(K)=XSQ(K1)
            YBA(K)=YSQ(K1)
  69      CONTINUE

          IF(DABS(PY).LT.TOL) THEN
C           CALCULATE PXY NUMERICALLY
            CALL RATENUM(XB,YB,XBA,YBA,ND,MY,PY,MX,PX,PXYA)
            PY=PXYA
            WRITE(6,367)
            WRITE(6,363) PY
          ENDIF
        ENDIF
  60  CONTINUE

      DO 100 J=1,4
C       SET COORDINATES OF THE SIDE J OF THE BLOCK
        DO 515 K=1,ND
          J1=2*(J-1)+K
          IF(J1.GT.8) J1=1
          K1=IJB(J1)
          XB(K)=XSQ(K1)
          YB(K)=YSQ(K1)
  515   CONTINUE 
        IF ((J.EQ.1).OR.(J.EQ.3)) THEN
          MXY=MX
          PXY=PX
        ENDIF
        IF ((J.EQ.2).OR.(J.EQ.4))  THEN
          MXY=MY
          PXY=PY
        ENDIF
        KO1=0
        DO 102 I=1,MXY
C         NUMBER OF FIRST NODE OF THE ELEMENT
          L1=LA+2*(I-1)+1
C         NUMBER OF THE LAST NODE OF THE ELEMENT
          L3=L1+2
C         IF (L3.GT.NEQ) L3=1
          IF (L3.GT.N1) L3=1
C         NUMBER OF THE MIDDLE NODE OF THE ELEMENT
          L2=L1+1
C         INDEX FOR NODE NUMBERING
          IC=LA+I
C         CALL SUBROUTINE SYNTEL, WITH DIAK=0 (START EXAMINING FEOM THE 1ST
C         NODE OF THE LINE)
          CALL SYNTEL(I,MXY,PXY,FUN1,KO1,0)
15        CONTINUE
          EKS=FUN1
          CALL MORFH(EKS,ND,SHP)
          CALL PRODUCT(XB,SHP,ND,DOT)
          XCR(IC)=DOT
          CALL PRODUCT(YB,SHP,ND,DOT)
          YCR(IC)=DOT
  102   CONTINUE
        LA=IC
C       NUMBER OF THE LAST NODE OF THE SIDE J OF THE SQUARE OR RECTANGLE
C        LCRN(J)=LA
        LCRN(J)=LA+1
        IF(J.EQ.4) LCRN(J)=1
  100 CONTINUE
  367 FORMAT(2X,'(**AUTOMATIC CALCULATION FOR THE RATE OF CHANGE
     & OF ELEMENTS)')
  361 FORMAT(2X,'TYPE OF LINEX.....',F12.3)
  363 FORMAT(2X,'TYPE OF LINEY.....',F12.3)
      RETURN
      END
C-----------------------------------------------------------------
       SUBROUTINE SYNTEL(I1,M,P,FUN1,KO1,KDIAK)
C
C  DEFINE THE COORDINATES OF THE N[ODES ON A LINE WITH INTERVAL -1,0,1
C  AND ORIGIN OF THE COORDINATES THE MIDDLE 0.
C    I1: NUMBER OF THE ELEMENT
C    M: TOTAL NUMBER OF ELEMENTS ON THE LINE
C     VALUES OF P:
C              1: UNIFORM SIZE OF ELEMENTS
C                 |--.--|--.--|--.--|--.--|
C                  1   1  1  1  1  1  1  1
C            P>1: GRADUALY INCRISING ELEMENTS, WITH RATIO P
C                 E.G. P=2: 
C                 |--.--|----.----|--------.--------|
C                  1  1   2   2      4        4
C          0<P<1: GRADUALY DECRISING ELEMENTS, DOUBLING
C                 E.G. P=0.5: 
C                 |--------.--------|----.----|--.--|
C                     4        4      2     2   1  1
C           P<-1: GRADUALY INCRISING-DECRISING ELEMENTS, WITH RATIO P
C                 E.G. P=-2: 
C                 |--.--|----.----|----.----|--.--|
C                  1  1   2   2     2    2   1  1
C                 OR
C                 |--.--|----.----|--------.--------|----.----|--.--|
C                  1  1   2   2      4        4       2    2   1  1
C         -1<P<0: GRADUALY DECRISING-INCRISING ELEMENTS, WITH RATIO P
C                 E.G. P=-0.5: 
C                 |----.----|--.--|--.--|----.----|
C                   2     2   1  1  1  1  2     2
C                 OR
C                 |--------.--------|----.----|--.--|----.----|--------.--------|
C                      4       4       2    2   1  1   2    2      4        4  
C
C     KDIAK:
C           0 :THE WHOLE LINE IS EXAMINED BY STARTING FROM THE 1ST NODE
C              (START OF THE LINE) TILL THE END NODE (END BUT ONE NODE OF 
C              END OF THE LINE)
C           1 :THE 2ND NODE OF THE LINE IS EXAMINED LONELY, SO THERE IS NEED
C              FOR FUN1 TO TAKE INITIAL VALUE FUN1=-1. THIS IS NEEDED IN 
C              THE SUBROUTINE   RATENUM .

      IMPLICIT REAL*8 (A-H,O-Y)
C
      TOL=1.0D-2
      SL=0.0D0
      RI=DFLOAT(I1)
      RM=DFLOAT(M)
C     IN CASE THAT I1 IS THE FIRST NODE OF THE LINE, THIS IS THE 
C     START EDGE, RETURN
      IF(I1.EQ.1) THEN
        FUN1=-1.0D0
        RETURN
      ENDIF
C     IN CASE THAT KDIAK=1
      IF(KDIAK.EQ.1) THEN
        FUN1=-1.0D0
      ENDIF
C     P EQUAL 1.0
C     -----------
      IF (DABS(P-1.0D0).LT.TOL) THEN 
        FUN1=-1.0D0+2.0D0*(RI-1.0D0)/RM
        RETURN
      ENDIF
C     P >1 , GRADUALLY INCRISING SIZE OF ELEMENTS, WITH RATIO P
C     E.G. P=2.0
C     ---------------------------------------------------------
      IF (P.GT.1.0D0) THEN
C       FIND THE TOTAL NUMBER OF DIVISIONS FOR ALL THE LINE
C       NUMBER OF ELEMENTS
        M1=M/2
        DO 15 K=1,M1
C         I IS THE NUMBER OF ELEMENTS, INCLUDING THE PRODUCTS OF QUADRATIC 
C           DEVISION
C         K IS THE NUMBER OF ELEMENTS BEFORE DIVISION TO QUADRATICS
          SL=SL+P**(K-1)
  15    CONTINUE
        SL=2.0D0*SL
        K=I1/2
        FUN1=FUN1+2.0D0*(P**(K-1))/SL
        RETURN
      ENDIF
C     0<P<1, GRADUALLY DECRISING SIZE OF ELEMENTS, WITH RATIO P
C     E.G. P=0.5
C     ---------------------------------------------------------
      IF((P.GT.0.0D0).AND.(P.LT.1.0D0)) THEN
C       FIND THE TOTAL NUMBER OF DIVISIONS FOR ALL THE LINE
C       NUMBER OF ELEMENTS
        M1=M/2
        P1=1.0D0/P
        DO 20 K=1,M1
C         I IS THE NUMBER OF ELEMENTS, INCLUDING THE PRODUCTS OF QUADRATIC 
C           DEVISION
C         K IS THE NUMBER OF ELEMENTS BEFORE DIVISION TO QUADRATICS
          SL=SL+P1**(M1-(K-1)-1)
  20    CONTINUE
        SL=2.0D0*SL
        K=I1/2
        FUN1=FUN1+2.0D0*(P1**(M1-(K-1)-1))/SL
        RETURN
      ENDIF
C     P<-1.0, GRADUALLY INCRISING IN THE MIDDLE-DECRISING AT THE EDGES SIZE
C     OF ELEMENTS, WITH RATIO P
C     E.G. P=-2.0
C     --------------------------------------------------------------------
      IF (P.LT.-1.0D0) THEN
        P1=DABS(P)
C       NUMBER OF ELEMENTS
        M1=M/2
C       THE LINE MAY HAVE EVEN OR ODD NUMBER OF ELEMENTS
C       REMAINDER = M1-INT(M1/2)*2
        LR=MOD(M1,2)
C       M1 EVEN (LR.EQ.0)
C       M1 ODD (LR.NE.0)
C       FIND THE TOTAL NUMBER OF DIVISIONS FOR ALL THE LINE
C       WORK WITH QUADRATIC WHOLE ELEMENTS (BEFORE DEVIDING THEM WITH THE 
C       MIDDLE NODE)
        M2=M1/2
        KE=0
        KO=0
        KK=0
C       M1 EVEN
        IF(LR.EQ.0) KE=M2
C       M1 ODD
        IF(LR.NE.0) KE=M2+1
        DO 17 K=1,M1
C         K COUNTER LOWER THAN THE (MIDDLE+1 FOR EVEN), (MIDDLE FOR ODD) NODE.
          IF(K.LE.KE) KK=K
C         K COUNTER GREATER THAN THE MIDDLE+1 NODE, AND M1 EVEN
          IF((K.GT.KE).AND.(LR.EQ.0)) THEN
            KK=KE-KO
            KO=KO+1
          ENDIF
C         K COUNTER GREATER THAN THE MIDDLE NODE, AND M1 ODD
          IF((K.GT.KE).AND.(LR.NE.0)) THEN
            KO=KO+1
            KK=KE-KO
          ENDIF
C          SL=SL+2.0D0**(KK-1)
          SL=SL+P1**(KK-1)
  17    CONTINUE
        SL=2.0D0*SL
C       CALCULATE THE INTRINSICT COORDINATE FUN1
C       WORK WITH ELEMENTS (AFTER DEVIDING THE QUADRATICS WITH THE 
C       MIDDLE NODE)
        KE=0
C        KO=0
        KK=0
C       M1 EVEN
        IF(LR.EQ.0) KE=M1
C       M1 ODD
        IF(LR.NE.0) KE=M1+1
C       I1 COUNTER LOWER THAN THE (MIDDLE+1 FOR EVEN), (MIDDLE FOR ODD) NODE.
        IF(I1.LE.(KE+1)) KK=I1/2
C       I1 COUNTER GREATER THAN THE MIDDLE+1 NODE, AND M1 EVEN
        IF((I1.GT.(KE+1)).AND.(LR.EQ.0)) THEN
          KK=(KE-KO1+1)/2
          KO1=KO1+1
        ENDIF
C       I1 COUNTER GREATER THAN THE MIDDLE NODE, AND M1 ODD
        IF((I1.GT.KE).AND.(LR.NE.0)) THEN
          KO1=KO1+1
          KK=(KE-KO1+1)/2
        ENDIF
C        FUN1=FUN1+2.0D0*(2.0D0**(KK-1))/SL
        FUN1=FUN1+2.0D0*(P1**(KK-1))/SL
        RETURN
      ENDIF
C     -1<P<0: GRADUALY DECRISING IN THE MIDDLE-INCRISING AT THE EDGES 
C     ELEMENTS, WITH RATIO P
C       E.G. P=-0.5:
C     ------------------------------------------------------------
C      IF (DABS(P+0.5D0).LT.TOL) THEN
      IF((P.LT.0.0D0).AND.(P.GT.-1.0D0)) THEN
        P1=DABS(P)
        P1=1.0D0/P1
C       NUMBER OF ELEMENTS
        M1=M/2
C       THE LINE MAY HAVE EVEN OR ODD NUMBER OF ELEMENTS
C       REMAINDER = M1-INT(M1/2)*2
        LR=MOD(M1,2)
C       M1 EVEN (LR.EQ.0)
C       M1 ODD (LR.NE.0)
C       FIND THE TOTAL NUMBER OF DIVISIONS FOR ALL THE LINE
C       WORK WITH QUADRATIC WHOLE ELEMENTS (BEFORE DEVIDING THEM WITH THE 
C       MIDDLE NODE)
        M2=M1/2
        KE=0
        KO=0
        KK=0
C       M1 EVEN
        IF(LR.EQ.0) KE=M2
C       M1 ODD
        IF(LR.NE.0) KE=M2+1
        DO 19 K=1,M1
C         K COUNTER LOWER THAN THE (MIDDLE+1 FOR EVEN), (MIDDLE FOR ODD) NODE.
          IF(K.LE.KE) KK=K
C         K COUNTER GREATER THAN THE MIDDLE+1 NODE, AND M1 EVEN
          IF((K.GT.KE).AND.(LR.EQ.0)) THEN
            KK=KE-KO
            KO=KO+1
          ENDIF
C         K COUNTER GREATER THAN THE MIDDLE NODE, AND M1 ODD
          IF((K.GT.KE).AND.(LR.NE.0)) THEN
            KO=KO+1
            KK=KE-KO
          ENDIF
          SL=SL+P1**(M2-(KK-1)-1)
  19    CONTINUE
        SL=2.0D0*SL
C       CALCULATE THE INTRINSICT COORDINATE FUN1
C       WORK WITH ELEMENTS (AFTER DEVIDING THE QUADRATICS WITH THE 
C       MIDDLE NODE)
        KE=0
        KK=0
C       M1 EVEN
        IF(LR.EQ.0) KE=M1
C       M1 ODD
        IF(LR.NE.0) KE=M1+1
C       I1 COUNTER LOWER THAN THE (MIDDLE+1 FOR EVEN), (MIDDLE FOR ODD) NODE.
        IF(I1.LE.(KE+1)) KK=I1/2
C       I1 COUNTER GREATER THAN THE MIDDLE+1 NODE, AND M1 EVEN
        IF((I1.GT.(KE+1)).AND.(LR.EQ.0)) THEN
          KK=(KE-KO1+1)/2
          KO1=KO1+1
        ENDIF
C       I1 COUNTER GREATER THAN THE MIDDLE NODE, AND M1 ODD
        IF((I1.GT.KE).AND.(LR.NE.0)) THEN
          KO1=KO1+1
          KK=(KE-KO1+1)/2
        ENDIF
        FUN1=FUN1+2.0D0*(P1**(M2-(KK-1)-1))/SL
        RETURN
      ENDIF
      RETURN
      END
C
C ----------------------------------------------------------------------
       SUBROUTINE RATENUM(XB,YB,XBA,YBA,NOD,MX,PX,MY,PY,PXYA)
C
C      GIVEN THE RATE OF CHANGE OF LENGTH ELEMENTS, IN THE SIDE OF A SQUARE
C      CALCULATES THE RATE IN THE OTHER DIRECTION, IN A SUCH A WAY THAT
C      AT THE CORNERS OF BOTH SIDES TO HAVE ABOUT THE SAME LENGTH OF ELEMENTS.
C
      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION XB(3),YB(3),XBA(3),YBA(3),SHP(3)
C
C     FIND THE INTRINSICT COORDINATE (LOCAL SYSTEM [-1,1]), AT THE 
C     2ND POINT OF THE LINE (1ST IS THE EDGE)
      I1=2
      KO1=0
C     START WITH THE RATE IN THE OTHER SIDE
      MXY=MY
      PXYA=PY
C     CALL SUBROUTINE SYNTEL, WITH DIAK=1 (TO GIVE INITIAL VALUE FUN1=-1)
      CALL SYNTEL(I1,MXY,PXYA,FUN1A,KO1,1)
C     FIND THE COORDINATES OF THE POSITION OF THE 2ND NODE OF THE OTHER SIDE
C     (THE 1ST NODE IS AT THE BEGINING OF THE LINE)
      EKS=FUN1A
      CALL MORFH(EKS,NOD,SHP)
      CALL PRODUCT(XBA,SHP,NOD,DOT)
      XCRA=DOT
      CALL PRODUCT(YBA,SHP,NOD,DOT)
      YCRA=DOT
C     LENGTH OF THE FIRST ELEMENT OF THE OTHER SIDE(FROM THE START OF
C     THE SIDE, TILL THE 2ND NODE)
      DSA=DSQRT((XCRA-XBA(1))**2+(YCRA-YBA(1))**2)
C     CONTINUE WITH THE CURRENT SIDE
      MXY=MX
C     WE WANT FOR THE RESPECTIVE 2ND POINT IN THE OTHER SIDE OF THE
C     RECTANGLE (J=2,4), TO HAVE ABOUT THE SAME VALUE FUN1A.
C     STARTING WITH VALUE PXYA(=PY), CALCULATE THE FUN1B. AN ITERRATIVE
C     LOOP STARTS, UNTIL FUN1B BECOMES ABOUT EQUAL TO FUN1A (WITH 
C     TOLERANCE XACC. THE RETURN VALUE OF PXYA IS THE WANTED RATE IN THE
C     OTHER SIDE OF THE SQUARE.
C     TOLERANCE 
      XACC=0.00005
C     START FROM FUN1A
C     KDIAK=0 : INCREASES THE RATE PXYA CONTINUSLY WITH STEP 0.1,
C               (STARTING FROM 0), UNTIL THE DIFFERENCE DIF=DS-DS1<0
      KDIAK=0 
      CALL CONVSQU(XB,YB,NOD,I1,MXY,PXYA,FUN1A,DSA,FDIF,KDIAK)
      IF(DABS(FDIF).LT.XACC) GO TO 30
C     KDIAK=1 : DECREASES THE ANGLE TH3 CONTINUSLY WITH STEP 0.001,
C               (STARTING FROM THE PREVIOUS VALUE), UNTIL THE DIFFERENCE
C               FUN1A-FUN1B>=0
      KDIAK=1 
      CALL CONVSQU(XB,YB,NOD,I1,MXY,PXYA,FUN1A,DSA,FDIF,KDIAK)
      IF(DABS(FDIF).LT.XACC) GO TO 30
C     KDIAK=2 : INCREASES AGAIN THE ANGLE TH3 CONTINUSLY WITH STEP 0.001,
C               (STARTING FROM THE PREVIOUS VALUE), UNTIL THE DIFFERENCE
C               FUN1A-FUN1B<0
      KDIAK=2
      CALL CONVSQU(XB,YB,NOD,I1,MXY,PXYA,FUN1A,DSA,FDIF,KDIAK)
  30  CONTINUE
      RETURN
      END
C
C ----------------------------------------------------------------------
      SUBROUTINE CONVSQU(XB,YB,NOD,I1,MXY,PXYA,FUN1A,DSA,FDIF,KDIAK)
C
C     FOR THE GIVEN VALUE OF RATE IN ONE SIDE OF A RECTANGLE PXYA,
C     CALCULATES THE RATE IN THE OTHER SIDE PXYB BY
C     FINDING THE DIFFERENCE DIF=FUN1A-FUN1B AND DEPENDING ON THE SIGN OF DIF
C     UNDIL DIF BECOMES ABOUT 0.
C
C     KDIAK=0 : INCREASES THE RATE PXYA CONTINUSLY WITH STEP 0.1,
C               (STARTING FROM 0), UNTIL THE DIFFERENCE DIF=FUN1A-FUN1B<=0
C     KDIAK=1 : DECREASES THE ANGLE TH3 CONTINUSLY WITH STEP 0.005,
C               (STARTING FROM THE PREVIOUS VALUE), UNTIL THE DIFFERENCE
C               DIF=FUN1A-FUN1B>=0
C     KDIAK=2 : INCREASES AGAIN THE ANGLE TH3 CONTINUSLY WITH STEP 0.0001,
C               (STARTING FROM THE PREVIOUS VALUE), UNTIL THE DIFFERENCE
C               DIF=FUN1A-FUN1B<=0
C     THE WHOLE PROCESS STOPS WHEN EITHER |FDIF|<XACC, OR AFTER FINISHING
C     THE ABOVE 3 STEPS WITH ESTIMATED ACCURACE NOT FAR FROM 0.0001.

      IMPLICIT REAL*8 (A-H,O-Y)
      DIMENSION XB(3),YB(3),SHP(3)
C
C     FOR THE GIVEN VALUE TH3, CALCULATE TH4 AND NEW DISTANCE AE=DS1
      PI=3.14159265359D0
C     TOLERANCE 
      XACC=0.00005
      IF(KDIAK.EQ.0) RAC=0.1D0
      IF(KDIAK.EQ.1) RAC=-0.01D0
      IF(KDIAK.EQ.2) RAC=0.001D0
      PXYB=PXYA
  20  CONTINUE
C
C     FOR A GIVEN PXYA, CALCULATE FUN1B
      KO1=0
C     CALL SUBROUTINE SYNTEL, WITH DIAK=1 (TO GIVE INITIAL VALUE FUN1=-1)
      CALL SYNTEL(I1,MXY,PXYA,FUN1B,KO1,1)
C     FIND THE COORDINATES OF THE NEW POSITION OF THE 2ND NODE OF THE LINE
C     (THE 1ST NODE IS AT THE BEGINING OF THE LINE)
      EKS=FUN1B
      CALL MORFH(EKS,NOD,SHP)
      CALL PRODUCT(XB,SHP,NOD,DOT)
      XCRB=DOT
      CALL PRODUCT(YB,SHP,NOD,DOT)
      YCRB=DOT
C     LENGTH OF THE FIRST ELEMENT OF THE CURRENT SIDE(FROM THE START OF
C     THE SIDE, TILL THE 2ND NODE)
      DSB=DSQRT((XCRB-XB(1))**2+(YCRB-YB(1))**2)
C     DIFFERENCE BETWEEN THE OLD AND NEW VALUE OF DS
      FDIF=DSA-DSB
C
      IF(DABS(FDIF).LT.XACC) GO TO 30
      IF((KDIAK.EQ.0).OR.(KDIAK.EQ.2)) THEN
        IF(FDIF.LE.0.0D0) GO TO 30
      ENDIF
      IF(KDIAK.EQ.1) THEN
        IF(FDIF.GE.0.0D0) GO TO 30
      ENDIF
C     INCREASE PXY TO RAC
      PXYA=PXYA+RAC
      GO TO 20
  30  CONTINUE
      RETURN
      END
C------------------------------------------------------------------------
      SUBROUTINE GEOCOMB(XCR,YCR,SEG,NCELE,JKODE,NS,N1,IB,
     &                  JL1,IBI,SGTYP,NTSG)
C     CREATES THE GEOMETRY OF A COMBOUND SHAPE MESH
C     NS: NUMBER OF SEGMENTS
C     XCR,YCR : COORDINATES  OF ALL THE NODES OF THE COMBOUND SHAPE 
C               (RETURN VALUE)
C     IBI : RETURN VALUE, COUNTER FOR NEXT READING FROM ARRAYS OF ONE DIMENSION
C     LOCAL VARIABLES:
C             XND,YND: TEMPORARY COORDINATES
C             RSQ: COORDINATES OF THE EXAMINING SEGMENT
C -----------------------------------------------------------------------
      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION SEG(NTSG*7),NCELE(NTSG)
      DIMENSION JKODE(NTSG)
      DIMENSION XND(50),YND(50)
      DIMENSION RSQ(6)
      DIMENSION NXELE(5),NYELE(5),PSAI(5)
      DIMENSION NREGI(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5),XCR0(5),YCR0(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &        TYPELY(5),NDIS(5)
      DIMENSION SGTYP(NTSG)
      PI=3.14159265359D0
C     PARAMETER OF THE DIVISION OF ELEMENTS
      PX=1.0D0
      LA=0
      DO 10 I=1,NS
        IBI=IBI+1
        JL=JL1+7*(I-1)
C       STRAIGHT LINE
C       -------------
        IF(JKODE(IBI).EQ.1) THEN
C         COORDINATES OF THE ENDS OF THE LINE
C         START X COORD.
          RSQ(1)=SEG(JL)
          RSQ(2)=SEG(JL+1)
          RSQ(5)=SEG(JL+2)
          RSQ(6)=SEG(JL+3)
C         COORDINATES OF THE MIDDLE NODES OF THE LINE
          RSQ(3)=(RSQ(1)+RSQ(5))/2.0D0
          RSQ(4)=(RSQ(2)+RSQ(6))/2.0D0
C         INTERPOLATION BY QUADRATIC SHAPE FUNCTIONS
          NOD=3
C         NUMBER OF NODES ON THE LINE, FROM THE KNOWN NUMBER OF ELEMENTS
C         THE LAST NODE IS NOT TAKEN INTO ACCOUNT. IT WILL BE CALCULATED
C         IN THE NEXT SEGMENT(AS FIRST NODE)
          NODSEG=2*NCELE(IBI)
C         ELEMENTS ON LINE, AFTER DIVIDING THE ORIGINAL ELEMENTS WITH
C         A MIDDLE NODE TO HAVE QUADRATIC ELEMENTS
          MX=2*NCELE(IBI)
C         LINE TYPE
C         PX=TYPELX(IB)
          PX=SGTYP(IBI)
          CALL GEOLIN(XND,YND,RSQ,NOD,MX,PX,N1,NODSEG,XLAST,YLAST)
          DO 20 J=1,NODSEG
            LA=LA+1
            XCR(LA)=XND(J)
            YCR(LA)=YND(J)
   20     CONTINUE
        ENDIF
C       ELLIPTICAL OR CIRCULAR SEGMENT
C       ------------------------------
        IF(JKODE(IBI).EQ.2) THEN
C         CONVERT THE ANGLES FROM DEGREES TO RADIANS
          SEG(JL+3)=SEG(JL+3)*PI/180.0D0
          SEG(JL+4)=SEG(JL+4)*PI/180.0D0
          SEG(JL+7)=SEG(JL+7)*PI/180.0D0  
C         COORDINATES OF THE CENTER OF THE SEGMENT
C         X COORD.
          X0=SEG(JL+1)
C         Y COORD.
          Y0=SEG(JL+2)
C         START ANGLE OF SEGMENT
          TH1=SEG(JL+3)
C         END ANGLE OF SEGMENT
          TH2=SEG(JL+4)
C         RADIUS OR SEMIAXIS
          RAD1=SEG(JL+5)
C         RATIO
          RATIO1=SEG(JL+6)
C         ROTATION
          PSI=SEG(JL+7)
C         INTERPOLATION BY QUADRATIC SHAPE FUNCTIONS
          NOD=3
C         ELEMENTS IN THE SEGMENT
          NELR=NCELE(IBI)
C         NUMBER OF NODES ON THE SEGMENT, FROM THE KNOWN NUMBER OF ELEMENTS
C         THE LAST NODE IS NOT TAKEN INTO ACCOUNT. IT WILL BE CALCULATED
C         IN THE NEXT SEGMENT(AS FIRST NODE)
          NODSEG=2*NCELE(IBI)
          NREGION=NREGI(IB)
          CALL GEOELL(XND,YND,X0,Y0,TH1,TH2,PSI,NELR,RAD1,
     &                  RATIO1,NODSEG,NREGION,XLAST,YLAST)
          DO 30 J=1,NODSEG
            LA=LA+1
            XCR(LA)=XND(J)
            YCR(LA)=YND(J)
   30     CONTINUE
        ENDIF
   10 CONTINUE
C     FOR OPEN BOUNDARIES FIND THE COORDIANATES OF THE LAST NODE
C     ACCEPT THE ENCLOSING ELEMENT SURFACE AS OPEN
      IF((NREGI(IB).EQ.3).OR.(NREGI(IB).EQ.4).OR.
     &   (NREGI(IB).EQ.5)) THEN
        LA=LA+1
        XCR(LA)=XLAST
        YCR(LA)=YLAST
      ENDIF
      JL1=JL1+7*NS
      RETURN
      END
