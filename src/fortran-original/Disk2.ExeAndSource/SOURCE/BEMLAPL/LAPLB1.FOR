      INTEGER*4 MINV[ALLOCATABLE](:)
      COMPLEX*16 ZLOAD1[ALLOCATABLE](:)
      COMPLEX*16 ZDINTX[ALLOCATABLE](:)
      COMPLEX*16 ZDINTY[ALLOCATABLE](:)
