      J2=J1+N1
      J3=J2+N1
      L1=1
      L2=L1+N2*N2
      L3=L2+N2*N2
      L4=L3+N2
      L5=L4+N2
C
      M1=1
      M2=M1+N6
C
      ML1=1
      ML2=ML1+N4*N3
      ML3=ML2+N4*N3
      ML4=ML3+N4*N3
C
        CALL DATAS(RARR(J1),RARR(J2),IARR(I1),IARR(I2),IARR(I3),
     &    IARR(I4),IARR(I5),NTOT,NPLOT,N1,N2,N3,N4,N9,MPL)
      IF(NINT.GT.0) THEN
        ALLOCATE (ZDINTX(N9*NINT),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
        ALLOCATE (ZDINTY(N9*NINT),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
        ALLOCATE (SDINT(N9*NINT),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
      ENDIF
C
        CALL GAUSWE
        CALL TRIGO(WR,WI,NF,DLANCZ,N9)
        WRITE(*,*) 'PLEASE WAIT..........'
        CALL LAPIN(RARR(J1),RARR(J2),IARR(I1),IARR(I2),IARR(I3),
     &    IARR(I4),IARR(I5),
     &    ZLOAD1,ZDINTX,ZDINTY,SDINT,NHPOS,TIMELAP,CFLAP,
     &    WR,WI,JP1,NF,DLANCZ,AXFFT,BXFFT,ARFFT,AIFFT,ZLT1,ZLT2,
     &    ZLT3,ZLD1,ZLD2,SLT1,SFARR,ZZARR(ML1),
     &    ZZARR(ML2),ZZARR(ML3),N1,N2,N3,N4,N5,N7,N8,N9,LINV,MINV,
     &    NTOT,NPLOT,NUNIT)
