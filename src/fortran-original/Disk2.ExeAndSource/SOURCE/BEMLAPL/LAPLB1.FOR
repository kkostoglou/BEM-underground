C------------------------------------------------
C
        SUBROUTINE TRIGO(WR,WI,NF,DLANCZ,N9)
C
C       NTINT ROOTS OF UNITY, LANCZOS CONVERGENCE FACTORS
C
C       NTINT IS NUMBER OF TIME AND/OR LAPLACE SPECTRUM POINTS
C       (IT CAN BE SET TO EITHER 20 OR 50)
C
        IMPLICIT REAL*8 (A-H,O-Y)
        DIMENSION WR(N9),WI(N9)
        DIMENSION DLANCZ(N9)
        N=N9
  15    NF=3
C
C       N ROOTS OF UNITY
C
        PI=3.141592653598979323D0
        WR(1)=1.0D0
        WI(1)=0.0D0
        COEF=2.0D0*PI
        MN=N/2+1
        DO 25 I=2,MN
        REX=DFLOAT(I-1)
        ANG=COEF*REX/DFLOAT(N)
        WR(I)=DCOS(ANG)
        WI(I)=DSIN(ANG)
  25    CONTINUE
        L=MN+1
        DO 45 I=L,N
        J=N-I+2
        WR(I)=WR(J)
        WI(I)=-WI(J)
  45    CONTINUE
C
C       LANCZOS FACTORS
C
        DN=DFLOAT(N)
        DPIN=3.14159265358979323D+00/DN
        DLANCZ(1)=1.0D+00
        DO 65 K=2,N
        DS=DPIN*DFLOAT(K-1)
        L=-1
        DTERM=1.0D+00
        DSOM=1.0D+00
  35    L=L+1
        DNOM=DFLOAT((2*L+2)*(2*L+3))
        DTERM=-DTERM*DS*DS/DNOM
        DSOM=DSOM+DTERM
        IF (DABS(DTERM) .GE. 1.0D-16) GO TO 35
        DLANCZ(K)=DSOM
  65    CONTINUE
        RETURN
        END
C------------------------------------------------
        SUBROUTINE LAPIN(XCR,YCR,KONN,NONN,MBCU,LBCU,NDTYPE,
     &    ZLOAD1,ZDINTX,ZDINTY,SDINT,NHPOS,
     &    TIME,CF,WR,WI,JP1,NF,DLANCZ,AX,BX,ARFFT,
     &    AIFFT,ZLT1,ZLT2,ZLT3,ZLD1,ZLD2,SLT1,
     &    SFDIAG,ZZ1,ZZ2,ZZ3,N1,N2,N3,N4,N5,N7,N8,N9,LINV,MINV,
     &    NTOT,NPLOT,NUNIT)
C
        IMPLICIT COMPLEX*16 (Z)
        IMPLICIT REAL*8 (A-H,O-Y)
        DIMENSION XCR(N1),YCR(N1)
        DIMENSION KONN(N3,N4),MBCU(N2)
        DIMENSION NONN(N1,N4)
        DIMENSION LBCU(N3),NDTYPE(N1)
        DIMENSION TIME(N9),CF(N9)
        DIMENSION WR(N9),WI(N9),JP1(N8)
        DIMENSION DLANCZ(N9)
        DIMENSION ARFFT(N9),AIFFT(N9)
        DIMENSION AX(N9),BX(N9)
        DIMENSION ZLT1(N9,N4,N3),ZLT2(N9,N4,N3),ZLT3(N9,N4,N3)
        DIMENSION ZLD1(N9,N4,N3),ZLD2(N9,N4,N3)
        DIMENSION SLT1(N9,N4,N3)
        DIMENSION SFDIAG(N1,2,2)
        DIMENSION LINV(N2),MINV(N2)
        DIMENSION ZZ1(N4,N3),ZZ2(N4,N3),ZZ3(N4,N3)
        DIMENSION NHPOS(N3)
        DIMENSION ZLOAD1(N5)
        DIMENSION NPLOT(NTOT)
        INTEGER*2 STAT,IERR
        COMMON/CONTR/NNODE,NELEM,NP
C                 MODIFICATION FOR VISCOELESTICITY
        COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
        COMMON/FREE/NFFS,NFRE
C       FREQUENCY FOR HARMONIC WAVE
        COMMON/FREQ/OFREQ
C       INTERNAL POINTS WITH THEIR CO-ORDINATES
        COMMON/INTERN/NINT,CINT(10,2)
        DIMENSION ZDINTX(N9,NINT),ZDINTY(N9,NINT),SDINT(N9,NINT)
        COMPLEX*16 ZGM[ALLOCATABLE](:,:)
        COMPLEX*16 ZFM[ALLOCATABLE](:,:)
        COMPLEX*16 ZLOAD[ALLOCATABLE](:)
        COMPLEX*16 ZTEMP[ALLOCATABLE](:)
        TOL=1.0E-11
        TOLC=0.5D0
C
        N=N9
        CALL CLRZRR(ZLT1,N9*N4*N3)
        CALL CLRZRR(ZLT2,N9*N4*N3)
        CALL CLRZRR(ZLT3,N9*N4*N3)
        CALL CLRZRR(ZLD1,N9*N4*N3)
        CALL CLRZRR(ZLD2,N9*N4*N3)
        CALL CLRZRR(ZDINTX,N9*NINT)
        CALL CLRZRR(ZDINTY,N9*NINT)
        NNODE1=0
        NELEM1=0
        DO I=1,NNODE
          IF(NDTYPE(I).EQ.4) GO TO 35
C         NODES WITHOUT THE NODES OF THE ENCLOSING ELEMENTS BOUNDARY
C         (THE ENCLOSING NODES HAVE THE LAST NUMBERS IN THE SEQUENCE)
          NNODE1=NNODE1+1
  35    CONTINUE
        END DO
C       IGNORE ELEMENTS OF THE ENCLOSING ELEMENTS BOUNDARY
        DO I=1,NELEM
          IF(LBCU(I).EQ.4) GO TO 30
C         ELEMENTS WITHOUT THE ELEMENTS OF THE ENCLOSING ELEMENTS BOUNDARY
C         (THE ENCLOSING NODES HAVE THE LAST NUMBERS IN THE SEQUENCE)
          NELEM1=NELEM1+1
  30      CONTINUE
        END DO
        NA1=NNODE1
        NA2=2*NNODE1
        NA3=NELEM1
        NA5=3*NNODE1
        ALLOCATE (ZGM(NA2,NA2),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
        ALLOCATE (ZFM(NA2,NA2),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
        ALLOCATE (ZLOAD(N2),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
        ALLOCATE (ZTEMP(N2),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
        PI=3.14159265359D0
        IF(OFREQ.GT.TOL) THEN
          TIM=2.0*PI/OFREQ
        ENDIF
        OMEGA=2.0D0*PI/TIM
        AK=6.0D0/TIM
        DT=TIM/DFLOAT(N)
        DO 2 K=1,N
          WRITE(*,*) '          TIME STEP : ', K
          CALL CLRZRR(ZZ1,N4*N3)
          CALL CLRZRR(ZZ2,N4*N3)
          CALL CLRZRR(ZZ3,N4*N3)
          TIME1=DT*DFLOAT(K-1)
          CF(K)=2.0D0*DEXP(AK*TIME1)/TIM
          TIME(K)=TIME1
          AKMG=OMEGA*DFLOAT(K-1)
          CALL BEM(AK,AKMG,XCR,YCR,KONN,NONN,MBCU,LBCU,NDTYPE,
     &      ZLOAD1,K,NHPOS,ZGM,ZFM,ZLOAD,ZTEMP,
     &      ZLT1,ZLT2,ZLT3,ZLD1,ZLD2,SFDIAG,ZZ1,ZZ2,ZZ3,ZDINTX,
     &      ZDINTY,NA1,NA2,NA3,N1,N2,N3,N4,N5,N7,N9,LINV,MINV)
  2       CONTINUE
  41    CONTINUE
C       CALCULATE AND SAVE IN FILE 13, THE HOOP STRESSES AND X,Y GLOBAL 
C       DISPLACEMENTS FOR PLOTING WITH POSTBEM
        NP1=NA3
        KDIAK1=0
        KDIAK2=0
        KDIAK3=0
        KDIAK4=0
        KDIAK5=0
        DO 20 L=1,NTOT
C         CASE OF HOOP STRESSES PLOTS  
C         NORMAL STRESS IN RADIAL DIRECTION SYSTEM (NPLOT=1)
C         OR IN CARTESIAN SYSTEM (NPLOT=11)
          IF(((NPLOT(L).EQ.1).OR.(NPLOT(L).EQ.11)).AND.(KDIAK1.NE.1))
     &    THEN
            KDIAK1=1
C           INDEX FOR STRESSES FOR THE UNITS CONVERSION
            KUN=1
C           INVERTION OF THE LAPLACE TRANSFORM TO OBTAIN THE HOOP STRESSES
            CALL FASTINV1(ZLT1,SLT1,CF,WR,WI,JP1,NF,DLANCZ,
     &          AX,BX,ARFFT,AIFFT,N,N3,N4,N8,N9,NP1,KUN,NUNIT)
          ENDIF
C         TANGENTIAL STRESS IN RADIAL DIRECTION SYSTEM (NPLOT=2)
C         OR IN CARTESIAN SYSTEM (NPLOT=12)
          IF(((NPLOT(L).EQ.2).OR.(NPLOT(L).EQ.12)).AND.(KDIAK2.NE.1))
     &    THEN
            KDIAK2=1
            KUN=1
C           INVERTION OF THE LAPLACE TRANSFORM TO OBTAIN THE RADIAL STRESSES
            CALL FASTINV1(ZLT2,SLT1,CF,WR,WI,JP1,NF,DLANCZ,
     &            AX,BX,ARFFT,AIFFT,N,N3,N4,N8,N9,NP1,KUN,NUNIT)
          ENDIF
C         SHEAR STRESS IN RADIAL DIRECTION SYSTEM (NPLOT=3)
C         OR IN CARTESIAN SYSTEM (NPLOT=13)
          IF(((NPLOT(L).EQ.3).OR.(NPLOT(L).EQ.13)).AND.(KDIAK3.NE.1))
     &    THEN
            KDIAK3=1
            KUN=1
C           INVERTION OF THE LAPLACE TRANSFORM TO OBTAIN THE SHEAR STRESSES
            CALL FASTINV1(ZLT3,SLT1,CF,WR,WI,JP1,NF,DLANCZ,
     &           AX,BX,ARFFT,AIFFT,N,N3,N4,N8,N9,NP1,KUN,NUNIT)
          ENDIF
C         CASE OF DEFORMED SHAPE PLOT(NPLOT=5) IN RADIAL DIRECTION,
C         OR X DISPLACEMENTS PLOT IN CARTESIAN SYSTEM(NPLOT=21)
          IF(((NPLOT(L).EQ.5).OR.(NPLOT(L).EQ.21)).AND.(KDIAK4.NE.1))
     &    THEN
            KDIAK4=1
C           INDEX FOR DISPLACEMENTS FOR THE UNITS CONVERSION
            KUN=2
C           INVERTION OF THE LAPLACE TRANSFORM TO OBTAIN THE DISPLACEMENTS
C           X DISPLACEMENTS
            CALL FASTINV1(ZLD1,SLT1,CF,WR,WI,JP1,NF,DLANCZ,
     &           AX,BX,ARFFT,AIFFT,N,N3,N4,N8,N9,NP1,KUN,NUNIT)
          ENDIF
C         CASE OF DEFORMED SHAPE PLOT(NPLOT=5) IN RADIAL DIRECTION,
C         OR Y DISPLACEMENTS PLOT IN CARTESIAN SYSTEM(NPLOT=22)
          IF(((NPLOT(L).EQ.5).OR.(NPLOT(L).EQ.22)).AND.(KDIAK5.NE.1))
     &    THEN
            KDIAK5=1
            KUN=2
C           INVERTION OF THE LAPLACE TRANSFORM TO OBTAIN THE DISPLACEMENTS
C           Y DISPLACEMENTS
            CALL FASTINV1(ZLD2,SLT1,CF,WR,WI,JP1,NF,DLANCZ,
     &           AX,BX,ARFFT,AIFFT,N,N3,N4,N8,N9,NP1,KUN,NUNIT)
          ENDIF
  20    CONTINUE
C       INTERNAL POINTS
        IF(NINT.NE.0) THEN
C         X DISPLACEMENTS
C         INDEX FOR DISPLACEMENTS FOR THE UNITS CONVERSION
          KUN=2
          CALL FASTINV2(ZDINTX,SDINT,CF,WR,WI,JP1,NF,DLANCZ,
     &          AX,BX,ARFFT,AIFFT,N,N4,N8,N9,NP1,KUN,NUNIT)
C         Y DISPLACEMENTS
          KUN=2
          CALL FASTINV2(ZDINTY,SDINT,CF,WR,WI,JP1,NF,DLANCZ,
     &          AX,BX,ARFFT,AIFFT,N,N4,N8,N9,NP1,KUN,NUNIT)
C   40     CONTINUE
        ENDIF
        GO TO 999
  988   STOP '....Not enough storage for data, aborting...'
  999   CONTINUE
        RETURN
        END
