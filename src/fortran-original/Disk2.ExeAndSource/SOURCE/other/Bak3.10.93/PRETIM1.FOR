              IF(DABS(EXPLSV).GT.TOL)THEN
                CALL TREFEXSV(XCR,YCR,SXX,SYY,SXY,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            SRXX,SRYY,SRXY,DRNORM,NDTYPE)
              ENDIF


C             CALCULATE THE EQUIVALENT TO SRXX,SRYY,SRXY INCIDENT STRESSES 
C             AND TRACTIONS,LOADS WITHOUT DELAYS 
C             (DELAYS ALREADY APPLIED IN SUBROUTINE REF)
              CALL REFLTIM(XCR,YCR,SLOADF,SLOAD2,SRXX,
     &          SRYY,SRXY,N1,N2,N3,N4,N5,CA,CB,NB0,NB1,NCOUNT,NB2,
     &          NBOUN,NSHAP,LCRN,NDTYPE,MBD)
            ENDIF
          ENDIF
CC         CASE OF NFFS=2 OR 3, CALCULATION OF THE FREE FIELD WITH SUBREGIONS
CCC         INCIDENT LOADS ARE CALCULATED ONLY FOR THE FREE SURFACE
CCC         AND FOR THE NON SIMULATION SURFACES
CC          IF(NFFS.EQ.2) THEN
CC          IF(NFFS.GT.2) THEN
CC         CASE OF NFFS=0 (INFINITE REGION-REFLECTION AS IN INFINITE REGION)
CC         OR 2 OR 3 (SUBREGIONS OR SIMULATION) 
C          IF((NFFS.EQ.0).OR.(NFFS.EQ.2).OR.(NFFS.EQ.3)) THEN
CC          IF(NFFS.GT.1) THEN
CC               .AND.(NFRE.EQ.1)) THEN
C            WVEL=C1
C            KPS=1
C            CALL WINCIDIM(XCR,YCR,SLOAD,SLOAD1,TSXX,TSYY,TSXY,
C     &         N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
C     &         XCEN,YCEN,NB2,SXX,SYY,SXY,WVEL,K,KEXPL,NBOUN,
C     &        NSHAP,LCRN,KPS)
C            IF (IEXIT.EQ.1) GO TO 999
C          ENDIF

C
C          ENDIF
   61    CONTINUE
C       ADD THE INCIDENT AND REFLECTED STRESSES
        DO 42 I=1,N5
          SLOAD1(I)=SLOAD1(I)+SLOAD2(I)
  42    CONTINUE
C       ADD THE INCIDENT AND REFLECTED TRACTIONS
        DO 44 I=1,N2
          SLOAD(I)=SLOAD(I)+SLOADF(I)
  44    CONTINUE
C       INCIDENT TRACTIONS OR FREE FIELD TRACTIONS(IF THERE IS FREE SURFACE)


C&&&&&&&&&&&&&
C        WRITE(3,*) SLOAD


        WRITE(1,*) SLOAD

