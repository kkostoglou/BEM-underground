C       OR FREE FIELD STRESSES (IF THERE IS FREE SURFACE)


C&&&&&&&&&&&&&&&
C        WRITE(2,*) SLOAD1
        WRITE(1,*) SLOAD1
  31  CONTINUE
  999 CONTINUE
      GO TO 998
 988  STOP '....Not enough storage for data, aborting...'
 998  CONTINUE
