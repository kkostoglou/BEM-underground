C^^^^^^^^^^^^^^^^^^^^^^^
C*****************
C      SUBROUTINE WRITEDAT(XCR,YCR,KONN,KONZON,KONNOT,KZON,NONN,
C     &  NONZON,NONNOT,MBCU,LBCU,NDTYPE,NZTYPE,NODZ,NNODEB,NELEMB,NELZ,
C     &  NTOT,NPLOT,NDTOT,NDPLOT,LETOT,LEPLOT,CA,CB,CP,NBOUN,
C     &  XCEN,YCEN,SIGC,FM,FS,KEXPL,NSHAP,LCRN,N1,N2,N3,N4,MND,
C     &  MPL,MBD,INES)

      SUBROUTINE WRITEDAT(XCR,YCR,KONN,KONZON,KONNOT,KZON,KONBOUN,
     &  NONN,NONZON,NONNOT,MBCU,LBCU,NDTYPE,NZTYPE,NODZ,NNODEB,
     &  NELEMB,NELZ,NTOT,NPLOT,NDTOT,NDPLOT,LETOT,LEPLOT,CA,CB,CP,
     &  NBOUN,XCEN,YCEN,SIGC,FM,FS,KEXPL,NSHAP,LCRN,N1,N2,N3,N4,MND,
     &  MPL,MBD,INES)

C     &  NGAUS,NSNG,NCASE,NONSNG,DNONSNG1,DNONSNG2)

C
C     LCRN(8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE. 
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY

C^^^^^^^^^^^^^^^^^^^^
C           INES : INDEX 0: NUMBER OF ELEMENTS IN A SEGMENT WERE 0
C                        1: THERE WERE NOT 0 NUMBER OF ELEMENTS IN ANY SEGMENT


      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      CHARACTER FNAMEIN*14,FNAMEPRE*14,DATE*35
      CHARACTER FNAMEPRO*14,FNAMEPOS*14
      CHARACTER TIME*15,SNAME*35
C
      DIMENSION LCRN(8)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON/GEOM3/FAI,PSAI
      COMMON/BLK20/DATE,TIME,SNAME,FNAMEIN,FNAMEPRE,
     &             FNAMEPRO,FNAMEPOS


C&&&&&&&&&&&&&&&&&&&&
C     COMMON BLOCK FOR ZONES: NZONE IS THE TOTAL NUMBER OF ZONE BOUNDARIES
C                             =0: NO ZONES, 1: ZONES ARE PRESENT
C      COMMON/RZON/NZBOUN1(5,5),NZBOUN2(5,5),RZYOUN(5),RZPOIS(5),
C     &            RZDENS(5)
      COMMON/RZON1/NZONE,RZLA(5),RZMU(5),RZNU(5),RZHO(5),CZ1(5),
     &             CZ2(5),FZVISC(5),NZMODE(5),IBOU(5,5)
C      REAL*8 RZLA,RZMU,RZNU,RZHO,CZ1,CZ2
c&&&&&&&&&&&&&&&&&&&&



CC&&&&&&&&&&&&&&&&&
CC     COMMON BLOCKS FOR LININGS:
CC       NLINE: NUMBER OF TOTAL BOUNDARIES WITH LINING
CC       LINBD: NUMBER OF LINED BOUNDARIES
CC       LINTH: THICKNESS OF LININGS PER BOUNDARY
C      COMMON/LIN1/NLINI,LINBD(5),THLIN(5)
CC      COMMON/LIN2/RLYOUN,RLPOIS,RLDENS,FLVISC,NLMODE
C      COMMON/LIN3/RLLA,RLMU,RLNU,RLHO,CL1,CL2
CC&&&&&&&&&&&&&&&&&&&&&

C&&&&&&&&&&&&&&&&
      DIMENSION NZTYPE(MBD,N1)






C^^^^^^^^^!!!!!!!!!!!!
C     INDICATION FOR THE INTERNAL POINT
      COMMON/FREQ/OFREQ
C     INTERNAL POINTS WITH THEIR CO-ORDINATES
      COMMON/INTERN/NINT,CINT(10,2)

      DIMENSION XCR(N1),YCR(N1)
      DIMENSION KONN(N3,N4),KONZON(N3,N4),KONNOT(N3,N4)
      DIMENSION NONN(N1,N4),NONZON(N1,N4),NONNOT(N1,N4)
      DIMENSION MBCU(N2),LBCU(N3)
      DIMENSION NDTYPE(N1)
      DIMENSION NELEMB(MBD),NNODEB(MBD),NREGI(5),NPLOT(MPL)
      DIMENSION PSAI(5)
      DIMENSION NDPLOT(MND),LEPLOT(2*MND)
      DIMENSION LDIR(3)
      DIMENSION NSHAP(NBOUN)
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &          TYPELY(5),NDIS(5)
C     NODZ: ARRAY OF INDEXES THAT INDICATE THE ZONE THAT EVERY NODE BELONGS
C     TOO (IF THERE ARE NOT ZONES IT HAS ZERO VALUES)
C     NELZ: ARRAY OF INDEXES THAT INDICATE THE ZONE THAT EVERY ELEMENT
C     BELONGS TOO (IF THERE ARE NOT ZONES IT HAS ZERO VALUES)
      DIMENSION NODZ(N1),NELZ(N3)
C     CONNECTIVITY ZONE'S ARRAY
      DIMENSION KZON(MBD,N3,N4)


C      DIMENSION NONSNG(NCASE),DNONSNG1(NCASE),DNONSNG2(NCASE)
C     CONTROL OF NUMERICAL INTEGRATION
C      COMMON/NUMER/NGAUS,NSNG,DNONSNG1(10),DNONSNG2(10),NONSNG(10)
C      COMMON/NUMER/NGAUS,NSNG,NCASE,DNONSNG1(10),DNONSNG2(10),
C     &             NONSNG(10)
      COMMON/NUMER/NGAUS,NSNG,NCASE,NONSNG(10),DNONSNG1(10),
     &             DNONSNG2(10)



C

C****************
C           CONNECTIVITY OF ZONE K, ELEMENT I, WITH NUMBERING IN THE
C           BOUNDARY ONLY (THE 2nd INDEX SHOULD BE NELEMB(K)
      DIMENSION KONBOUN(MBD,N3,3)



C&&&&&&&&&&&&&&&&&
C     IN CASE OF NO EXISTENCE OF ZONES,
C     DEFAULT VALUES FOR ZONES CONNECTIVITY ARRAY KZON (THE SAME AS KONN)
      IF(NZONE.EQ.1) THEN
        DO I=1,N3
          DO II=1,N4
            KZON(1,I,II)=KONN(I,II)
          END DO
        END DO
        DO I=1,N1
          NZTYPE(1,I)=7
        END DO
      END IF








      NOD=3

C     INDEX FOR THE EXISTENCE OF A FREE SURFACE
C     NFRE=0: NO FREE SURFACE EXISTS
C     NFRE=1: FREE SURFACE EXISTS
      NFRE=0
      DO 1 I=1,NBOUN
        IF(NREGI(I).EQ.4) NFRE=1
  1   CONTINUE
      WRITE(1,*) RLA,RMU,RNU,RHO,C1,C2,TIM,NFRE
C     GEOMETRY
      WRITE(1,*) XCR
      WRITE(1,*) YCR
C     ELEMENT CONNECTIVITY (NUMBERS OF FIRST, MIDDLE AND LAST NODES OF 
C     ALL THE ELEMENTS)
      WRITE(1,*) KONN
C     NODE CONNECTIVITY (NUMBERS OF PREVIUS, CURRENT AND NEXT NODES OF 
C     ALL THE NODES)
      WRITE(1,*) NONN
C     MBCU: 0 TRACTION PRESCRIBED CONDITION, 1 DISPLACEMENT
      WRITE(1,*) MBCU
C     TYPE OF ELEMENT (LBCU:
C         0:COMMON CASE,           1:ON INCLUSION SURFACE,
C         2:ON FREE SURFACE,       3:ON SIMULATION SURFACE,
C         4:ON ENCLOSING BOUNDARY, 5:OUTER ZONE'S BOUNDARY
C         6:INNER ZONE'S BOUNDARY, 7:INNER ZONE'S FREE BOUNDARY)
C
      WRITE(1,*) LBCU
C     TYPE OF NODE (NDTYPE:
C         0:COMMON CASE,           1:ON INCLUSION SURFACE,
C         2:ON FREE SURFACE,       3:ON SIMULATION SURFACE,
C         4:ON ENCLOSING BOUNDARY, 5:OUTER ZONE'S BOUNDARY
C         6:INNER ZONE'S BOUNDARY, 7:INNER ZONE'S FREE BOUNDARY)
      WRITE(1,*) NDTYPE


C^^^^^^^^^^^^!!!!!!!!!!
      WRITE(1,*) OFREQ
      WRITE(1,*) NINT,CINT



C&&&&&&&&&&&&&&&&&&&&&&&&
C     DATA FOR ZONES (5 BOUNDARIES)
      WRITE(1,*) NZONE,RZLA,RZMU,RZNU,RZHO,CZ1,CZ2,FZVISC,NZMODE,IBOU
      WRITE(1,*) KZON
      WRITE(1,*) NZTYPE
      WRITE(1,*) NODZ,NELZ

C****************
C           CONNECTIVITY OF ZONE K, ELEMENT I, WITH NUMBERING IN THE
C           BOUNDARY ONLY (THE 2nd INDEX SHOULD BE NELEMB(K)
      WRITE(1,*) KONBOUN

C     CONTROL OF NUMERICAL INTEGRATION
      WRITE(1,*) NGAUS,NSNG,NCASE,NONSNG,DNONSNG1,DNONSNG2


C     WRITE DATA TO THE POSTDAT FILE, FOR LATER READING IN POSTPROCESSING
C
      WRITE(4,*)NTOT,NPLOT
      WRITE(4,190)FNAMEPRO,FNAMEPOS
  190 FORMAT(A14,A14)
C  190 FORMAT(A,A)
      WRITE(4,*)NDOMA,CA,CB,CP,
     &    NNODEB,NELEMB,NBOUN,NREGI,XCEN,YCEN,FAI,PSAI
      WRITE(4,*) FNAMEIN
      WRITE(4,*) NDTOT,NDPLOT,LETOT,LEPLOT
C      WRITE(4,*) NDTOT
C      WRITE(4,*) NDPLOT
C      WRITE(4,*) LETOT
C      WRITE(4,*) LEPLOT
C
C     WRITE IN FILE 4 THE UNIAXIAL COMPRESSIVE STRESS AND THE COSTANTS FOR
C     FAILURE CRITERIA (POSTPROCCESING ONLY) AND THE TYPES OF PLOT
      WRITE(4,*)SIGC,FM,FS,KEXPL
C     WRITE ON FILE THE CODES FOR THE BOUNDARIES SHAPES AND THE CODE
C     OF DISCONTINUITY, FOR USE IN POSTPROCESSING
      WRITE(4,*) NSHAP,NDIS,LCRN
C^^^^^^^^^^^^^^^^^^^^^
      WRITE(4,*) INES



C
C     PRESENT THE DATA IN FILE 6
C     WRITE FOR EVERY NODE
C         THE COORDINATES X,Y,
C         THE PRESCRIBE BOUNDARY CONDITION COND (0: TRACTION, 1: DISPLACEMENT)
C         THE TYPE OF THE NODE (0: COMMON CASE, 1: NODE ON INCLUSION SURFACE,
C                     2: NODE ON FREE SURFACE, 3: NODE ON SIMULATION SURFACE,
C                     4: NODE ON ENCLOSING BOUNDARY)
      WRITE(6,100)
      WRITE(6,110)
CC      WRITE(6,115)
      WRITE(6,120)
      WRITE(6,125)
      DO 20 I=1,NNODE
        WRITE(6,130)I,XCR(I),YCR(I),MBCU(I),NDTYPE(I)
  20  CONTINUE
  100 FORMAT(//T2,'MESH NODES')
  110 FORMAT(T2,  '==========')
C  120 FORMAT(/2X,'NODE',2X,'      X       ',2X,'      Y       ')
  120 FORMAT(T2,'NODE',T9,'    X(m)',T20,'   Y(m)',T31,'COND',
     &       T36,'TYPE')
  125 FORMAT(T2,39('-'))
C  130 FORMAT(/2X,I3,2X,E8.3,2X,E8.3)
  130 FORMAT(T2,I3,T9,F12.3,T20,F12.3,T31,I3,T38,I3)


C     WRITE THE ZONES CONNECTIVITY
      IF(NZONE.GT.1) THEN
        WRITE(6,140)
        WRITE(6,150)
        WRITE(6,160)
C        WRITE(6,170)
        DO 30 I=1,NELEM
          DO 32 J=1,NOD
            LN=KONN(I,J)
            LDIR(J)=LN
  32      CONTINUE
          WRITE(6,180)I,(LDIR(K),K=1,3),LBCU(I)
  30    CONTINUE
  140   FORMAT(//T2,'ZONES NODES')
  150   FORMAT(T2,  '===========')
  160   FORMAT(T2,'ZONE',T9,'     NODE ',T38,'TYPE')
  165   FORMAT(T2,'----',T9,'     ---- ',T38,'----')
C  170   FORMAT(T12,'FIRST',T20,'MIDDLE',T28,'LAST')
  175   FORMAT(T2,39('-'))
C  180   FORMAT(9X,3(2X,I5))
  180   FORMAT(T2,I3,T9,I3,T20,I3,T31,I3,T36,I3)
      ENDIF

      WRITE(6,94)
      WRITE(6,96)
      WRITE(6,98)
      WRITE(6,100)
      WRITE(6,102)
  94  FORMAT(//2X,'MATERIAL PROPERTIES')
  96  FORMAT(2X,   '===================')
  98  FORMAT(2X,' ZONE   LAME`S CONSTANTS       POISSON`S',
     &' RATIO   MASS DENSITY     SEISMIC VELOSITIES')
  100 FORMAT(2X,'        LAMDA         MU             NU',
     &'              RO             C1          C2')
  102 FORMAT(2X,'--------------------------------------------------',
     &'-------------------------------------')
      DO 68 II=1,NZONE
        WRITE(6,104) II,RZLA(II),RZMU(II),RZNU(II),RZHO(II),
     &                  CZ1(II),CZ2(II)
  104   FORMAT(2X,I3,1X,E12.6,1X,E12.6,3X,E12.6,5X,E12.6,1X,
     &             E12.6,1X,E12.6)





CC     WRITE THE PRESCRIBED BOUNDARY CONDITION AT THE NODES
CC            0: TRACTION PRESCRIBED CONDITION 
CC            0: DISPLACEMENT PRESCRIBED CONDITION 
C      WRITE(6,190)
C      WRITE(6,200)
C
C      WRITE(6,210)
C      WRITE(6,220)
C      WRITE(6,230)
C      WRITE(6,240) (MBCU(I),I=1,2*NNODE)
C  38  CONTINUE
C  190 FORMAT(//2X,' PRESCRIBED BOUNDARY CONDITIONS')
C  200 FORMAT(/2X,  ' ==============================')
C  210 FORMAT(/10X,' 0: TRACTION PRESCRIBED CONDITION')
C  220 FORMAT(/10X,' 1: DISPLACEMENT -//-     -//-')
C  230 FORMAT(/2X, 5(' NODE ',2X,' COND '))
C  240 FORMAT(5(2X,I5))
      RETURN
      END
