      CALL MOVETO(XPOS,YPOS,XYS)
      WRITE(BUFFER,"('(',F6.2,',',F6.2,')')") X0,Y0
      CALL OUTGTEXT('Wavefront Position : '//
     &               BUFFER(1:LEN_TRIM(BUFFER)))

c************
      ELSE
        CALL OUTTEXT('Error: cannot set font')
      END IF


  12  CONTINUE
C      CALL GSCALE
C
C$ENDIF


      RETURN
      END
