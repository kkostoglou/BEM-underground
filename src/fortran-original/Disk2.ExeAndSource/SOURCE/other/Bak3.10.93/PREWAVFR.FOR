$DEBUG
C---------------------------------------------------------------------------
      SUBROUTINE WAVEFIR(XCR,YCR,XD,YD,CA,CB,CP,N1,
     &              XCEN,YCEN,NNODEB,NBOUN,INES)

C^^^^^^^^^^^^^^^^^^^^
C           INES : INDEX 0: NUMBER OF ELEMENTS IN A SEGMENT WERE 0
C                        1: THERE WERE NOT 0 NUMBER OF ELEMENTS IN ANY SEGMENT


C     DETERMINE THE POSITION OF THE WAVE FRONT WHEN IT FIRST IMPINGES (ARRIVES)
C     AT THE SURFACE OF THE MESH
C     XCR,YCR : COORDINATES OF THE NODES OF THE MESH
C     CA,CB,CP: RETURNED VALUES OF THE CONSTANTS OF THE EQUATION OF
C               LINE OF WAVE FRONT
C               THE EQUATION OF THE WAVEFRONT, IS THE EQUATION OF A 
C               NORMAL TO A STRAIGHT LINE WITH ANGLE FAI WITH X AXIS
C               (AXIS OF INCIDENT WAVE)
C               CA=COS(FAI), CB=SIN(FAI)
C               CP: DISTANCE OF THE ORIGIN OF GLOBAL CENTER OF THE MESH
C                   XCEN,YCEN FROM THE WAVEFRONT LINE (ALWAYS POSSITIVE)
C               CA*XCR(I)+CB*YCR(I)-CP=0
C               ARRIVES FOR THE FIRST TIME
C     XCEN,YCEN: THE CENTER OF THE MESH (OF ALL THE BOUNDARIES)
C     XD, YD   : COORDINATES NODES OF THE MESH, IGNORING THE NODES OF 
C                AN ACTUAL FREE SURFACE BOUNDARY
C---------------------------------------------------------------------------
        IMPLICIT COMPLEX*16 (Z)
        IMPLICIT REAL*8 (A-H,O-Y)
C     ******COMMONBLOCKS********
C
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM4/NXELE,NYELE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
C     ****************************
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION NXELE(5),NYELE(5),PSAI(5)
      DIMENSION NREGI(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &          TYPELY(5),NDIS(5)
      DIMENSION XD(N1),YD(N1)
      DIMENSION NNODEB(NBOUN)
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5),XSID(5),YSID(5)
C
C     TOLERANCE 
      TOL=1.0E-11
      PI=3.14159265359D0
      KMIN=1
      CALL CLRARR(XD,N1)
      CALL CLRARR(YD,N1)



C
C     LOOP FOR ALL THE BOUNDARY SHAPES
C      NCOUNT=0
      NB0=0
C      NBN=0
      CEN1=0.0D0


C^^^^^^^^^^^^^^^^^^^^^^^
      NB0=1



      DO 61 L=1,NBOUN

C^^^^^^^^^^^^^^^^^^^^^^^^
C       IN CASE OF 0 ELEMENTS ON A FREE SURFACE BOUNDARY
        IF((NREGI(L).EQ.4).AND.(INES.EQ.0)) GO TO 61



CCCCCCCCCCCCCCCCCCCCCCCCCCCCC
CCCCCCCCCCCCCCCCCCCCCCCCCCCCC
C!!!!!!!!!!!!!!!!!!!!!!!!!!!!
C     ATTENTIONNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNNN
C       DON'T IGNORE THE NODES OF THE FREE SURFACE, BECAUSE THEY ARE 
C       NEEDED IN CALCULATING THE INCIDENT STRESSES ON THE FREE
C       SURFACE (WQAVE PARALLEL TO THE FREE SURFACE OR NOT)
C
CCCCCCCCCCCCCCCCCCCCCCCCCCCC
CCCCCCCCCCCCCCCCCCCCCCCCCCCC
CC       IGNORE THE NODES OF THE FREE SURFACE BOUNDARY
CC       AT THE SURFACE OF THE MESH
C       COUNTER FOR THE STARTING NUMBER OF NODE OF A BOUNDARY
CC       FOR FREE SURFACE BOUNDARY DON'T TAKE INTO ACCOUNT THE NODES 
CC       OF THE FREE SURFACE
        IF(L.EQ.1) THEN
          NB0=1
          GO TO 54
        ENDIF
C       NUMBER OF FIRST NODE IN THE BOUNDARY
        NB0=NB0+NNODEB(L-1)
C       NUMBER OF NODES OF THE BOUNDARY
  54    NB1=NNODEB(L)
C       NUMBER OF LAST NODE IN THE BOUNDARY
        NB2=NB2+NB1
CCCCCCCCCCCCCCCCCCCCCC
CCCCCCCCCCCCCCCCCCCCCC
C        IF(NREGI(L).EQ.4) GO TO 61
CCCCCCCCCCCCCCCCCCCCCC
CCCCCCCCCCCCCCCCCCCCCC
C
C       COUNTER FOR NODE NUMBERING
        NCN=NB0






C
C       COORDINATE SYSTEM FIRST, WITH ORIGIN  
C       THE LOCAL CENTER XCR0,YCR0 OF THE BOUNDARY
C       -------------------------------------
      DO 80 I=1,NB1
C        XD(I)=XD(I)-XCEN
C        YD(I)=YD(I)-YCEN
        XD(NCN)=XCR(NCN)-XCR0(L)
        YD(NCN)=YCR(NCN)-YCR0(L)
        NCN=NCN+1
  80  CONTINUE
      NCN=NB0
      PMIN=0.0D0
      DO 50 I=1,NB1
C       FIND THE NODE WHICH HAS POLAR ANGLE PTH CLOSER TO FAI P1(R1,TH1)
C       POLAR ANGLE OF NODE I
C       INITIAL VALUE OF PMIN
C        YCR1=YCR(I)
C        YCR1=YD(I)
C        XCR1=XD(I)
        YCR1=YD(NCN)
        XCR1=XD(NCN)
        IF(DABS(XCR1).LT.TOL) XCR1=TOL
        PTH=DATAN2(YCR1,XCR1)
C           ATTENTION   !!!!!!!!!!!!!!
        IF(PTH.LT.0.0D0) PTH=2.0D0*PI+PTH
C
C        PF=DABS(DABS(PTH)-FAI)
        PF=DABS(PTH-FAI)
        IF(I.EQ.1) PMIN=PF
        IF(PF.LT.PMIN)THEN
C          KMIN=I
          KMIN=NCN
          PMIN=PF
        ENDIF
        NCN=NCN+1
  50  CONTINUE
C     EQUATION OF THE LINE (E) PASSING THROUGH P(R1,FAI) AND PERPENDICULAR TO
C     LINE FROM THE ORIGIN OF COORDINATES AT ANGLE FAI
      CA=DCOS(FAI)
      CB=DSIN(FAI)
C      I=0
      NCN=NB0
  52  YCR1=YD(KMIN)
      XCR1=XD(KMIN)
      IF(DABS(XCR1).LT.TOL) XCR1=TOL
C     ATTENTIONNNNNNNNNNNNNNNNNNNNNNN
C      PTH=DATAN2(YCR1,XCR1)
      R0=DSQRT(XCR1**2+YCR1**2)
C     DISTANCE OF THE ORIGIN XCEN,YCEN FROM WAVEFRONT LINE WITH EQUATION
C        CA*XD(I)+CB*YD(I)-CP=0
C        CP=R0*COS(PTH-FAI)
C     ATTENTIONNNNNNNNNNNNNNNNNNNNNNN
C      CP=R0*DCOS(PTH-FAI)
      CP=R0
C     DISTANCE OF THE CENTER XCEN,YCEN FROM THE NEW WAVEFRONT
C      IF(CC.LE.0.0D0)SIGN=1.0D0
C      IF(CC.GT.0.0D0)SIGN=-1.0D0
C  55  DO 60 I=1,N1
C     EXAMINE ALL THE NODES THAT ARE BEHIND WAVEFRONT LINE
C     FIND THE POINTS OF INTERSECTION OF WAVEFRONT LINE WITH AXES
C      XI=-CC/CA
C      YI=-CC/CB
C  55   NCN=NCN+1
  55   CONTINUE
C       I=I+1
C        YCR1=YD(I)
C        XCR1=XD(I)
        YCR1=YD(NCN)
        XCR1=XD(NCN)
        IF(DABS(XCR1).LT.TOL) XCR1=TOL
        PTH=DATAN2(YCR1,XCR1)
C        IF(PTH.LT.0.0) PTH=2*PI+PTH
C       ONLY POINTS BETWEEN FAI-PI/2 AND FAI+PI/2
        F1=FAI-PI/2.0D0
        F2=FAI+PI/2.0D0
        IF((PTH.GT.F1).AND.(PTH.LT.F2))THEN
          IF(PTH.LT.0.0) PTH=2.0D0*PI+PTH
C         POINT ON THE WAVEFRONT LINE  WITH POLAR ANGLE PTH
C         ONLY POINTS BEHIND OR UPON WAVEFRONT LINE
C         DISTANCE OF NODE I FROM WAVEFRONT
C         POSITIVE IF NODE I AND THE ORIGIN XCEN,YCEN ARE ON OPOSITE SIDE
C         NEGATIVE, IF THEY ARE IN THE SAME SIDE
C          CD=XD(I)*DCOS(FAI)+YD(I)*DSIN(FAI)-CP
C          CD=XD(I)*CA+YD(I)*CB-CP
          CD=XD(NCN)*CA+YD(NCN)*CB-CP
          IF(CD.GT.0.0D0) THEN
C
C              KMIN=I
              KMIN=NCN
C              I=0
C              IF(I.EQ.N1) GO TO 60
C              IF(I.EQ.NBN) GO TO 60
C              IF(NCN.EQ.NBN) GO TO 60
              IF(NCN.EQ.NB2) GO TO 60
              GO TO 52
        ENDIF
      ENDIF
C      IF(I.EQ.N1) GO TO 60
C      IF(I.EQ.NBN) GO TO 60
C      IF(NCN.EQ.NBN) GO TO 60
      IF(NCN.EQ.NB2) GO TO 60
      NCN=NCN+1
      GO TO 55
   60 CONTINUE
      YCR1=YD(KMIN)
      XCR1=XD(KMIN)
      IF(DABS(XCR1).LT.TOL) XCR1=TOL
      PTH=DATAN2(YCR1,XCR1)
      IF(PTH.LT.0.0) PTH=2.0D0*PI+PTH
      R0=DSQRT(XCR1**2+YCR1**2)
C     DISTANCE OF THE LOCAL ORIGIN OF BOUNDARY XCR0,YCR0 FROM WAVEFRONT LINE
C        CP=R0*COS(PTH-FAI)
C      CP=R0*DCOS(PTH-FAI)
C     ATTENTIONNNNNNNNNNNNNNNNNNNN
       CP=R0
CC     BACK TO GLOBAL COORDINATE SYSTEM 
C      DO 90 I=1,N1
C        XD(I)=XD(I)+XCEN
C        YD(I)=YD(I)+YCEN
C  90  CONTINUE

C     DISTANCE OF THE GLOBAL ORIGIN XCEN,YCEN FROM  THE WAVEFRONT OF 
C     BOUNDARY L, IN LOCAL SYSTEM
C     CALCULATE FIRST THE COORDINATES OF THE GLOBAL CENTER TO THE 
C     LOCAL CENTER
C
      XCEN1=XCEN-XCR0(L)
      YCEN1=YCEN-YCR0(L)
C
      CEN=XCEN1*CA+YCEN1*CB-CP

C      IF(CEN.GT.0.0D0)THEN  
C     CEN IS NEGATIVE WHEN THE GLOBAL ORIGIN  (XCEN,YCEN) AND THE 
C     LOCAL ORIGIN XCR0,YCR0, ARE FROM THE SAME SIDE OF THE LINE.
C     ACCEPT THIS WAVEFRONT AS THE FINAL
      IF(CEN.LT.CEN1)THEN
C       BACK TO GLOBAL COORDINATE SYSTEM
C       DISTANCE OF THE CENTER OF THE MESH XCEN,YCEN  FROM THE WAVEFRONT
C
CCNODE I WITH  GLOBAL COORDINATES 
CC       XCR1+XCR0(L), YCR1+YCR0(L)
C       CA=COS(FAI),CB=SIN(FAI) THE SAME
C       -------------------------------------
        CEN1=CEN
        CA1=CA
        CB1=CB
C        XCEN1=XCEN1+XCR0(L)
C        YCEN1=YCEN1+YCR0(L)
C        CP1=XCEN1*CA+YCEN1*CB-CP
C        XCEN1=XCEN
C        YCEN1=YCEN
C        CP1=XCEN1*CA+YCEN1*CB-CP
        CP1=CEN
      ENDIF
C


C      NCN=NCN+1
  61  CONTINUE
C
C     FINAL WAVEFRONT:
      CA=CA1
      CB=CB1
C     CP: ALWAYS POSSITIVE
      CP=DABS(CP1)

      RETURN
      END 
