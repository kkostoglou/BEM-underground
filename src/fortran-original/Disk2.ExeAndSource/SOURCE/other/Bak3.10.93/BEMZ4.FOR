        END DO
        DO 20 I=1,NL
C        ZC(I)=DCMPLX(0.0D0,0.0D0)
        DO 10 J=1,NC
        ZC(I,J)=ZA(I,J)*ZB(J)
  10    CONTINUE
  20    CONTINUE
        RETURN
        END
