C------------------------------------------------
        SUBROUTINE ZMINV(A,N,L,M)
C
        IMPLICIT COMPLEX*16 (A-H)
        IMPLICIT REAL*8 (R)
        DIMENSION A(N*N),L(N),M(N)
C
        DO 5 I=1,N
          L(I)=0
          M(I)=0
  5     CONTINUE
        NLIN=6
        NK=-N
        DO 180 K=1,N
        NK=NK+N
        L(K)=K
        M(K)=K
        KK=NK+K
        BIGA=A(KK)
        DO 20 J=K,N
        IZ=N*(J-1)
        DO 20 I=K,N
        IJ=IZ+I
        CA=A(IJ)
        RA=CDABS(CA)
        RB=CDABS(BIGA)
        IF (RB-RA) 10,20,20
  10    BIGA=A(IJ)
        L(K)=I
        M(K)=J
  20    CONTINUE
C
C       INTERCHANGE ROWS
C
        J=L(K)
        IF (J-K) 50,50,30
  30    KI=K-N
        DO 40 I=1,N
        KI=KI+N
        HOLD=-A(KI)
        JI=KI-K+J
        A(KI)=A(JI)
  40    A(JI)=HOLD
C
C       INTERCHANGE COLUMNS
C
  50    I=M(K)
        IF (I-K) 80,80,60
  60    JP=N*(I-1)
        DO 70 J=1,N
        JK=NK+J
        JI=JP+J
        HOLD=-A(JK)
        A(JK)=A(JI)
  70    A(JI)=HOLD

  80    CONTINUE

C        WRITE (NLIN,91)K
C  91    FORMAT ('  K =',I3)
C        WRITE (NLIN,92)BIGA
C  92    FORMAT ('      BIGA=',E12.6,E12.6)

C  80    IF (CDABS(BIGA)-1.0D-15) 90,100,100
        IF (CDABS(BIGA)-1.0D-15) 90,100,100
  90    CONTINUE
        WRITE (NLIN,93)
  93   FORMAT(10X,'ERROR : ')
        WRITE (NLIN,95) K,BIGA
  95    FORMAT(20X,'DURING A MATRIX INVERSION OPERATION A ZERO',/
     &    20X,'DETERMINANT HAS BEEN DETECTED. THE RUN HAS BEEN',/
     &    20X,'TERMINATED. ROW OR COLUMN NO. WAS ',I4,/
     &    20X,'DETERMINANT VALUE WAS ',E12.6,E12.6)
        STOP
  100   DO 120 I=1,N
        IF (I-K) 110,120,110
  110   IK=NK+I
        A(IK)=A(IK)/(-BIGA)
  120   CONTINUE
C
C       REDUCE MATRIX
C
        DO 150 I=1,N
        IK=NK+I
        HOLD=A(IK)
        IJ=I-N
        DO 150 J=1,N
        IJ=IJ+N
        IF (I-K) 130,150,130
  130   IF (J-K) 140,150,140
  140   KJ=IJ-I+K
        A(IJ)=HOLD*A(KJ)+A(IJ)
  150   CONTINUE
C
C       DEVIDE BY PIVOT
C
        KJ=K-N
        DO 170 J=1,N
        KJ=KJ+N
        IF (J-K) 160,170,160
  160   A(KJ)=A(KJ)/BIGA
  170   CONTINUE
C
C       PRODUCT OF PIVOTS
C       REPLACE PIVOT BY RECIPROCAL
C
        A(KK)=1.0D0/BIGA
  180   CONTINUE
C
C       FINAL ROW AND COLUMN INTERCHANGE
C
        K=N
  190   K=(K-1)
        IF (K) 260,260,200
  200   I=L(K)
        IF (I-K) 230,230,210
  210   JQ=N*(K-1)
        JR=N*(I-1)
        DO 220 J=1,N
        JK=JQ+J
        HOLD=A(JK)
        JI=JR+J
        A(JK)=-A(JI)
  220   A(JI)=HOLD
  230   J=M(K)
        IF (J-K) 190,190,240
  240   KI=K-N
        DO 250 I=1,N
        KI=KI+N
        HOLD=A(KI)
        JI=KI-K+J
        A(KI)=-A(JI)
  250   A(JI)=HOLD
        GO TO 190
  260   RETURN
        END
C------------------------------------------------
        SUBROUTINE ZVPROD(ZA,ZB,N,ZC)
C
C       PRODUCT OF COMPLEX SQUARE MATRIX TIMES COMPLEX VECTOR
C
        IMPLICIT COMPLEX*16 (Z)
        DIMENSION ZA(N,N),ZB(N),ZC(N)
C
        DO 20 I=1,N
        ZC(I)=DCMPLX(0.0D0,0.0D0)
        DO 10 J=1,N
        ZC(I)=ZC(I)+ZA(I,J)*ZB(J)
  10    CONTINUE
  20    CONTINUE
        RETURN
        END
C------------------------------------------------
        SUBROUTINE ZAPROD(ZA,ZB,NL,NC,ZC)
C
C       PRODUCT OF COMPLEX NON-SQUARE MATRIX ZA[NL,NC]
C       TIMES COMPLEX VECTOR ZB[NC]
C
        IMPLICIT COMPLEX*16 (Z)
        DIMENSION ZA(NL,NC),ZB(NC),ZC(NL)
C
        DO I=1,NL
          ZC(I)=DCMPLX(0.0D0,0.0D0)
        END DO
        DO 20 I=1,NL
C        ZC(I)=DCMPLX(0.0D0,0.0D0)
        DO 10 J=1,NC
        ZC(I)=ZC(I)+ZA(I,J)*ZB(J)
  10    CONTINUE
  20    CONTINUE
        RETURN
        END
C
C------------------------------------------------
        SUBROUTINE ZSPROD(ZA,ZB,NL,NC,ZC)
C
C       PRODUCT OF COMPLEX NON-SQUARE MATRIX ZA[NL,NC]
C       TIMES COMPLEX VECTOR ZB[NC]
C
        IMPLICIT COMPLEX*16 (Z)
        DIMENSION ZA(NL,NC),ZB(NC),ZC(NL,NC)
C
        DO I=1,NL
        DO J=1,NC
          ZC(I,J)=DCMPLX(0.0D0,0.0D0)
