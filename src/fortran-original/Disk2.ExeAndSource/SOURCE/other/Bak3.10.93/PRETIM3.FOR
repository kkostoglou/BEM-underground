C      RAT2=-PRAT/RAT
C      ENDIF 
C       CALCULATE THE INCIDENT EXPLOSIVE STRESSES AT POINT B IN THE
C       RAY DIRECTION
C       RSTE,RNSTE=0,RNORME=0
C        CALL EXPLOS(XBD,YBD,SXXE,SYYE,SXYE,TSXXE,TSYYE,TSXYE,
C     &          RSTE,RNSTE,RNORME,K)
C       STRESSES WITH OUT DECAYING
C          ^^^^^^^^^^^^^^^^^^^^^^^^^^^^
      CALL TEXPLOSQ(XBD,YBD,SRSTE,SRNSTE,SRNORME,K,0,T1,KPS)
C          ^^^^^^^^^^^^^^^^^^^^^^^^^^^^
      IF(IEXIT.EQ.1) GO TO 99
      TSXX1=SRSTE
      TSYY1=SRNSTE
C      BTSXY1=RNORME
      TSXY1=0.0D0
C     TRANSFORMATION OF THE INCIDENT P STRESSES FROM ANGLE 
C     OF INCIDENCE FAI1 TO THE GLOBAL COORDINATE SYSTEM FIRST
C     P-WAVE (NORMAL STRESSES ONLY WITHOUT SHEAR

      CALL STRGLOB(TSXX1,TSYY1,TSXY1,FN1,FN2,
     &       SXXP,SYYP,SXYP)
