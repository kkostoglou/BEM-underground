      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C      DIMENSION XY(3,2),RN(2)
C
C
C     TOLERANCE 
      TOL=1.0E-11
CC     VISCOLASTISCITY
C      CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
      RK=C1/C2
C     PEAK PRESSURE
C      R=EXPLR
      XE=EXPLX
      YE=EXPLY
      R=DSQRT((XE-XI)**2+(YE-YI)**2)
C     CASE THAT THE DISTANCE IS 0, ERROR, PRINT A MESSAGE
      IF(R.LT.TOL) THEN
C        WRITE(6,566) EXPLX,EXPLY,NCN,XI,YI
        WRITE(6,566) EXPLX,EXPLY,XI,YI
        IEXIT=1
      ENDIF

      W=EXPLW
      EN=EXPLN
      EN1=EXPLN1
      B=EXPLB
      F=EXPLF
C     FOR P WAVE, MULTIPLY BY THE RATE EXPLP
      IF(KPS.EQ.1) C12=C1*EXPLP
C     FOR SV WAVE, MULTIPLY BY THE RATE EXPLSV
      IF(KPS.EQ.2) C12=C2*EXPLSV
C     CASE OF QUBIC ROOT FORMULA
      IF(NFORM.EQ.1) THEN
        P0=B*F*RHO*C12*(R/W**(1.0D0/3.0D0))**(-EN)
      ENDIF
C     CASE OF SQUARE ROOT FORMULA
      IF(NFORM.EQ.2) THEN
        P0=B*F*RHO*C12*(R/W**(1.0D0/2.0D0))**(-EN)
      ENDIF
C     CASE OF OTHER TYPE FORMULA
      IF(NFORM.EQ.3) THEN
        P0=B*F*W**EN/R**EN1
      ENDIF
C
      P=P0
C     THE DECAY OF THE WAVE 
CC       A. IN THE ANALALYTICAL METHOD IS INSIDE THE LAPLACE TRANSFORMATION
CC           (THE TRASFORMATION OF A DECAYING FUNCTION WAS TAKEN, IN 
CC           SUBROUTINE TDECEXPL FOR THE INCIDENT WAVE, AND IN 
CC           SUBROUTINE REFEXP FOR THE REFLECTED WAVE, VALUE FOR P=1)
CC           SO THE LAPLACE TRANSFORM IS P0*F(S)
CC       B. IN THE NUMERICAL METHOD THE VALUES OF THE FUNCTION IN TIME DOMAIN
CC           ARE NEEDED.
C     DECAY OF WAVE IN TIME
C     NDECAY=0: NO DECAY, NDECAY=1: DECAY
C      IF((KDIAK.EQ.1).AND.(NDECAY.EQ.1)) THEN
      IF(NDECAY.EQ.1) THEN
C       ARRIVAL TIME


        TA=R/C12
        DT=TIM/DFLOAT(NSTEP)
        TIME1=DT*DFLOAT(K-1)

        TIME2=TIME1-TA
        IF(TIME2.LT.0.0D0) THEN
          TIME2=0.0D0
          P=0.0D0
          GO TO 41
        ENDIF



C        P=P0*EXP(-TIME1/TA)
        P=P0*EXP(-TIME2/TA)
  41    CONTINUE
      ENDIF
C     THE INCOMING STRESSES OF P-WAVE ARE ALWAYS COMPRESSIONAL(-)
      RSTE=-P
      RNSTE=0.0D0
      RNORME=0.0D0
      TRSTE=RSTE
C     FOR SV EXPLOSIVE WAVE
      IF(KPS.EQ.2) THEN
        RSTE=DCMPLX(0.0D0,0.0D0)
        RNORME=-P
      ENDIF
CC     FIND THE STRESS S*N/(1-N) IN THE NORMAL DIRECTION
C      TRNSTE=TRSTE*RNU/(1.0D0-RNU)
C     SHEAR STRESS IN THE INCOMING DIRECTION
      TRNORME=0.0D0
  566  FORMAT(/,10X,'  ERROR - DISTANCE BETWEEN EXPLOSION POINT '
     &        /,10X,'(',F12.3,F12.3') AND NODE ',I3,' (',F12.3,F12.3,')'
     &        /,10X,' FOUND 0, NOT PERMITED. CHECK THE COORDINATES '
     &        /,10X,' OF EXPLOSION POINT IN MODULUS LOADS')
      RETURN
      END
