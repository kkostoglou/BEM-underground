      SUBROUTINE TREFEXP(XCR,YCR,SXX,SYY,SXY,WVEL,
     &            N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &            JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &            SRXX,SRYY,SRXY,TH0,TH3,TH4,K,KEXPL,NDTYPE)

C
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS IN THE TIME DOMAIN, 
C   ON THE SURFACE OF THE GEOMETRICAL SHAPE (ANY SHAPE) 
C   SXX,SYY,SXY: INCIDENT STRESSES IN GLOBAL COORDINATE SYSTEM (WITHOUT
C                THE ADDITIONAL VERTIACAL STRESSES) 
C     ZLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     ZLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLIDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   ZRXX,ZRYY,ZRXY: RETURNED VALUES OF REFLECTED STRESSES AT EVERY NODE
C                   WITH DELAYS OF ARRIVING WAVE, IN THE GLOBAL COORDINATE 
C                   SYSTEM
C   KEXPL=1: THE LOADS ARE FROM EXPLOSION POINT
C -----------------------------------------------------------------------
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
      COMMON/BLKEX/IEXIT
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION RN(2)
      DIMENSION NREGI(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &     TYPELY(5),NDIS(5)
      DIMENSION JKODE(NBNT)
      DIMENSION NSHAP(NBOUN)
C      DIMENSION NNODEB(NBOUN)
C      DIMENSION NELEMB(NBOUN)
      DIMENSION NSEGM(NBOUN)
      DIMENSION SEG(NBNT*7)
      DIMENSION SRXX(N1),SRYY(N1),SRXY(N1)

      DIMENSION NDTYPE(N1)



C      DIMENSION TH0(N1),TH3(N1),TH4(N1)
C      ALP(N1),ALSV(N1),KANGL(N1)
C      DIMENSION FAI1(N1),FAI2(NCN)
C      DIMENSION BTHEP(N1),BTHANP(N1),DTHEP(N1),DTHANSV(N1)
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
C
      SRXXP=0.0D0
      SRXXSV=0.0D0
      SRYYP=0.0D0
      SRYYSV=0.0D0
      SRXYP=0.0D0
      SRXYPV=0.0D0
C
C
CC     FAI: ANGLE OF AXIS OF WAVEFRONT WITH X-AXIS (0<=FAI<=PI)
C     WAI: ANGLE OF LINE OF FREE SURFACE WITH X-AXIS (0<=WAI<=PI)
C
      RK=DSQRT(2.0D0*(1.0D0-RNU)/(1.0D0-2.0D0*RNU))
C     OR RK=C1/C2
      IF(DABS(RK).LT.TOL) RK=TOL
C     CALCULATE THE EQUATION OF THE LINE OF THE FREE SURFACE
C             CE*X+CF*Y-CQ=0
C     AND THE DIRECTION COSINES RN OF THE UNIT NORMAL VECTOR
C     COUNTER TO FIND THE COORDINATES OF THE NODES IN ARRAY SEG (ONLY
C     COMBOUND SHAPES)
      JL=0
      IBI=0
C     LOOP FOR ALL THE BOUNDARIES
      DO 15 IB=1,NBOUN 
C       FOR COMBOUND BOUNDARY
        IF(NSHAP(IB).LT.0) THEN
C         ATTENTION   
C         ********** RESTRICTION OF THE PROGRAM *************
C         THE PROGRAM ACCEPTS ONLY ONE LINE FREE SURFACE(SO NS=1)
C         NS=NSEGM(IB)
C          DO 29 J=1,NS
          J=1
          JL=JL+7*(J-1)
          IBI=IBI+1
          JKODE1=JKODE(IBI)
          NREGI1=NREGI(IB)
C         FREE SURFACE BOUNDARY
          IF(NREGI1.EQ.4) THEN
C             STRAIGHT LINE COMBOUND BOUNDARY
              NRF=0
C             STRAIGHT LINE REFLECTION FREE SURFACES
              IF(NSHAP(IB).EQ.4) NRF=1
C
C           CALCULATE THE EQUATION OF THE LINE OF THE FREE SURFACE
C                   CE*X+CF*Y-CQ=0
C           AND THE DIRECTION COSINES RN OF THE UNIT NORMAL VECTOR
            CALL SURFLINE(JKODE1,SEG,JL,RN,THN1,CE,CF,CQ,NBNT,
     &                       IB,NRF)
            RN1=RN(1)
            RN2=RN(2)
C           EXAMINE THE REFLECTION CONDITIONS, AND CALCULATE THE
C           DISTANCE CHA (ABSOLUTE VALUE) OF EXPLOSION POINT A FROM THE 
C           LINE OF FREE SURFACE
            CALL REFCONEX(CE,CF,CQ,KREFL,CHA)
            IF(IEXIT.EQ.1) GO TO 99        
C           CASE NOT REFLECTION CONDITIONS
            IF(KREFL.EQ.0) GO TO 99
          ENDIF
C          CONTINUE
        ENDIF
  15  CONTINUE



C     CALCULATE THE REFLECTING STRESSES
      JL=0
      IBI=0
C     COUNTER FOR NODE NUMBERING
      NCN=NB0

C     CASE NOT REFLECTION CONDITIONS
      IF(KREFL.EQ.0) GO TO 99
C     CASE THAT THE INCIDENT WAVE IS PARALLEL TO THE FREE SURFACE,
C     IT CANOT BE REFLECTED.
C     BUT EVEN IF THE FREE SURFACE IS TRACTION FREE, THERE IS
C     TANGENTIAL INCIDENT STRESSES  EQUAL TO THE INCIDENT(CALCULATED
C     IN SUBROUTINE WINCID)
C
      IF(KREFL.EQ.2) GO TO 99






C     COUNTER FOR NODE NUMBERING
      NCN=NB0
C     LOOP FOR ALL THE NODES OF THE BOUNDARY
      DO 50 I=1,NB1


C^^^^^^^^^^^^!!!!!!!!!!!!!!!!
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 89





C        INRF1=0
C        INRF2=0
        XCR1=XCR(NCN)
        YCR1=YCR(NCN)


CCCCC       ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
        CALL TPATEXP(XCR1,YCR1,CE,CF,CQ,CHA,TH00,TH33,TH44,THN1,RK,
     &    BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,INRF1,INRF2,
     &    ALP,ALSV,FAI1,FAI2,XBB,YBB,XDD,YDD,KANGL,T1)
CCCCC       ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
C
C       FIND THE REFLECTED STRESSES FIELD FOR POINT B
        THEP=BTHEP
        THANP=BTHANP
        THANSV=BTHANSV
        XBD=XBB
        YBD=YBB
        FN1=DCOS(FAI1)
        FN2=DSIN(FAI1)
CCCCC       ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
        KPS=1
        CALL TREFLDEX(THEP,THANP,THANSV,RK,XBD,YBD,K,
     &   FN1,FN2,RN1,RN2,RAT1,RAT2,SRXXP,SRYYP,SRXYP,
     &   SRXXCP,SRYYCP,SRXYCP,T1,KPS)
CCCCC       ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
        IF(IEXIT.EQ.1) GO TO 99
        BRAT1=RAT1
        BRAT2=RAT2
        BSRXXP=SRXXP
        BSRYYP=SRYYP
        BSRXYP=SRXYP
        BSRXXCP=SRXXCP
        BSRYYCP=SRYYCP
        BSRXYCP=SRXYCP
C
C       FIND THE REFLECTED STRESSES FIELD FOR POINT D
        THEP=DTHEP
        THANP=DTHANP
        THANSV=DTHANSV
        XBD=XDD
        YBD=YDD
        FN1=DCOS(FAI2)
        FN2=DSIN(FAI2)
CCCCC       ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
        KPS=1
        CALL TREFLDEX(THEP,THANP,THANSV,RK,XBD,YBD,K,
     &   FN1,FN2,RN1,RN2,RAT1,RAT2,SRXXP,SRYYP,SRXYP,
     &   SRXXCP,SRYYCP,SRXYCP,T1,KPS)
CCCCC       ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
        IF(IEXIT.EQ.1) GO TO 99
        DRAT1=RAT1
        DRAT2=RAT2
        DSRXXP=SRXXP
        DSRYYP=SRYYP
        DSRXYP=SRXYP
        DSRXXCP=SRXXCP
        DSRYYCP=SRYYCP
        DSRXYCP=SRXYCP

CCC       FIND THE DISTANCE OF PATERN OF THE RAYS OF THE REFLECTED WAVES
CCC           ABE AND CDE
CC        CALL PATEXP(XCR1,YCR1,CE,CF,CQ,TH0,TH2,KANGL,THN1,
CC     &       XCEN,YCEN,CA,CB,CP,INRF1,INRF2,ALP,ALSV)
CC       DELAY FOR ARRIVING AT NODE NCN OF THE REFLECTED WAVE
CC       P-REFLECTED WAVE
CC        ZDELAY1=CDEXP(-ALP(I)*ZK)
C        SDELAY1=CDEXP(-ALP*ZK)
CC       SV-REFLECTED WAVE
CC        ZDELAY2=CDEXP(-ALSV(I)*ZK)
C        ZDELAY2=CDEXP(-ZALSV*ZK)

C       DELAY FOR ARRIVING AT NODE NCN OF THE REFLECTED WAVE
C       P-REFLECTED WAVE
C        T2=ALP/C1
        T2=ALP
        SDELAY1=0.0D0
	IF (T1.GE.T2) SDELAY1=1.0D0

C^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
	IF(DABS(T1-T2).LT. TOL) SDELAY1=1.0D0


C       SV-REFLECTED WAVE
C        T3=ALSV/C2
        T3=ALSV
        SDELAY2=0.0D0
	IF (T1.GE.T3) SDELAY2=1.0D0

C^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
	IF(DABS(T1-T3).LT. TOL) SDELAY2=1.0D0


C  43    CONTINUE
C
C       FIND THE REFLECTED STRESSES FIELD
C       REFLECTED STRESSES AT EVERY NODE
C       IN LOCAL COORDINATE AXIS, WITH X AXIS OUTWORD RADIAL TO FREE 
C       SURFACE (AS UNIT VECTORS N:RADIAL, Q:TANGENT) 
C       AND ORIGIN ON THE FREE SURFACE
C       TOTAL SXX FROM P AND SV REFLECTED STRESSES, WITH DELAY
C       FOR BOUNDARY OTHER THAN THE FREE SURFACE, TAKE THE INCREASED 
C       FROM THE CONFINEMENT STRESSES
        IF(NREGI(NCOUNT).NE.4) THEN
C         POINT B
          BSRXXP=BSRXXCP
          BSRYYP=BSRYYCP
          BSRXYP=BSRXYCP
C         POINT D
          DSRXXP=DSRXXCP
          DSRYYP=DSRYYCP
          DSRXYP=SRXYCP
        ENDIF



C
C       REFLECTED STRESSES 
C           TRIIP =SRIIP*A1/A0 =SRIIP*RAT1
C           TRIISV=SRIISV*A2/A0=SRIISV*RAT2
C       POINT B
        BTRXXP=BSRXXP*BRAT1
        BTRXXSV=BSRXXSV*BRAT2
        BTRYYP=BSRYYP*BRAT1
        BTRYYSV=BSRYYSV*BRAT2
        BTRXYP=BSRXYP*BRAT1
        BTRXYSV=BSRXYSV*BRAT2
C       POINT D
        DTRXXP=DSRXXP*DRAT1
        DTRXXSV=DSRXXSV*DRAT2
        DTRYYP=DSRYYP*DRAT1
        DTRYYSV=DSRYYSV*DRAT2
        DTRXYP=DSRXYP*DRAT1
        DTRXYSV=DSRXYSV*DRAT2
C       CASE B OR D BEHIND THE WAVEFRONT, THE CONTRIBUTION IN THE ACTUAL
C       STRESSES IS 0
        IF(INRF1.EQ.1) THEN
C        IF(ALP(I).GT.1.0D0) THEN
C        IF(DREAL(ALP).GT.1.0D0) THEN
C         POINT B
          BTRXXP=0.0D0
          BTRYYP=0.0D0
          BTRXYP=0.0D0
C         POINT D
          DTRXXP=0.0D0
          DTRYYP=0.0D0
          DTRXYP=0.0D0
         ENDIF
        IF(INRF2.EQ.1) THEN
C        IF(ALSV(I).EQ.1) THEN
C        IF(DREAL(ZALSV).EQ.1.0D0) THEN
C         POINT B
          BTRXXSV=0.0D0
          BTRYYSV=0.0D0
          BTRXYSV=0.0D0
C         POINT D
          DTRXXSV=0.0D0
          DTRYYSV=0.0D0
          DTRXYSV=0.0D0
         ENDIF
C       TOTAL REFLECTED STRESSES OF P AND SV REFLECTED WAVE, WITH DELAYS
C       AT NODE E
        SRXX1=BTRXXP*SDELAY1+DTRXXSV*SDELAY2
        SRYY1=BTRYYP*SDELAY1+DTRYYSV*SDELAY2
        SRXY1=BTRXYP*SDELAY1+DTRXYSV*SDELAY2
C
C       TRANSFORMATION OF THESE STRESSES BACK TO THE GLOBAL COORDINATE SYSTEM
        CALL STRGLOB(SRXX1,SRYY1,SRXY1,RN1,RN2,
     &                     SRXX11,SRYY11,SRXY11)
C       SUPERIMPOSE P AND SV TRACTIONS
        SRXX(NCN)=SRXX(NCN)+SRXX11
        SRYY(NCN)=SRYY(NCN)+SRYY11
        SRXY(NCN)=SRXY(NCN)+SRXY11


  89    CONTINUE



        NCN=NCN+1
  50  CONTINUE

C  46  CONTINUE

  99  CONTINUE
      RETURN
      END
C ----------------------------------------------------------------------
      SUBROUTINE TPATEXP(XCR1,YCR1,CE,CF,CQ,CHA,TH0,TH3,TH4,THN1,RK,
     &    BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,INRF1,INRF2,
     &    ALP,ALSV,FAI1,FAI2,XBB,YBB,XDD,YDD,KANGL,T1)

C             XCEN,YCEN,CA,CB,CP,
C     &       BTHEP,BTHANP,DTHEP,DTHANSV)
C
C     CALCULATES THE DISTANCE OF PATERN OF THE RAYS OF THE REFLECTED WAVE 
C           ABE AND CDE
C     XCR1,YCR1: COORDINATES OF THE NODE NCN IN THE GLOBAL SYSTEM
C     EQUATION OF THE LINE OF THE FREE SURFACE
C                 CE*X+CF*Y-CQ=0
C     CHA      : DISTANCE CHA (ABSOLUTE VALUE) OF EXPLOSION POINT A FROM THE 
C                LINE OF FREE SURFACE
C     TH1=TH0  : ANGLE OF INCIDENT P-WAVE AT POINT B
C     TH2=TH0  : ANGLE OF REFLECTED SV-WAVE AT POINT B
C     TH3      : ANGLE OF INCIDENT P-WAVE AT POINT D
C     TH4      : ANGLE OF REFLECTED SV-WAVE AT POINT D
C
C     KANGL    : INDEX FOR CALCULATING THE ANGLES OF INCIDENT AND REFLECTED
C                RETURN VALUE
C                  1: TH0=TH0,     TH2=TH2
C                  2: TH0=2PI-TH0, TH2=2PI-TH2
C     THN1     : ANGLE OF X GLOBAL AXIS WITH THE UNIT NORMAL VECTOR
C     RK       = C1/C2
C     XCEN,YCEN: COORDINATES OF THE CENTER OF THE MESH (OF ALL THE BOUNDARIES)
C     CA,CB,CP : VALUES OF THE CONSTANTS OF THE EQUATION OF LINE OF WAVE FRONT
C                    CA*XCR(I)+CB*YCR(I)-CP=0
C
C     ALP      : TOTAL DELAY OF PATERN P-WAVE RAY, RETURN VALUE
C                    ABE=PWAV AB + PWAV  BE
C     ALSV     : TOTAL DELAY OF PATERN P,SV-WAVE RAY , RETURN VALUE
C                    CDE=PWAV CD + SVWAV DE 
C     FAI1,FAI2: ANGLE OF ATTACK OF P-P, P-SV WAVE RESPECTIVELLY.
C                IT IS THE ANGLE OF X GLOBAL AXIS WITH THE TAIL OF THE WAVE 
C     XBB,YBB,XDD,YDD: COORDINATES OF B AND D POINTS IN GLOBAL COORD SYSTEM,
C                      RETURN VALUE
CC     INRF1,INRF2: INDEX 
C     WHEN THE POINTS B OR D ARE BEHIND THE WAVEFRONT
C             ALP=2.0   ALSV=2.0
C     (THIS ESPECIALLY HAPPENS IN CASES OF SV WAVES,
C     WITH ANGLE OF INCIDENCE NEAR THE CRITICAL ANGLE). IN THIS CASE THE
C     ACTUAL REFLECTED STRESS IS 0.
C
C     DISTANCE OF NODE E FROM THE LINE OF FREE SURFACE BEL: REFLECTED P-WAVE
C                                                      DEL: REFLECTED SV-WAVE
C     IN LOCAL COORDINATE SYSTEM WITH ORIGIN AT THE ACTUAL NODE, AND 
C     AXES X',Y' PARALLEL TO N,Q  (N: UNIT VECTOR NORMAL TO FREE SURFACE
C                                 (Q: UNIT VECTOR TANGENT TO FREE SURFACE)
C
CC     CASE NDIAK=1, CALCULATE THE ANGLES TH1,TH2,TH3,TH4
CC     CASE NDIAK=2, THE ANGLES TH1,TH2,TH3,TH4 ARE KNOWN
C
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
C
C     DISTANCE OF NODE E FROM THE LINE OF FREE SURFACE
C     POSITIVE IF NODE I AND THE ORIGIN XCR0,YCR0 ARE IN THE OPOSITE SIDE,
C     NEGATIVE, IF THEY ARE IN THE SAME SIDE
C     ALWAYS IT IS NEGATIVE
C      CH=XCR(I)*DCOS(WAI)+YCR(I)*DSIN(WAI)-CQ
C      CH=XCR1*CE+YCR1*CF-CQ
C
      CH=XCR1*CE+YCR1*CF-CQ
C     TAKE ABSOLUTE VALUE, FREE SURFACE ALWAYS ABOVE NODES
      CH=DABS(CH)
C
C     ATTENTION      0 DEGREES !!!!!!!!!!!!!!!!!!!!!!!
C     NOT PERMITED FROM THIS PROGRAM
C
C     CALCULATION OF ANGLES TH1=TH2=TH0, TH3 AND TH4
      CALL REFANGEX(XCR1,YCR1,RK,CH,CHA,THT0,THT3,THT4,
     &  BTHEP,BTHANP,BTHANSV,DTHEP,DTHANP,DTHANSV,THN1,KANGL)
C
        BEL=CH/DCOS(THT0)
C        DEL=CH/DCOS(THT2)
        DEL=CH/DCOS(THT4)
C       COORDINATES IN LOCAL SYSTEM
        YBB1=BEL*DSIN(THT0)
        XBB1=CH
C        YDD1=DEL*DSIN(THT2)
        YDD1=DEL*DSIN(THT4)
        XDD1=CH
C       TRANSFORMATION OF COORDINATES FROM LOCAL SYSTEM WITH ORIGIN 
C       AT THE ACTUAL NODE AND AXES PARALLEL TO N,Q, 
C       TO A SYSTEM WITH ORIGIN AGAIN AT THE NODE AND
C       AXES PARALLEL TO AXES OF GLOBAL SYSTEM
C       POINT B
C        XBB=XBB1*DCOS(WAI)-YBB1*DSIN(WAI)+XCEN
C        YBB=XBB1*DSIN(WAI)+YBB1*DCOS(WAI)+YCEN
C
        WAI=THN1
        WN1=DCOS(WAI)
        WN2=DSIN(WAI)
        XBB=XBB1*WN1-YBB1*WN2
        YBB=XBB1*WN2+YBB1*WN1
C       POINT D
C        XDD=XDD1*DCOS(WAI)-YDD1*DSIN(WAI)+XCEN
C        YDD=XDD1*DSIN(WAI)+YDD1*DCOS(WAI)+YCEN
        XDD=XDD1*WN1-YDD1*WN2
        YDD=XDD1*WN2+YDD1*WN1
C
     
C       COORDINATES IN THE GLOBAL SYSTEM
        XBB=XCR1+XBB
        YBB=YCR1+YBB
        XDD=XCR1+XDD
        YDD=YCR1+YDD
C
C       SAVE THESE DISTANCES FOR DRAWING LATER IN SUBROUTINE RAYEXPL
        WRITE(11,*) XBB,YBB,XDD,YDD
C
C       THE DISTANCE OF THE NODE FROM THE EPLOSIVE POINT A, IS TAKEN ALWAYS
C       POSSITIVE. 
C       ************** USER'S RESPONSIBILITY ***************
C       THIS MEANS THAT THE EXPLOSIVE POINT A, IS ALWAYS OUT OF THE
C       MESH, AND THIS IS RESPONSIBILITY OF THE USER.
C       IF WE WANT THE WAVE AT T=0 INCIDE THE MESH, THEN THE DELAYS BEHIND
C       THE MESH MUST BE =0
C       DISTANCE OF POINTS B,D (ON THE LINE OF FREE SURFACE) FROM 
C       THE EXPLOSION POINT A.
CC        ABL=XBB*CA+YBB*CB-CP
CC        CDL=XDD*CA+YDD*CB-CP
CC
CC       DISTANCE OF POINTS B,D (ON THE LINE OF FREE SURFACE) FROM 
CC       THE WAVEFRONT LINE CA*X+CB*Y+(-CP)=0 (POSITION AT T=0)
CC       D=+-[CA*X1+CB*Y1+(-CP)]
CC       THE SIGN +OR- IS THAT OF CB. 
CC       THE DISTANCE IS POSSITIVE, IF THE NODE IS OVER THE LINE (OVER
CC       IN ACCORDANCE WITH POSSITIVE Y), AND NEGATIVE IF IT IS 
CC       UNDER THE LINE
CC       CP IN COORDINATE SYSTEM, WITH ORIGIN  
CC       THE CENTER OF THE MESH XCEN,YCEN
CC        XD(I)=XD(I)-XCEN
CC        YD(I)=YD(I)-YCEN
C        XBBG=XBB-XCEN
C        YBBG=YBB-YCEN
C        XDDG=XDD-XCEN
C        YDDG=YDD-YCEN
CC
CC
C        ABL=XBBG*CA+YBBG*CB-CP
C        CDL=XDDG*CA+YDDG*CB-CP
C
        ABL=DSQRT((EXPLX-XBB)**2+(EXPLY-YBB)**2)
        ADL=DSQRT((EXPLX-XDD)**2+(EXPLY-YDD)**2)

CC       IF ABL OR CDL IS POSSITIVE, IT MEANS THAT THE POINT B OR D IS
CC       BEHIND THE WAVEFRONT (THIS IS ESPECIALLY HAPPEN IN CASE OF SV WAVES,
CC       WITH ANGLE OF INCIDENCE NEAR THE CRITICAL ANGLE). IN THIS CASE THE 
CC       ACTUAL REFLECTED STRESS IS 0.
C        IF(ABL.GT.0.0D0) INRF1=1
C        IF(CDL.GT.0.0D0) INRF2=1
C       DISTANCES ALWAYS POSSITIVE
        ABL=DABS(ABL)
        ADL=DABS(ADL)
C
        BEL=DABS(BEL)
        DEL=DABS(DEL)
CC
CC       VISCOELASTIC BEHAVIOR
C        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
C
C       TOTAL DISTANCE OF THE PATERN OF RAYS
        ALP=(ABL+BEL)/C1
        ALSV=ADL/C1+DEL/C2
C       IF ABL OR ADL IS POSSITIVE, IT MEANS THAT THE POINT B OR D IS
C       BEHIND THE WAVEFRONT, GIVE ALP,ALS THE VALUE OF 2.0D0
        IF(INRF1.EQ.1) THEN ALP=2.0D0
        IF(INRF2.EQ.1) THEN ALSV=2.0D0
C
C      CALCULATE THE FAI1,FAI2
C      GLOBAL COORD. OF B : XBB,YBB
C      GLOBAL COORD. OF D : XDD,YDD
C      FAI1
       DIFX=EXPLX-XBB
       DIFY=EXPLY-YBB
       IF(DABS(DIFX).LT.TOL) DIFX=TOL
       FAI1=DATAN2(DIFY,DIFX)
       IF(FAI1.LT.0.0D0) FAI1=2.0D0*PI+FAI1
C      FAI2
       DIFX=EXPLX-XDD
       DIFY=EXPLY-YDD
       IF(DABS(DIFX).LT.TOL) DIFX=TOL
       FAI2=DATAN2(DIFY,DIFX)
       IF(FAI2.LT.0.0D0) FAI2=2.0D0*PI+FAI2
       RETURN
       END
