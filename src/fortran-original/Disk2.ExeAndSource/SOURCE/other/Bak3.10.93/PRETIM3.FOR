      SUBROUTINE TEXPLOSQ(XI,YI,RSTE,RNSTE,RNORME,K,KDIAK,T1,KPS)
C     CALCULATES THE STRESSES AT A NODE OF THE MESH, IN TIME DOMAIN,
C     DUE TO A POINT EXPLOSION SOURCE, WITH OR WITHOUT DELAYS
C     THE DELAYS ARE INTRODUCED LATER IN SUBROUTINE DECEXPL
C     XI,YI:COORDINATES OF NODE I
C     K    : NUMBER OF CURRENT TIME STEP
C     SXXE,SYYE,SXYE: STRESSES AT NODE I, IN GLOBAL COORDINATE SYSTEM
C                     WITHOUT THE ADDITIONAL CONFINING STRESSES
C                     RETURN VALUE
C     TSXXE,TSYYE,TSXYE: STRESSES AT NODE I, IN GLOBAL COORDINATE SYSTEM
C                     WITH THE ADDITIONAL CONFINING STRESSES
C                     RETURN VALUE
C     RSTE : INCOMING STRESSES IN THE DIRECTION OF RAYS, RETURN VALUE
