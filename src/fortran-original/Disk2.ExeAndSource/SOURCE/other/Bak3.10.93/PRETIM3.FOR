C       REFLECTED STRESSES 
C           TRIIP =SRIIP*A1/A0 =SRIIP*RAT1
C           TRIISV=SRIISV*A2/A0=SRIISV*RAT2
C       POINT B
        BTRXXP=BSRXXP*BRAT1
        BTRXXSV=BSRXXSV*BRAT2
        BTRYYP=BSRYYP*BRAT1
        BTRYYSV=BSRYYSV*BRAT2
        BTRXYP=BSRXYP*BRAT1
        BTRXYSV=BSRXYSV*BRAT2
C       POINT D
        DTRXXP=DSRXXP*DRAT1
        DTRXXSV=DSRXXSV*DRAT2
        DTRYYP=DSRYYP*DRAT1
        DTRYYSV=DSRYYSV*DRAT2
        DTRXYP=DSRXYP*DRAT1
        DTRXYSV=DSRXYSV*DRAT2
C       CASE B OR D BEHIND THE WAVEFRONT, THE CONTRIBUTION IN THE ACTUAL
C       STRESSES IS 0
C        IF(INRF1.EQ.1) THEN
C        IF(ALP(I).GT.1.0D0) THEN
        IF(DREAL(ALP).GT.1.0D0) THEN
C         POINT B
          BTRXXP=0.0D0
          BTRYYP=0.0D0
          BTRXYP=0.0D0
C         POINT D
          DTRXXP=0.0D0
          DTRYYP=0.0D0
          DTRXYP=0.0D0
         ENDIF
C        IF(INRF2.EQ.1) THEN
C        IF(ALSV(I).EQ.1) THEN
        IF(DREAL(ALSV).EQ.1.0D0) THEN
C         POINT B
          BTRXXSV=0.0D0
          BTRYYSV=0.0D0
          BTRXYSV=0.0D0
C         POINT D
          DTRXXSV=0.0D0
          DTRYYSV=0.0D0
          DTRXYSV=0.0D0
         ENDIF
C       TOTAL REFLECTED STRESSES OF P AND SV REFLECTED WAVE, WITH DELAYS
C       AT NODE E
        SRXX1=BTRXXP*SDELAY1/RK+DTRXXSV*SDELAY2/RK
        SRYY1=BTRYYP*SDELAY1/RK+DTRYYSV*SDELAY2/RK
        SRXY1=BTRXYP*SDELAY1/RK+DTRXYSV*SDELAY2/RK
C
C       TRANSFORMATION OF THESE STRESSES BACK TO THE GLOBAL COORDINATE SYSTEM
        CALL STRGLOB(SRXX1,SRYY1,SRXY1,RN1,RN2,
     &                     SRXX11,SRYY11,SRXY11)
C       SUPERIMPOSE P AND SV TRACTIONS
        SRXX(NCN)=SRXX(NCN)+SRXX11
        SRYY(NCN)=SRYY(NCN)+SRYY11
        SRXY(NCN)=SRXY(NCN)+SRXY11


  89    CONTINUE


        NCN=NCN+1
  50  CONTINUE

C  46  CONTINUE

  99  CONTINUE
      RETURN
      END
