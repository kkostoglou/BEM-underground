C       KRONECKER DELTA
        D(1,1)=1.0D0
        D(2,1)=0.0D0
        D(1,2)=0.0D0
        D(2,2)=1.0D0

CC&&&&&&&&&&&&&&&&&&&
CC       NO ZONES
CC        IF(KZN.EQ.0) THEN
C        IF(KZN.EQ.1) THEN
C          RNU1=RNU
C          RMU1=RMU
C        ENDIF
CC       YES ZONES
CC        IF(KZN.EQ.1) THEN
C        IF(KZN.GT.1) THEN
          RNU1=RZNU(KZN)
          RMU1=RZMU(KZN)
C        ENDIF
        CALL CLRARR(SU,4)
        CALL CLRARR(ST,4)
