        RC(2)=(X2-Y2)/R
        DRN=RC(1)*RN(1)+RC(2)*RN(2)
C
        DO 1 I=1,2
        DO 1 J=1,2
        SU(I,J)=(-(3.0D0-4.0D0*RNU1)*DLOG(R)*D(I,J)+RC(I)*RC(J))/
     &              (8.0D0*PI*RMU1*(1.0D0-RNU1))
