        ST(I,J)=-(DRN*((1.0D0-2.0D0*RNU1)*D(I,J)+2.0D0*RC(I)*RC(J))-
     &          (1.0D0-2.0D0*RNU1)*(RC(I)*RN(J)-RC(J)*RN(I)))/
     &          (4.0D0*PI*(1.0D0-RNU1)*R)
  1     CONTINUE
        RETURN
        END

