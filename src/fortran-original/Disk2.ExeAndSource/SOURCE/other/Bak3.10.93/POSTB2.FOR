          NNODE1=NNODE1+1
  35    CONTINUE
        END DO
C       IGNORE ELEMENTS OF THE ENCLOSING ELEMENTS BOUNDARY
        DO I=1,NELEM
          IF(LBCU(I).EQ.4) GO TO 36
