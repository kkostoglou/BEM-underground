      CALL MAXIMA2(SLT1,R1MIN,R1MAX,NZONE*N9*N4*N3)
      CALL MAXIMA2(SLT2,R2MIN,R2MAX,NZONE*N9*N4*N3)
      CALL MAXIMA2(SLT3,R3MIN,R3MAX,NZONE*N9*N4*N3)


C     FIND THE MAX MAX OF ALL HOOP STRESSES, FOR UNIFORM SCALING
      R1MIN=AMIN1(R1MIN,R2MIN)
      R1MIN=AMIN1(R1MIN,R3MIN)
      R1MAX=AMAX1(R1MAX,R2MAX)
      R1MAX=AMAX1(R1MAX,R3MAX)
