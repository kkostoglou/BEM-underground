CC      VAX STATION
CC          CALL GROUTE('SELECT LT4207;EXIT')
CC      HP COLORPLOT
CC          CALL GROUTE('S PHP7475A;E')
CC          THIS GIVES A FILE WITH NAME HPGL, WHICH CAN BE PLOTED.
CC          IN EVERY RUN IT IS OVERWRITTEN, SO IT MUST BE RENAMED.
CC      HP PAINTJET
CC          CALL GROUTE('S GHP3630;E')
CC          THIS GIVES A FILE WITH NAME UNIRAS.RDB.  AFTER THIS
CC          RUN THE PROGRAM
CC          DHCPCL (OR CALL GHCPCL INCIDE OF A PROGRAM AT THE END)
CC       HOST RASTER MODE
CC      CALL GROUTE('SELECT MRASDR;EXIT')
CC      CALL GROUTE('SELECT MRASDR;EXIT')
C      CALL GOPEN
