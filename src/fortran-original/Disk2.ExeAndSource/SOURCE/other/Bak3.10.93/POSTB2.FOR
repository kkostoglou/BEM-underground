      ALLOCATE (SLT1(NZONE,N9,3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (SLT2(NZONE,N9,3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (SLT3(NZONE,N9,3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (SLD1(N9,3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (SLD2(N9,3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (XCE(NZONE,N3,(NSUB+1)),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (YCE(NZONE,N3,(NSUB+1)),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (XCED(N3,(NSUB+1)),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (YCED(N3,(NSUB+1)),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (XCN(NZONE,3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (YCN(NZONE,3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (XCND(3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
      ALLOCATE (YCND(3,N3),STAT=IERR)
      IF(IERR.NE.0) GO TO 988
