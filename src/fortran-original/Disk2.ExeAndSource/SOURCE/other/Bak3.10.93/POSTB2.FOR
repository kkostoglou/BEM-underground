      DIMENSION LCRN(MBD,8)
C
      INTEGER*2 ISTATUS,MAXX,MAXY,MMAX
      INTEGER*2 XV(2),YV(2),XHALF,YHALF
      INTEGER*4 IDUMMY
      INTEGER*4            ifont
      CHARACTER*10         options(6)
      COMMON /FNTS/NFONTS,IFONT,OPTIONS,MAXX,MAXY
C
      REAL*8 SLT1[ALLOCATABLE](:,:,:,:)
      REAL*8 SLT2[ALLOCATABLE](:,:,:,:)
      REAL*8 SLT3[ALLOCATABLE](:,:,:,:)
      REAL*8 SLD1[ALLOCATABLE](:,:,:)
      REAL*8 SLD2[ALLOCATABLE](:,:,:)
      REAL*8 XCE[ALLOCATABLE](:,:,:)
      REAL*8 YCE[ALLOCATABLE](:,:,:)
      REAL*8 XCED[ALLOCATABLE](:,:)
      REAL*8 YCED[ALLOCATABLE](:,:)
      REAL*8 XCN[ALLOCATABLE](:,:,:)
      REAL*8 YCN[ALLOCATABLE](:,:,:)
      REAL*8 XCND[ALLOCATABLE](:,:)
      REAL*8 YCND[ALLOCATABLE](:,:)
      REAL*8 SDINTX[ALLOCATABLE](:,:)
      REAL*8 SDINTY[ALLOCATABLE](:,:)
