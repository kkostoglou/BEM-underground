      CALL MAXIMA2(SLD1,R4MIN,R4MAX,N9*N4*N3)
      CALL MAXIMA2(SLD2,R5MIN,R5MAX,N9*N4*N3)
C     FIND THE MAX MAX OF ALL DISPLACEMENTS, FOR UNIFORM SCALING
      R2MIN=AMIN1(R4MIN,R5MIN)
      R2MAX=AMAX1(R4MAX,R5MAX)


C^^^^^^^^^^^!!!!!!!!!!!!!!
C     MAX OF INTERNAL DISPLACEMENTS
      CALL MAXIMA2(SDINTX,R4MIN,R4MAX,N9*NINT)
      CALL MAXIMA2(SDINTY,R5MIN,R5MAX,N9*NINT)
C     FIND THE MAX MAX OF ALL DISPLACEMENTS, FOR UNIFORM SCALING
      R3MIN=AMIN1(R4MIN,R5MIN)
      R3MAX=AMAX1(R4MAX,R5MAX)

C
C     FOR THE CASE OF RADIAL DIAGRAMS, ADD THE MAXIMUM OF THE COORDINATES
C
      RX1=XMAX-XMIN
      RY1=YMAX-YMIN
      DIAM=AMAX1(ABS(RX1),ABS(RY1))
C
      RATE1=AMAX1(ABS(R1MIN),ABS(R1MAX))
      RATE2=AMAX1(ABS(R2MIN),ABS(R2MAX))
      IF(RATE1.LT.TOL) RATE1=TOL
      IF(RATE2.LT.TOL) RATE2=TOL
C     WITH THIS VALUE RATE1 WE MULTIPLY THE STRESSE TO CONVERT THEM TO
C     DISTANCE AND SUBSIQUENTLY ADD THE RADIAL DISTANCE AS IT IS. FOR
C     THE DISPLACEMENTS WE USE ANOTHER VALUE RATE2.
C     FOR CHANGING THE SIZE OF THE DIAGRAMS, CHANGE THE DENOMENATOR
C     2.0 MEANS THAT THE RADIAL LENGTH OF THE GRAPH WILL HAVE MAXIMUM VALUE 
C     EQUAL TO D/2. IF INSTEAD OF 2 WE PUT 1.5, WE HAVE BIGER RADIAL DISTANCE. 
C     AND IF WE PUT 3 WE HAVE SMALLER RADIAL DISTANCE.
C   
      RATE1=DIAM/(5.0*RATE1)
      RATE2=DIAM/(10.0*RATE2)
      R11MIN=R1MIN*RATE1
      R11MAX=R1MAX*RATE1
      R22MIN=R2MIN*RATE2
      R22MAX=R2MAX*RATE2


      R11MIN=R11MIN+XYMIN
      R11MAX=R11MAX+XYMAX
      R22MIN=R22MIN+XYMIN
      R22MAX=R22MAX+XYMAX

      DT=TIM/DFLOAT(NTINT)
      IPSG=0
C      CALL GRPSIZ(XMMS,YMMS)
C      CALL GVPORT(XMMS*0.1,YMMS*0.1,XMMS*0.8,YMMS*0.8)
C      CALL GWBOX(1.0,1.0,0.0)
C      CALL GLIMIT(XYMIN,XYMAX,XYMIN,XYMAX,0.0,0.0)
C      CALL GSCALE
C      CALL GCLEAR
C
CC     SET TEXT FONT DUPLEX ROMAN, BEST FIT
C      CALL RTXFON('DUPL',0)
C     COURIER FONTS
      IFONT=1
      CALL FONTREG


      NDIAK=1
C     IN THE 1ST LOOP
C     CREATE A SEGMENT FOR PLOTING WITH RASCON
C      IF(NCOUNT.EQ.1) THEN
        IPSG=IPSG+1
C        CALL GSEGCR(IPSG)
C      ENDIF
C      CALL PLOTDOM(XD,YD,NNODEB,NBOUN,N1,NDIAK,
C     &  XYMIN,XYMAX,NSHAP,NDIS,LCRN)

      CALL PLOTDOM(XCR,YCR,NNODEB,NBOUN,N1,NDIAK,
     &  XYMIN,XYMAX,NSHAP,NDIS,LCRN,MBD)



C     ELASTODYNAMIC CASE ONLY (TIME DOMAIN OR LAPLACE DOMAIN (TRANSIENT
C     OR STEADY STATE CASE))
      IF((NDOMA.EQ.1).OR.(NDOMA.EQ.2).OR.(NDOMA.EQ.4))THEN
C       NOT EXPLOSIVE CASE
        IF(KEXPL.EQ.0) THEN
          CALL WAVFRONT(CP1,XCEN1,YCEN1,XMAX,YMAX,NCOUNT)
        ENDIF
      ENDIF
C     CLOSE THE SEGMENT
C      IF(NCOUNT.EQ.1) 
C      CALL GSEGCL(IPSG)
C      CALL GDIAGC('WAIT')
      READ(*,*)

C     FIND THE NUMBER OF THE JOINING ELEMENTS AT A NODE (IS THE SAME 
C     AS THE NUMBER OF THE TIMES THE NODE APPEARS IN THE ELEMENTS)
      DO 63 I=1,N1
        LDIR1(I)=0
  63  CONTINUE
      DO 65 JCL=1,NELEM
        DO 65 I=1,NOD
          LN=KONN(JCL,I)
          LDIR1(LN)=LDIR1(LN)+1
  65  CONTINUE

C     INDEXES FOR SEVERAL CASES OF PLOTS
      DO 23 I=1,INDX
        KPLOT(I)=0
  23  CONTINUE
C       KDIM=0
      DO 62 IPL=1,NTOT
C
C       INDEXES FOR PLOTS ON THE PERIPHERY
C       NUMERICAL VALUES OF STRESSES ONLY ON THE NODES THAT ARE SPECIFIED
C       IN NODE.PLOTS
        IF(NPLOT(IPL).EQ.26) KPLOT(1)=1
C
C       INDEXES FOR CARTESIAN COORDINATES PLOTS
C       CHECK IF ALL THE PLOTS ARE DRAWN IN THE SAME PAGE (NPLOT=28)
C        IF(NPLOT(IPL).EQ.28) KPLOT=1
        IF(NPLOT(IPL).EQ.28) KPLOT(2)=1
C       CHECK IF THE PLOTS ARE DRAWN IN DIMENSIONLESS X (TIME) AXIS (NPLOT=29)
C       AS X VALUES ARE THE TIME STEPS
C        IF(NPLOT(IPL).EQ.29) KDIM=1
        IF(NPLOT(IPL).EQ.29) KPLOT(3)=1
C       CHECK TO SEE IF THE STRESSES ON THE PERIPHERY, ARE PLOTED
C       FOR EVERY ELEMENT, WITHOUT TAKING THE MEAN VALUE BETWEEN 
C       NEIGHBORHOUND NODES (NPLOT=27)
        KDIAK=0
        IF(NPLOT(IPL).EQ.27) KPLOT(4)=1
  62  CONTINUE


C     APPEND THE RESULTS OF PROCESSING IN THE POSTPROCESSING FILE,
C     WHICH IS THE SAME AS THE PREPROCESSING FILE

      DO 20 NCOUNT=1,NTINT
        TT=C1*DT*DFLOAT(NCOUNT-1)
C        CP1=SNGL(CP)-SNGL(TT)
        CP1=CP-TT
C       PLOT THE GRAPHS
        DO 92 IPL=1,NTOT
C
C       PLOTS IN RADIAL DIRECTION TO THE MESH SURFACE (ON THE PERIPHERY)
C       ================================================================
C       PLOT THE HOOP NORMAL STRESSES
        IF(NPLOT(IPL).EQ.1) THEN
C          CALL CLREAL(SR1,N4*N3)
C          CALL CLREAL(SRT1,MBD*N4*N3)
          CALL CLREAL(SRT1,NZONE*N4*N3)

C          CALL GDIAGC('WAIT')
C          DO 31 I=1,NNODE

          DO 31 K=1,NZONE

          DO 31 I=1,NELEM
            DO 31 J=1,NOD
C             HOOP STRESSES NORMAL
C              SR1(J,I)=SLT1(NCOUNT,J,I)
              SRT1(K,J,I)=SLT1(K,NCOUNT,J,I)

  31      CONTINUE
CC         NEW SCALING
C          CALL GLIMIT(R11MIN,R11MAX,R11MIN,R11MAX,0.0,0.0)
C          CALL GSCALE

C          XW(1)=1.2*R11MIN
C          YW(1)=1.2*R11MAX
C          XW(2)=1.2*R11MIN
C          YW(2)=1.2*R11MAX
C          ISTATUS=SETWINDOW(.TRUE.,XW(1),YW(1),XW(2),YW(2))

C         CREATE A SEGMENT FOR PLOTING WITH RASCON
C          IPSG=IPSG+1
C          CALL GSEGCR(IPSG)
C          TITLE='Normal stresses'
C         SI UNIT SYSTEM
          IF(NUNIT.EQ.1) TITLE='Normal Stresses (MPa)'
C         IMPERIAL UNIT SYSTEM
          IF(NUNIT.EQ.2) TITLE='Normal Stresses (psi)'
          CALL PLOTHOOP(XCR,YCR,SRT1,RATE1,XCE,YCE,
     &      XCN,YCN,KONN,KZON,N1,N3,N4,N7,N9,NSUB,NNODEB,NELEMB,
     &      NBOUN,CP1,XCEN1,YCEN1,NCOUNT,SLNT1,LDIR1,NPLOT,NTOT,
