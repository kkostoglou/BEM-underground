        ALLOCATE (SDINTX(N9,NINT),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
        ALLOCATE (SDINTY(N9,NINT),STAT=IERR)
        IF(IERR.NE.0) GO TO 988
      ENDIF
      CALL CLRARR(SDINTX,N9*NINT)
      CALL CLRARR(SDINTY,N9*NINT)
C
C     INTERNAL POINTS
      IF(NINT.NE.0) THEN
        READ(3,*)SDINTX
        READ(3,*)SDINTY
  66    CONTINUE
      ENDIF
C
      PI=3.14159265359D0
      TOL=1.0E-6
      TOL1=1.0E-11
      NOD=3
C^^^^^^^^^^^^^^^!!!!!!!!!!!!!!!
C       IGNORE NODES OF THE ENCLOSING ELEMENTS BOUNDARY
        NNODE1=0
        NELEM1=0
        DO I=1,NNODE
          IF(NDTYPE(I).EQ.4) GO TO 35
C         NODES WITHOUT THE NODES OF THE ENCLOSING ELEMENTS BOUNDARY
