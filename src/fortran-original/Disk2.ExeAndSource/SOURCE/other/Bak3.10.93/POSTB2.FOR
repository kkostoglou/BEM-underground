  36      CONTINUE
        END DO
        NA1=NNODE1
        NA2=2*NNODE1
        NA3=NELEM1
        NA5=3*NNODE1

C     CONVERT DOUBLE PRECISION TO REAL
      CA1=CA
      CB1=CB
      CP1=CP
C      YCEN1=SNGL(YCEN)

      XCEN1=XCEN
      YCEN1=YCEN
C      DO 10 I=1,N1
C        XD(I)=SNGL(XCR(I))
C        YD(I)=SNGL(YCR(I))
C  10  CONTINUE
C     PLOT THE MESH 
C     -------------
C      CALL MAXIMA(XD,YD,XMIN,YMIN,XMAX,YMAX,N1)
      CALL MAXIMA(XCR,YCR,XMIN,YMIN,XMAX,YMAX,N1)

CC     SPARC STATION SCREEN
