      SUBROUTINE PLMESH(XCR,YCR,
     &  NSUB,CA,CB,CP,NNODEB,NELEMB,NBOUN,XCEN,YCEN,
     &  SRT1,SRD1,SR2,SA1,SLNT1,SLND1,LDIR1,XTIME,KONN,KZON,NTOT,
     &  NPLOT,NDTOT,NDPLOT,LETOT,LEPLOT,KEXPL,NSHAP,NDIS,LCRN,LBCU,
     &  NDTYPE,N1,N2,N3,N4,N7,N9,MND,NUNIT,MBD,NPLZON,MZN)
C
C     PLOTS THE MESH AND THE ACTUAL WAVE FRONT AT ANY TIME STEP
C     XCR,YCR  : COORDINATES OF THE NODES DOUBLE PRECISION
C     XD,YD    : TRANSFORMATION OF COORDINATES IN REAL
C     SR       : STRESS TENSOR OF THIS STEP
C     CA,CB,CP: VALUES OF THE CONSTANTS OF THE EQUATION OF
C               LINE OF WAVE FRONT
C               THE EQUATION OF THE WAVEFRONT, IS THE EQUATION OF A 
C               NORMAL TO A STRAIGHT LINE WITH ANGLE FAI WITH X AXIS
C               (AXIS OF INCIDENT WAVE)
C               CA=COS(FAI), CB=SIN(FAI)
C               CA*XCR(I)+CB*YCR(I)-CP=0
C
C     FAI     : ANGLE OF ROTATION
C     XCEN,YCEN: CENTER OF THE LOCAL SYSTEM

C
      IMPLICIT REAL*8 (A-H,O-Y)
      INCLUDE 'FGRAPH.FD'
      PARAMETER(INDX=4)
      COMMON/TIT/FNAMEIN,TITLE,TITLY
      COMMON/CONTR/NNODE,NELEM,NTINT,NP
      COMMON/GEOM3/FAI,PSAI
      COMMON/PROBL/NDOMA,NREGI
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM
C&&&&&&&&&&&&&&&&&&&&
C     COMMON BLOCK FOR ZONES: NZONE IS THE TOTAL NUMBER OF ZONE BOUNDARIES
C                             =0: NO ZONES, >0: ZONES ARE PRESENT
      COMMON/RZON1/NZONE,RZLA(5),RZMU(5),RZNU(5),RZHO(5),CZ1(5),
     &             CZ2(5),FZVISC(5),NZMODE(5),IBOU(5,5)
      CHARACTER FNAMEIN*14,TITLE*45,TITLY*20
C
      DIMENSION XCR(N1),YCR(N1)
      DIMENSION NNODEB(NBOUN),NELEMB(NBOUN)
      DIMENSION PSAI(5),NPLOT(NTOT)
      DIMENSION NPLZON(MZN)
      DIMENSION SRT1(NZONE,N4,N3)
      DIMENSION SRD1(N4,N3),SR2(N4,N3)
      DIMENSION SA1(N9)
      DIMENSION XTIME(N9)
      DIMENSION KONN(N3,N4)
      DIMENSION NREGI(5)
      DIMENSION NDPLOT(NDTOT),LEPLOT(LETOT),KPLOT(INDX)
      DIMENSION LDIR1(N1),SLNT1(NZONE,N1),SLND1(N1)
      DIMENSION NSHAP(NBOUN),NDIS(5)
      DIMENSION XW(2),YW(2)
      DIMENSION LBCU(N3),NDTYPE(N1)
C     CONNECTIVITY ZONE'S ARRAY
      DIMENSION KZON(NZONE,N3,N4)
C     FREQUENCY FOR HARMONIC WAVE
      COMMON/FREQ/OFREQ
C     INTERNAL POINTS WITH THEIR CO-ORDINATES
      COMMON/INTERN/NINT,CINT(10,2)
C
C     LCRN(MBD,8): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE.
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
