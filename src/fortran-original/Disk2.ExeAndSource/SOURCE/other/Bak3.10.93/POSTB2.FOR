      CALL DATAS(XCR,YCR,SLT1,SLT2,SLT3,SLD1,SLD2,
     &  KONN,KZON,MBCU,LBCU,NDTYPE,N1,N2,N3,N4,N7,N9,NTOT,
     &  NPLOT,NSHAP,NDIS,LCRN,NBOUN,NZONE)
