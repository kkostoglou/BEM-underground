C          CALL GSEGCR(IPSG)
C          TITLE='Shear Stresses'
C         SI UNIT SYSTEM
          IF(NUNIT.EQ.1) TITLE='Shear Stresses (MPa)'
C         IMPERIAL UNIT SYSTEM
          IF(NUNIT.EQ.2) TITLE='Shear Stresses (psi)'

C          CALL PLOTHOOP(XCR,YCR,SR1,RATE1,XCE,YCE,
C     &      XCN,YCN,KONN,NONN,N1,N3,N4,N7,N9,NSUB,NNODEB,NELEMB,
