        SUBROUTINE FFCT(VR,VI,NT,WR,WI,JP1,NF,AR,AI,N8)
C
C       FAST FOURIER ALGORITHM FOR INVERSE TRANSFORMATION
C
C       VR, VI ARE REAL AND IMAGINARY PARTS OF FUNCTION TO BE INVERTED
C       NT IS NUMBER OF LAPLACE SPECTRUM POINTS
C
        IMPLICIT REAL*8 (A-H,O-Y)
C        DIMENSION VR(1),VI(1)
        DIMENSION VR(NT),VI(NT)
C                           ################################
C                           !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
C       MODIFICATION FOR 200 TIME STEPS
C        DIMENSION AR(50),AI(50),AUXR(5),AUXI(5)
C        DIMENSION AR(200),AI(200),
        DIMENSION AUXR(5),AUXI(5)
C        COMMON/TRIG/WR(50),WI(50),JP1(5),JC1(5),NF
C        COMMON/TRIG/WR(200),WI(200),JP1(5),JC1(5),NF
        DIMENSION AR(NT),AI(NT)
        DIMENSION WR(NT),WI(NT),JP1(N8),JC1(5)
C
        N=NT
        K=1
        J=0
        GO TO 8
  4     LP=1
        LS=0
        NM=NF-1
        DO 9 KK=1,NM
        LC=JC1(KK+1)-1
        LP=LP*JP1(KK)
        LS=LS+LC*LP
  9     CONTINUE
        LS=LS+JC1(1)
        AR(K)=VR(LS)
        AI(K)=VI(LS)
        K=K+1
  7     JC1(J)=JC1(J)+1
        NST=JC1(J)-JP1(J)
        IF (NST) 8,8,6
  8     JM=J+1
        IF (JM-NF) 2,2,1
  2     DO 3 L=JM,NF
        JC1(L)=1
  3     CONTINUE
  1     J=NF
        GO TO 4
  6     J=J-1
        IF (J) 5,5,7
  5     DO 11 I=1,N
        VR(I)=AR(I)
        VI(I)=AI(I)
  11    CONTINUE
        NUR=N
        DO 25 I=1,NF
        K=NF-I+1
        NU=JP1(K)
        NUR=NUR/NU
        NUD=N/(NUR*NU)
        LRD=NUR*NUD
        LDU=NUD*NU
        LS=(NUR-1)*LDU+1
        DO 24 KRE=1,LS,LDU
        KRE1=KRE-1
        DO 22 LE=1,NUD
        LE1=LE-1
        JAC=NUR*LE1
        DO 21 NS=1,NU
        AUXR(NS)=0.0D0
        AUXI(NS)=0.0D0
        LA=LE+KRE1
        DO 20 NUT=1,NU
        M=JAC*(NUT-1)
        MQ=M/N
        M=M+1-MQ*N
        Q=WI(M)
        AUXR(NS)=AUXR(NS)+VR(LA)*WR(M)-VI(LA)*Q
        AUXI(NS)=AUXI(NS)+VR(LA)*Q+VI(LA)*WR(M)
        LA=LA+NUD
  20    CONTINUE
        JAC=JAC+LRD
  21    CONTINUE
        LA=LE+KRE1
        DO 23 NS=1,NU
        VR(LA)=AUXR(NS)
        VI(LA)=AUXI(NS)
        LA=LA+NUD
  23    CONTINUE
  22    CONTINUE
  24    CONTINUE
  25    CONTINUE
        RETURN
        END


