      SUBROUTINE WRITEDAT(XCR,YCR,KONN,KZON,
     &  MBCU,LBCU,NDTYPE,NZTYPE,NODZ,NNODEB,
     &  NELEMB,NELZ,NTOT,NPLOT,NDTOT,NDPLOT,LETOT,LEPLOT,CA,CB,CP,
     &  NBOUN,XCEN,YCEN,SIGC,FM,FS,KEXPL,NSHAP,LCRN,N1,N2,N3,N4,MND,
     &  MPL,MBD,INES,NPLZON,MZN)
C
C     LCRN(5,MBD): NUMBER OF THE CORNER NODES FOR SQUARE OR RECTANGLE.
C              THE 4 FIRST NUMBERS ARE THE CORNER NODES AND THE LAST 4
C              ARE THE DUPLICATED CORNER NODES. IT IS RETURN VALUE FROM
C              SUBROUTINE MESH4, NEEDED FOR THE CASE OF DUPLICATE CORNER
C              NODES OF DISCONTINUTY (MBD BOUNDARIES TOTAL)

C^^^^^^^^^^^^^^^^^^^^
C           INES : INDEX 0: NUMBER OF ELEMENTS IN A SEGMENT WERE 0
C                        1: THERE WERE NOT 0 NUMBER OF ELEMENTS IN ANY SEGMENT


      IMPLICIT COMPLEX*16 (Z)
      IMPLICIT REAL*8 (A-H,O-Y)
C
      CHARACTER FNAMEIN*14,FNAMEPRE*14,DATE*35
      CHARACTER FNAMEPRO*14,FNAMEPOS*14
      CHARACTER TIME*15,SNAME*35
C
      DIMENSION LCRN(MBD,8)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
      COMMON/GEOM3/FAI,PSAI
      COMMON/BLK20/DATE,TIME,SNAME,FNAMEIN,FNAMEPRE,
     &             FNAMEPRO,FNAMEPOS


C&&&&&&&&&&&&&&&&&&&&
C     COMMON BLOCK FOR ZONES: NZONE IS THE TOTAL NUMBER OF ZONE BOUNDARIES
C                             =0: NO ZONES, 1: ZONES ARE PRESENT
C      COMMON/RZON/NZBOUN1(5,5),NZBOUN2(5,5),RZYOUN(5),RZPOIS(5),
C     &            RZDENS(5)
      COMMON/RZON1/NZONE,RZLA(5),RZMU(5),RZNU(5),RZHO(5),CZ1(5),
     &             CZ2(5),FZVISC(5),NZMODE(5),IBOU(5,5)
C      REAL*8 RZLA,RZMU,RZNU,RZHO,CZ1,CZ2
c&&&&&&&&&&&&&&&&&&&&
      DIMENSION NZTYPE(NZONE,N1)
C     INDICATION FOR THE INTERNAL POINT
      COMMON/FREQ/OFREQ
C     INTERNAL POINTS WITH THEIR CO-ORDINATES
      COMMON/INTERN/NINT,CINT(10,2)
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
      COMMON/PRESS/KINSI,PINSI

      DIMENSION XCR(N1),YCR(N1)
      DIMENSION KONN(N3,N4)
      DIMENSION MBCU(N2),LBCU(N3)
      DIMENSION NDTYPE(N1)
      DIMENSION NELEMB(MBD),NNODEB(MBD),NREGI(5),NPLOT(MPL)
      DIMENSION PSAI(5)


      DIMENSION NDPLOT(MND),LEPLOT(2*MND)
      DIMENSION NPLZON(MZN)
C      DIMENSION NDPLOT(N1),LEPLOT(N2)
C      DIMENSION NPLZON(NZONE)





      DIMENSION LDIR(3)
      DIMENSION NSHAP(NBOUN)
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)
      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &          TYPELY(5),NDIS(5)
C     NODZ: ARRAY OF INDEXES THAT INDICATE THE ZONE THAT EVERY NODE BELONGS
C     TOO (IF THERE ARE NOT ZONES IT HAS ZERO VALUES)
C     NELZ: ARRAY OF INDEXES THAT INDICATE THE ZONE THAT EVERY ELEMENT
C     BELONGS TOO (IF THERE ARE NOT ZONES IT HAS ZERO VALUES)
      DIMENSION NODZ(N1),NELZ(N3)
C     CONNECTIVITY ZONE'S ARRAY
c      DIMENSION KZON(MBD,N3,N4)
      DIMENSION KZON(NZONE,N3,N4)
      DIMENSION PINSI(5)


C      DIMENSION NONSNG(NCASE),DNONSNG1(NCASE),DNONSNG2(NCASE)
C     CONTROL OF NUMERICAL INTEGRATION
      COMMON/NUMER/NGAUS,NSNG,NCASE,NONSNG(10),DNONSNG1(10),
     &             DNONSNG2(10)
C****************
C           CONNECTIVITY OF ZONE K, ELEMENT I, WITH NUMBERING IN THE
C           BOUNDARY ONLY (THE 2nd INDEX SHOULD BE NELEMB(K)
C      DIMENSION KONBOUN(MBD,N3,3)
C      DIMENSION KONBOUN(NBOUN,N3,3)
C&&&&&&&&&&&&&&&&&
C     IN CASE OF NO EXISTENCE OF ZONES,
C     DEFAULT VALUES FOR ZONES CONNECTIVITY ARRAY KZON (THE SAME AS KONN)
      IF(NZONE.EQ.1) THEN
        DO I=1,N3
          DO II=1,N4
            KZON(1,I,II)=KONN(I,II)
          END DO
        END DO
c        DO I=1,N1
c          NZTYPE(1,I)=7
c        END DO
      END IF
      NOD=3
C     INDEX FOR THE EXISTENCE OF A FREE SURFACE
C     NFRE=0: NO FREE SURFACE EXISTS
C     NFRE=1: FREE SURFACE EXISTS
      NFRE=0
      DO 1 I=1,NBOUN
        IF(NREGI(I).EQ.4) NFRE=1
  1   CONTINUE
      WRITE(1,*) RLA,RMU,RNU,RHO,C1,C2,TIM,NFRE
C     GEOMETRY
      WRITE(1,*) XCR
      WRITE(1,*) YCR
C     ELEMENT CONNECTIVITY (NUMBERS OF FIRST, MIDDLE AND LAST NODES OF 
C     ALL THE ELEMENTS)
      WRITE(1,*) KONN
cC     NODE CONNECTIVITY (NUMBERS OF PREVIUS, CURRENT AND NEXT NODES OF
cC     ALL THE NODES)
c      WRITE(1,*) NONN



C     MBCU: 0 TRACTION PRESCRIBED CONDITION, 1 DISPLACEMENT
      WRITE(1,*) MBCU
C     TYPE OF ELEMENT (LBCU:
C         0:COMMON CASE,           1:ON INCLUSION SURFACE,
C         2:ON FREE SURFACE,       3:ON SIMULATION SURFACE,
C         4:ON ENCLOSING BOUNDARY, 5:OUTER ZONE'S BOUNDARY
C         6:INNER ZONE'S BOUNDARY, 7:INNER ZONE'S FREE BOUNDARY)
C
      WRITE(1,*) LBCU
C     TYPE OF NODE (NDTYPE:
C         0:COMMON CASE,           1:ON INCLUSION SURFACE,
C         2:ON FREE SURFACE,       3:ON SIMULATION SURFACE,
C         4:ON ENCLOSING BOUNDARY, 5:OUTER ZONE'S BOUNDARY
C         6:INNER ZONE'S BOUNDARY, 7:INNER ZONE'S FREE BOUNDARY)
      WRITE(1,*) NDTYPE


C^^^^^^^^^^^^!!!!!!!!!!
      WRITE(1,*) OFREQ
      WRITE(1,*) NINT,CINT



cC&&&&&&&&&&&&&&&&&&&&&&&&
cC     DATA FOR ZONES (5 BOUNDARIES)
c      WRITE(1,*) NZONE,RZLA,RZMU,RZNU,RZHO,CZ1,CZ2,FZVISC,NZMODE,IBOU
      WRITE(1,*) KZON
      WRITE(1,*) NZTYPE
      WRITE(1,*) NODZ,NELZ

CC****************
CC           CONNECTIVITY OF ZONE K, ELEMENT I, WITH NUMBERING IN THE
CC           BOUNDARY ONLY (THE 2nd INDEX SHOULD BE NELEMB(K)
C      WRITE(1,*) KONBOUN

C     CONTROL OF NUMERICAL INTEGRATION
      WRITE(1,*) NGAUS,NSNG,NCASE,NONSNG,DNONSNG1,DNONSNG2


C     WRITE DATA TO THE POSTDAT FILE, FOR LATER READING IN POSTPROCESSING
C
      WRITE(4,*)NTOT,NPLOT
      WRITE(4,190)FNAMEPRO,FNAMEPOS


  190 FORMAT(A14,A14)
C  190 FORMAT(A,A)

C      WRITE(4,*)NDOMA,CA,CB,CP,
C     &    NNODEB,NELEMB,NBOUN,NREGI,XCEN,YCEN,FAI,PSAI
      WRITE(4,*) NDOMA,NNODEB,NELEMB,NBOUN,NREGI
      WRITE(4,*) CA,CB,CP
      WRITE(4,*) XCEN,YCEN,FAI,PSAI

C      WRITE(4,*) FNAMEIN
C      WRITE(4,191) FNAMEIN
C  191 FORMAT(A14)
      WRITE(4,*) FNAMEIN

C      WRITE(4,*) NDTOT,NDPLOT,LETOT,LEPLOT,NPLZON
      WRITE(4,*) NDTOT
      WRITE(4,*) NDPLOT
      WRITE(4,*) LETOT
      WRITE(4,*) LEPLOT
      WRITE(4,*) NPLZON

C
C     WRITE IN FILE 4 THE UNIAXIAL COMPRESSIVE STRESS AND THE COSTANTS FOR
C     FAILURE CRITERIA (POSTPROCCESING ONLY) AND THE TYPES OF PLOT
C      WRITE(4,*)SIGC,FM,FS,KEXPL
      WRITE(4,*)SIGC,FM,FS
C     WRITE ON FILE THE CODES FOR THE BOUNDARIES SHAPES AND THE CODE
C     OF DISCONTINUITY, FOR USE IN POSTPROCESSING
C      WRITE(4,*) NSHAP,NDIS,LCRN
      WRITE(4,*) KEXPL,NSHAP,NDIS,LCRN
C^^^^^^^^^^^^^^^^^^^^^
      WRITE(4,*) INES

C      WRITE(4,*) EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
C     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY
C      WRITE(4,*) KINSI,PINSI
      WRITE(4,*) EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV
      WRITE(4,*) NFORM,NDECAY,KINSI,PINSI



C
C     PRESENT THE DATA IN FILE 6
C     WRITE FOR EVERY NODE
C         THE COORDINATES X,Y,
C         THE PRESCRIBE BOUNDARY CONDITION COND (0: TRACTION, 1: DISPLACEMENT)
C         THE TYPE OF THE NODE (0: COMMON CASE, 1: NODE ON INCLUSION SURFACE,
C                     2: NODE ON FREE SURFACE, 3: NODE ON SIMULATION SURFACE,
C                     4: NODE ON ENCLOSING BOUNDARY)
      WRITE(6,100)
      WRITE(6,110)
CC      WRITE(6,115)
      WRITE(6,120)
      WRITE(6,125)
      DO 20 I=1,NNODE
        WRITE(6,130)I,XCR(I),YCR(I),MBCU(I),NDTYPE(I)
  20  CONTINUE
  100 FORMAT(//T2,'MESH NODES')
  110 FORMAT(T2,  '==========')
C  120 FORMAT(/2X,'NODE',2X,'      X       ',2X,'      Y       ')
  120 FORMAT(T2,'NODE',T9,'    X(m)',T20,'   Y(m)',T31,'COND',
     &       T36,'TYPE')
  125 FORMAT(T2,39('-'))
C  130 FORMAT(/2X,I3,2X,E8.3,2X,E8.3)
  130 FORMAT(T2,I3,T9,F12.3,T20,F12.3,T31,I3,T38,I3)



C     WRITE THE CONNECTIVITY OF THE ELEMENTS
      WRITE(6,140)
      WRITE(6,150)
      WRITE(6,160)
      WRITE(6,170)
      WRITE(6,125)
      DO 30 I=1,NELEM
        DO 32 J=1,NOD
          LN=KONN(I,J)
          LDIR(J)=LN
  32    CONTINUE
        WRITE(6,180)I,(LDIR(K),K=1,3),LBCU(I)
C        WRITE(6,180)I,(LDIR(K),K=1,3)

  30  CONTINUE
  140 FORMAT(//T2,'MESH ELEMENTS')
  150 FORMAT(T2,  '=============')
  160 FORMAT(T2,'ELEMENT',T9,'     CONNECTIVITY ',T38,'TYPE')
C  160 FORMAT(T2,'ELEMENT',T9,'     CONNECTIVITY ')
C  165 FORMAT(T2,'-------',T9,'     ------------ ',T38,'----')
  170 FORMAT(T9,'FIRST',T20,'MIDDLE',T31,'LAST')
  175 FORMAT(T2,39('-'))
C  180 FORMAT(9X,3(2X,I5))
  180 FORMAT(T2,I3,T9,I3,T20,I3,T31,I3,T36,I3)





      WRITE(6,90)
      WRITE(6,91)
  90  FORMAT(//T2,'ZONE DATA')
  91  FORMAT(T2,  '=========')

      DO 68 K=1,NZONE
        WRITE(6,92) K
        WRITE(6,93)
  92    FORMAT(/T2,'ZONE : ',I3)
  93    FORMAT(T2, '-----------')
        WRITE(6,94)
        WRITE(6,96)
  94    FORMAT(5X,'ZONE NODES')
  96    FORMAT(5X,'----------')
        WRITE(6,97)
        WRITE(6,98)
        WRITE(6,102)
  97    FORMAT(T5,'     ',T9,'     B   O   U   N   D   A   R   Y')
  98    FORMAT(T5,'  ZONE   OUTER  INNER1  INNER2  INNER3  INNER4')
  102   FORMAT(5X,'----------------------------------------------')
C       NUMBER OF ENLOSING BOUNDARIES OF ZONE K
C       IBOUN(K,1) IS THE OUTER BOUNDARY OF ZONE K AND IBOUN(K,2) THE INNER
        LO=IBOU(K,1)
        LI1=IBOU(K,2)
        LI2=IBOU(K,3)
        LI3=IBOU(K,4)
        LI4=IBOU(K,5)
C       CASE THAT THE INNER BOUNDARY IS A FREE BOUNDARY
        IF(LI.LT.0) LI=-LI
        WRITE(6,114) K,LO,LI1,LI2,LI3,LI4
  114   FORMAT(5X,I3,5X,I3,5X,I3,5X,I3,5X,I3,5X,I3)
        WRITE(6,103)
        WRITE(6,104)
  103   FORMAT(20X,'NODE   TYPE')
  104   FORMAT(20X,'-----------')
        DO 22 ICL=1,NNODE
          KDIAK=0
C         PROCEED ONLY FOR THE NODES OF THE ZONE K
C         SEARCH ARRAY KZON (ZONE K), TO FIND IF NODE ICL IS INCLUDED
          KZDIAK=0
          DO 311 KK=1,N3
          DO 311 KKK=1,NOD
            K1=KZON(K,KK,KKK)
            IF(ICL.EQ.K1) KZDIAK=1
  311     CONTINUE
          IF(KZDIAK.EQ.1) THEN
            WRITE(6,116) ICL,NZTYPE(K,ICL)
  116       FORMAT(20X,I3,2X,I3)
          ENDIF
  22    CONTINUE
C       WRITE THE CONNECTIVITY OF THE ELEMENTS OF THE ZONE
        WRITE(6,240)
        WRITE(6,250)
        WRITE(6,260)
        WRITE(6,270)
        WRITE(6,275)
        DO 330 I=1,NELEM

C         PROCEED ONLY FOR THE ELEMENTS OF THE ZONE K
C         SEARCH ARRAY KZON (ZONE K), TO FIND IF ELEMENT ICL IS INCLUDED
          KZDIAK1=0
          DO 511 KKK=1,NOD
            K1=KZON(K,I,KKK)
C           THE ELEMENT JCL IS PART OF THE ZONE K, ONLY IF ALL THE
C           CONNECTIVITY NODES ARE NOT 0
            IF(K1.GT.0) KZDIAK1=1
  511     CONTINUE
          IF(KZDIAK1.EQ.1) THEN


            DO 232 J=1,NOD
              LN=KZON(K,I,J)
              LDIR(J)=LN
  232        CONTINUE
C             WRITE(6,280)I,(LDIR(K1),K1=1,3),LBCU(I)
             WRITE(6,280)I,(LDIR(K1),K1=1,3)
C  230      CONTINUE
           ENDIF

  330      CONTINUE
  240     FORMAT(T5,'ZONE ELEMENTS')
  250     FORMAT(T5, '-------------')
C  260     FORMAT(T5,'ELEMENT',T12,'     CONNECTIVITY ',T41,'TYPE')
  260     FORMAT(T5,'ELEMENT',T12,'     CONNECTIVITY ')
  270     FORMAT(T12,'FIRST',T23,'MIDDLE',T34,'LAST')
  275     FORMAT(T5,39('-'))
C  180     FORMAT(9X,3(2X,I5))
  280     FORMAT(T5,I3,T12,I3,T23,I3,T34,I3,T39,I3)
C        ENDIF


  68  CONTINUE



CC     WRITE THE PRESCRIBED BOUNDARY CONDITION AT THE NODES
CC            0: TRACTION PRESCRIBED CONDITION 
CC            0: DISPLACEMENT PRESCRIBED CONDITION 
C      WRITE(6,190)
C      WRITE(6,200)
C
C      WRITE(6,210)
C      WRITE(6,220)
C      WRITE(6,230)
C      WRITE(6,240) (MBCU(I),I=1,2*NNODE)
C  38  CONTINUE
C  190 FORMAT(//2X,' PRESCRIBED BOUNDARY CONDITIONS')
C  200 FORMAT(/2X,  ' ==============================')
C  210 FORMAT(/10X,' 0: TRACTION PRESCRIBED CONDITION')
C  220 FORMAT(/10X,' 1: DISPLACEMENT -//-     -//-')
C  230 FORMAT(/2X, 5(' NODE ',2X,' COND '))
C  240 FORMAT(5(2X,I5))
      RETURN
      END
