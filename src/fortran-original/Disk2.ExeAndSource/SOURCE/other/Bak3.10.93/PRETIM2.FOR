C              TSXX1=0.0D0
C              TSYY1=0.0D0
C              TSXY1=DRNORM
C              CALL STRGLOB(TSXX1,TSYY1,TSXY1,FN1,FN2,
C     &                        SXXSV,SYYSV,SXYSV)
C
CC             TRANSFORNATION OF THESE INCIDENT SV STRESSES FROM THE
CC             GLOBAL COORDINATE SYSTEM TO THE LOCAL SYSTEM WITH X1,X2 AXIS 
CC             OUTWORD NORMAL AND TANGENTIAL UNIT VECTORS,(-RQ,RN) TO THE 
CC             FREE SURFACE
CC
CC             SV-WAVE 
CC              S11SV=SXXSV*RN1**2+2.0D0*SXYSV*RN2*RN1+
CC     &                 SYYSV*RN2**2
CC              S22SV=SXXSV*RN2**2-2.0D0*SXYSV*RN2*RN1+
CC     &                 SYYSV*RN1**2
CC              S12SV=(SYYSV-SXXSV)*RN2*RN1+
CC     &                 SXYSV*(RN1**2-RN2**2)
CC
C              CALL STRLOC(SXXSV,SYYSV,SXYSV,RN1,RN2,
C     &                       S11SV,S22SV,S12SV)
CC
C              CALL REFSTRSV(THEP,THANP,THANSV,THCR,RK,KANGL,
C     &                        C11P,C22P,C12P,C11SV,C22SV,C12SV)
C              SRXXP=C11P*S11SV
C              SRXXSV=C11SV*S11SV
C              SRYYP=C22P*S22SV
