CC             SIN(WAI)*X+COS(WAI)*Y-CQ=0
CC             CE*X+CF*Y-CQ=0
CCC              CE=DSIN(WAI)
CCC              CF=DCOS(WAI)
C              CE=RN1
C              CF=RN2
C              DIAG=DSQRT((RSY2-RSY1)**2+(RSX2-RSX1)**2)
C              IF(DABS(DIAG).LT.TOL) DIAG=TOL
C              CQ=(RSX1*RSY2-RSY1*RSX2)/DIAG
CC       FIND THE REFLECTED STRESSES FIELD
CC
CC             SV-WAVE
CC             -------
CC             CALL REFAMSV(THEP,THANP,THANSV,THCR,RK,
CC    &                       KANGL,RAT1,RAT2)
CC             TRANSFORNATION OF THE INCIDENT SV STRESSES FROM ANGLE 
CC             OF INCIDENCE FAI TO THE GLOBAL COORDINATE SYSTEM FIRST
CC             SV-WAVE (ONLY SHEAR)
C              FN1=DCOS(FAI)
C              FN2=DSIN(FAI)
CC              SXXSV=-2.0D0*DRNORM*FN1*FN2
CC              SYYSV=2.0D0*DRNORM*FN1*FN2
CC              SXYSV=DRNORM*(FN1**2-FN2**2)
