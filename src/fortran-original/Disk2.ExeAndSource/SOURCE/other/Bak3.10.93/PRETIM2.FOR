C ----------------------------------------------------------------------
      SUBROUTINE REFPTIM(XCR,YCR,SXX,SYY,SXY,
     &          N1,N2,N3,N4,N5,CA,CB,CP,NB0,NB1,T1,NCOUNT,
     &          JKODE,NSHAP,NBOUN,NSEGM,SEG,NBNT,XCEN,YCEN,
     &          SRXX,SRYY,SRXY,DRSTRE,DRNSTRE,NDTYPE)
C
C   CALCULATES AND SAVES ON TAPE 1, THE LOADS IN THE TIME DOMAIN, 
C   ON THE SURFACE OF THE GEOMETRICAL SHAPE (ANY SHAPE) 
C   SXX,SYY,SXY: INCIDENT STRESSES IN GLOBAL COORDINATE SYSTEM (WITHOUT
C                THE ADDITIONAL VERTIACAL STRESSES) 
C     SLOAD TRACTIONS, ARE THE INCIDENT STRESSES IN X AND Y DIRECTIONS
C   (CARTESIAN COORDINATES)
C     SLOAD1 TRACTIONS, ARE THE INCIDENT STRESSES IN RADIAL,HOOP AND SHEAR 
C   DIRECTION (CYLIDRICAL COORDINATES)
C     THE LOADS ARE CONSIDERED POSSITIVE WHEN ARE DIRECTED IN
C   THE POSSITIVE CARTESIAN AXIS,OR IN THE POSITIVE NORMAL AND TANGENTIAL
C   UNIT VECTOR, (INWARD NORMAL FOR CAVITY)  
C   NB1: NUMBER OF THE NODES OF THE BOUNDARY
C   NB0: GLOBAL NUMBER OF THE STARTING NODE OF THE BOUNDARY
C   SRXX,SRYY,SRXY: RETURNED VALUES OF REFLECTED STRESSES AT EVERY NODE
C                   WITH DELAYS OF ARRIVING WAVE, IN THE GLOBAL COORDINATE 
C                   SYSTEM
CC   KEXPL=1: THE LOADS ARE FROM EXPLOSION POINT
C -----------------------------------------------------------------------
      IMPLICIT REAL*8 (A-H,O-Y)
C
      COMMON/CONTR/NNODE,NELEM,NSTEP,NHOOP
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/PROBL/NDOMA,NREGI,NUNIT
      COMMON/GEOM3/FAI,PSAI
      COMMON/GEOM2/RAD,RATIO,SID,XSID,YSID,XSTA,YSTA,XLAS,YLAS,
     &             XCR0,YCR0,TYPELX,TYPELY,NDIS
C
      DIMENSION PSAI(5)
      DIMENSION XCR(N1),YCR(N1)
C      DIMENSION XY(3,2),SPOINT(3),SHP(3),DSHP(3)
      DIMENSION RN(2)
C          ,RQ(2)
      DIMENSION NREGI(5)
      DIMENSION XCR0(5),YCR0(5)
      DIMENSION RAD(5),RATIO(5),SID(5)
      DIMENSION XSID(5),YSID(5)

      DIMENSION XSTA(5),YSTA(5),XLAS(5),YLAS(5),TYPELX(5),
     &          TYPELY(5),NDIS(5)
      DIMENSION JKODE(NBNT)
      DIMENSION NSHAP(NBOUN)
C      DIMENSION NNODEB(NBOUN)
C      DIMENSION NELEMB(NBOUN)
      DIMENSION NSEGM(NBOUN)
      DIMENSION SEG(NBNT*7)
      DIMENSION SRXX(N1),SRYY(N1),SRXY(N1)
      DIMENSION NDTYPE(N1)



C
C      DATA SPOINT/-1.,0.,1./
      PI=3.14159265359D0
C     TOLERANCE 
      TOL=1.0E-11
C
      SRXXP=0.0D0
      SRXXSV=0.0D0
      SRYYP=0.0D0
      SRYYSV=0.0D0
      SRXYP=0.0D0
      SRXYPV=0.0D0
      SRXYSV=0.0D0
C
C
C          FAI: ANGLE OF AXIS OF WAVEFRONT WITH X-AXIS (0<=FAI<=PI)
C          WAI: ANGLE OF LINE OF FREE SURFACE WITH X-AXIS (0<=WAI<=PI)
C     FIND THE ANGLE WAI
C     COUNTER TO FIND THE COORDINATES OF THE NODES IN ARRAY SEG (ONLY
C     COMBOUND SHAPES)
      FAI1=FAI
      JL=0
      IBI=0
C     COUNTER FOR NODE NUMBERING
      NCN=NB0
C     CALCULATE THE REFLECTING STRESSES
      DO 46 IB=1,NBOUN 
C       FOR COMBOUND BOUNDARY, OR STRAIGHT LINE REFLECTION FREE SURFACES
        IF((NSHAP(IB).LT.0).OR.(NSHAP(IB).EQ.4)) THEN
C          ATTENTION   
C          ********** RESTRICTION OF THE PROGRAM *************
C          THE PROGRAM ACCEPTS ONLY ONE LINE FREE SURFACE(SO NS=1)
            J=1
            JL=JL+7*(J-1)
            IBI=IBI+1
            JKODE1=JKODE(IBI)
            NREGI1=NREGI(IB)
C           FREE SURFACE BOUNDARY
            IF(NREGI1.EQ.4) THEN
C             STRAIGHT LINE COMBOUND BOUNDARY
              NRF=0
C             STRAIGHT LINE REFLECTION FREE SURFACES
              IF(NSHAP(IB).EQ.4) NRF=1
C
C             CALCULATE THE EQUATION OF THE LINE OF THE FREE SURFACE
C                 CE*X+CF*Y-CQ=0
C             AND THE DIRECTION COSINES RN OF THE UNIT NORMAL VECTOR
              CALL SURFLINE(JKODE1,SEG,JL,RN,THN1,CE,CF,CQ,NBNT,
     &                       IB,NRF)
              RN1=RN(1)
              RN2=RN(2)



C              IF(JKODE(IBI).EQ.1) THEN
CC               COORDINATES OF THE ENDS OF THE LINE OF THE FREE BOUNDARY
C                IBIF=IBI
CC               START X COORD.
C                RSX1=SEG(JL+1)
CC               START Y COORD.
C                RSY1=SEG(JL+2)
CC               END X COORD.
C                RSX2=SEG(JL+3)
CC               END Y COORD.
C                RSY2=SEG(JL+4)
C              ENDIF
C              NOD=3
C              XY(1,1)=RSX1
C              XY(1,2)=RSY1
C              XY(3,1)=RSX2
C              XY(3,2)=RSY2
CC             COOORDINATES OF THE MIDDLE OF THE LINE
C              XY(2,1)=(RSX1+RSX2)/2.0D0
C              XY(2,2)=(RSY1+RSY2)/2.0D0
CC             INTERPOLATION FOR THE MIDDLE NODE (EKS=0)
C              EKS=SPOINT(2)
C              CALL CSHAPE(EKS,NOD,XY,SHP,DSHP,RN,DETJ)
CC             FIND THE NORMAL AND TANGENT UNIT VECTORS FOR THE MIDDLE NODE 
CC             WHICH ARE THE SAME FOR ALL THE LINE
C              RQ(1)=-RN(2)
C              RQ(2)=RN(1)
C              RN1=RN(1)
C              RN2=RN(2)
C              RQ1=RQ(1)
C              RQ2=RQ(2)
CC    
CC             CALCULATE THE ANGLE THN1
C              RN11=RN1
C              IF(DABS(RN11).LT.TOL)THEN
C               IF (RN11.LT.0.0D0) RN11=-TOL
C               IF (RN11.GT.0.0D0) RN11=TOL
C               IF (RN11.EQ.0.0D0) THEN
C                 IF (RQ1.LT.0.0D0) THN1=PI/2.0D0
C                 IF (RQ1.GT.0.0D0) THN1=3.0D0*PI/2.0D0
C                 GO TO 34
C                ENDIF
C              ENDIF
C              THN1=DATAN2(RN2,RN11)
C  34          CONTINUE
C              IF(THN1.LT.0.0D0) THN1=2.0D0*PI+THN1


C             CHECK IF THE REFLECTION CONDITION IS FULLFILED
              CALL REFLCOND(FAI1,THN1,KREFL,KANGL)
C             CASE NOT REFLECTION CONDITIONS
              IF(KREFL.EQ.0) GO TO 49
C
C               ATTENTION    !!!!!!!!!!!!!!!!!!!!!!!
C             ABSOLUTE VALUE IS TAKEN ( 0<=TH0<=PI/2
              TH0=DABS(PI-DABS(FAI1-THN1))
C   
C             P-WAVE
C             ------
C             CALCULATE THE ANGLE TH2 (ANGLE OF REFLECTED SHEAR SV WAVE WITH
C             THE NORMAL TO THE FREE SURFACE)
C             SIN(TH2)=SIN(TH0)/RK
              RK=DSQRT(2.0D0*(1.0D0-RNU)/(1.0D0-2.0D0*RNU))
C             OR RK=C1/C2
              IF(DABS(RK).LT.TOL) RK=TOL
              SINTH2=DSIN(TH0)/RK
C               ATTENTION       !!!!!!!!!!!!!!!!!!!
C             TH2 ALWAYS POSITIVE AND 0<=TH2<=PI/2
              TH2=DABS(DASIN(SINTH2))
C
C             ANGLES OF INCIDENT AND REFLECTED WAVE IN LOCAL SYSTEM WITH 
C             CENTER AT POINT B
              THEP=PI-TH0
              THANP=PI+TH0
              THANSV=PI+TH2
              IF(KANGL.EQ.2) THEN
                THEP=PI+TH0
                THANP=PI-TH0
                THANSV=PI-TH2
              ENDIF
              FN1=DCOS(FAI1)
              FN2=DSIN(FAI1)

C
C             FIND THE REFLECTED STRESSES FIELD
C                ^^^^^^^^^^^^^^^^^^^^^^^
              CALL TREFLD(THEP,THANP,THANSV,RK,DRSTRE,DRNSTRE,
     &           XBB,YBB,XDD,YDD,K,FN1,FN2,RN1,RN2,RAT1,RAT2,
     &           SRXXP,SRYYP,SRXYP,SRXXCP,SRYYCP,SRXYCP,T1)
C                ^^^^^^^^^^^^^^^^^^^^^^^^











CC             EQUATION OF THE LINE OF THE FREE SURFACE, IN GLOBAL SYSTEM
CC             PASSING THROUGH POINTS (RSX1,RSY1),(RSX2,RSY2)
CC                (Y2-Y1)*X+(X1-X2)*Y-(X1Y2-Y1X2)=0
CC             OR DIAG=SQRT((Y2-Y1)**2+(X2-X1)**2)
CC                ((Y2-Y1)/DIAG)*X+((X2-X1)/DIAG)*Y-(X1Y2-Y1X2)/DIAG=0
CC             SIN(WAI)*X+COS(WAI)*Y-CQ=0
CC             CE*X+CF*Y-CQ=0
C              CE=RN1
C              CF=RN2
C              DIAG=DSQRT((RSY2-RSY1)**2+(RSX2-RSX1)**2)
C              IF(DABS(DIAG).LT.TOL) DIAG=TOL
C              CQ=(RSX1*RSY2-RSY1*RSX2)/DIAG
CC             FIND THE REFLECTED STRESSES FIELD
CC             TRANSFORNATION OF THE INCIDENT P STRESSES FROM ANGLE 
CC             OF INCIDENCE FAI TO THE GLOBAL COORDINATE SYSTEM FIRST
CC             P-WAVE (NORMAL STRESSES ONLY WITHOUT SHEAR
C              FN1=DCOS(FAI)
C              FN2=DSIN(FAI)
CC              SXXP=DRSTRE*FN1**2+DRNSTRE*FN2**2
CC              SYYP=DRSTRE*FN2**2+DRNSTRE*FN1**2
CC              SXYP=(DRSTRE-DRNSTRE)*FN2*FN1
C
C              TSXX1=DRSTRE
C              TSYY1=DRNSTRE
C              TSXY1=0.0D0
C              CALL STRGLOB(TSXX1,TSYY1,TSXY1,FN1,FN2,
C     &                        SXXP,SYYP,SXYP)
CC
CC             TRANSFORNATION OF THESE INCIDENT P STRESSES FROM THE
CC             GLOBAL COORDINATE SYSTEM TO THE LOCAL SYSTEM WITH X1,X2 AXIS 
CC             OUTWORD NORMAL AND TANGENTIAL UNIT VECTORS,(-RQ,RN) TO THE 
CC             FREE SURFACE
CC             P-WAVE 
CC              S11P=SXXP*RN1**2+2.0D0*SXYP*RN2*RN1+
CC     &                 SYYP*RN2**2
CC              S22P=SXXP*RN2**2-2.0D0*SXYP*RN2*RN1+
CC     &                 SYYP*RN1**2
CC              S12P=(SYYP-SXXP)*RN2*RN1+
CC     &                 SXYP*(RN1**2-RN2**2)
CC
C              CALL STRLOC(SXXP,SYYP,SXYP,RN1,RN2,S11P,S22P,S12P)
CC
CC             STRESS REFLECTION COEFFICIENTS IN LOCAL COORDINATE SYSTEM
CC             WITH AXES NORMAL AND TANGENT TO THE FREE SURFACE (UNIT VECTORS
CC             N AND Q)
CC
CC
C              CALL REFSTRP(THEP,THANP,THANSV,RK,
C     &                        C11P,C22P,C12P,C11SV,C22SV,C12SV)
C              SRXXP=C11P*S11P
C              SRXXSV=C11SV*S11P
C              SRYYP=C22P*S22P
C              SRYYSV=C22SV*S22P
C              SRXYP=C12P*S12P
C              SRXYSV=C12SV*S12P
CC             FOR NODES NOT LYING ON THE FREE SURFACE, ADD THE CONFINING
CC             STRESSES DUE TO THE REFLECTED P-WAVE.
CC             TRANSFORMATION OF THE STRESSES SRXXP,SRYYP,SRXYP FROM THE
CC             LOCAL(GLOBAL) COORDINATE SYSTEM (AXES NORMAL AND TANGENT 
CC             TO THE FREE SURFACE), TO A SYSTEM WITH X AXIS THE REFLECTED 
CC             P-WAVE WHICH MAKES AN ANGLE THANP
CC
CC
C              RNT1=DCOS(THANP)
C              RNT2=DSIN(THANP)
CC              SRXXP1=SRXXP*RNT1**2+2.0D0*SRXYP*RNT2*RNT1+
CC     &                 SRYYP*RNT2**2
CC              SRYYP1=SRXXP*RNT2**2-2.0D0*SRXYP*RNT2*RNT1+
CC     &                 SRYYP*RNT1**2
CC              SRXYP1=(SRYYP-SRXXP)*RNT2*RNT1+
CC     &                 SRXYP*(RNT1**2-RNT2**2)
CC
C              CALL STRLOC(SRXXP,SRYYP,SRXYP,RNT1,RNT2,
C     &                       SRXXP1,SRYYP1,SRXYP1)
CC
C              SRXXCP=SRYYP1*RNU/(1.0D0-RNU)
C              SRYYCP=SRXXP1*RNU/(1.0D0-RNU)
CC             SUM OF CONFINING AND OTHER STRESSES:
C              SRXXP1=SRXXP1+SRXXCP
C              SRYYP1=SRYYP1+SRYYCP
CC              SRXYP1=SRXYP1
CC             TRANSFORMATION OF THESE TOTAL PRESSURES FROM THE DIRECTION
CC             WITH ANGLE THANP, BACK TO THE LOCAL(GLOBAL)  COORDINATE SYSTEM
CC
CC              SRXXCP=(SRXXP1*RNT1**2+SRYYP1*RNT2**2-
CC     &                   2.0D0*SRXYP1*RN2*RNT1)
CC              SRYYCP=(SRXXP1*RNT2**2+SRYYP1*RNT1**2+
CC     &              2.0D0*SRXYP1*RNT2*RNT1)
CC              SRXYCP=((SRXXP1-SRYYP1)*RNT2*RNT1+SRXYP1*
CC     &              (RNT1**2-RNT2**2))
CC
C              CALL STRGLOB(SRXXP1,SRYYP1,SRXYP1,RNT1,RNT2,
C     &                        SRXXCP,SRYYCP,SRXYCP)





            ENDIF
  49      CONTINUE
        ENDIF
  46  CONTINUE
C     CASE NOT REFLECTION CONDITIONS
      IF(KREFL.EQ.0) GO TO 99
C
C     CASE THAT THE INCIDENT WAVE IS PARALLEL TO THE FREE SURFACE,
C     IT CANOT BE REFLECTED.
C     BUT EVEN IF THE FREE SURFACE IS TRACTION FREE, THERE IS
C     TANGENTIAL INCIDENT STRESSES  EQUAL TO THE INCIDENT(CALCULATED
C     IN SUBROUTINE WINCID)
C
      IF(KREFL.EQ.2) GO TO 99
      DO 50 I=1,NB1



C^^^^^^^^^^^^!!!!!!!!!!!!!!!!
C        FOR NODES ON ENCLOSING ELEMENTS SURFACE, DON'T CALCULATE LOADS
         IF(NDTYPE(I).EQ.4) GO TO 89







        INRF1=0
        INRF2=0
        XCR1=XCR(NCN)
        YCR1=YCR(NCN)








C        CH=XCR1*CE+YCR1*CF-CQ
CC       TAKE ABSOLUTE VALUE, FREE SURFACE ALWAYS ABOVE NODES
C        CH=DABS(CH)
CC
CC       ATTENTION      0 DEGREES !!!!!!!!!!!!!!!!!!!!!!!
CC       NOT PERMITED FROM THIS PROGRAM
CC       DISTANCE OF NODE E FROM THE LINE OF FREE SURFACE BEL: REFLECTED P-WAVE
CC                                                        DEL: REFLECTED SV-WAVE
CC       IN LOCAL COORDINATE SYSTEM WITH ORIGIN AT THE ACTUAL NODE, AND 
CC       AXES X',Y' PARALLEL TO N,Q  (N: UNIT VECTOR NORMAL TO FREE SURFACE
CC                                   (Q: UNIT VECTOR TANGENT TO FREE SURFACE)
CC       ANGLES TH0 AND TH2 IN LOCAL SYSTEM
C        THT0=TH0
C        THT2=TH2
C        IF(KANGL.EQ.2) THEN
C          THT0=2*PI-TH0
C          THT2=2*PI-TH2
C        ENDIF
C        BEL=CH/DCOS(THT0)
C        DEL=CH/DCOS(THT2)
CC       BEL,DEL ALWAYS POSITIVE, BECAUSE CH>0, COS(TH0)=COS(2PI-TH0)>0
CC       COORDINATES IN LOCAL SYSTEM
C        YBB1=BEL*DSIN(THT0)
C        XBB1=CH
C        YDD1=DEL*DSIN(THT2)
C        XDD1=CH
CC       XBB1,XDD1: POSITIVE FOR TH0=TH0
CC                  NEGATIVE FOR TH0=2PI-TH0
CC       YBB1,YDD1: ALWAYS POSITIVE
CC       TRANSFORMATION OF COORDINATES FROM LOCAL SYSTEM WITH ORIGIN 
CC       AT THE ACTUAL NODE AND AXES PARALLEL TO N,Q, 
CC       TO A SYSTEM WITH ORIGIN AGAIN AT THE NODE AND
CC       AXES PARALLEL TO AXES OF GLOBAL SYSTEM
CC       POINT B
CC        XBB=XBB1*DCOS(WAI)-YBB1*DSIN(WAI)+XCEN
CC        YBB=XBB1*DSIN(WAI)+YBB1*DCOS(WAI)+YCEN
CC
C        WAI=THN1
C        WN1=DCOS(WAI)
C        WN2=DSIN(WAI)
C        XBB=XBB1*WN1-YBB1*WN2
C        YBB=XBB1*WN2+YBB1*WN1
CC       POINT D
CC        XDD=XDD1*DCOS(WAI)-YDD1*DSIN(WAI)+XCEN
CC        YDD=XDD1*DSIN(WAI)+YDD1*DCOS(WAI)+YCEN
C        XDD=XDD1*WN1-YDD1*WN2
C        YDD=XDD1*WN2+YDD1*WN1
CC    
CC       COORDINATES IN THE GLOBAL SYSTEM
C        XBB=XCR1+XBB
C        YBB=YCR1+YBB
C        XDD=XCR1+XDD
C        YDD=YCR1+YDD
CC################################################################
CC       ATTTENTIONNNNNNNNNNNNNNNNNNNNNNNNNNNNN !!!!!!!!!
CC       THE DISTANCE OF THE NODE FROM THE WAVEFRONT IS TAKEN ALWAYS
CC       POSSITIVE. 
CC       THIS MEANS THAT THE WAVEFRONT AT TIME T=0, IS ALWAYS OUT OF THE
CC       MESH, AND THIS IS TRUE, SINCE THE PROGRAM AUTOMATICALLY PUTS
CC       THE WAVEFRONT OUTSIDE THE MESH (EXCEPT FOR THE BOUNDARY OF THE
CC       FREE SURFACE THAT IS NOT TAKEN INTO ACCOUNT)
CC       IF WE WANT THE WAVE AT T=0 INCIDE THE MESH, THEN THE DELAYS BEHINFD
CC       THE MESH MUST BE =0
CC       DISTANCE OF POINTS B,D (ON THE LINE OF FREE SURFACE) FROM 
CC       THE WAVEFRONT LINE CA*X+CB*Y-CP=0 (POSITION AT T=0)
CC       NEGATIVE IF NODE I AND THE ORIGIN XCR0,YCR0 ARE IN THE SAME 
CC       SIDE OF THE LINE, POSITIVE IF THEY ARE IN THE OPPOSITE SIDE
CC       CP IN COORDINATE SYSTEM, WITH ORIGIN  
CC       THE CENTER OF THE MESH XCEN,YCEN
CC       -------------------------------------
C        XBBG=XBB-XCEN
C        YBBG=YBB-YCEN
C        XDDG=XDD-XCEN
C        YDDG=YDD-YCEN
CC
C        ABL=XBBG*CA+YBBG*CB-CP
C        CDL=XDDG*CA+YDDG*CB-CP
CC       IF ABL OR CDL IS POSSITIVE, IT MEANS THAT THE POINT B OR D IS
CC       BEHIND THE WAVEFRONT (THIS IS ESPECIALLY HAPPEN IN CASE OF SV WAVES,
CC       WITH ANGLE OF INCIDENCE NEAR THE CRITICAL ANGLE). IN THIS CASE THE 
CC       ACTUAL REFLECTED STRESS IS 0.
C        IF(ABL.GT.0.0D0) INRF1=1
C        IF(CDL.GT.0.0D0) INRF2=1
CC       DISTANCES ALWAYS POSSITIVE
C        ABL=DABS(ABL)
C        CDL=DABS(CDL)
CC
C        BEL=DABS(BEL)
C        DEL=DABS(DEL)
CC
CC       DELAY
C        ALP=(ABL+BEL)/C1
C        ALSV=CDL/C1+DEL/C2
CC        ALP=BEL/C1
CC        ALSV=DEL/C2







C       FIND THE DELAY OF PATERN OF THE RAYS OF THE REFLECTED WAVE 
C           ABE AND CDE
C       ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
        CALL TPATP(XCR1,YCR1,CE,CF,CQ,TH0,TH2,KANGL,THN1,
     &       XCEN,YCEN,CA,CB,CP,INRF1,INRF2,ALP,ALSV,T1)
C       ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
C       DELAY FOR ARRIVING AT NODE NCN OF THE REFLECTED WAVE
C       P-REFLECTED WAVE
C        SDELAY1=CDEXP(-ALP*ZK)
C        T2=ALP/C1
        T2=ALP
        SDELAY1=0.0D0
	IF (T1.GE.T2) SDELAY1=1.0D0


C^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
	IF(DABS(T1-T2).LT. TOL) SDELAY1=1.0


C       SV-REFLECTED WAVE
C        ZDELAY2=CDEXP(-ALSV*ZK)
C        T3=ALSV/C2
        T3=ALSV
        SDELAY2=0.0D0
	IF (T1.GE.T3) SDELAY2=1.0D0

C^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
	IF(DABS(T1-T3).LT. TOL) SDELAY2=1.0



C  43    CONTINUE
C
C       FIND THE REFLECTED STRESSES FIELD
C       REFLECTED STRESSES AT EVERY NODE
C       IN LOCAL COORDINATE AXIS, WITH X AXIS OUTWORD RADIAL TO FREE 
C       SURFACE (AS UNIT VECTORS N:RADIAL, Q:TANGENT) 
C       AND ORIGIN ON THE FREE SURFACE
C       TOTAL SXX FROM P AND SV REFLECTED STRESSES, WITH DELAY
CC       FOR BOUNDARY OTHER THAN THE FREE SURFACE, TAKE THE INCREASED
CC       FROM THE CONFINEMENT STRESSES
C        IF(NREGI(NCOUNT).NE.4) THEN
          SRXXP=SRXXCP
          SRYYP=SRYYCP
          SRXYP=SRXYCP
C        ENDIF
        TRXXP=SRXXP*RAT1
        TRXXSV=SRXXSV*RAT2
        TRYYP=SRYYP*RAT1
        TRYYSV=SRYYSV*RAT2
        TRXYP=SRXYP*RAT1
        TRXYSV=SRXYSV*RAT2
C       CASE B OR D BEHIND THE WAVEFRONT, THE CONTRIBUTION IN THE ACTUAL
C       STRESSES IS 0
        IF(INRF1.EQ.1) THEN
          TRXXP=0.0D0
          TRYYP=0.0D0
          TRXYP=0.0D0
         ENDIF
        IF(INRF2.EQ.1) THEN
          TRXXSV=0.0D0
          TRYYSV=0.0D0
          TRXYSV=0.0D0
         ENDIF
C        SRXX1=SRXXP*RAT1*SDELAY1+
C     &            SRXXSV*RAT2*SDELAY2
C       TOTAL SYY FROM P AND SV REFLECTED STRESSES, WITH DELAY
C        SRYY1=SRYYP*RAT1*SDELAY1+
C     &            SRYYSV*RAT2*SDELAY2
C        SRXY1=SRXYP*RAT1*SDELAY1+
C     &            SRXYSV*RAT2*SDELAY2
C
C       TOTAL REFLECTED STRESSES OF P AND SV REFLECTED WAVE, WITH DELAYS
        SRXX1=TRXXP*SDELAY1+TRXXSV*SDELAY2
        SRYY1=TRYYP*SDELAY1+TRYYSV*SDELAY2
        SRXY1=TRXYP*SDELAY1+TRXYSV*SDELAY2
C
C
C       TRANSFORMATION OF THESE STRESSES BACK TO THE GLOBAL COORDINATE SYSTEM
CC         SUPERIMPOSE P AND SV TRACTIONS
C          SRXX(NCN)=SRXX(NCN)+(SRXX1*RN1**2+SRYY1*RN2**2-
C     &                 2.0D0*SRXY1*RN2*RN1)
C          SRYY(NCN)=SRYY(NCN)+(SRXX1*RN2**2+SRYY1*RN1**2+
C     &              2.0D0*SRXY1*RN2*RN1)
C          SRXY(NCN)=SRXY(NCN)+((SRXX1-SRYY1)*RN2*RN1+SRXY1*
C     &              (RN1**2-RN2**2))C

          CALL STRGLOB(SRXX1,SRYY1,SRXY1,RN1,RN2,
     &                     SRXX11,SRYY11,SRXY11)
C         SUPERIMPOSE P AND SV TRACTIONS
          SRXX(NCN)=SRXX(NCN)+SRXX11
          SRYY(NCN)=SRYY(NCN)+SRYY11
          SRXY(NCN)=SRXY(NCN)+SRXY11
C

  89    CONTINUE

        NCN=NCN+1
  50  CONTINUE
  99  CONTINUE
      RETURN
      END
C
C ----------------------------------------------------------------------
      SUBROUTINE TPATP(XCR1,YCR1,CE,CF,CQ,TH0,TH2,KANGL,THN1,
     &       XCEN,YCEN,CA,CB,CP,INRF1,INRF2,ALP,ALSV,T1)
C
C     CALCULATES THE DISTANCE OF PATERN OF THE RAYS OF THE REFLECTED WAVE 
C           ABE AND CDE
C     XCR1,YCR1: COORDINATES OF THE NODE NCN IN THE GLOBAL SYSTEM
C     EQUATION OF THE LINE OF THE FREE SURFACE
C                 CE*X+CF*Y-CQ=0
C     TH0      : ANGLE OF INCIDENT AND REFLECTED P-WAVE
C     TH2      : ANGLE OF REFLECTED SV-WAVE
C     KANGL    : INDEX FOR CALCULATING THE ANGLES OF INCIDENT AND REFLECTED
C                RETURN VALUE
C                  1: TH0=TH0,     TH2=TH2
C                  2: TH0=2PI-TH0, TH2=2PI-TH2
C     THN1     : ANGLE OF X GLOBAL AXIS WITH THE UNIT NORMAL VECTOR
C     XCEN,YCEN: COORDINATES OF THE CENTER OF THE MESH (OF ALL THE BOUNDARIES)
C     CA,CB,CP : VALUES OF THE CONSTANTS OF THE EQUATION OF LINE OF WAVE FRONT
C                    CA*XCR(I)+CB*YCR(I)-CP=0
C     INRF1,INRF2: INDEX WHEN =1, THE POINTS B OR D ARE BEHIND THE 
C     WAVEFRONT (THIS ESPECIALLY HAPPENS IN CASES OF SV WAVES,
C     WITH ANGLE OF INCIDENCE NEAR THE CRITICAL ANGLE). IN THIS CASE THE
C     ACTUAL REFLECTED STRESS IS 0.
C
C     ALP      : TOTAL DELAY OF PATERN P-WAVE RAY, RETURN VALUE
C                    ABE=PWAV AB + PWAV  BE
C     ALSV     : TOTAL DELAY OF PATERN P,SV-WAVE RAY , RETURN VALUE
C                    CDE=PWAV CD + SVWAV DE 

      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      PI=3.14159265359D0

C       DISTANCE OF NODE I FROM THE LINE OF FREE SURFACE
C       POSITIVE IF NODE I AND THE ORIGIN XCR0,YCR0 ARE IN THE OPOSITE SIDE,
C       NEGATIVE, IF THEY ARE IN THE SAME SIDE
C       ALWAYS IT IS NEGATIVE
C        CH=XCR(I)*DCOS(WAI)+YCR(I)*DSIN(WAI)-CQ
C        CH=XCR1*CE+YCR1*CF-CQ
C
        CH=XCR1*CE+YCR1*CF-CQ
C       TAKE ABSOLUTE VALUE, FREE SURFACE ALWAYS ABOVE NODES
        CH=DABS(CH)
C
C       ATTENTION      0 DEGREES !!!!!!!!!!!!!!!!!!!!!!!
C       NOT PERMITED FROM THIS PROGRAM
C       DISTANCE OF NODE E FROM THE LINE OF FREE SURFACE BEL: REFLECTED P-WAVE
C                                                        DEL: REFLECTED SV-WAVE
C       IN LOCAL COORDINATE SYSTEM WITH ORIGIN AT THE ACTUAL NODE, AND 
C       AXES X',Y' PARALLEL TO N,Q  (N: UNIT VECTOR NORMAL TO FREE SURFACE
C                                   (Q: UNIT VECTOR TANGENT TO FREE SURFACE)
C       ANGLES TH0 AND TH2 IN LOCAL SYSTEM
        THT0=TH0
        THT2=TH2
        IF(KANGL.EQ.2) THEN
          THT0=2*PI-TH0
          THT2=2*PI-TH2
        ENDIF
        BEL=CH/DCOS(THT0)
        DEL=CH/DCOS(THT2)
C       COORDINATES IN LOCAL SYSTEM
        YBB1=BEL*DSIN(THT0)
        XBB1=CH
        YDD1=DEL*DSIN(THT2)
        XDD1=CH
C       XBB1,XDD1: POSITIVE FOR TH0=TH0
C                  NEGATIVE FOR TH0=2PI-TH0
C       YBB1,YDD1: ALWAYS POSITIVE
C       TRANSFORMATION OF COORDINATES FROM LOCAL SYSTEM WITH ORIGIN 
C       AT THE ACTUAL NODE AND AXES PARALLEL TO N,Q, 
C       TO A SYSTEM WITH ORIGIN AGAIN AT THE NODE AND
C       AXES PARALLEL TO AXES OF GLOBAL SYSTEM
C       POINT B
C        XBB=XBB1*DCOS(WAI)-YBB1*DSIN(WAI)+XCEN
C        YBB=XBB1*DSIN(WAI)+YBB1*DCOS(WAI)+YCEN
C
        WAI=THN1
        WN1=DCOS(WAI)
        WN2=DSIN(WAI)
        XBB=XBB1*WN1-YBB1*WN2
        YBB=XBB1*WN2+YBB1*WN1
C       POINT D
C        XDD=XDD1*DCOS(WAI)-YDD1*DSIN(WAI)+XCEN
C        YDD=XDD1*DSIN(WAI)+YDD1*DCOS(WAI)+YCEN
        XDD=XDD1*WN1-YDD1*WN2
        YDD=XDD1*WN2+YDD1*WN1
C
     
C       COORDINATES IN THE GLOBAL SYSTEM
        XBB=XCR1+XBB
        YBB=YCR1+YBB
        XDD=XCR1+XDD
        YDD=YCR1+YDD
C
C       SAVE THESE DISTANCES FOR DRAWING LATER IN SUBROUTINE RAYPLANL
        WRITE(11,*) XBB,YBB,XDD,YDD

C
C       THE DISTANCE OF THE NODE FROM THE WAVEFRONT IS TAKEN ALWAYS
C       POSSITIVE. 
C       THIS MEANS THAT THE WAVEFRONT AT TIME T=0, IS ALWAYS OUT OF THE
C       MESH, AND THIS IS TRUE, SINCE THE PROGRAM AUTOMATICALLY PUTS
C       THE WAVEFRONT OUTSIDE THE MESH (EXCEPT FOR THE BOUNDARY OF THE
C       FREE SURFACE THAT IS NOT TAKEN INTO ACCOUNT)
C       IF WE WANT THE WAVE AT T=0 INCIDE THE MESH, THEN THE DELAYS BEHIND
C       THE MESH MUST BE =0
C       DISTANCE OF POINTS B,D (ON THE LINE OF FREE SURFACE) FROM 
C       THE WAVEFRONT LINE CA*X+CB*Y-CP=0 (POSITION AT T=0)
C       POSITIVE IF NODE I AND THE ORIGIN XCR0,YCR0 ARE IN THE OPPOSITE
C       SIDE OF THE LINE, NEGATIVE IF THEY ARE IN THE SAME SIDE
CC        ABL=XBB*CA+YBB*CB-CP
CC        CDL=XDD*CA+YDD*CB-CP
CC
CC       DISTANCE OF POINTS B,D (ON THE LINE OF FREE SURFACE) FROM 
CC       THE WAVEFRONT LINE CA*X+CB*Y+(-CP)=0 (POSITION AT T=0)
CC       D=+-[CA*X1+CB*Y1+(-CP)]
CC       THE SIGN +OR- IS THAT OF CB. 
CC       THE DISTANCE IS POSSITIVE, IF THE NODE IS OVER THE LINE (OVER
CC       IN ACCORDANCE WITH POSSITIVE Y), AND NEGATIVE IF IT IS 
CC       UNDER THE LINE
C       CP IN COORDINATE SYSTEM, WITH ORIGIN  
C       THE CENTER OF THE MESH XCEN,YCEN
C        XD(I)=XD(I)-XCEN
C        YD(I)=YD(I)-YCEN
        XBBG=XBB-XCEN
        YBBG=YBB-YCEN
        XDDG=XDD-XCEN
        YDDG=YDD-YCEN
C
C
        ABL=XBBG*CA+YBBG*CB-CP
        CDL=XDDG*CA+YDDG*CB-CP
C       IF ABL OR CDL IS POSSITIVE, IT MEANS THAT THE POINT B OR D IS
C       BEHIND THE WAVEFRONT (THIS IS ESPECIALLY HAPPEN IN CASE OF SV WAVES,
C       WITH ANGLE OF INCIDENCE NEAR THE CRITICAL ANGLE). IN THIS CASE THE 
C       ACTUAL REFLECTED STRESS IS 0.
        IF(ABL.GT.0.0D0) INRF1=1
        IF(CDL.GT.0.0D0) INRF2=1
C       DISTANCES ALWAYS POSSITIVE
        ABL=DABS(ABL)
        CDL=DABS(CDL)
C
        BEL=DABS(BEL)
        DEL=DABS(DEL)
C
CC       VISCOELASTIC BEHAVIOR
C        CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
C       TOTAL DISTANCE OF THE PATERN OF RAYS
        ALP=(ABL+BEL)/C1
        ALSV=CDL/C1+DEL/C2
       RETURN
       END
C ----------------------------------------------------------------------
       SUBROUTINE TREFLD(THEP,THANP,THANSV,RK,DRSTRE,DRNSTRE,
     &   XBB,YBB,XDD,YDD,K,FN1,FN2,RN1,RN2,RAT1,RAT2,
     &   SRXXP,SRYYP,SRXYP,SRXXCP,SRYYCP,SRXYCP,T1)
C     CALCULATES THE REFLECTED STRESS FIELD
      IMPLICIT REAL*8 (A-H,O-Y)
      COMMON/MATER/RLA,RMU,RNU,RHO,C1,C2,TIM,FVISC,NMODE
      COMMON/EXPL/EXPLX,EXPLY,EXPLW,EXPLB,EXPLF,EXPLN,
     &            EXPLN1,EXPLP,EXPLSV,NFORM,NDECAY

C             FIND THE REFLECTED STRESSES FIELD
C             P-WAVE
C             ------
C             AMPLITUDE REFLECTION COEFFICIENTS FOR P-WAVE
              CALL REFAMP(THEP,THANP,THANSV,RK,RAT1,RAT2)
C
C                SPECIAL CASE NOT TAKEN INTO ACCOUNT
CC               SPECIAL CASE TH0=0 (GRAZING INCIDENCE)
C                IF((DABS(TH0-PI/2.0D0).LT.1.0E-4).OR.
C     &                (DABS(TH0-PI/2.0D0).LT.1.0E-4)) THEN
C                RAT=2.0D0*DSQRT(RK*RK-1.0D0)
C                PRAT=RK*RK-2.0D0
C                RAT1=-PRAT**2/(2.0D0*RAT)
C                RAT2=-PRAT/RAT
C                ENDIF 
C             TRANSFORNATION OF THE INCIDENT P STRESSES FROM ANGLE 
C             OF INCIDENCE FAI1 TO THE GLOBAL COORDINATE SYSTEM FIRST
C             P-WAVE (NORMAL STRESSES ONLY WITHOUT SHEAR
              TSXX1=DRSTRE
              TSYY1=DRNSTRE
              TSXY1=0.0D0
              CALL STRGLOB(TSXX1,TSYY1,TSXY1,FN1,FN2,
     &                        SXXP,SYYP,SXYP)
C
C             TRANSFORNATION OF THESE INCIDENT P STRESSES FROM THE
C             GLOBAL COORDINATE SYSTEM TO THE LOCAL SYSTEM WITH X1,X2 AXIS 
C             OUTWORD NORMAL AND TANGENTIAL UNIT VECTORS,(-RQ,RN) TO THE 
C             FREE SURFACE
C             P-WAVE 
              CALL STRLOC(SXXP,SYYP,SXYP,RN1,RN2,S11P,S22P,S12P)
C
C             STRESS REFLECTION COEFFICIENTS IN LOCAL COORDINATE SYSTEM
C             WITH AXES NORMAL AND TANGENT TO THE FREE SURFACE (UNIT VECTORS
C             N AND Q)
C
C             P-WAVE
C             ------
              CALL REFSTRP(THEP,THANP,THANSV,RK,
     &          C11P,C22P,C12P,C11SV,C22SV,C12SV)
              SRXXP=C11P*S11P
              SRXXSV=C11SV*S11P
              SRYYP=C22P*S22P
              SRYYSV=C22SV*S22P
              SRXYP=C12P*S12P
              SRXYSV=C12SV*S12P
C
C             FOR NODES NOT LYING ON THE FREE SURFACE, ADD THE CONFINING
C             STRESSES DUE TO THE REFLECTED P-WAVE.
C             TRANSFORMATION OF THE STRESSES SRXXP,SRYYP,SRXYP FROM THE
C             LOCAL(GLOBAL) COORDINATE SYSTEM (AXES NORMAL AND TANGENT 
C             TO THE FREE SURFACE), TO A SYSTEM WITH X AXIS THE REFLECTED 
C             P-WAVE WHICH MAKES AN ANGLE THANP
C
C
              RNT1=DCOS(THANP)
              RNT2=DSIN(THANP)
C
              CALL STRLOC(SRXXP,SRYYP,SRXYP,RNT1,RNT2,
     &                       SRXXP1,SRYYP1,SRXYP1)
C
CC             VISCOELASTIC BEHAVIOR
C              CALL VISCOEL(ZK,ZMU,ZLA,ZNU,ZC1,ZC2)
CC
              SRXXCP=SRYYP1*RNU/(1.0D0-RNU)
              SRYYCP=SRXXP1*RNU/(1.0D0-RNU)
C             SUM OF CONFINING AND OTHER STRESSES:
              SRXXP1=SRXXP1+SRXXCP
              SRYYP1=SRYYP1+SRYYCP
C              SRXYP1=SRXYP1
C             TRANSFORMATION OF THESE TOTAL PRESSURES FROM THE DIRECTION
C             WITH ANGLE THANP, BACK TO THE LOCAL(GLOBAL)  COORDINATE SYSTEM
              CALL STRGLOB(SRXXP1,SRYYP1,SRXYP1,RNT1,RNT2,
     &                        SRXXCP,SRYYCP,SRXYCP)

              RETURN
              END
